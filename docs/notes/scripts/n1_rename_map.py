#!/usr/bin/env python3
"""N1: write the old -> new name map (docs/notes/n1-rename-map.md, plus a JSON form).

  python3 docs/notes/scripts/n1_rename_map.py <old-tree> <qt-map.json> <out.md> <out.json>

<old-tree> is a checkout of ff0fcb4 (metadata/ at least); <qt-map.json> is the map written by
n1_rewrite_qt_overrides.py. GTK names are compared kind by kind (GIR name) between the trees.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]


def gtk_kinds(meta: Path) -> dict:
    out = {}
    for p in sorted(meta.glob("*.json")):
        d = json.loads(p.read_text())
        if isinstance(d, dict) and d.get("kind") in ("object", "interface"):
            out[p.stem] = d
    return out


def main() -> int:
    old_root, qt_map_path, out_md, out_json = map(Path, sys.argv[1:5])
    old, new = gtk_kinds(old_root / "metadata/gtk"), gtk_kinds(ROOT / "metadata/gtk")
    qt = json.loads(qt_map_path.read_text())
    J = {"gtk": {"tags": {}, "props": {}, "attrs": {}, "synthetic": {}}, "qt": qt,
         "events_removed_aliases": {"click": "clicked", "change": "changed", "close": "close-request (GTK) / close (Qt)"}}
    md = ["# N1 rename map: old -> new names", "",
          "Generated by `docs/notes/scripts/n1_rename_map.py` (lane N1, from ff0fcb4). Rule and decisions:",
          "`docs/notes/n1-rename.md`. Machine-readable: `docs/notes/n1-rename-map.json`.", "",
          "- Handlers are `on<event>` with the new event name (`ontext-changed`); `…capture` is unchanged.",
          "- The DOM-style aliases are gone: `onclick` -> `onclicked`, `onchange` -> `onchanged`,",
          "  `onclose` -> `onclose-request` (GTK) / `onclose` is now Qt's native `close` event.",
          "- `bind:<name>` uses the new prop name (`bind:current-index`).",
          "- `parent:<attr>` child attributes use the new attr names (`parent:column-span`).",
          "- Methods (`bind:this` calls) are not renamed.",
          "- AppKit and WinUI already followed the rule: no names changed there.", ""]

    # ---- GTK ----------------------------------------------------------------------------------
    md += ["## GTK", "", "### Element tags", "", "| GIR class | old | new |", "|---|---|---|"]
    for k in sorted(set(old) | set(new)):
        ot = (old.get(k, {}).get("element") or {}).get("tag")
        nt = (new.get(k, {}).get("element") or {}).get("tag")
        if ot != nt:
            J["gtk"]["tags"][ot or f"(none: {k})"] = nt
            md.append(f"| Gtk{k} | {ot or '—'} | {nt or '—'} |")
    md += ["", "`<window>` was GtkApplicationWindow; it is now GtkWindow (the backend sets `application` on both).",
           "GtkApplicationWindow is `<application-window>`. Fixtures keep `<window>`.", "",
           "Unchanged tags (single-word classes) keep their name: box, button, label, entry, grid, ...", ""]
    syn = {"menubar": "menu-bar", "toolbar": "tool-bar", "contextmenu": "context-menu", "menuseparator": "menu-separator",
           "menu": "menu", "action": "action", "virtuallist": "virtual-list", "canvas": "canvas"}
    J["gtk"]["synthetic"] = syn
    md += ["### Hand-written (synthetic) GTK kinds", "", "| old | new |", "|---|---|"]
    md += [f"| {a} | {b} |" for a, b in syn.items()]
    md += ["", "### Props (old camelCase -> GObject name; per kind, only names that changed)", "",
           "Rule: every prop is now its GObject property name (`canShrink` -> `can-shrink`). Inherited props are",
           "listed on the declaring kind (Widget, Editable, Orientable, ...).", ""]
    for k in sorted(new):
        if k not in old:
            continue
        op = {p["name"]: p.get("js_name") for p in old[k].get("properties", [])}
        ch = []
        for p in new[k].get("properties", []):
            o = op.get(p["name"])
            if o and o != p["js_name"]:
                ch.append((o, p["js_name"]))
        if ch:
            J["gtk"]["props"][k] = dict(ch)
            md.append(f"- **Gtk{k}**: " + ", ".join(f"`{a}`→`{b}`" for a, b in ch))
    md += ["", "### Child attributes (`parent:`)", "", "| parent | old | new |", "|---|---|---|"]
    for k in sorted(new):
        if k not in old:
            continue
        oa = [a["name"] for s in (old[k].get("children") or {}).get("slots", []) for a in s.get("attrs", [])]
        na = [a["name"] for s in (new[k].get("children") or {}).get("slots", []) for a in s.get("attrs", [])]
        for a, b in zip(oa, na):
            if a != b:
                J["gtk"]["attrs"].setdefault(k, {})[a] = b
                md.append(f"| Gtk{k} | {a} | {b} |")
    md += ["", "Signals: unchanged (GObject names were already used), except the removed DOM aliases above.", ""]

    # ---- Qt -----------------------------------------------------------------------------------
    md += ["## Qt", "", "### Element tags", "", "| class | old | new |", "|---|---|---|"]
    for o, rec in sorted(qt["tags"].items(), key=lambda kv: kv[1]["new"]):
        md.append(f"| {rec['class']} | {o} | {rec['new']} |")
    md += ["", "- `contextmenu` is gone: a `<menu>` inserted into a widget that is not a menu, menu bar or tool bar is",
           "  that widget's context menu (popup/popdown methods are on `menu`).",
           "- `menuseparator` is gone: `<action separator={true} />` (QAction::setSeparator).",
           "- `box` -> `box-layout` (a QWidget with a QBoxLayout): `orientation=\"horizontal|vertical\"` becomes the native",
           "  `direction=\"left-to-right|right-to-left|top-to-bottom|bottom-to-top\"` (QBoxLayout::Direction). Same on `frame`",
           "  and `group-box`. The Qt style property `orientation` is `direction` too.",
           "- `grid` -> `grid-layout` (a QWidget with a QGridLayout).", "",
           "### Props (per element; `inherit:<Class>` blocks apply to every element of that class and its subclasses)", ""]
    for el in sorted(qt["props"]):
        ch = [(a, b) for a, b in qt["props"][el].items() if a != b]
        if ch:
            md.append(f"- **{el}**: " + ", ".join(f"`{a}`→`{b}`" for a, b in ch))
    md += ["", "### Events (signals)", ""]
    for el in sorted(qt["signals"]):
        ch = [(a, b) for a, b in qt["signals"][el].items() if a != b]
        if ch:
            md.append(f"- **{el}**: " + ", ".join(f"`{a}`→`{b}`" for a, b in ch))
    md += ["", "### Child attributes (`parent:`)", ""]
    for el in sorted(qt["attrs"]):
        ch = [(a, b) for a, b in qt["attrs"][el].items() if a != b]
        if ch:
            md.append(f"- **{el}**: " + ", ".join(f"`{a}`→`{b}`" for a, b in ch))
    md += ["", "### `bind:` names", ""]
    for el in sorted(qt["bindings"]):
        ch = [(a, b) for a, b in qt["bindings"][el].items() if a != b]
        if ch:
            md.append(f"- **{el}**: " + ", ".join(f"`bind:{a}`→`bind:{b}`" for a, b in ch))
    md += ["", "Synthetic Qt names kept (no native counterpart): canvas, virtual-list (was virtuallist), the action",
           "`group` prop, the event-filter events key-press, key-release, mouse-press, mouse-release, mouse-move,",
           "wheel, focus-in, focus-out, enter, leave, resize, context-menu; renamed: double-click -> mouse-double-click,",
           "close-request -> close (closeEvent).", ""]
    md += ["## AppKit, WinUI", "", "No changes: tags were already class names without prefix in kebab-case and members kebab(native).", ""]
    out_md.write_text("\n".join(md) + "\n")
    out_json.write_text(json.dumps(J, indent=1, sort_keys=True) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
