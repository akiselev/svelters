#!/usr/bin/env python3
"""Generates the `svelters:qt/<ns>` modules from the Qt type facts (metadata/qt/types/Qt*.json, N2).

The Qt counterpart of tools/metadata/gtk/gen_types.py. Output (deterministic, checked in):
  packages/types/qt/<ns>/<Class>.js     one file per class, one named export, no top-level side effects
  packages/types/qt/<ns>/index.js       re-exports
  packages/types/qt/<ns>.d.ts           `declare module 'svelters:qt/<ns>'` typings (one TS overload per C++ overload)
  packages/types/qt/manifest.json       per class: native name, hierarchy, imports, signature references (Q9)
  packages/types/package.json           the `./qt/*` and `./manifest-qt` exports (tools/metadata/common/types_pkg.py)
  docs/site/src/content/docs/types/qt/  a page per curated type and an index of every bound type

Runtime contract with the generated C++ (gen_types_cpp.py): kinds are C++ class names; overloads keep one JS
name and the C++ thunk picks one at run time (decision Q4), so methods pass their arguments through as given;
a static that shares its name with an instance method is called as `static:<name>`; constructors are the
static `new`, and QObject classes with a default constructor also take a props object (`construct`).

Generated code only calls `packages/types/src/core.js`. Import cycles that contain an `extends` edge are
broken as in the GTK generator: the wrap import that would close one falls back to the nearest ancestor.

  python3 tools/metadata/qt/gen_types_js.py --write
  python3 tools/metadata/qt/gen_types_js.py --check
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "tools/metadata/common"))
import types_qt_classify as TQ  # noqa: E402
from gen_cpp import enum_member_names  # noqa: E402
import types_pkg  # noqa: E402

PKG = ROOT / "packages/types"
OUT = PKG / "qt"
DOCS = ROOT / "docs/site/src/content/docs/types/qt"
HEADER = "// Generated by tools/metadata/qt/gen_types_js.py from metadata/qt/types/*.json. Do not edit.\n"

JS_RESERVED = {"break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum",
               "export", "extends", "false", "finally", "for", "function", "if", "import", "in", "instanceof", "new", "null",
               "return", "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with", "yield",
               "let", "static", "await", "async", "of", "arguments", "eval", "interface", "package", "private", "protected",
               "public", "implements"}
INSTANCE_RESERVED = {"constructor", "prototype", "dispose", "on", "equals", "equal", "svlHandle", "disposed", "nativeType",
                     "__svlBoxed", "__proto__"}
STATIC_RESERVED = {"name", "length", "prototype", "caller", "arguments", "call", "apply", "bind", "native", "bases",
                   "signalArgs", "from"}
WRAPPED = ("object", "value", "unique", "item")
STRING_FORM = {"QUrl", "QIcon", "QFont", "QKeySequence"}
SHAPES = {
    "Rect": "{ x: number; y: number; width: number; height: number }",
    "Size": "{ width: number; height: number }",
    "Point": "{ x: number; y: number }",
    "Insets": "{ top: number; right: number; bottom: number; left: number }",
    "Color": "{ red: number; green: number; blue: number; alpha: number }",
    "DateParts": "{ year: number; month: number; day: number }",
    "TimeParts": "{ hour: number; minute: number; second: number; ms: number }",
}


def inst_name(js: str) -> str:
    return js + "_" if js in INSTANCE_RESERVED else js


def static_name(js: str) -> str:
    return js + "_" if js in STATIC_RESERVED else js


def ident(name: str) -> str:
    return name + "_" if name in JS_RESERVED else name


def ns_of(rec: dict) -> str:
    return rec["js_module"].split("/")[-1]


def ins_of(o: dict) -> list[dict]:
    return [p for p in o["params"] if p["type"].get("out") is not True]


def outs_of(o: dict) -> list[dict]:
    return [p for p in o["params"] if p["type"].get("out")]


class Gen:
    def __init__(self, facts: dict) -> None:
        self.types: dict[str, dict] = facts["types"]
        self.enums: dict[str, dict] = facts["enums"]
        self.classes = dict(self.types)
        self.warnings: list[str] = []
        self.enum_js = {full: sorted(enum_member_names(e["members"])) for full, e in self.enums.items()}
        self.fallback: dict[tuple[str, str], str] = {}
        self._plan_imports()

    # ---- hierarchy ----
    def parent(self, q: str) -> str | None:
        p = self.types[q].get("parent")
        return p if p in self.classes and self.types[q]["category"] != "statics" else None

    def ancestors(self, q: str) -> list[str]:
        out, p = [], self.parent(q)
        while p and p not in out:
            out.append(p)
            p = self.parent(p)
        return out

    def root_base(self, q: str) -> str:
        return "NativeValue" if self.types[q]["category"] == "value" else "NativeObject"

    # ---- wraps ----
    def wrap_target(self, t: dict) -> str | None:
        if t["k"] in WRAPPED and t.get("t") in self.classes and self.types[t["t"]]["category"] != "statics":
            return t["t"]
        if t["k"] == "list":
            return self.wrap_target(t["of"])
        return None

    def wraps_of(self, q: str) -> set[str]:
        rec = self.types[q]
        out: set[str] = set()
        for sec in ("methods", "statics"):
            for ovs in rec[sec].values():
                for o in ovs:
                    for t in [o["ret"]] + [p["type"] for p in outs_of(o)]:
                        w = self.wrap_target(t)
                        if w:
                            out.add(w)
        for p in rec["properties"]:
            w = self.wrap_target(p["type"])
            if w:
                out.add(w)
        for s in rec["signals"]:
            for a in s["args"]:
                w = self.wrap_target(a["type"])
                if w:
                    out.add(w)
        out.discard(q)
        return out

    def _reaches_with_extends(self, edges: dict, start: str, goal: str) -> bool:
        seen, stack = set(), [(start, False)]
        while stack:
            n, used = stack.pop()
            if (n, used) in seen:
                continue
            seen.add((n, used))
            if n == goal and used:
                return True
            p = self.parent(n)
            if p:
                stack.append((p, True))
            for w in edges.get(n, ()):
                stack.append((w, used))
        return False

    def _plan_imports(self) -> None:
        edges: dict[str, set[str]] = {q: set() for q in self.classes}
        for q in sorted(self.classes):
            for w in sorted(self.wraps_of(q)):
                target = None
                for cand in [w] + self.ancestors(w):
                    if cand == q or cand in self.ancestors(q) or not self._reaches_with_extends(edges, cand, q):
                        target = cand
                        break
                if target is None:
                    self.fallback[(q, w)] = self.root_base(w)
                elif target != w:
                    self.fallback[(q, w)] = target
                if target and target != q:
                    edges[q].add(target)

    def wrap_class(self, q: str, w: str) -> str:
        return self.fallback.get((q, w), w)

    def imports_of(self, q: str) -> list[str]:
        out: list[str] = []
        p = self.parent(q)
        if p:
            out.append(p)
        for w in sorted(self.wraps_of(q)):
            t = self.wrap_class(q, w)
            if t in self.classes and t != q and t not in out:
                out.append(t)
        return out

    def w_expr(self, q: str, t: dict, e: str) -> str:
        w = self.wrap_target(t)
        if not w:
            return e
        if t["k"] == "list":
            return f"({e})?.map((e) => {self.w_expr(q, t['of'], 'e')}) ?? null"
        cls = self.wrap_class(q, w)
        fn = "wrapValue" if t["k"] == "value" else "wrapObject"
        return f"{fn}({cls}, {e})"

    # ---- JS ----
    def instance_names(self, q: str) -> set[str]:
        out: set[str] = set()
        for c in [q] + self.ancestors(q):
            out |= set(self.types[c]["methods"])
        return out

    def group_js(self, q: str, js: str, ovs: list[dict], static: bool) -> str:
        native = self.types[q]["name"]
        if static:
            wire = ("static:" + js) if js in self.instance_names(q) else js
            call = f"callStatic({native!r}, {wire!r}, args)"
            name = static_name(js)
        else:
            call = f"call(this, {js!r}, args)"
            name = inst_name(js)
        head = f"  {'static ' if static else ''}{name}(...args) {{"
        if len(ovs) == 1 and outs_of(ovs[0]):
            o = ovs[0]
            parts = []
            if o["ret"]["k"] != "void":
                parts.append(f"ret: {self.w_expr(q, o['ret'], '__res.ret')}")
            for p in outs_of(o):
                parts.append(f"{p['name']}: {self.w_expr(q, p['type'], '__res.' + p['name'])}")
            return f"{head}\n    const __res = {call};\n    return {{ {', '.join(parts)} }};\n  }}"
        if all(o["ret"]["k"] == "void" for o in ovs) and not any(outs_of(o) for o in ovs):
            return f"{head}\n    {call};\n  }}"
        exprs = {self.w_expr(q, o["ret"], call) for o in ovs if not outs_of(o)}
        expr = exprs.pop() if len(exprs) == 1 and not any(outs_of(o) for o in ovs) else call
        return f"{head}\n    return {expr};\n  }}"

    def ctor_props(self, q: str) -> dict:
        pm: dict[str, list[str]] = {}
        for c in reversed([q] + self.ancestors(q)):
            for p in self.types[c]["properties"]:
                if p["writable"]:
                    pm[p["name"]] = [p["name"]]
        return pm

    def ctor_setters(self, q: str) -> dict[str, tuple[str, dict]]:
        """Props-object keys backed by a one-argument setter but no Q_PROPERTY (QTextDocument `plainText`):
        key -> (setter, its parameter type)."""
        props = self.ctor_props(q)
        out: dict[str, tuple[str, dict]] = {}
        for c in reversed([q] + self.ancestors(q)):
            for js, ovs in self.types[c]["methods"].items():
                if not (js.startswith("set") and len(js) > 3 and js[3].isupper()):
                    continue
                key = js[3].lower() + js[4:]
                one = [o for o in ovs if len(ins_of(o)) >= 1 and sum(1 for p in ins_of(o) if not p.get("default")) <= 1 and not outs_of(o)]
                if key in props or not one:
                    continue
                out[key] = (js, ins_of(one[0])[0]["type"])
        return dict(sorted(out.items()))

    def class_js(self, q: str) -> str:
        rec = self.types[q]
        name, cat = rec["name"], rec["category"]
        parent = self.parent(q)
        imports = self.imports_of(q)
        body: list[str] = [f"  static native = {name!r};"]
        if cat != "statics":
            body.append(f"  static bases = {json.dumps([q] + self.ancestors(q))};")
        sigargs = {}
        for s in rec["signals"]:
            spec, has = [], False
            for a in s["args"]:
                w = self.wrap_target(a["type"]) if a["type"]["k"] != "list" else None
                if w:
                    spec.append(f"['{'v' if a['type']['k'] == 'value' else 'o'}', () => {self.wrap_class(q, w)}]")
                    has = True
                else:
                    spec.append("null")
            if has:
                sigargs[s["name"]] = "[" + ", ".join(spec) + "]"
        if sigargs:
            body.append("  static signalArgs = {\n" + ",\n".join(f"    {k!r}: {v}" for k, v in sorted(sigargs.items())) + ",\n  };")
        if cat != "statics":
            has_new = bool(rec["constructors"])
            lines = ["  static [CONSTRUCT](...args) {"]
            if cat in ("object", "model") and rec["constructible"]:
                pm = json.dumps(self.ctor_props(q), sort_keys=True).replace('"', "'")
                st = self.ctor_setters(q)
                if st:
                    sm = json.dumps({k: v[0] for k, v in st.items()}, sort_keys=True).replace('"', "'")
                    lines.append(f"    if (isProps(args)) return constructObject({name!r}, this, args[0], {pm}, {sm});")
                else:
                    lines.append(f"    if (isProps(args)) return construct({name!r}, constructProps(this, args[0], {pm}));")
            if has_new:
                lines.append(f"    return callStatic({name!r}, 'new', args);")
            else:
                lines.append(f"    throw new TypeError({(name + ' cannot be constructed from JS')!r});")
            lines.append("  }")
            body.append("\n".join(lines))
        if cat == "value" and not (parent and self.types[parent]["category"] == "value"):
            body.append("  equal(other) {\n    return call(this, 'equals', [other]);\n  }")
        for js, ovs in sorted(rec["statics"].items()):
            body.append(self.group_js(q, js, ovs, True))
        for js, ovs in sorted(rec["methods"].items()):
            body.append(self.group_js(q, js, ovs, False))
        for p in rec["properties"]:
            n = inst_name(p["name"])
            body.append(f"  get {n}() {{\n    return {self.w_expr(q, p['type'], f'getProp(this, {p['name']!r})')};\n  }}")
            if p["writable"]:
                body.append(f"  set {n}(v) {{\n    setProp(this, {p['name']!r}, v);\n  }}")
        text = "\n\n".join(body)
        if cat == "statics":
            code = f"export class {name} {{\n{text}\n}}\n"
        else:
            code = f"export class {name} extends {parent or self.root_base(q)} {{\n{text}\n}}\n"
        needed = set()
        if not parent and cat != "statics":
            needed.add(self.root_base(q))
        tail = code.split("\n", 1)[1]
        for fn in ("call", "callStatic", "getProp", "setProp", "construct", "constructProps", "constructObject", "isProps", "wrapObject",
                   "wrapValue", "CONSTRUCT", "NativeObject", "NativeValue"):
            if re.search(r"(?<![\w.'])" + re.escape(fn) + r"\b(?!')", tail):
                needed.add(fn)
        head = HEADER
        if needed:
            head += f"import {{ {', '.join(sorted(needed))} }} from '../../src/core.js';\n"
        for i in imports:
            r = self.types[i]
            path = f"./{r['name']}.js" if ns_of(r) == ns_of(rec) else f"../{ns_of(r)}/{r['name']}.js"
            head += f"import {{ {r['name']} }} from '{path}';\n"
        return head + "\n" + code

    # ---- d.ts ----
    def ts(self, t: dict, param: bool = False) -> str:
        k = t["k"]
        if k == "bool":
            return "boolean"
        if k in ("int", "float"):
            return "number"
        if k == "string":
            return "string"
        if k == "bytes":
            return "Uint8Array"
        if k == "variant":
            return "unknown"
        if k == "void":
            return "void"
        if k == "date":
            return "DateParts"
        if k == "time":
            return "TimeParts"
        if k == "datetime":
            return "Date"
        if k == "record":
            return "Color | string" if t["t"] == "Color" else t["t"]
        if k in ("enum", "flags"):
            names = self.enum_js.get(t["t"])
            u = " | ".join(f"'{n}'" for n in names) if names else "string"
            return u if k == "enum" else f"Array<{u}>"
        if k == "list":
            return f"Array<{self.ts(t['of'], param)}>"
        if k == "async":
            return f"Promise<{self.ts(t['of'])}>"
        if k in WRAPPED:
            c = t.get("t")
            if c not in self.classes or self.types[c]["category"] == "statics":
                return "unknown"
            if k == "value":
                return f"{c} | string" if param and c in STRING_FORM else c
            return f"{c} | null"
        return "unknown"

    @staticmethod
    def params_ts(names_types: list[tuple[str, str, bool]]) -> str:
        seen: set[str] = set()
        out = []
        for i, (n, t, opt) in enumerate(names_types):
            n = ident(re.sub(r"\W", "_", n) or f"arg{i}")
            while n in seen:
                n = f"{n}{i}"
            seen.add(n)
            out.append(f"{n}{'?' if opt else ''}: {t}")
        return ", ".join(out)

    def overload_ts(self, o: dict, multi: bool, same_wrap: bool) -> str:
        ins = ins_of(o)
        opt = []
        trailing = True
        for p in reversed(ins):
            trailing = trailing and bool(p.get("default"))
            opt.append(trailing)
        opt.reverse()
        ps = self.params_ts([(p["name"], self.ts(p["type"], True), d) for p, d in zip(ins, opt)])
        outs = outs_of(o)
        if outs:
            if multi:
                ret = "unknown"
            else:
                parts = ([f"ret: {self.ts(o['ret'])}"] if o["ret"]["k"] != "void" else []) + [f"{p['name']}: {self.ts(p['type'])}" for p in outs]
                ret = "{ " + "; ".join(parts) + " }"
        else:
            ret = self.ts(o["ret"]) if same_wrap else ("unknown" if o["ret"]["k"] != "void" else "void")
        return f"({ps}): {ret}"

    def group_ts(self, q: str, js: str, ovs: list[dict]) -> list[str]:
        multi = len(ovs) > 1
        wraps = {repr(self.wrap_target(o["ret"])) for o in ovs if not outs_of(o)}
        same = len(wraps) <= 1
        return [self.overload_ts(o, multi, same) for o in ovs]

    def member_sigs(self, q: str) -> tuple[dict, dict, dict]:
        """(instance methods, statics, props) of a class: JS name -> tuple of signatures / type."""
        rec = self.types[q]
        meth = {inst_name(js): tuple(self.group_ts(q, js, ovs)) for js, ovs in rec["methods"].items()}
        stat = {static_name(js): tuple(self.group_ts(q, js, ovs)) for js, ovs in rec["statics"].items()}
        props = {inst_name(p["name"]): (self.ts(p["type"]), p["writable"]) for p in rec["properties"]}
        return meth, stat, props

    def dts(self, ns: str) -> str:
        qs = sorted(q for q, r in self.classes.items() if ns_of(r) == ns)
        ext: dict[str, set[str]] = {}
        for q in qs:
            rec = self.types[q]
            for w in set(rec["refs"]) | set(self.imports_of(q)) | ({self.parent(q)} if self.parent(q) else set()):
                if w in self.classes and ns_of(self.types[w]) != ns:
                    ext.setdefault(ns_of(self.types[w]), set()).add(w)
        lines = [HEADER.rstrip(), f"declare module 'svelters:qt/{ns}' {{",
                 "  import type { NativeObject, NativeValue } from '@svelters/types/core';"]
        for ons in sorted(ext):
            lines.append(f"  import type {{ {', '.join(sorted(ext[ons]))} }} from 'svelters:qt/{ons}';")
        lines.append("")
        for shape, body in SHAPES.items():
            lines.append(f"  export type {shape} = {body};")
        for q in qs:
            rec = self.types[q]
            cat = rec["category"]
            parent = self.parent(q)
            meth, stat, props = self.member_sigs(q)
            a_meth: dict = {}
            a_stat: dict = {}
            a_props: dict = {}
            for a in reversed(self.ancestors(q)):
                m2, s2, p2 = self.member_sigs(a)
                a_meth.update(m2)
                a_stat.update(s2)
                a_props.update(p2)
            lines.append("")
            lines.append(f"  /** `{q}` ({rec['module']}), {cat}, lifetime {rec['lifetime']}" + (f", since Qt {rec['since']}" if rec.get("since") else "") + " */")
            if cat == "statics":
                lines.append(f"  export class {q} {{")
            else:
                kw = "abstract class" if rec["abstract"] else "class"
                lines.append(f"  export {kw} {q} extends {parent or self.root_base(q)} {{")
            lines.append("    static readonly native: string;")
            if cat in ("object", "model") and rec["constructible"]:
                cp = "; ".join([f"{p}?: {self.ts(self.prop_type(q, p), True)}" for p in self.ctor_props(q)]
                               + [f"{k}?: {self.ts(t, True)}" for k, (_, t) in self.ctor_setters(q).items()])
                lines.append(f"    constructor(props?: {{ {cp} }});")
            if cat != "statics" and not rec["abstract"]:
                for o in rec["constructors"]:
                    sig = self.overload_ts(o, True, True).rsplit("):", 1)[0] + ")"
                    if cat in ("object", "model") and rec["constructible"] and not ins_of(o):
                        continue
                    lines.append(f"    constructor{sig};")
            if cat == "value" and not (parent and self.types[parent]["category"] == "value"):
                lines.append(f"    equal(other: {q}): boolean;")
            for n, sigs in sorted(stat.items()):
                if n in a_stat and a_stat[n] != sigs:
                    lines.append(f"    /** overrides an inherited static with another signature */\n    static {n}(...args: any[]): any;")
                    continue
                for s in sigs:
                    lines.append(f"    static {n}{s};")
            for n, sigs in sorted(meth.items()):
                if n in a_props:
                    self.warnings.append(f"typings: {q}.{n} shadows an inherited property (untyped)")
                    continue
                if n in a_meth and a_meth[n] != sigs:
                    lines.append(f"    /** overrides an inherited method with another signature */\n    {n}(...args: any[]): any;")
                    continue
                for s in sigs:
                    lines.append(f"    {n}{s};")
            for n, (t, w) in sorted(props.items()):
                if n in a_meth:
                    self.warnings.append(f"typings: property {q}.{n} shadows an inherited method (untyped)")
                    continue
                if n in a_props and a_props[n] != (t, w):
                    t = "any"
                lines.append(f"    {'' if w else 'readonly '}{n}: {t};")
            sigs = self.signals_all(q)
            if sigs:
                lines.append("    on(signal: string, fn: (...args: any[]) => void): () => void;")
                for s in sigs:
                    args = self.params_ts([(a["name"], self.ts(a["type"]), False) for a in s["args"]])
                    lines.append(f"    on(signal: '{s['name']}', fn: ({args}) => void): () => void;")
            lines.append("  }")
        lines.append("}")
        return "\n".join(lines) + "\n"

    def prop_type(self, q: str, name: str) -> dict:
        for c in [q] + self.ancestors(q):
            for p in self.types[c]["properties"]:
                if p["name"] == name:
                    return p["type"]
        return {"k": "variant"}

    def signals_all(self, q: str) -> list[dict]:
        """Own signals plus inherited ones (TS overloads of `on` must repeat the base's)."""
        out, seen = [], set()
        for c in [q] + self.ancestors(q):
            for s in self.types[c]["signals"]:
                if s["name"] not in seen:
                    seen.add(s["name"])
                    out.append(s)
        return out

    # ---- manifest ----
    def manifest(self) -> dict:
        mods: dict[str, dict] = {}
        for q in sorted(self.classes):
            r = self.types[q]
            ns = ns_of(r)
            m = mods.setdefault(f"svelters:qt/{ns}", {"dir": ns, "exports": {}})
            m["exports"][q] = {
                "file": f"{ns}/{q}.js", "native": q, "category": r["category"], "extends": self.parent(q),
                "implements": [], "imports": self.imports_of(q),
                "signature": sorted(set(w for w in r["refs"] if w in self.classes) | set(r["enums"])),
            }
        return {"schema": "svelters-types-manifest/v1", "toolkit": "qt", "modules": mods}

    # ---- docs ----
    LIFETIME = {
        "object": "a **SHARED** handle when JS makes it (`new`): one JS object per native object (`===` works); `dispose()` or the wrapper's garbage collection deletes a parentless object, and a QObject parent that takes it over owns it from then on. Objects a getter returns are **borrowed**: JS never deletes them and the handle goes stale when Qt deletes the object.",
        "value": "an immutable **VALUE** handle: a copy of the Qt value, no identity (`equals()` compares natively), a new handle per crossing, released by `dispose()` or garbage collection. Non-const members are hidden (decision Q3).",
        "unique": "a JS-owned object (**OWNED**): it is deleted on `dispose()` or when the wrapper is collected. Qt never returns one JS did not make.",
        "item": "an **item**: owned by JS until a container takes it (`appendRow`, `setItem`, `push`; the PySide ownership facts say which), then borrowed; a `take*` result gives it back. Items JS cannot watch for deletion are never handed out.",
        "statics": "a namespace of static functions: it has no instances.",
    }

    def doc_page(self, q: str) -> str:
        r = self.types[q]
        cat = "object" if r["category"] == "model" else r["category"]
        ns = ns_of(r)
        lines = ["---", f"title: {q}", f'description: "{q} from svelters:qt/{ns}, a {r["category"]} class generated from qdoc, PySide6 and moc facts."',
                 "---", "", "```js", f"import {{ {q} }} from 'svelters:qt/{ns}';", "```", "", "## Class", "",
                 f"`{q}` ({r['module']}, `{r['header']}`), category **{r['category']}**.", "",
                 f"Lifetime: {self.LIFETIME[cat]}", ""]
        if self.parent(q):
            lines += [f"It extends `{self.parent(q)}`.", ""]
        lines += [f"Facts: `metadata/qt/types/{r['module']}.json`; ledger fact ids `svelters-api:v1:type:qt:{r['module']}:{q}:*` in `metadata/verified/qt.json`.", ""]
        lines += ["## Construct", ""]
        if r["category"] in ("object", "model") and r["constructible"]:
            lines += [f"`new {q}({{ ...props }})` creates it with construct-time properties: "
                      + ", ".join(f"`{p}`" for p in self.ctor_props(q)) + ".", ""]
        if r["constructors"] and not r["abstract"]:
            lines.append("Constructors (one JS constructor; the backend picks the overload from the arguments):")
            lines.append("")
            for o in r["constructors"]:
                lines.append(f"- `new {q}({', '.join(p['name'] for p in ins_of(o))})`")
            lines.append("")
        elif not (r["category"] in ("object", "model") and r["constructible"]):
            lines += ["Not constructible from JS.", ""]

        def section(title: str, groups: dict, static: bool):
            if not groups:
                return
            lines.extend([f"## {title}", ""])
            for js, ovs in sorted(groups.items()):
                for o in ovs:
                    args = ", ".join(p["name"] for p in ins_of(o))
                    outs = outs_of(o)
                    extra = f" → `{{{', '.join((['ret'] if o['ret']['k'] != 'void' else []) + [p['name'] for p in outs])}}}`" if outs else ""
                    lines.append(f"- `{(q + '.') if static else ''}{js}({args})`{extra}" + (f" (since Qt {o['since']})" if o.get("since") else ""))
            lines.append("")

        section("Statics", r["statics"], True)
        if r["properties"]:
            lines += ["## Properties", ""]
            for p in r["properties"]:
                lines.append(f"- `{p['name']}` ({p['type']['k']}{'' if p['writable'] else ', read-only'})")
            lines.append("")
        section("Methods", r["methods"], False)
        if r["signals"]:
            lines += ["## Signals", ""]
            for s in r["signals"]:
                lines.append(f"- `on('{s['name']}', ({', '.join(a['name'] for a in s['args'])}) => ...)`")
            lines.append("")
        if r["hidden"]:
            lines += ["## Hidden", "", "Reached otherwise (a property) or mutators of a value class: " + ", ".join(f"`{h}`" for h in r["hidden"]) + ".", ""]
        if r["blocked"]:
            lines += ["## Not bound", ""]
            for k, why in r["blocked"].items():
                lines.append(f"- `{k}`: {why}")
            lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    def doc_index(self) -> str:
        lines = ["---", "title: Non-UI types (Qt)", 'description: "QtCore, QtGui and QtWidgets non-widget classes as ES module named exports (svelters:qt/core, ...)."',
                 "---", "",
                 "Every bound non-widget Qt class is a named export of `svelters:qt/core`, `svelters:qt/gui` or `svelters:qt/widgets`. Widgets stay elements (tags).",
                 "", "```svelte", "<script>", "  import { QTextDocument } from 'svelters:qt/gui';",
                 "  const doc = new QTextDocument({ plainText: 'Hello' });", "</script>", "<text-edit document={doc} />", "```", "",
                 "- **Objects** (`QTimer`, `QStringListModel`): one JS object per QObject. What JS makes is SHARED: `dispose()` (or garbage collection) deletes a parentless object; a QObject parent takes ownership. Returned objects are borrowed.",
                 "- **Values** (`QUrl`, `QFont`, `QModelIndex`): immutable VALUE handles with `equals()`; non-const members are hidden. A `QModelIndex` is held as a persistent index.",
                 "- **Unique objects** (`QMimeDatabase`, `QTemporaryDir`): owned by JS, deleted on `dispose()`.",
                 "- **Items** (`QStandardItem`): owned by JS until a container takes them.",
                 "- **Overloads**: one JS name per C++ name; the backend picks the overload from the arguments' count and JS types.",
                 "- **Release builds** keep only what an app imports plus the types its signatures mention (`packages/types/qt/manifest.json`).",
                 "", "## Curated types", ""]
        for q in sorted(self.classes):
            if self.types[q]["curated"]:
                lines.append(f"- [{q}]({q.lower()}/)")
        lines += ["", "## All bound types", ""]
        for ns in ("core", "gui", "widgets"):
            qs = sorted(q for q in self.classes if ns_of(self.types[q]) == ns)
            if qs:
                lines.append(f"- `svelters:qt/{ns}`: " + ", ".join(f"`{q}` ({self.types[q]['category']})" for q in qs))
        return "\n".join(lines) + "\n"

    # ---- files ----
    def files(self) -> dict[Path, str]:
        out: dict[Path, str] = {}
        by_ns: dict[str, list[str]] = {}
        for q in sorted(self.classes):
            by_ns.setdefault(ns_of(self.types[q]), []).append(q)
            out[OUT / ns_of(self.types[q]) / f"{q}.js"] = self.class_js(q)
        for ns, qs in sorted(by_ns.items()):
            out[OUT / ns / "index.js"] = HEADER + "".join(f"export {{ {q} }} from './{q}.js';\n" for q in qs)
            out[OUT / f"{ns}.d.ts"] = self.dts(ns)
        out[OUT / "manifest.json"] = json.dumps(self.manifest(), indent=1, sort_keys=True) + "\n"
        own = {"./manifest-qt": "./qt/manifest.json"}
        for ns in sorted(by_ns):
            own[f"./qt/{ns}"] = {"types": f"./qt/{ns}.d.ts", "default": f"./qt/{ns}/index.js"}
        out[PKG / "package.json"] = types_pkg.package_json(PKG / "package.json", own, "./qt/", ["./manifest-qt"])
        for q in sorted(self.classes):
            if self.types[q]["curated"]:
                out[DOCS / f"{q.lower()}.md"] = self.doc_page(q)
        out[DOCS / "index.md"] = self.doc_index()
        return out


def write_all(files: dict[Path, str], check: bool) -> int:
    bad: list[str] = []
    wanted = set(files)
    for p, text in files.items():
        if check:
            if not p.exists() or p.read_text() != text:
                bad.append(str(p.relative_to(ROOT)))
        elif not p.exists() or p.read_text() != text:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
    for p in list(OUT.rglob("*.js")) + list(DOCS.glob("*.md")):
        if p not in wanted:
            if check:
                bad.append(str(p.relative_to(ROOT)) + " (stale)")
            else:
                p.unlink()
    if bad:
        print("gen_types_js: generated files are stale: " + ", ".join(bad[:10]) + (" ..." if len(bad) > 10 else "")
              + "\n  run `python3 tools/metadata/qt/gen_types_js.py --write`", file=sys.stderr)
        return 1
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    g = Gen(TQ.load_facts())
    files = g.files()
    rc = write_all(files, not a.write)
    for w in sorted(set(g.warnings)):
        print("gen_types_js: warning:", w, file=sys.stderr)
    if rc == 0:
        print(f"gen_types_js: {len(g.classes)} classes, {len(files)} files {'written' if a.write else 'are current'}")
    return rc


if __name__ == "__main__":
    sys.exit(main())
