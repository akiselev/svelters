"""The JS side of the WinUI non-GUI type layer (N4), from the type facts: `svelters:winui/<namespace>` ES modules
(one file per class, `index.js` re-exports, no top-level side effects: decision Q9), typings, the manifest the M6
linker reads, and the docs pages. Used by gen_types_winui.py.

Runtime contract with the backend (crates/svelters-winui/src/types/): kinds are full native names
(`Windows.Foundation.Uri`); methods and props are camelCase JS names, events kebab-case; a static that shares its
name with an instance method is `static:<name>`; constructors are the static `new` (overloads by argument count) and
default-constructible classes also take a props object (`construct`). Generated code only calls
packages/types/src/core.js and packages/types/winui/_rt.js.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import types_winui_classify as C

ROOT = Path(__file__).resolve().parents[3]
PKG = ROOT / "packages/types"
OUT = PKG / "winui"
DOCS = ROOT / "docs/site/src/content/docs/types/winui"
HEADER = "// Generated by tools/metadata/winui/gen_types_winui.py from metadata/winui/types/*.json. Do not edit.\n"
ROOT_CLASS = "Windows.Foundation.IInspectable"

JS_RESERVED = {"break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum",
               "export", "extends", "false", "finally", "for", "function", "if", "import", "in", "instanceof", "new", "null",
               "return", "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with", "yield",
               "let", "static", "await", "async", "of", "arguments", "eval", "interface", "package", "private", "protected",
               "public", "implements"}
INSTANCE_RESERVED = {"constructor", "prototype", "dispose", "on", "svlHandle", "disposed", "nativeType", "peek", "__proto__"}
STATIC_RESERVED = {"name", "length", "prototype", "caller", "arguments", "call", "apply", "bind", "native", "bases",
                   "signalArgs", "from"}


def inst_name(js: str) -> str:
    return js + "_" if js in INSTANCE_RESERVED else js


def static_name(js: str) -> str:
    return js + "_" if js in STATIC_RESERVED else js


def ident(name: str) -> str:
    name = re.sub(r"\W", "_", name) or "arg"
    return name + "_" if name in JS_RESERVED else name


def ns_dir(ns: str) -> str:
    return ns.lower()


def generic_head(full: str) -> str:
    return C.parse(full)[0]


class Gen:
    def __init__(self, facts: dict, ing: C.Ingest) -> None:
        self.ing = ing
        self.kinds: dict[str, dict] = facts["kinds"]
        self.enums: dict[str, dict] = facts["enums"]
        self.structs: dict[str, dict] = facts["structs"]
        self.warnings: list[str] = []
        # JS classes: every bound non-generic kind, one class per generic definition, and the IInspectable root.
        self.classes: dict[str, dict] = {}
        for n, r in self.kinds.items():
            if C.parse(n)[1]:
                self.classes.setdefault(generic_head(n), {**r, "full": generic_head(n), "name": generic_head(n).rsplit(".", 1)[1],
                                                         "generic_of": n, "parent": None, "implements": []})
            else:
                self.classes[n] = r
        self.classes[ROOT_CLASS] = {"full": ROOT_CLASS, "name": "IInspectable", "namespace": "Windows.Foundation", "category": "interface",
                                    "props": [], "methods": {}, "statics": {}, "events": [], "constructors": [], "parent": None,
                                    "implements": [], "thread": "any", "curated": False, "abstract": True, "blocked": {}, "hidden": [],
                                    "refs": [], "kind": "interface", "excluded": {}}
        self.fallback: dict[tuple[str, str], str] = {}
        self.alias: dict[str, str] = {}
        self.local_ts: set[str] = set()
        self._plan_imports()

    # ---- hierarchy and imports (cycles through an `extends` edge are broken as in the GTK/Qt generators)
    def parent(self, q: str) -> str | None:
        p = self.classes[q].get("parent")
        return p if p in self.classes else None

    def ancestors(self, q: str) -> list[str]:
        out, p = [], self.parent(q)
        while p and p not in out:
            out.append(p)
            p = self.parent(p)
        return out

    def class_of(self, t: dict) -> str | None:
        """The JS class an object slot wraps as."""
        if t.get("k") != "object":
            return None
        full = t["t"]
        head = generic_head(full)
        if head in self.classes:
            return head
        return ROOT_CLASS

    def wraps_in(self, t: dict) -> set[str]:
        out = set()
        c = self.class_of(t)
        if c:
            out.add(c)
        if t.get("k") == "variant":
            out.add(ROOT_CLASS)
        for key in ("of", "key"):
            if isinstance(t.get(key), dict):
                out |= self.wraps_in(t[key])
        return out

    def wraps_of(self, q: str) -> set[str]:
        rec = self.classes[q]
        out: set[str] = set()
        for sec in ("methods", "statics"):
            for ovs in rec[sec].values():
                for o in ovs:
                    out |= self.wraps_in(o["ret"])
                    for p in o["outs"]:
                        out |= self.wraps_in(p["slot"])
        for p in rec["props"]:
            out |= self.wraps_in(p["slot"])
        for e in rec["events"]:
            for a in e["args"]:
                out |= self.wraps_in(a["slot"])
        out.discard(q)
        return out

    def _reaches_with_extends(self, edges: dict, start: str, goal: str) -> bool:
        seen, stack = set(), [(start, False)]
        while stack:
            n, used = stack.pop()
            if (n, used) in seen:
                continue
            seen.add((n, used))
            if n == goal and used:
                return True
            p = self.parent(n)
            if p:
                stack.append((p, True))
            for w in edges.get(n, ()):
                stack.append((w, used))
        return False

    def _plan_imports(self) -> None:
        edges: dict[str, set[str]] = {q: set() for q in self.classes}
        for q in sorted(self.classes):
            for w in sorted(self.wraps_of(q)):
                target = None
                for cand in [w] + self.ancestors(w):
                    if cand == q or cand in self.ancestors(q) or not self._reaches_with_extends(edges, cand, q):
                        target = cand
                        break
                if target is None:
                    self.fallback[(q, w)] = ROOT_CLASS
                elif target != w:
                    self.fallback[(q, w)] = target
                if target and target != q:
                    edges[q].add(target)

    def wrap_class(self, q: str, w: str) -> str:
        return self.fallback.get((q, w), w)

    def imports_of(self, q: str) -> list[str]:
        out: list[str] = []
        p = self.parent(q)
        if p:
            out.append(p)
        for w in sorted(self.wraps_of(q)):
            t = self.wrap_class(q, w)
            if t in self.classes and t != q and t not in out:
                out.append(t)
        return out

    def jsname(self, q: str) -> str:
        return self.alias.get(q, self.classes[q]["name"])

    def plan_alias(self, q: str) -> None:
        """Local names of the classes `q`'s module imports (an import that clashes with another name is aliased)."""
        self.alias = {q: self.classes[q]["name"]}
        used = {self.classes[q]["name"]}
        for i in self.imports_of(q):
            n = self.classes[i]["name"]
            if n in used:
                n = f"{n}_{ns_dir(self.classes[i]['namespace']).replace('.', '_')}"
            used.add(n)
            self.alias[i] = n

    # ---- JS expressions
    def w_expr(self, q: str, t: dict, e: str) -> str:
        k = t.get("k")
        if k == "object":
            c = self.wrap_class(q, self.class_of(t))
            return f"wrapObject({self.jsname(c)}, {e})"
        if k == "variant":
            return f"wrapAny({self.jsname(self.wrap_class(q, ROOT_CLASS))}, {e})"
        if k == "list":
            inner = self.w_expr(q, t["of"], "x")
            return e if inner == "x" else f"({e})?.map((x) => {inner}) ?? null"
        if k == "map":
            inner = self.w_expr(q, t["of"], "x")
            return e if inner == "x" else f"mapValues({e}, (x) => {inner})"
        if k == "pair":
            ki = self.w_expr(q, t["key"], "x.key")
            vi = self.w_expr(q, t["of"], "x.value")
            return e if (ki, vi) == ("x.key", "x.value") else f"((x) => x && {{ key: {ki}, value: {vi} }})({e})"
        return e

    def shape_of(self, q: str, o: dict) -> str | None:
        """The result-shaping function of an overload (None: the raw result)."""
        ret = o["ret"]["of"] if o["ret"]["k"] == "async" else o["ret"]
        if o["outs"]:
            parts = []
            if ret["k"] != "void":
                parts.append(f"ret: {self.w_expr(q, ret, 'r[0]')}")
            for i, p in enumerate(o["outs"]):
                parts.append(f"{ident(p['name'])}: {self.w_expr(q, p['slot'], f'r[{i + 1}]')}")
            return f"(r) => ({{ {', '.join(parts)} }})"
        e = self.w_expr(q, ret, "r")
        return None if e == "r" else f"(r) => {e}"

    def instance_names(self, q: str) -> set[str]:
        out: set[str] = set()
        for c in [q] + self.ancestors(q):
            out |= set(self.classes[c]["methods"])
        return out

    def group_js(self, q: str, js: str, ovs: list[dict], static: bool) -> str:
        native = self.classes[q]["full"]
        wire = ("static:" + js) if static and js in self.instance_names(q) else js
        name = static_name(js) if static else inst_name(js)
        kw = "static " if static else ""
        is_async = all(o["ret"]["k"] == "async" for o in ovs)
        shapes = {self.shape_of(q, o) for o in ovs}
        shape = shapes.pop() if len(shapes) == 1 else None
        if len(shapes) > 0:
            self.warnings.append(f"{native}.{js}: overloads differ in result shape (raw results)")
        if is_async:
            arities = sorted({len(o["params"]) for o in ovs})
            recv = repr(native) if static else "this"
            fn = "staticAsync" if static else "instanceAsync"
            return f"  {kw}{name}(...args) {{\n    return {fn}({recv}, {wire!r}, args, {arities}{', ' + shape if shape else ''});\n  }}"
        call = f"callStatic({native!r}, {wire!r}, args)" if static else f"call(this, {wire!r}, args)"
        if all(o["ret"]["k"] == "void" for o in ovs) and not any(o["outs"] for o in ovs):
            return f"  {kw}{name}(...args) {{\n    {call};\n  }}"
        if shape:
            return f"  {kw}{name}(...args) {{\n    return ({shape})({call});\n  }}"
        return f"  {kw}{name}(...args) {{\n    return {call};\n  }}"

    def ctor_props(self, q: str) -> dict:
        pm: dict[str, list[str]] = {}
        for c in reversed([q] + self.ancestors(q)):
            for p in self.classes[c]["props"]:
                if p["set"]:
                    pm[p["name"]] = [p["name"]]
        return pm

    def class_js(self, q: str) -> str:
        self.plan_alias(q)
        rec = self.classes[q]
        name, cat = rec["name"], rec["category"]
        native = rec["full"]
        parent = self.parent(q)
        body: list[str] = [f"  static native = {native!r};"]
        statics_only = cat == "statics"
        if not statics_only:
            body.append(f"  static bases = {json.dumps([self.classes[c]['full'] for c in [q] + self.ancestors(q)])};")
        sigargs = {}
        for e in rec["events"]:
            spec, has = [], False
            for a in e["args"]:
                c = self.class_of(a["slot"])
                if c:
                    spec.append(f"['o', () => {self.jsname(self.wrap_class(q, c))}]")
                    has = True
                else:
                    spec.append("null")
            if has:
                sigargs[e["name"]] = "[" + ", ".join(spec) + "]"
        if sigargs:
            body.append("  static signalArgs = {\n" + ",\n".join(f"    {k!r}: {v}" for k, v in sorted(sigargs.items())) + ",\n  };")
        if not statics_only:
            ctors = rec["constructors"] if "generic_of" not in rec else []
            lines = ["  static [CONSTRUCT](...args) {"]
            if any(not c["params"] for c in ctors):
                pm = json.dumps(self.ctor_props(q), sort_keys=True).replace('"', "'")
                lines.append(f"    if (isPropsFor(args, {pm})) return construct({native!r}, constructProps(this, args[0], {pm}));")
            if ctors:
                lines.append(f"    return callStatic({native!r}, 'new', args);")
            else:
                lines.append(f"    throw new TypeError({(native + ' cannot be constructed from JS')!r});")
            lines.append("  }")
            body.append("\n".join(lines))
        for js, ovs in sorted(rec["statics"].items()):
            if all(o.get("prop") == "get" for o in ovs) and len(ovs) == 1 and not ovs[0]["params"]:
                o = ovs[0]
                e = self.w_expr(q, o["ret"], f"callStatic({native!r}, {js!r}, [])")
                body.append(f"  static get {static_name(js)}() {{\n    return {e};\n  }}")
            else:
                body.append(self.group_js(q, js, ovs, True))
        for js, ovs in sorted(rec["methods"].items()):
            body.append(self.group_js(q, js, ovs, False))
        for p in rec["props"]:
            n = inst_name(p["name"])
            if p["get"]:
                read = "observed" if p.get("dp") else "getProp"
                body.append(f"  get {n}() {{\n    return {self.w_expr(q, p['slot'], f'{read}(this, {p['name']!r})')};\n  }}")
            if p["set"]:
                body.append(f"  set {n}(v) {{\n    setProp(this, {p['name']!r}, v);\n  }}")
        text = "\n\n".join(body)
        if statics_only:
            code = f"export class {name} {{\n{text}\n}}\n"
        else:
            base = self.jsname(parent) if parent else "NativeObject"
            code = f"export class {name} extends {base} {{\n{text}\n}}\n"
        needed = set()
        if not parent and not statics_only:
            needed.add("NativeObject")
        tail = code.split("\n", 1)[1]
        core = ("call", "callStatic", "getProp", "observed", "setProp", "construct", "constructProps", "wrapObject", "CONSTRUCT", "NativeObject")
        rt = ("instanceAsync", "staticAsync", "isPropsFor", "wrapAny", "mapValues")
        for fn in core + rt:
            if re.search(r"(?<![\w.'])" + re.escape(fn) + r"\b(?!')", tail):
                needed.add(fn)
        head = HEADER
        c_need = sorted(n for n in needed if n in core)
        r_need = sorted(n for n in needed if n in rt)
        if c_need:
            head += f"import {{ {', '.join(c_need)} }} from '../../src/core.js';\n"
        if r_need:
            head += f"import {{ {', '.join(r_need)} }} from '../_rt.js';\n"
        my_ns = self.classes[q]["namespace"]
        for i in self.imports_of(q):
            r = self.classes[i]
            path = f"./{r['name']}.js" if r["namespace"] == my_ns else f"../{ns_dir(r['namespace'])}/{r['name']}.js"
            local = self.jsname(i)
            head += f"import {{ {r['name']}{'' if local == r['name'] else ' as ' + local} }} from '{path}';\n"
        return head + "\n" + code

    # ---- typings
    def enum_ts(self, full: str) -> str:
        e = self.enums.get(full)
        if not e:
            return "string | number"
        names = sorted({C.kebab(n) for n in e["native"]})
        u = " | ".join(f"'{n}'" for n in names) or "string"
        return u

    def type_ref(self, ns: str, full: str, ext: dict) -> str:
        """A name exported by another namespace's module (imported as a type; aliased when it clashes)."""
        tns, tname = full.rsplit(".", 1)
        if tns == ns:
            return tname
        names = ext.setdefault(tns, {})
        if tname not in names:
            taken = self.local_ts | {a for m in ext.values() for a in m.values()}
            names[tname] = tname if tname not in taken else f"{tname}_{ns_dir(tns).replace('.', '_')}"
        return names[tname]

    def ts(self, ns: str, t: dict, ext: dict, param: bool = False) -> str:
        k = t["k"]
        if k == "bool":
            return "boolean"
        if k in ("int", "float", "timespan"):
            return "number"
        if k in ("string", "char", "guid"):
            return "string"
        if k == "void":
            return "void"
        if k == "datetime":
            return "Date"
        if k == "variant":
            return "unknown"
        if k == "record":
            return self.type_ref(ns, t["t"], ext)
        if k == "enum":
            return self.type_ref(ns, t["t"], ext) + (" | number" if param else "")
        if k == "flags":
            return f"Array<{self.type_ref(ns, t['t'], ext)}>" + (" | number" if param else "")
        if k == "nullable":
            return f"{self.ts(ns, t['of'], ext, param)} | null"
        if k == "list":
            return f"Array<{self.ts(ns, t['of'], ext)}>"
        if k == "map":
            return f"Record<string, {self.ts(ns, t['of'], ext)}>"
        if k == "pair":
            return f"{{ key: {self.ts(ns, t['key'], ext)}; value: {self.ts(ns, t['of'], ext)} }}"
        if k == "async":
            return f"Promise<{self.ts(ns, t['of'], ext)}>"
        if k == "widget":
            return "NativeElement | null"
        if k == "object":
            c = self.class_of(t)
            name = self.type_ref(ns, self.classes[c]["full"], ext)
            if C.parse(t["t"])[1]:
                args = ", ".join(self.generic_arg_ts(ns, a, ext) for a in C.parse(t["t"])[1])
                name = f"{name}<{args}>"
            return f"{name} | null"
        return "unknown"

    def generic_arg_ts(self, ns: str, a: str, ext: dict) -> str:
        try:
            ty = C.Types(self.ing, {}, {"scope": sorted({k.rsplit('.', 1)[0] for k in self.kinds}), "roots": list(self.kinds)})
            s = ty.slot(a, ret=True)
        except C.Block:
            return "unknown"
        return self.ts(ns, s, ext).replace(" | null", "")

    def params_ts(self, ns: str, ps: list[dict], ext: dict, min_arity: int) -> str:
        seen: set[str] = set()
        out = []
        for i, p in enumerate(ps):
            n = ident(p["name"])
            while n in seen:
                n = f"{n}{i}"
            seen.add(n)
            out.append(f"{n}{'?' if i >= min_arity else ''}: {self.ts(ns, p['slot'], ext, True)}")
        return ", ".join(out)

    def overload_ts(self, ns: str, o: dict, ext: dict) -> str:
        ps = self.params_ts(ns, o["params"], ext, len(o["params"]))
        is_async = o["ret"]["k"] == "async"
        ret = o["ret"]["of"] if is_async else o["ret"]
        if o["outs"]:
            parts = ([f"ret: {self.ts(ns, ret, ext)}"] if ret["k"] != "void" else []) + [f"{ident(p['name'])}: {self.ts(ns, p['slot'], ext)}" for p in o["outs"]]
            r = "{ " + "; ".join(parts) + " }"
        else:
            r = self.ts(ns, ret, ext)
        if is_async:
            ps = (ps + ", " if ps else "") + "asyncOptions?: AsyncOptions"
            r = f"Promise<{r}>"
        return f"({ps}): {r}"

    def generic_dts(self, ns: str, q: str, ext: dict) -> list[str]:
        """A generic interface class (`IVector<T>`): members of the definition, generic parameters kept."""
        head = q
        d = self.ing.get(head)
        gens = d.get("generics") or []
        rec = self.classes[q]
        lines = [f"  /** `{head}<{', '.join(gens)}>`: a native collection or event-args interface (SHARED handle). */",
                 f"  export class {rec['name']}<{', '.join(g + ' = unknown' for g in gens)}> extends NativeObject {{",
                 "    static readonly native: string;"]
        inst = rec["generic_of"]
        inst_args = C.parse(inst)[1]
        sub = dict(zip(inst_args, gens))

        def g(t: dict, spelled: str) -> str:
            s = spelled[4:] if spelled.startswith("out ") else spelled
            if s in sub:
                return sub[s]
            if any(a in s for a in inst_args):
                return "any"
            return self.ts(ns, t, ext)
        for js, ovs in sorted(rec["methods"].items()):
            for o in ovs:
                ps = ", ".join(f"{ident(p['name'])}: {g(p['slot'], p['type'])}" for p in o["params"])
                if o["outs"]:
                    parts = ([f"ret: {g(o['ret'], o['ret_native'])}"] if o["ret"]["k"] != "void" else []) + [f"{ident(p['name'])}: {g(p['slot'], p['type'])}" for p in o["outs"]]
                    r = "{ " + "; ".join(parts) + " }"
                else:
                    r = g(o["ret"], o["ret_native"])
                lines.append(f"    {inst_name(js)}({ps}): {r};")
        for p in rec["props"]:
            lines.append(f"    {'' if p['set'] else 'readonly '}{inst_name(p['name'])}: {g(p['slot'], p['type'])};")
        for e in rec["events"]:
            lines.append(f"    on(signal: '{e['name']}', fn: (...args: any[]) => void): () => void;")
        lines.append("  }")
        return lines

    def dts(self, ns: str) -> str:
        qs = sorted(q for q, r in self.classes.items() if r["namespace"] == ns)
        ext: dict[str, dict[str, str]] = {}
        self.local_ts = ({self.classes[q]["name"] for q in qs} | {e.rsplit(".", 1)[1] for e in self.enums if e.rsplit(".", 1)[0] == ns}
                         | {x.rsplit(".", 1)[1] for x in self.structs if x.rsplit(".", 1)[0] == ns})
        body: list[str] = []
        for full in sorted(e for e in self.enums if e.rsplit(".", 1)[0] == ns):
            body.append(f"  /** `{full}` ({'flags: a list of names' if self.enums[full]['flags'] else 'enum'}). */")
            body.append(f"  export type {full.rsplit('.', 1)[1]} = {self.enum_ts(full)};")
        for full in sorted(s for s in self.structs if s.rsplit(".", 1)[0] == ns):
            fields = []
            for f in self.structs[full]["fields"]:
                ty = C.Types(self.ing, {}, {"scope": [], "roots": []})
                try:
                    s = ty.slot(f["type"])
                    fields.append(f"{f['name']}: {self.ts(ns, s, ext, True)}")
                except C.Block:
                    fields.append(f"{f['name']}: unknown")
            body.append(f"  /** `{full}` (a record: a plain object by value). */")
            body.append(f"  export interface {full.rsplit('.', 1)[1]} {{ {'; '.join(fields)} }}")
        for q in qs:
            rec = self.classes[q]
            if "generic_of" in rec:
                body.extend(self.generic_dts(ns, q, ext))
                continue
            cat = rec["category"]
            parent = self.parent(q)
            body.append("")
            body.append(f"  /** `{rec['full']}`: {cat}, lifetime SHARED, thread {rec['thread']}. */")
            if cat == "statics":
                body.append(f"  export class {rec['name']} {{")
            else:
                base = self.type_ref(ns, self.classes[parent]["full"], ext) if parent else "NativeObject"
                kw = "abstract class" if not rec["constructors"] else "class"
                body.append(f"  export {kw} {rec['name']} extends {base} {{")
            body.append("    static readonly native: string;")
            if cat != "statics":
                arities = sorted({len(c["params"]) for c in rec["constructors"]})
                if 0 in arities:
                    pm = self.ctor_props(q)
                    cp = []
                    for pn in pm:
                        pt = self.prop_type(q, pn)
                        cp.append(f"{pn}?: {self.ts(ns, pt, ext, True)}")
                    body.append(f"    constructor(props?: {{ {'; '.join(cp)} }});")
                for c in rec["constructors"]:
                    if c["params"]:
                        body.append(f"    constructor({self.params_ts(ns, c['params'], ext, len(c['params']))});")
            for js, ovs in sorted(rec["statics"].items()):
                if all(o.get("prop") == "get" for o in ovs) and len(ovs) == 1 and not ovs[0]["params"]:
                    body.append(f"    static readonly {static_name(js)}: {self.ts(ns, ovs[0]['ret'], ext)};")
                    continue
                for o in ovs:
                    body.append(f"    static {static_name(js)}{self.overload_ts(ns, o, ext)};")
            for js, ovs in sorted(rec["methods"].items()):
                for o in ovs:
                    body.append(f"    {inst_name(js)}{self.overload_ts(ns, o, ext)};")
            for p in rec["props"]:
                remark = "" if p.get("dp") else ""
                t = self.ts(ns, p["slot"], ext)
                if p.get("dp"):
                    body.append("    /** Reactive: a DependencyProperty (WinUI announces its changes). */")
                body.append(f"    {'' if p['set'] else 'readonly '}{inst_name(p['name'])}: {t};{remark}")
            if rec["events"]:
                body.append("    on(signal: string, fn: (...args: any[]) => void): () => void;")
                for e in rec["events"]:
                    args = ", ".join(f"{ident(a['name'])}: {self.ts(ns, a['slot'], ext)}" for a in e["args"])
                    body.append(f"    on(signal: '{e['name']}', fn: ({args}) => void): () => void;")
            body.append("  }")
        lines = [HEADER.rstrip(), f"declare module '{C.js_module(ns)}' {{",
                 "  import type { NativeObject, NativeElement, AsyncOptions } from '@svelters/types/core';"]
        for ons in sorted(ext):
            if ons != ns and ext[ons]:
                names = ", ".join(n if a == n else f"{n} as {a}" for n, a in sorted(ext[ons].items()))
                lines.append(f"  import type {{ {names} }} from '{C.js_module(ons)}';")
        lines.append("")
        lines.extend(body)
        lines.append("}")
        return "\n".join(lines) + "\n"

    def prop_type(self, q: str, name: str) -> dict:
        for c in [q] + self.ancestors(q):
            for p in self.classes[c]["props"]:
                if p["name"] == name:
                    return p["slot"]
        return {"k": "variant"}

    # ---- manifest (Q9)
    def manifest(self) -> dict:
        mods: dict[str, dict] = {}
        for q in sorted(self.classes):
            r = self.classes[q]
            ns = r["namespace"]
            m = mods.setdefault(C.js_module(ns), {"dir": ns_dir(ns), "exports": {}})
            sig = set()
            for w in self.wraps_of(q):
                sig.add(self.classes[w]["full"])
            for x in r.get("refs", []):
                if x in self.classes:
                    sig.add(self.classes[x]["full"])
                elif C.parse(x)[0] in self.classes:
                    sig.add(C.parse(x)[0])
            m["exports"][r["name"]] = {
                "file": f"{ns_dir(ns)}/{r['name']}.js", "native": r["full"], "category": r["category"],
                "extends": self.classes[self.parent(q)]["full"] if self.parent(q) else None,
                "implements": [], "imports": [self.classes[i]["full"] for i in self.imports_of(q)],
                "signature": sorted(sig - {r["full"]}),
            }
        return {"schema": "svelters-types-manifest/v1", "toolkit": "winui", "modules": mods}

    # ---- docs
    def doc_page(self, q: str) -> str:
        r = self.classes[q]
        ns = r["namespace"]
        mod = C.js_module(ns)
        lines = ["---", f"title: {r['name']}", f'description: "{r["full"]} from {mod}, a {r["category"]} class generated from winmd facts."',
                 "---", "", "```js", f"import {{ {r['name']} }} from '{mod}';", "```", "", "## Class", "",
                 f"`{r['full']}`, category **{r['category']}**, thread class **{r['thread']}**.", "",
                 "Lifetime: a **SHARED** handle: one JS object per native object (`===` works), holding one COM reference; "
                 "`dispose()` or the wrapper's garbage collection releases it (never `Close()`: that is an explicit method).", ""]
        if r["thread"] != "any":
            lines += ["Thread: XAML and Composition objects live on the one UI thread; a handle for an object of another "
                      "thread's dispatcher is refused (NON-GUI-TYPES section 4.1).", ""]
        if self.parent(q):
            lines += [f"It extends `{self.classes[self.parent(q)]['full']}`.", ""]
        lines += [f"Facts: `metadata/winui/types/{ns}.json`; ledger fact ids `svelters-api:v1:type:winui:{ns}:{r['name']}:*` "
                  "in `metadata/verified/winui.json`.", "", "## Construct", ""]
        ctors = r["constructors"]
        if any(not c["params"] for c in ctors):
            lines += [f"`new {r['name']}({{ ...props }})` activates it and sets the props: " + ", ".join(f"`{p}`" for p in self.ctor_props(q)) + ".", ""]
        for c in ctors:
            if c["params"]:
                lines.append(f"- `new {r['name']}({', '.join(p['name'] for p in c['params'])})`")
        if any(c["params"] for c in ctors):
            lines += ["", "One JS constructor: the backend picks the factory method by argument count.", ""]
        if not ctors:
            lines += ["Not constructible from JS.", ""]

        def section(title: str, groups: dict, static: bool):
            if not groups:
                return
            lines.extend([f"## {title}", ""])
            for js, ovs in sorted(groups.items()):
                for o in ovs:
                    args = ", ".join(p["name"] for p in o["params"])
                    a = " (async: a Promise; `{ signal }` cancels)" if o["ret"]["k"] == "async" else ""
                    outs = f" → `{{{', '.join((['ret'] if o['ret']['k'] != 'void' else []) + [p['name'] for p in o['outs']])}}}`" if o["outs"] else ""
                    lines.append(f"- `{(r['name'] + '.') if static else ''}{js}({args})`{outs}{a}")
            lines.append("")

        section("Statics", r["statics"], True)
        if r["props"]:
            lines += ["## Properties", ""]
            for p in r["props"]:
                bits = ([] if p["set"] else ["read-only"]) + (["reactive (DependencyProperty)"] if p.get("dp") else [])
                lines.append(f"- `{p['name']}` ({p['slot']['k']}{''.join(', ' + b for b in bits)})")
            lines.append("")
        section("Methods", r["methods"], False)
        if r["events"]:
            lines += ["## Events", ""]
            for e in r["events"]:
                lines.append(f"- `on('{e['name']}', ({', '.join(a['name'] for a in e['args'])}) => ...)`")
            lines.append("")
        if r["blocked"]:
            lines += ["## Not bound", ""]
            for k, why in sorted(r["blocked"].items()):
                lines.append(f"- `{k}`: {why}")
            lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    def doc_index(self) -> str:
        lines = ["---", "title: Non-UI types (WinUI)", 'description: "Windows Runtime classes as ES module named exports (svelters:winui/windows.foundation, ...)."',
                 "---", "",
                 "Every bound Windows Runtime class is a named export of `svelters:winui/<namespace>` (the namespace in lower case). "
                 "WinUI controls stay elements (tags).", "",
                 "```svelte", "<script>", "  import { Uri } from 'svelters:winui/windows.foundation';",
                 "  import { StorageFolder, FileIO } from 'svelters:winui/windows.storage';",
                 "  const uri = new Uri('https://example.com/a?x=1');",
                 "  const folder = await StorageFolder.getFolderFromPathAsync(dir);",
                 "  const file = await folder.createFileAsync('note.txt', 'replace-existing');",
                 "  await FileIO.writeTextAsync(file, 'hello');", "</script>", "<text-block text={uri.host} />", "```", "",
                 "- **Objects**: one JS object per native object, a SHARED handle (one COM reference); `dispose()` or garbage "
                 "collection releases it. `Close()` (IClosable) is an explicit method.",
                 "- **Records** (`Color`, `Thickness`, `CornerRadius`, `Point`): plain objects with camelCase field names. "
                 "`DateTime` is a `Date`, `TimeSpan` milliseconds.",
                 "- **Enums**: kebab-case names in and out (native and camelCase names and numbers are accepted); flags are lists of names.",
                 "- **Async** (`IAsyncOperation`, `IAsyncAction`): Promises; a trailing `{ signal }` cancels (`IAsyncInfo.Cancel`); "
                 "a failure rejects with `NativeError { domain: 'winrt', code }` (`file-not-found`, `access-denied`, ...).",
                 "- **Collections**: `IVectorView`/`IIterable` results are arrays, `IMapView` plain objects; `IVector`/`IMap` "
                 "results are live objects (`getAt`, `size`, `append`, `insert`, `lookup`, ...).",
                 "- **Overloads**: one JS name; the backend picks the overload by argument count.",
                 "- **Threads**: one UI thread; completions hop to it before anything is converted.", "",
                 "## Curated types", ""]
        for q in sorted(self.classes):
            if self.classes[q].get("curated"):
                lines.append(f"- [{self.classes[q]['full']}]({self.classes[q]['name'].lower()}/)")
        lines += ["", "## All bound types", ""]
        by_ns: dict[str, list[str]] = {}
        for q, r in self.classes.items():
            by_ns.setdefault(r["namespace"], []).append(q)
        for ns in sorted(by_ns):
            lines.append(f"- `{C.js_module(ns)}`: " + ", ".join(f"`{self.classes[q]['name']}` ({self.classes[q]['category']})" for q in sorted(by_ns[ns])))
        return "\n".join(lines) + "\n"

    def files(self, types_pkg) -> dict[Path, str]:
        out: dict[Path, str] = {}
        by_ns: dict[str, list[str]] = {}
        for q in sorted(self.classes):
            ns = self.classes[q]["namespace"]
            by_ns.setdefault(ns, []).append(q)
            out[OUT / ns_dir(ns) / f"{self.classes[q]['name']}.js"] = self.class_js(q)
        # Namespaces that only hold records or enums still get a (types-only) module.
        for full in list(self.enums) + list(self.structs):
            by_ns.setdefault(full.rsplit(".", 1)[0], [])
        for ns, qs in sorted(by_ns.items()):
            out[OUT / ns_dir(ns) / "index.js"] = HEADER + "".join(f"export {{ {self.classes[q]['name']} }} from './{self.classes[q]['name']}.js';\n" for q in qs)
            out[OUT / f"{ns_dir(ns)}.d.ts"] = self.dts(ns)
        out[OUT / "manifest.json"] = json.dumps(self.manifest(), indent=1, sort_keys=True) + "\n"
        own = {"./manifest-winui": "./winui/manifest.json"}
        for ns in sorted(by_ns):
            own[f"./winui/{ns_dir(ns)}"] = {"types": f"./winui/{ns_dir(ns)}.d.ts", "default": f"./winui/{ns_dir(ns)}/index.js"}
        out[PKG / "package.json"] = types_pkg.package_json(PKG / "package.json", own, "./winui/", ["./manifest-winui"])
        for q in sorted(self.classes):
            if self.classes[q].get("curated"):
                out[DOCS / f"{self.classes[q]['name'].lower()}.md"] = self.doc_page(q)
        out[DOCS / "index.md"] = self.doc_index()
        return out
