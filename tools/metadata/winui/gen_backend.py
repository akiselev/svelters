def setter_expr(ty: dict, var: str = "v") -> str:
    """Rust expression converting the svl Value `v` into the native setter argument (or `?`-able result)."""
    t = ty["t"]
    if t == "Str":
        return f"&conv::hstring({var})?"
    if t == "Bool":
        return f"conv::bool_({var})?"
    if t == "I32":
        return f"conv::i32_({var})?"
    if t == "F64":
        return f"conv::f64_({var})?"
    if t == "Enum":
        return f"{rs_path(ty['enum'])}(conv::enum_({var}, &ENUMS[{ty['index']}])?)"
    if t == "Thickness":
        return f"conv::thickness({var})?"
    if t == "NullableBool":
        return f"conv::nullable_bool({var})?"
    if t == "ObjectString":
        return f"conv::boxed_str({var})?.as_ref()"
    raise GenError(f"no setter conversion for {t}")


def getter_expr(ty: dict, call: str) -> str:
    t = ty["t"]
    if t == "Str":
        return f"Value::Str({call}.map_err(conv::err)?.to_string_lossy())"
    if t == "Bool":
        return f"Value::Bool({call}.map_err(conv::err)?)"
    if t == "I32":
        return f"Value::I64({call}.map_err(conv::err)? as i64)"
    if t == "F64":
        return f"Value::F64({call}.map_err(conv::err)?)"
    if t == "Enum":
        return f"conv::enum_name(&ENUMS[{ty['index']}], {call}.map_err(conv::err)?.0)"
    if t == "Thickness":
        return f"conv::thickness_value({call}.map_err(conv::err)?)"
    if t == "NullableBool":
        return f"conv::nullable_bool_value({call}.ok())"
    if t == "ObjectString":
        return f"conv::unboxed_value({call}.ok())"
    raise GenError(f"no getter conversion for {t}")


def payload_expr(item: dict, m: Model) -> str:
    ref = item["ref"]
    src = "a" if item["from"] == "args" else "s"
    call = f"{src}.{item['prop']}()"
    if ref == "string":
        return f"{call}.map(|x| Value::Str(x.to_string_lossy())).unwrap_or(Value::Null)"
    if ref == "f64":
        return f"{call}.map(Value::F64).unwrap_or(Value::Null)"
    if ref == "bool":
        return f"{call}.map(Value::Bool).unwrap_or(Value::Null)"
    if ref in ("i32", "u32"):
        return f"{call}.map(|x| Value::I64(x as i64)).unwrap_or(Value::Null)"
    if ref.startswith("enum<"):
        return f"{call}.map(|x| Value::I64(x.0 as i64)).unwrap_or(Value::Null)"
    raise GenError(f"payload {item['prop']}: type {ref} not supported")


def gen_dispatch(m: Model) -> str:
    o = [HEADER, "//! Typed windows-rs calls per id, parallel to the tables in names.rs (Windows only).\n\n",
         "#![allow(non_snake_case, clippy::all, unused_imports)]\n",
         "use super::names::*;\n", "use crate::conv::{self, R};\n", "use crate::custom;\n", "use crate::sink::{Registration, Sink};\n",
         "use svelters_abi::Value;\n", "use windows_core::{IInspectable, Interface};\n\n",
         "type WinResult<T> = windows_core::Result<T>;\n\n"]
    # create
    o.append("pub static CREATE: &[fn() -> WinResult<IInspectable>] = &[\n")
    for k in m.kinds:
        o.append(f"    || Ok({rs_path(k['class'])}::new()?.into()),\n")
    o.append("];\n\n")
    # props
    for i, p in enumerate(m.props):
        cls = rs_path(p["class"])
        fn = f"prop{i}_{snake(short(p['class']))}_{snake(p['native'])}"
        if p["ty"]["t"] == "Custom":
            o.append(f"fn set_{fn}(o: &IInspectable, v: &Value) -> R<()> {{\n    custom::{p['ty']['custom']}_set(&o.cast::<{cls}>().map_err(conv::err)?, v)\n}}\n")
            o.append(f"fn get_{fn}(o: &IInspectable) -> R<Value> {{\n    custom::{p['ty']['custom']}_get(&o.cast::<{cls}>().map_err(conv::err)?)\n}}\n")
            p["fn"] = fn
            continue
        if p["write"]:
            o.append(f"fn set_{fn}(o: &IInspectable, v: &Value) -> R<()> {{\n"
                     f"    o.cast::<{cls}>().map_err(conv::err)?.Set{p['native']}({setter_expr(p['ty'])}).map_err(conv::err)\n}}\n")
        if p["read"]:
            o.append(f"fn get_{fn}(o: &IInspectable) -> R<Value> {{\n"
                     f"    let t = o.cast::<{cls}>().map_err(conv::err)?;\n    Ok({getter_expr(p['ty'], 't.' + p['native'] + '()')})\n}}\n")
        p["fn"] = fn
    o.append("\npub static PROP_SET: &[Option<fn(&IInspectable, &Value) -> R<()>>] = &[\n")
    for p in m.props:
        o.append(f"    Some(set_{p['fn']}),\n" if p["write"] else "    None,\n")
    o.append("];\n\npub static PROP_GET: &[Option<fn(&IInspectable) -> R<Value>>] = &[\n")
    for p in m.props:
        o.append(f"    Some(get_{p['fn']}),\n" if p["read"] or p["ty"]["t"] == "Custom" else "    None,\n")
    o.append("];\n\n")
    # events
    for i, e in enumerate(m.events):
        cls = rs_path(e["class"])
        if e["notify"]:
            fn = f"event{i}_{snake(short(e['class']))}_notify_{snake(e['native'])}"
            e["fn"] = fn
            o.append(f"fn {fn}(o: &IInspectable, sink: Sink) -> WinResult<Registration> {{\n"
                     f"    crate::sink::notify(o, &{cls}::{e['native']}Property()?, sink)\n}}\n")
            continue
        fn = f"event{i}_{snake(short(e['class']))}_{snake(e['native'])}"
        e["fn"] = fn
        body = []
        needs_sender = any(x["from"] == "sender" for x in e["payload"])
        if needs_sender:
            body.append(f"        let Some(s) = s.as_ref().and_then(|s| s.cast::<{cls}>().ok()) else {{ return }};")
        needs_args = any(x["from"] == "args" for x in e["payload"]) or e["o"].get("result") or e["o"].get("close")
        if needs_args:
            body.append("        let Some(a) = a.as_ref() else { return };")
        args = ", ".join(payload_expr(x, m) for x in e["payload"])
        if e["o"].get("close"):
            body.append("        if sink.close() {\n            let _ = a.SetHandled(true);\n        }")
        elif e["o"].get("sync"):
            res = e["o"].get("result")
            body.append(f"        let reply = sink.sync(vec![{args}]);")
            if res:
                body.append(f"        if conv::is_true(&reply) {{\n            let _ = a.Set{res['prop']}(true);\n        }}")
        else:
            body.append(f"        sink.post(vec![{args}]);")
        sv = "s" if needs_sender else "_s"
        av = "a" if needs_args else "_a"
        o.append(f"fn {fn}(o: &IInspectable, sink: Sink) -> WinResult<Registration> {{\n"
                 f"    o.cast::<{cls}>()?.{e['native']}(move |{sv}, {av}| {{\n" + "\n".join(body) + "\n    }).map(Into::into)\n}\n")
    o.append("\npub static EVENT_CONNECT: &[fn(&IInspectable, Sink) -> WinResult<Registration>] = &[\n")
    for e in m.events:
        o.append(f"    {e['fn']},\n")
    o.append("];\n\n")
    # slots
    o.append("pub enum SlotOps {\n"
             "    /// A single-child property (`Content`): set, read back.\n"
             "    Single { set: fn(&IInspectable, Option<&IInspectable>) -> WinResult<()>, get: fn(&IInspectable) -> Option<IInspectable> },\n"
             "    /// A `UIElementCollection` property (`Children`).\n"
             "    Many { items: fn(&IInspectable) -> WinResult<crate::bindings::Microsoft::UI::Xaml::Controls::UIElementCollection> },\n"
             "}\n\n")
    o.append("pub static SLOT_OPS: &[SlotOps] = &[\n")
    for s in m.slots:
        cls = rs_path(s["class"])
        if s["many"]:
            o.append(f"    SlotOps::Many {{ items: |p| p.cast::<{cls}>()?.{s['native']}() }},\n")
        elif s["element_param"]:
            o.append(f"    SlotOps::Single {{\n        set: |p, c| {{\n"
                     f"            let c = c.map(|c| c.cast::<crate::bindings::Microsoft::UI::Xaml::UIElement>()).transpose()?;\n"
                     f"            p.cast::<{cls}>()?.Set{s['native']}(c.as_ref())\n        }},\n"
                     f"        get: |p| p.cast::<{cls}>().ok()?.{s['native']}().ok().map(|c| c.into()),\n    }},\n")
        else:
            o.append(f"    SlotOps::Single {{\n        set: |p, c| p.cast::<{cls}>()?.Set{s['native']}(c),\n"
                     f"        get: |p| p.cast::<{cls}>().ok()?.{s['native']}().ok(),\n    }},\n")
    o.append("];\n\n")
    # attrs
    o.append("pub static ATTR_SET: &[fn(&IInspectable, &Value) -> R<()>] = &[\n")
    for a in m.attrs:
        target = a["target"][len("object<"):-1]
        o.append(f"    |c, v| {rs_path(a['class'])}::Set{a['native']}(&c.cast::<{rs_path(target)}>().map_err(conv::err)?, conv::i32_(v)?).map_err(conv::err),\n")
    o.append("];\n\npub static ATTR_GET: &[fn(&IInspectable) -> R<Value>] = &[\n")
    for a in m.attrs:
        target = a["target"][len("object<"):-1]
        o.append(f"    |c| Ok(Value::I64({rs_path(a['class'])}::Get{a['native']}(&c.cast::<{rs_path(target)}>().map_err(conv::err)?).map_err(conv::err)? as i64)),\n")
    o.append("];\n\n")
    # methods
    for i, mt in enumerate(m.methods):
        cls = rs_path(mt["class"])
        fn = f"method{i}_{snake(short(mt['class']))}_{snake(mt['native'])}"
        mt["fn"] = fn
        argv = []
        for j, p in enumerate(mt["params"]):
            argv.append(setter_expr(p["ty"], f"conv::arg(args, {j})?"))
        call = f"t.{mt['native']}({', '.join(argv)})"
        ret = "Ok(Value::Null)" if not mt["ret"] else f"Ok({getter_expr(mt['ret'], call)})"
        stmt = f"    {call}.map_err(conv::err)?;\n    Ok(Value::Null)" if not mt["ret"] else f"    {ret}"
        o.append(f"fn {fn}(o: &IInspectable, args: &[Value]) -> R<Value> {{\n"
                 f"    conv::arity(args, {len(mt['params'])})?;\n    let t = o.cast::<{cls}>().map_err(conv::err)?;\n{stmt}\n}}\n")
    o.append("\npub static METHOD_CALL: &[fn(&IInspectable, &[Value]) -> R<Value>] = &[\n")
    for mt in m.methods:
        o.append(f"    {mt['fn']},\n")
    o.append("];\n")
    return "".join(o)


# ---- bindgen filter -------------------------------------------------------------------------------

def gen_filter(m: Model) -> str:
    members: dict[str, set[str]] = {}

    def add(cls: str, *names: str) -> None:
        members.setdefault(cls, set()).update(names)

    for k in m.kinds:
        ctor = m.classes[k["class"]]["constructors"][0]["id"]
        add(k["class"], "CreateInstance") if ctor == "ctor:composable" else add(k["class"])
        for c in k["chain"]:
            add(c)
    for p in m.props:
        if p["ty"]["t"] == "Custom":
            add(p["class"], f"get_{p['native']}")
            continue
        if p["read"]:
            add(p["class"], f"get_{p['native']}")
        if p["write"]:
            add(p["class"], f"put_{p['native']}")
    delegates = set()
    for e in m.events:
        if e["notify"]:
            # The DependencyProperty identifier (a static getter) and the callback API (sink.rs).
            add(e["class"], f"get_{e['native']}Property")
            add("Microsoft.UI.Xaml.DependencyObject", "RegisterPropertyChangedCallback", "UnregisterPropertyChangedCallback")
            add("Microsoft.UI.Xaml.DependencyProperty")
            delegates.add("Microsoft.UI.Xaml.DependencyPropertyChangedCallback")
            continue
        add(e["class"], f"add_{e['native']}", f"remove_{e['native']}")
        # The typed event wrappers construct the delegate (`KeyEventHandler::new`), which bindgen only
        # emits for delegates the filter selects.
        delegates.add(e["delegate"].split("<", 1)[0])
        args = e["args"]
        for x in e["payload"]:
            if x["from"] == "args":
                add(args, f"get_{x['prop']}")
            else:
                add(e["class"], f"get_{x['prop']}")
        res = e["o"].get("result")
        if res:
            add(args, f"get_{res['prop']}", f"put_{res['prop']}")
        if e["o"].get("close"):
            add(args, "get_Handled", "put_Handled")
        if "." in args:          # not `object` (EventHandler<object>)
            add(args)
    for s in m.slots:
        add(s["class"], f"get_{s['native']}") if s["many"] else add(s["class"], f"get_{s['native']}", f"put_{s['native']}")
    for a in m.attrs:
        add(a["class"], f"Get{a['native']}", f"Set{a['native']}")
    for mt in m.methods:
        add(mt["class"], mt["native"])
    lines = []
    for cls in sorted(members):
        names = sorted(members[cls])
        lines.append(f"{cls}::{{{', '.join(names)}}}\n")
    lines += [f"{e}\n" for e in sorted(m.enums)]
    lines += [f"{d}\n" for d in sorted(delegates)]
    return ("# @generated by tools/metadata/winui/gen_backend.py: windows-bindgen member filter for src/bindings.rs.\n"
            "# Kinds, props, events, slots, attrs and methods from the overrides:\n" + "".join(lines) +
            "# Runtime (backend.rs, app.rs, conv.rs, custom.rs, testing.rs):\n" + RUNTIME_FILTER)


# ---- tests ----------------------------------------------------------------------------------------

def expected_value(p: dict, v) -> str:
    """Rust `Value` the getter returns after setting test value v."""
    t = p["ty"]["t"]
    if t in ("Str", "ObjectString"):
        return f"Value::Str({rs_str(str(v))}.into())"
    if t in ("Bool", "NullableBool"):
        return f"Value::Bool({str(bool(v)).lower()})"
    if t == "I32":
        return f"Value::I64({int(v)})"
    if t == "F64":
        return f"Value::F64({float(v)!r})"
    if t == "Enum":
        return f"Value::Str({rs_str(kebab(str(v)))}.into())"
    if t == "Thickness":
        parts = [x.strip() for x in str(v).split(",")]
        if len(parts) == 1:
            parts *= 4
        elif len(parts) == 2:
            parts = [parts[0], parts[1], parts[0], parts[1]]
        return f"Value::Str({rs_str(','.join(str(float(x)).removesuffix('.0') for x in parts))}.into())"
    if t == "Custom":
        return f"Value::Str({rs_str(','.join(x.strip() for x in str(v).split(',')))}.into())"
    raise GenError(t)


def test_value(p: dict, v) -> str:
    t = p["ty"]["t"]
    if isinstance(v, bool):
        return f"Value::Bool({str(v).lower()})"
    if isinstance(v, int) and t != "F64":
        return f"Value::I64({v})"
    if isinstance(v, (int, float)):
        return f"Value::F64({float(v)!r})"
    return f"Value::Str({rs_str(str(v))}.into())"


def first_kind(m: Model, cls: str) -> dict:
    for k in m.kinds:
        if cls in k["chain"]:
            return k
    raise GenError(f"no kind for {cls}")


def test_values(p: dict) -> list:
    """The values a prop's test writes, in order (a manual `test` is one value, an inferred one a list)."""
    v = p["o"].get("test")
    if v is None:
        return []
    return list(v) if isinstance(v, list) else [v]


def gen_tests(m: Model) -> str:
    o = [HEADER, "//! One verification test per annotated fact. Windows only: `cargo test -p svelters-winui --test generated`.\n",
         "//! Each test runs on the one STA thread of the harness (harness = false). Inferred facts use the\n",
         "//! table-driven checks of `svelters_winui::testing` (one row each, at the end of TESTS).\n\n",
         "#[cfg(windows)]\nmod tests {\n",
         "use svelters_abi::Value;\nuse svelters_winui::testing::{self as t, Harness, Reply};\n\n"]
    tests: list[tuple[str, str]] = []     # hand-shaped tests: (fn name, body)
    rows: list[tuple[str, str]] = []      # table rows: (test name, call)
    seen: set[str] = set()

    def fact(cls: str, sec: str, name: str, test: str, record: dict, src: str, strength: str | None = None) -> None:
        origin = m.origin(cls, sec, name)
        rec = {"fact": m.fact_id(cls, sec, name), "kind": short(cls), "section": sec, "name": name, "origin": origin,
               "tests": [test], "fingerprint": svmeta.fingerprint({"record": record, "test": src})}
        if origin == "inferred":
            rec["record_fp"] = m.layers.record_fp(cls, sec, name)
        if strength:
            rec["strength"] = strength
        m.facts.append(rec)

    def add_test(name: str, body: str) -> None:
        if name in seen:
            raise GenError(f"two facts generate the test {name}")
        seen.add(name)
        tests.append((name, body))

    def add_row(name: str, call: str) -> None:
        if name in seen:
            raise GenError(f"two facts generate the test {name}")
        seen.add(name)
        rows.append((name, call))

    notify_test: dict[tuple[str, str], tuple[str, str]] = {}    # (class, event name) -> (test name, call)
    for p in m.props:
        k = first_kind(m, p["class"])
        tag = rs_str(k["tag"])
        name = f"prop_{snake(k['tag'])}_{snake(p['native'])}"
        vals = test_values(p)
        if isinstance(p["o"].get("test"), list):
            cases = ", ".join(f"({test_value(p, v)}, {expected_value(p, v)})" for v in vals)
            call = f"t::roundtrip({tag}, {rs_str(p['name'])}, &[{cases}])"
            fact(p["class"], "props", p["native"], name, {"o": p["o"], "ty": p["ty"]}, call)
            add_row(name, call)
        elif vals:
            body = (f"    let mut h = Harness::new();\n    let w = h.create({tag});\n"
                    f"    h.set(w, {rs_str(p['name'])}, {test_value(p, vals[0])}).unwrap();\n"
                    f"    assert_eq!(h.get(w, {rs_str(p['name'])}).unwrap(), {expected_value(p, vals[0])});\n")
            fact(p["class"], "props", p["native"], name, {"o": p["o"], "ty": p["ty"]}, body)
            add_test(name, body)
        elif p["origin"] == "inferred" and p["read"] and not p["write"]:
            call = f"t::readable({tag}, {rs_str(p['name'])})"
            fact(p["class"], "props", p["native"], name, {"o": p["o"], "ty": p["ty"]}, call)
            add_row(name, call)
    for s in m.slots:
        k = first_kind(m, s["class"])
        name = f"slot_{snake(k['tag'])}_{snake(s['name'])}"
        child = "text-block"
        if s["many"]:
            body = (f"    let mut h = Harness::new();\n    let p = h.create({rs_str(k['tag'])});\n"
                    f"    let a = h.create({rs_str(child)});\n    let b = h.create({rs_str(child)});\n"
                    f"    h.insert(p, a, None, Some({rs_str(s['name'])})).unwrap();\n"
                    f"    h.insert(p, b, Some(a), Some({rs_str(s['name'])})).unwrap();\n"
                    f"    assert_eq!(h.slot_items(p, {rs_str(s['name'])}), vec![b, a], \"before= inserts in front\");\n"
                    f"    h.remove(p, b).unwrap();\n    assert_eq!(h.slot_items(p, {rs_str(s['name'])}), vec![a]);\n"
                    f"    h.remove(p, b).unwrap_err();\n    h.remove(p, a).unwrap();\n"
                    f"    assert!(h.slot_items(p, {rs_str(s['name'])}).is_empty());\n")
        else:
            body = (f"    let mut h = Harness::new();\n    let p = h.create({rs_str(k['tag'])});\n"
                    f"    let a = h.create({rs_str(child)});\n    let b = h.create({rs_str(child)});\n"
                    f"    h.insert(p, a, None, Some({rs_str(s['name'])})).unwrap();\n"
                    f"    assert_eq!(h.slot_items(p, {rs_str(s['name'])}), vec![a]);\n"
                    f"    h.insert(p, b, None, Some({rs_str(s['name'])})).unwrap_err();\n"
                    f"    h.remove(p, a).unwrap();\n    assert!(h.slot_items(p, {rs_str(s['name'])}).is_empty());\n"
                    f"    h.insert(p, b, None, Some({rs_str(s['name'])})).unwrap();\n"
                    f"    assert_eq!(h.slot_items(p, {rs_str(s['name'])}), vec![b]);\n")
        fact(s["class"], "slots", s["name"], name, {"o": s["o"], "many": s["many"]}, body)
        add_test(name, body)
    for a in m.attrs:
        k = first_kind(m, a["class"])
        name = f"attr_{snake(k['tag'])}_{snake(a['native'])}"
        body = (f"    let mut h = Harness::new();\n    let p = h.create({rs_str(k['tag'])});\n"
                f"    let c = h.create(\"text-block\");\n    h.insert(p, c, None, None).unwrap();\n"
                f"    h.set_attr(p, c, {rs_str(a['name'])}, Value::I64({a['o']['test']})).unwrap();\n"
                f"    assert_eq!(h.get_attr(p, c, {rs_str(a['name'])}).unwrap(), Value::I64({a['o']['test']}));\n"
                f"    h.set_attr(p, c, {rs_str(a['name'])}, Value::Null).unwrap();\n"
                f"    assert_eq!(h.get_attr(p, c, {rs_str(a['name'])}).unwrap(), Value::I64({a['default']}));\n"
                f"    h.remove(p, c).unwrap();\n"
                f"    h.set_attr(p, c, {rs_str(a['name'])}, Value::I64(1)).unwrap_err();\n")
        fact(a["class"], "attached", a["native"], name, {"o": a["o"]}, body)
        add_test(name, body)
    for e in m.events:
        k = first_kind(m, e["class"])
        tag = rs_str(k["tag"])
        if e["notify"]:
            p = e["prop"]
            vals = test_values(p)
            name = f"notify_{snake(k['tag'])}_{snake(e['native'])}"
            if not vals:
                m.unusable(e["class"], "notify", e["native"], f"{e['file']}: notify {e['native']}: the prop has no test value to write")
                continue
            call = (f"t::notify({tag}, {rs_str(p['name'])}, {rs_str(e['name'])}, "
                    f"&[{', '.join(test_value(p, v) for v in vals)}])")
            fact(e["class"], "notify", e["native"], name, {"o": e["o"], "prop": p["o"]}, call)
            add_row(name, call)
            notify_test[(e["class"], e["name"])] = (name, call)
            continue
        trig = e["o"].get("trigger")
        name = f"event_{snake(k['tag'])}_{snake(e['native'])}"
        inferred = e["origin"] == "inferred"
        if e["o"].get("close"):
            body = (f"    let mut h = Harness::new();\n    let w = h.create({tag});\n"
                    f"    h.call(w, \"activate\", &[]).unwrap();\n    h.listen(w, {rs_str(e['name'])}, true).unwrap();\n"
                    f"    h.call(w, \"close\", &[]).unwrap();\n    h.pump(200);\n"
                    f"    assert_eq!(h.events(w, {rs_str(e['name'])}), 1, \"close while listened is vetoed and posted\");\n"
                    f"    assert!(h.gone(w).is_none(), \"vetoed window stays alive\");\n"
                    f"    h.listen(w, {rs_str(e['name'])}, false).unwrap();\n"
                    f"    h.call(w, \"close\", &[]).unwrap();\n    h.pump(200);\n"
                    f"    assert_eq!(h.gone(w), Some(svelters_abi::SVL_GONE_CLOSED));\n")
            fact(e["class"], "events", e["native"], name, {"o": e["o"]}, body)
            add_test(name, body)
            continue
        if not trig:
            if inferred:
                call = f"t::connect({tag}, {rs_str(e['name'])})"
                fact(e["class"], "events", e["native"], name, {"o": e["o"]}, call, strength="connect")
                add_row(name, call)
            continue
        lines = [f"    let mut h = Harness::new();\n    let w = h.create({tag});\n"]
        if trig == "mount":
            if k["el"].get("lifetime") == "toplevel":
                m.unusable(e["class"], "events", e["native"], f"{e['file']}: event {e['native']}: a toplevel cannot be mounted")
                continue
            lines.append(f"    h.listen(w, {rs_str(e['name'])}, true).unwrap();\n"
                         "    let win = h.create(\"window\");\n    h.insert(win, w, None, None).unwrap();\n"
                         "    h.call(win, \"activate\", &[]).unwrap();\n    h.pump(300);\n"
                         f"    assert!(h.events(w, {rs_str(e['name'])}) >= 1, \"raised when mounted in an activated window\");\n")
            body = "".join(lines)
            fact(e["class"], "events", e["native"], name, {"o": e["o"]}, body)
            add_test(name, body)
            continue
        if k["el"].get("lifetime") != "toplevel":
            lines.append("    let win = h.create(\"window\");\n    h.insert(win, w, None, None).unwrap();\n"
                         "    h.call(win, \"activate\", &[]).unwrap();\n    h.pump(100);\n")
        if trig.startswith("set:"):
            prop, val = trig[4:].split("=", 1)
            p = next((x for x in m.props if x["native"] == prop and x["class"] in k["chain"]), None)
            if p is None:
                m.unusable(e["class"], "events", e["native"], f"{e['file']}: event {e['native']}: trigger prop {prop} is not exposed")
                continue
            pre = {"true": True, "false": False}.get(val, val)
            if pre is False:
                lines.append(f"    h.set(w, {rs_str(p['name'])}, Value::Bool(true)).unwrap();\n    h.pump(50);\n")
        lines.append(f"    h.listen(w, {rs_str(e['name'])}, true).unwrap();\n")
        res = e["o"].get("result")
        if res:
            lines.append("    h.reply(Reply::Bool(true));\n")
        if trig == "invoke":
            lines.append("    h.invoke(w).unwrap();\n")
        else:
            v = {"true": True, "false": False}.get(val, val)
            if p["ty"]["t"] == "F64":
                v = float(val)
            lines.append(f"    h.set(w, {rs_str(p['name'])}, {test_value(p, v)}).unwrap();\n")
        lines.append("    h.pump(200);\n")
        if inferred:
            lines.append(f"    assert!(h.events(w, {rs_str(e['name'])}) >= 1, \"event delivered\");\n")
        else:
            lines.append(f"    assert_eq!(h.events(w, {rs_str(e['name'])}), 1, \"event delivered once\");\n")
        if e["payload"]:
            lines.append(f"    assert_eq!(h.last_args(w, {rs_str(e['name'])}).len(), {len(e['payload'])}, \"payload arity\");\n")
        if res and trig.startswith("set:Text"):
            lines.append(f"    assert_ne!(h.get(w, \"text\").unwrap(), Value::Str({rs_str(trig.split('=', 1)[1])}.into()), \"{res['prop']} = true vetoes the change\");\n")
        body = "".join(lines)
        fact(e["class"], "events", e["native"], name, {"o": e["o"]}, body)
        add_test(name, body)
    for mt in m.methods:
        if mt["origin"] != "inferred":
            continue
        k = first_kind(m, mt["class"])
        name = f"method_{snake(k['tag'])}_{snake(mt['native'])}"
        if mt["params"]:
            m.unusable(mt["class"], "methods", mt["native"], f"{mt['file']}: method {mt['native']}: no generated test for arguments")
            continue
        call = f"t::call0({rs_str(k['tag'])}, {rs_str(mt['name'])})"
        fact(mt["class"], "methods", mt["native"], name, {"o": mt["o"], "ret": mt["ret"]}, call)
        add_row(name, call)
    # A generic binding is verified by its change event's test (the notify test writes the prop and sees the callback).
    for cls, ov in sorted(m.ovr.items(), key=lambda kv: short(kv[0])):
        chain = [cls] + m.classes[cls]["bases"]
        for b in ov.get("bindings", []):
            sig = (b.get("change") or {}).get("signal", "")
            hit = next((notify_test[(c, sig)] for c in chain if (c, sig) in notify_test), None)
            if hit is None:
                continue                 # an event-driven binding (manual): covered by its event's own test, if any
            fact(cls, "bindings", b["name"], hit[0], {"o": b}, hit[1])
    for name, body in tests:
        o.append(f"pub fn {name}() {{\n{body}}}\n\n")
    o.append("pub static TESTS: &[(&str, fn())] = &[\n" + "".join(f"    ({rs_str(n)}, {n}),\n" for n, _ in tests)
             + "".join(f"    ({rs_str(n)}, || {call}),\n" for n, call in rows) + "];\n}\n\n")
    o.append("fn main() {\n    // Lists and runs nothing off Windows, so cargo test and nextest see an empty target.\n"
             "    #[cfg(windows)]\n    let tests = tests::TESTS;\n    #[cfg(not(windows))]\n    let tests: &[(&str, fn())] = &[];\n"
             "    std::process::exit(svelters_winui::harness::main(tests));\n}\n")
    return "".join(o)

def toolkit_version(m: Model) -> str:
    """The WinUI package the metadata was ingested from (`microsoft.windowsappsdk.winui 2.3.9` -> 2.3.9): the
    version the ledger records results for."""
    return next(iter(m.classes.values()))["source"]["package"].rsplit(" ", 1)[1]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the checked-in outputs are stale")
    a = ap.parse_args()
    try:
        m = Model()
        outs = {OUT_NAMES: gen_names(m), OUT_DISPATCH: gen_dispatch(m), OUT_FILTER: gen_filter(m), OUT_TESTS: gen_tests(m)}
        outs[OUT_FACTS] = json.dumps({"toolkit": "winui", "version": toolkit_version(m),
                                      "facts": sorted(m.facts, key=lambda f: f["fact"]),
                                      "untestable": sorted(m.untestable, key=lambda f: f["fact"])},
                                     indent=1, sort_keys=True) + "\n"
    except GenError as e:
        print(f"gen_backend: {e}", file=sys.stderr)
        return 1
    stale = [p for p, text in outs.items() if not p.exists() or p.read_text() != text]
    if a.check:
        for p in stale:
            print(f"gen_backend: {p.relative_to(ROOT)} is stale", file=sys.stderr)
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(outs[p])
    print(f"gen_backend: {len(m.kinds)} kinds, {len(m.props)} props, {len(m.events)} events, {len(m.slots)} slots, "
          f"{len(m.attrs)} attrs, {len(m.methods)} methods, {len(m.facts)} facts "
          f"({sum(1 for f in m.facts if f['origin'] == 'inferred')} inferred, {len(m.untestable)} untestable); {len(stale)} files written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
