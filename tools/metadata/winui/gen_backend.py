#!/usr/bin/env python3
"""Generate the WinUI backend tables, the windows-bindgen filter and the verification tests.

Inputs (only these):
  metadata/winui/*.json             upstream facts from the winmd (ingest.py)
  metadata/overrides/winui/*.yaml   annotations: which kinds, props, events, slots, attrs and methods
                                    are exposed, and how (schema: override.schema.json)
  metadata/inferred/winui/*.yaml    the inferred layer (infer.py), same schema, under the manual one;
                                    minus metadata/inferred/winui/_parked.json (layers.py merges them)
Outputs (checked in, byte-identical on rerun):
  crates/svelters-winui/src/generated/names.rs     platform-neutral tables (every target)
  crates/svelters-winui/src/generated/dispatch.rs  typed windows-rs calls per id (cfg(windows))
  crates/svelters-winui/src/generated/facts.json   fact id -> test name + fingerprint (ledger input)
  crates/svelters-winui/tests/generated.rs         one verification test per annotated fact
  crates/svelters-winui/bindings.filter            the windows-bindgen member filter (regen.sh feeds it to
                                                   `winmd-tool bindgen` -> src/bindings.rs)

Naming: tag = native class name in kebab-case (StackPanel -> stack-panel); props, events, slots,
attributes and methods = native member names in kebab-case (IsChecked -> is-checked).

  python3 tools/metadata/winui/gen_backend.py [--check]
"""
