def color_text(v: str) -> str:
    """parse.rs `color` then `color_text`: the read-back form of a color sample."""
    h = str(v).strip().lower()
    if h == "transparent":
        return "#00000000"
    h = h.lstrip("#")
    if len(h) in (3, 4):
        h = "".join(c * 2 for c in h)
    return "#" + (h[:6] if len(h) == 8 and h[6:] == "ff" else h)


def iso_ms(v) -> float:
    """parse.rs `datetime_ms` of a sample: epoch milliseconds."""
    import datetime as dt
    if isinstance(v, (int, float)):
        return float(v)
    s = str(v).replace("Z", "+00:00")
    d = dt.datetime.fromisoformat(s)
    if d.tzinfo is None:
        d = d.replace(tzinfo=dt.timezone.utc)
    return float(round(d.timestamp() * 1000))


def nums_text(v, n4: bool) -> str:
    """Thickness / CornerRadius read-back text of a sample."""
    parts = [x.strip() for x in str(v).split(",")]
    if len(parts) == 1:
        parts *= 4
    elif len(parts) == 2 and not n4:
        parts = [parts[0], parts[1], parts[0], parts[1]]
    return ",".join(str(float(x)).removesuffix(".0") for x in parts)


def expected_value(p: dict, v) -> str:
    """Rust `Value` the getter returns after setting test value v."""
    t = p["ty"]["t"]
    if v is None:
        return "Value::Null"
    if t in ("Color", "Brush", "SolidBrush", "NullableColor"):
        return f"Value::Str({rs_str(color_text(v))}.into())"
    if t in ("DateTime", "NullableDateTime"):
        return f"Value::DateTime({iso_ms(v)!r})"
    if t in ("TimeSpan", "NullableTimeSpan", "F32", "NullableF64"):
        return f"Value::F64({float(v)!r})"
    if t == "FontWeight":
        return f"Value::I64({int(v)})"
    if t == "CornerRadius":
        return f"Value::Str({rs_str(nums_text(v, True))}.into())"
    if t == "Icon":
        return f"Value::Str({rs_str(kebab(str(v)))}.into())"
    if t in ("Str", "ObjectString", "FontFamily", "Uri", "ImageSource"):
        return f"Value::Str({rs_str(str(v))}.into())"
    if t in ("Bool", "NullableBool"):
        return f"Value::Bool({str(bool(v)).lower()})"
    if t == "I32":
        return f"Value::I64({int(v)})"
    if t == "F64":
        return f"Value::F64({float(v)!r})"
    if t == "Enum":
        return f"Value::Str({rs_str(kebab(str(v)))}.into())"
    if t == "Thickness":
        return f"Value::Str({rs_str(nums_text(v, False))}.into())"
    if t == "Custom":
        return f"Value::Str({rs_str(','.join(x.strip() for x in str(v).split(',')))}.into())"
    raise GenError(t)


def test_value(p: dict, v) -> str:
    t = p["ty"]["t"]
    if v is None:
        return "Value::Null"
    if isinstance(v, bool):
        return f"Value::Bool({str(v).lower()})"
    if isinstance(v, int) and t not in ("F64", "F32", "NullableF64", "TimeSpan", "NullableTimeSpan"):
        return f"Value::I64({v})"
    if isinstance(v, (int, float)):
        return f"Value::F64({float(v)!r})"
    return f"Value::Str({rs_str(str(v))}.into())"


def first_kind(m: Model, cls: str) -> dict:
    for k in m.kinds:
        if cls in k["chain"]:
            return k
    raise GenError(f"no kind for {cls}")


def stable(ty: dict | None) -> dict | None:
    """A wire type without its table index (`Enum` index into ENUMS): fingerprints must not change when another
    fact enters or leaves the tables (parking one would otherwise invalidate the others)."""
    return None if ty is None else {k: v for k, v in ty.items() if k != "index"}


def test_values(p: dict) -> list:
    """The values a prop's test writes, in order (a manual `test` is one value, an inferred one a list)."""
    v = p["o"].get("test")
    if v is None:
        return []
    return list(v) if isinstance(v, list) else [v]


def gen_tests(m: Model) -> str:
    o = [HEADER, "//! One verification test per annotated fact. Windows only: `cargo test -p svelters-winui --test generated`.\n",
         "//! Each test runs on the one STA thread of the harness (harness = false). Inferred facts use the\n",
         "//! table-driven checks of `svelters_winui::testing` (one row each, at the end of TESTS).\n\n",
         "#[cfg(windows)]\nmod tests {\n",
         "use svelters_abi::Value;\nuse svelters_winui::testing::{self as t, Harness, Reply};\n\n"]
    tests: list[tuple[str, str]] = []     # hand-shaped tests: (fn name, body)
    rows: list[tuple[str, str]] = []      # table rows: (test name, call)
    seen: set[str] = set()

    def fact(cls: str, sec: str, name: str, test: str, record: dict, src: str, strength: str | None = None) -> None:
        origin = m.origin(cls, sec, name)
        rec = {"fact": m.fact_id(cls, sec, name), "kind": short(cls), "section": sec, "name": name, "origin": origin,
               "tests": [test], "fingerprint": svmeta.fingerprint({"record": record, "test": src})}
        if origin == "inferred":
            rec["record_fp"] = m.layers.record_fp(cls, sec, name)
        if strength:
            rec["strength"] = strength
        m.facts.append(rec)

    def add_test(name: str, body: str) -> None:
        if name in seen:
            raise GenError(f"two facts generate the test {name}")
        seen.add(name)
        tests.append((name, body))

    def add_row(name: str, call: str) -> None:
        if name in seen:
            raise GenError(f"two facts generate the test {name}")
        seen.add(name)
        rows.append((name, call))

    notify_test: dict[tuple[str, str], tuple[str, str]] = {}    # (class, event name) -> (test name, call)
    for p in m.props:
        k = first_kind(m, p["class"])
        tag = rs_str(k["tag"])
        name = f"prop_{snake(k['tag'])}_{snake(p['native'])}"
        vals = test_values(p)
        if isinstance(p["o"].get("test"), list):
            cases = ", ".join(f"({test_value(p, v)}, {expected_value(p, v)})" for v in vals)
            call = f"t::roundtrip({tag}, {rs_str(p['name'])}, &[{cases}])"
            fact(p["class"], "props", p["native"], name, {"o": p["o"], "ty": stable(p["ty"])}, call)
            add_row(name, call)
        elif vals:
            body = (f"    let mut h = Harness::new();\n    let w = h.create({tag});\n"
                    f"    h.set(w, {rs_str(p['name'])}, {test_value(p, vals[0])}).unwrap();\n"
                    f"    assert_eq!(h.get(w, {rs_str(p['name'])}).unwrap(), {expected_value(p, vals[0])});\n")
            fact(p["class"], "props", p["native"], name, {"o": p["o"], "ty": stable(p["ty"])}, body)
            add_test(name, body)
        elif p["origin"] == "inferred" and p["read"] and not p["write"]:
            call = f"t::readable({tag}, {rs_str(p['name'])})"
            fact(p["class"], "props", p["native"], name, {"o": p["o"], "ty": stable(p["ty"])}, call)
            add_row(name, call)
    for s in m.slots:
        k = first_kind(m, s["class"])
        name = f"slot_{snake(k['tag'])}_{snake(s['name'])}"
        child = s["child"]
        if s["many"]:
            body = (f"    let mut h = Harness::new();\n    let p = h.create({rs_str(k['tag'])});\n"
                    f"    let a = h.create({rs_str(child)});\n    let b = h.create({rs_str(child)});\n"
                    f"    h.insert(p, a, None, Some({rs_str(s['name'])})).unwrap();\n"
                    f"    h.insert(p, b, Some(a), Some({rs_str(s['name'])})).unwrap();\n"
                    f"    assert_eq!(h.slot_items(p, {rs_str(s['name'])}), vec![b, a], \"before= inserts in front\");\n"
                    f"    h.remove(p, b).unwrap();\n    assert_eq!(h.slot_items(p, {rs_str(s['name'])}), vec![a]);\n"
                    f"    h.remove(p, b).unwrap_err();\n    h.remove(p, a).unwrap();\n"
                    f"    assert!(h.slot_items(p, {rs_str(s['name'])}).is_empty());\n")
        else:
            body = (f"    let mut h = Harness::new();\n    let p = h.create({rs_str(k['tag'])});\n"
                    f"    let a = h.create({rs_str(child)});\n    let b = h.create({rs_str(child)});\n"
                    f"    h.insert(p, a, None, Some({rs_str(s['name'])})).unwrap();\n"
                    f"    assert_eq!(h.slot_items(p, {rs_str(s['name'])}), vec![a]);\n"
                    f"    h.insert(p, b, None, Some({rs_str(s['name'])})).unwrap_err();\n"
                    f"    h.remove(p, a).unwrap();\n    assert!(h.slot_items(p, {rs_str(s['name'])}).is_empty());\n"
                    f"    h.insert(p, b, None, Some({rs_str(s['name'])})).unwrap();\n"
                    f"    assert_eq!(h.slot_items(p, {rs_str(s['name'])}), vec![b]);\n")
        fact(s["class"], "slots", s["name"], name, {"o": s["o"], "many": s["many"], "elem": s["elem"]}, body)
        add_test(name, body)
    for a in m.attrs:
        k = first_kind(m, a["class"])
        name = f"attr_{snake(k['tag'])}_{snake(a['native'])}"
        val = (lambda x: f"Value::I64({int(x)})") if a["ty"]["t"] == "I32" else (lambda x: f"Value::F64({float(x)!r})")
        body = (f"    let mut h = Harness::new();\n    let p = h.create({rs_str(k['tag'])});\n"
                f"    let c = h.create(\"text-block\");\n    h.insert(p, c, None, None).unwrap();\n"
                f"    h.set_attr(p, c, {rs_str(a['name'])}, {val(a['o']['test'])}).unwrap();\n"
                f"    assert_eq!(h.get_attr(p, c, {rs_str(a['name'])}).unwrap(), {val(a['o']['test'])});\n"
                f"    h.set_attr(p, c, {rs_str(a['name'])}, Value::Null).unwrap();\n"
                f"    assert_eq!(h.get_attr(p, c, {rs_str(a['name'])}).unwrap(), {val(a['default'])});\n"
                f"    h.remove(p, c).unwrap();\n"
                f"    h.set_attr(p, c, {rs_str(a['name'])}, Value::I64(1)).unwrap_err();\n")
        # The record without the wire type for i32 attrs keeps the pre-WP-W fingerprints of Grid.Row & co.
        rec = {"o": a["o"]} if a["ty"]["t"] == "I32" else {"o": a["o"], "ty": a["ty"]["t"]}
        fact(a["class"], "attached", a["native"], name, rec, body)
        add_test(name, body)
    for e in m.events:
        k = first_kind(m, e["class"])
        tag = rs_str(k["tag"])
        if e["notify"]:
            p = e["prop"]
            vals = test_values(p)
            name = f"notify_{snake(k['tag'])}_{snake(e['native'])}"
            if not vals:
                m.unusable(e["class"], "notify", e["native"], f"{e['file']}: notify {e['native']}: the prop has no test value to write")
                continue
            call = (f"t::notify({tag}, {rs_str(p['name'])}, {rs_str(e['name'])}, "
                    f"&[{', '.join(test_value(p, v) for v in vals)}])")
            fact(e["class"], "notify", e["native"], name, {"o": e["o"], "prop": p["o"]}, call)
            add_row(name, call)
            notify_test[(e["class"], e["name"])] = (name, call)
            continue
        trig = e["o"].get("trigger")
        name = f"event_{snake(k['tag'])}_{snake(e['native'])}"
        inferred = e["origin"] == "inferred"
        if e["o"].get("check"):
            # A hand-written check in crates/svelters-winui/src/testing.rs (events a prop write cannot raise).
            call = f"t::{e['o']['check']}()"
            fact(e["class"], "events", e["native"], name, {"o": e["o"]}, [call, OBSERVE_FN_VERSION])
            add_row(name, call)
            continue
        if e["o"].get("close"):
            body = (f"    let mut h = Harness::new();\n    let w = h.create({tag});\n"
                    f"    h.call(w, \"activate\", &[]).unwrap();\n    h.listen(w, {rs_str(e['name'])}, true).unwrap();\n"
                    f"    h.call(w, \"close\", &[]).unwrap();\n    h.pump(200);\n"
                    f"    assert_eq!(h.events(w, {rs_str(e['name'])}), 1, \"close while listened is vetoed and posted\");\n"
                    f"    assert!(h.gone(w).is_none(), \"vetoed window stays alive\");\n"
                    f"    h.listen(w, {rs_str(e['name'])}, false).unwrap();\n"
                    f"    h.call(w, \"close\", &[]).unwrap();\n    h.pump(200);\n"
                    f"    assert_eq!(h.gone(w), Some(svelters_abi::SVL_GONE_CLOSED));\n")
            fact(e["class"], "events", e["native"], name, {"o": e["o"]}, body)
            add_test(name, body)
            continue
        if not trig:
            if inferred:
                call = f"t::connect({tag}, {rs_str(e['name'])})"
                fact(e["class"], "events", e["native"], name, {"o": e["o"]}, call, strength="connect")
                add_row(name, call)
            continue
        lines = [f"    let mut h = Harness::new();\n    let w = h.create({tag});\n"]
        if trig == "mount":
            if k["el"].get("lifetime") == "toplevel":
                m.unusable(e["class"], "events", e["native"], f"{e['file']}: event {e['native']}: a toplevel cannot be mounted")
                continue
            lines.append(f"    h.listen(w, {rs_str(e['name'])}, true).unwrap();\n"
                         "    let win = h.create(\"window\");\n    h.insert(win, w, None, None).unwrap();\n"
                         "    h.call(win, \"activate\", &[]).unwrap();\n    h.pump(300);\n"
                         f"    assert!(h.events(w, {rs_str(e['name'])}) >= 1, \"raised when mounted in an activated window\");\n")
            body = "".join(lines)
            fact(e["class"], "events", e["native"], name, {"o": e["o"]}, body)
            add_test(name, body)
            continue
        if k["el"].get("lifetime") != "toplevel":
            lines.append("    let win = h.create(\"window\");\n    h.insert(win, w, None, None).unwrap();\n"
                         "    h.call(win, \"activate\", &[]).unwrap();\n    h.pump(100);\n")
        if trig.startswith("set:"):
            prop, val = trig[4:].split("=", 1)
            p = next((x for x in m.props if x["native"] == prop and x["class"] in k["chain"]), None)
            if p is None:
                m.unusable(e["class"], "events", e["native"], f"{e['file']}: event {e['native']}: trigger prop {prop} is not exposed")
                continue
            pre = {"true": True, "false": False}.get(val, val)
            if pre is False:
                lines.append(f"    h.set(w, {rs_str(p['name'])}, Value::Bool(true)).unwrap();\n    h.pump(50);\n")
        lines.append(f"    h.listen(w, {rs_str(e['name'])}, true).unwrap();\n")
        res = e["o"].get("result")
        if res:
            lines.append("    h.reply(Reply::Bool(true));\n")
        if trig == "invoke":
            lines.append("    h.invoke(w).unwrap();\n")
        else:
            v = {"true": True, "false": False}.get(val, val)
            if p["ty"]["t"] == "F64":
                v = float(val)
            lines.append(f"    h.set(w, {rs_str(p['name'])}, {test_value(p, v)}).unwrap();\n")
        lines.append("    h.pump(200);\n")
        if inferred:
            lines.append(f"    assert!(h.events(w, {rs_str(e['name'])}) >= 1, \"event delivered\");\n")
        else:
            lines.append(f"    assert_eq!(h.events(w, {rs_str(e['name'])}), 1, \"event delivered once\");\n")
        if e["payload"]:
            lines.append(f"    assert_eq!(h.last_args(w, {rs_str(e['name'])}).len(), {len(e['payload'])}, \"payload arity\");\n")
        if res and trig.startswith("set:Text"):
            lines.append(f"    assert_ne!(h.get(w, \"text\").unwrap(), Value::Str({rs_str(trig.split('=', 1)[1])}.into()), \"{res['prop']} = true vetoes the change\");\n")
        body = "".join(lines)
        fact(e["class"], "events", e["native"], name, {"o": e["o"]}, body)
        add_test(name, body)
    for mt in m.methods:
        k = first_kind(m, mt["class"])
        name = f"method_{snake(k['tag'])}_{snake(mt['native'])}"
        if mt["o"].get("check"):
            # A hand-written check in crates/svelters-winui/src/testing.rs (async natives, dialogs).
            call = f"t::{mt['o']['check']}()"
            fact(mt["class"], "methods", mt["native"], name, {"o": mt["o"]}, [call, OBSERVE_FN_VERSION])
            add_row(name, call)
            continue
        args = mt["o"].get("args")
        if mt["origin"] != "inferred" and args is None:
            continue
        if mt["params"] and args is None:
            m.unusable(mt["class"], "methods", mt["native"], f"{mt['file']}: method {mt['native']}: no generated test for arguments")
            continue
        if args is not None:
            if len(args) != len(mt["params"]):
                m.unusable(mt["class"], "methods", mt["native"], f"{mt['file']}: method {mt['native']}: {len(args)} test arguments for {len(mt['params'])} parameters")
                continue
            argv = ", ".join(test_value(p, v) for p, v in zip(mt["params"], args))
            call = f"t::call_args({rs_str(k['tag'])}, {rs_str(mt['name'])}, &[{argv}])"
        else:
            call = f"t::call0({rs_str(k['tag'])}, {rs_str(mt['name'])})"
        fact(mt["class"], "methods", mt["native"], name, {"o": mt["o"], "ret": stable(mt["ret"])}, call)
        add_row(name, call)
    # A generic binding is verified by its change event's test (the notify test writes the prop and sees the callback).
    for cls, ov in sorted(m.ovr.items(), key=lambda kv: short(kv[0])):
        chain = [cls] + m.classes[cls]["bases"]
        for b in ov.get("bindings", []):
            sig = (b.get("change") or {}).get("signal", "")
            hit = next((notify_test[(c, sig)] for c in chain if (c, sig) in notify_test), None)
            if hit is None:
                continue                 # an event-driven binding (manual): covered by its event's own test, if any
            fact(cls, "bindings", b["name"], hit[0], {"o": b}, hit[1])
    # Observe facts (milestone R4, REACTIVITY.md 4.5): one row per exposed prop with a fact, through the real
    # ABI v2.6 path (`observe` -> DP callback / event -> host.prop_changed). Facts of props the backend does not
    # expose have no row (no prop id to observe): they stay inferred, without a test.
    fires_rs = {"on_change": "OnChange", "on_set": "OnSet"}
    for p in m.props:
        rec = p.get("obs")
        if rec is None:
            continue
        k = first_kind(m, p["class"])
        tag = rs_str(k["tag"])
        name = f"observe_{snake(k['tag'])}_{snake(p['native'])}"
        verify = rec.get("verify") or {}
        vals = test_values(p)
        if rec["class"] in ("none", "set_only"):
            check, strength = "t::ObsCheck::Unsupported", "unsupported"
        elif rec["class"] == "constant":
            check, strength = "t::ObsCheck::Refused", "refused"
        elif not p["obs_mechs"]:
            continue                 # no mechanism the winmd backs: answered unsupported, no row
        elif verify.get("check") == "cross":
            check, strength = f"t::ObsCheck::Cross(t::Trig::{verify['trigger'].replace('-', '_').title().replace('_', '')})", "change"
        elif p["write"] and vals and p["ty"]["t"] != "Custom":
            check = f"t::ObsCheck::Change(vec![{', '.join(test_value(p, v) for v in vals)}])"
            strength = "change"
        else:
            check, strength = "t::ObsCheck::Connect", "connect"
        fires = f"t::Fires::{fires_rs.get(rec.get('fires'), 'Any')}"
        call = f"t::observe({tag}, {rs_str(p['name'])}, {check}, {fires})"
        record = {k2: v2 for k2, v2 in rec.items() if k2 not in ("layer", "record_fp")}
        f = {"fact": rec["fact"], "kind": m.owner_key(p["class"]), "section": "observe", "name": p["native"], "origin": rec["layer"],
             "tests": [name], "fingerprint": svmeta.fingerprint({"record": record, "test": [call, OBSERVE_FN_VERSION]}),
             "strength": strength}
        if rec["layer"] == "inferred":
            f["record_fp"] = rec["record_fp"]
        m.facts.append(f)
        add_row(name, call)
    for name, body in tests:
        o.append(f"pub fn {name}() {{\n{body}}}\n\n")
    o.append("pub static TESTS: &[(&str, fn())] = &[\n" + "".join(f"    ({rs_str(n)}, {n}),\n" for n, _ in tests)
             + "".join(f"    ({rs_str(n)}, || {call}),\n" for n, call in rows) + "];\n}\n\n")
    o.append("fn main() {\n    // Lists and runs nothing off Windows, so cargo test and nextest see an empty target.\n"
             "    #[cfg(windows)]\n    let tests = tests::TESTS;\n    #[cfg(not(windows))]\n    let tests: &[(&str, fn())] = &[];\n"
             "    std::process::exit(svelters_winui::harness::main(tests));\n}\n")
    return "".join(o)

def toolkit_version(m: Model) -> str:
    """The WinUI package the metadata was ingested from (`microsoft.windowsappsdk.winui 2.3.9` -> 2.3.9): the
    version the ledger records results for."""
    return next(iter(m.classes.values()))["source"]["package"].rsplit(" ", 1)[1]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the checked-in outputs are stale")
    a = ap.parse_args()
    try:
        m = Model()
        outs = {OUT_NAMES: gen_names(m), OUT_DISPATCH: gen_dispatch(m), OUT_FILTER: gen_filter(m), OUT_TESTS: gen_tests(m)}
        outs[OUT_FACTS] = json.dumps({"toolkit": "winui", "version": toolkit_version(m),
                                      "facts": sorted(m.facts, key=lambda f: f["fact"]),
                                      "untestable": sorted(m.untestable, key=lambda f: f["fact"])},
                                     indent=1, sort_keys=True) + "\n"
    except GenError as e:
        print(f"gen_backend: {e}", file=sys.stderr)
        return 1
    stale = [p for p, text in outs.items() if not p.exists() or p.read_text() != text]
    if a.check:
        for p in stale:
            print(f"gen_backend: {p.relative_to(ROOT)} is stale", file=sys.stderr)
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(outs[p])
    print(f"gen_backend: {len(m.kinds)} kinds, {len(m.props)} props, {len(m.events)} events, {len(m.slots)} slots, "
          f"{len(m.attrs)} attrs, {len(m.methods)} methods, {len(m.facts)} facts "
          f"({sum(1 for f in m.facts if f['origin'] == 'inferred')} inferred, {len(m.untestable)} untestable); {len(stale)} files written")
    return 0


