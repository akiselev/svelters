def ty_rs(ty: dict) -> str:
    t = ty["t"]
    if t in ("Enum", "Icon"):
        return f"Ty::{t}({ty['index']})"
    return f"Ty::{t}"


def gen_names(m: Model) -> str:
    o = [HEADER, "//! Platform-neutral tables: kinds, props, events, slots, attributes, methods, enums. Ids are index + 1.\n\n",
         "use crate::table::*;\n\n"]
    o.append("pub static CLASSES: &[&str] = &[\n" + "".join(f"    {rs_str(c)},\n" for c in m.class_names) + "];\n\n")
    o.append("pub static KINDS: &[Kind] = &[\n")
    for k in m.kinds:
        chain = ", ".join(str(m.class_index[c]) for c in k["chain"] if c in m.class_index)
        tc = m.kind_text_content(k)
        o.append(f"    Kind {{ tag: {rs_str(k['tag'])}, native: {rs_str(k['class'])}, chain: &[{chain}], "
                 f"toplevel: {'true' if k['el'].get('lifetime') == 'toplevel' else 'false'}, "
                 f"text_content: {('Some(' + rs_str(tc) + ')') if tc else 'None'}, default_slot: {m.kind_default_slot(k)} }},\n")
    o.append("];\n\n")
    o.append("pub static PROPS: &[Prop] = &[\n")
    for p in m.props:
        o.append(f"    Prop {{ name: {rs_str(p['name'])}, native: {rs_str(p['native'])}, class: {p['ci']}, ty: {ty_rs(p['ty'])}, "
                 f"read: {str(p['read']).lower()}, write: {str(p['write']).lower()} }},\n")
    o.append("];\n\n")
    obs_class = {None: "Unknown", "constant": "Constant", "set_only": "SetOnly", "exact": "Exact", "partial": "Partial", "none": "None"}
    o.append("/// ABI v2.6 observe facts, parallel to PROPS (metadata/observe/winui.json).\n")
    o.append("pub static OBSERVE: &[Observe] = &[\n")
    for p in m.props:
        rec = p.get("obs") or {}
        o.append(f"    Observe {{ class: ObsClass::{obs_class[rec.get('class')]}, "
                 f"proportional: {str(rec.get('value_cost') == 'proportional').lower()} }},\n")
    o.append("];\n\n")
    o.append("pub static EVENTS: &[Event] = &[\n")
    for e in m.events:
        payload = ", ".join(rs_str(x["name"]) for x in e["payload"])
        o.append(f"    Event {{ name: {rs_str(e['name'])}, native: {rs_str(e['native'])}, class: {e['ci']}, "
                 f"sync: {str(bool(e['o'].get('sync'))).lower()}, close: {str(bool(e['o'].get('close'))).lower()}, "
                 f"notify: {str(e['notify']).lower()}, payload: &[{payload}] }},\n")
    o.append("];\n\n")
    o.append("pub static SLOTS: &[Slot] = &[\n")
    for s in m.slots:
        o.append(f"    Slot {{ name: {rs_str(s['name'])}, native: {rs_str(s['native'])}, class: {s['ci']}, many: {str(s['many']).lower()}, "
                 f"default: {str(s['default']).lower()} }},\n")
    o.append("];\n\n")
    o.append("pub static ATTRS: &[Attr] = &[\n")
    for a in m.attrs:
        o.append(f"    Attr {{ name: {rs_str(a['name'])}, native: {rs_str(a['native'])}, owner: {a['ci']}, slot: {a['slot'] + 1}, "
                 f"ty: {ty_rs(a['ty'])}, default: {float(a['default'])!r} }},\n")
    o.append("];\n\n")
    o.append("pub static METHODS: &[Method] = &[\n")
    for mt in m.methods:
        params = ", ".join(f"({rs_str(p['name'])}, {ty_rs(p['ty'])})" for p in mt["params"])
        ret = f"Some({ty_rs(mt['ret'])})" if mt["ret"] else "None"
        o.append(f"    Method {{ name: {rs_str(mt['name'])}, native: {rs_str(mt['native'])}, class: {mt['ci']}, params: &[{params}], ret: {ret} }},\n")
    o.append("];\n\n")
    o.append("pub static ENUMS: &[Enum] = &[\n")
    for en in m.enums:
        t = m.types.get(en)
        if not t or t["category"] != "enum":
            raise GenError(f"enum {en} missing from metadata/winui/_types.json")
        members = ", ".join(f"({rs_str(n)}, {v})" for n, v in t["members"])
        o.append(f"    Enum {{ native: {rs_str(en)}, members: &[{members}] }},\n")
    o.append("];\n")
    return "".join(o)


# ---- dispatch.rs ----------------------------------------------------------------------------------

# Wire types converted by one conv.rs function pair `<fn>(v) -> R<T>` / `<fn>_value(T) -> Value` (value types) or
# `<fn>(v) -> R<Option<T>>` / `<fn>_value(Option<IInspectable>) -> Value` (object types, null clears).
VALUE_CONV = {"F32": "f32_", "CornerRadius": "corner_radius", "Color": "color", "FontWeight": "font_weight",
              "DateTime": "datetime", "TimeSpan": "timespan"}
OBJECT_CONV = {"Brush": "brush", "SolidBrush": "solid_brush", "FontFamily": "font_family", "Uri": "uri",
               "ImageSource": "image_source"}
NULLABLE_OF = {"NullableF64": "f64_", "NullableDateTime": "datetime", "NullableTimeSpan": "timespan", "NullableColor": "color"}


def setter_expr(ty: dict, var: str = "v") -> str:
    """Rust expression converting the svl Value `v` into the native setter argument (or `?`-able result)."""
    t = ty["t"]
    if t in VALUE_CONV:
        return f"conv::{VALUE_CONV[t]}({var})?"
    if t in OBJECT_CONV:
        return f"conv::{OBJECT_CONV[t]}({var})?.as_ref()"
    if t == "Icon":
        return f"conv::icon({var}, &ENUMS[{ty['index']}])?.as_ref()"
    if t in NULLABLE_OF:
        return f"conv::nullable({var}, conv::{NULLABLE_OF[t]})?"
    if t == "Str":
        return f"&conv::hstring({var})?"
    if t == "Bool":
        return f"conv::bool_({var})?"
    if t == "I32":
        return f"conv::i32_({var})?"
    if t == "F64":
        return f"conv::f64_({var})?"
    if t == "Enum":
        return f"{rs_path(ty['enum'])}(conv::enum_({var}, &ENUMS[{ty['index']}])?)"
    if t == "Thickness":
        return f"conv::thickness({var})?"
    if t == "NullableBool":
        return f"conv::nullable_bool({var})?"
    if t == "ObjectString":
        return f"conv::boxed_str({var})?.as_ref()"
    raise GenError(f"no setter conversion for {t}")


def getter_expr(ty: dict, call: str) -> str:
    t = ty["t"]
    if t == "F32":
        return f"Value::F64({call}.map_err(conv::err)? as f64)"
    if t in VALUE_CONV:
        return f"conv::{VALUE_CONV[t]}_value({call}.map_err(conv::err)?)"
    if t in OBJECT_CONV:
        return f"conv::{OBJECT_CONV[t]}_value({call}.ok().map(Into::into))"
    if t == "Icon":
        return f"conv::icon_value({call}.ok().map(Into::into), &ENUMS[{ty['index']}])"
    if t in NULLABLE_OF:
        val = "Value::F64" if t == "NullableF64" else f"conv::{NULLABLE_OF[t]}_value"
        return f"{call}.ok().map_or(Value::Null, {val})"
    if t == "Str":
        return f"Value::Str({call}.map_err(conv::err)?.to_string_lossy())"
    if t == "Bool":
        return f"Value::Bool({call}.map_err(conv::err)?)"
    if t == "I32":
        return f"Value::I64({call}.map_err(conv::err)? as i64)"
    if t == "F64":
        return f"Value::F64({call}.map_err(conv::err)?)"
    if t == "Enum":
        return f"conv::enum_name(&ENUMS[{ty['index']}], {call}.map_err(conv::err)?.0)"
    if t == "Thickness":
        return f"conv::thickness_value({call}.map_err(conv::err)?)"
    if t == "NullableBool":
        return f"conv::nullable_bool_value({call}.ok())"
    if t == "ObjectString":
        return f"conv::unboxed_value({call}.ok())"
    raise GenError(f"no getter conversion for {t}")


def payload_expr(item: dict, m: Model) -> str:
    ref = item["ref"]
    src = "a" if item["from"] == "args" else "s"
    call = f"{src}.{item['prop']}()"
    if ref == "string":
        return f"{call}.map(|x| Value::Str(x.to_string_lossy())).unwrap_or(Value::Null)"
    if ref == "f64":
        return f"{call}.map(Value::F64).unwrap_or(Value::Null)"
    if ref == "bool":
        return f"{call}.map(Value::Bool).unwrap_or(Value::Null)"
    if ref in ("i32", "u32"):
        return f"{call}.map(|x| Value::I64(x as i64)).unwrap_or(Value::Null)"
    if ref.startswith("enum<"):
        return f"{call}.map(|x| Value::I64(x.0 as i64)).unwrap_or(Value::Null)"
    if ref in VALUE_TYPES and VALUE_TYPES[ref] in VALUE_CONV:
        return f"{call}.map(conv::{VALUE_CONV[VALUE_TYPES[ref]]}_value).unwrap_or(Value::Null)"
    if ref in VALUE_TYPES and VALUE_TYPES[ref] in NULLABLE_OF:
        t = VALUE_TYPES[ref]
        val = "Value::F64" if t == "NullableF64" else f"conv::{NULLABLE_OF[t]}_value"
        return f"{call}.ok().map_or(Value::Null, {val})"
    raise GenError(f"payload {item['prop']}: type {ref} not supported")


def gen_dispatch(m: Model) -> str:
    o = [HEADER, "//! Typed windows-rs calls per id, parallel to the tables in names.rs (Windows only).\n\n",
         "#![allow(non_snake_case, clippy::all, unused_imports)]\n",
         "use super::names::*;\n", "use crate::conv::{self, R};\n", "use crate::custom;\n", "use crate::sink::{Registration, Sink};\n",
         "use svelters_abi::Value;\n", "use windows_core::{IInspectable, Interface};\n\n",
         "type WinResult<T> = windows_core::Result<T>;\n\n"]
    # create
    o.append("pub static CREATE: &[fn() -> WinResult<IInspectable>] = &[\n")
    for k in m.kinds:
        o.append(f"    || Ok({rs_path(k['class'])}::new()?.into()),\n")
    o.append("];\n\n")
    # props
    for i, p in enumerate(m.props):
        cls = rs_path(p["class"])
        fn = f"prop{i}_{snake(short(p['class']))}_{snake(p['native'])}"
        if p["ty"]["t"] == "Custom":
            o.append(f"fn set_{fn}(o: &IInspectable, v: &Value) -> R<()> {{\n    custom::{p['ty']['custom']}_set(&o.cast::<{cls}>().map_err(conv::err)?, v)\n}}\n")
            o.append(f"fn get_{fn}(o: &IInspectable) -> R<Value> {{\n    custom::{p['ty']['custom']}_get(&o.cast::<{cls}>().map_err(conv::err)?)\n}}\n")
            p["fn"] = fn
            continue
        if p["write"]:
            o.append(f"fn set_{fn}(o: &IInspectable, v: &Value) -> R<()> {{\n"
                     f"    o.cast::<{cls}>().map_err(conv::err)?.Set{p['native']}({setter_expr(p['ty'])}).map_err(conv::err)\n}}\n")
        if p["read"]:
            o.append(f"fn get_{fn}(o: &IInspectable) -> R<Value> {{\n"
                     f"    let t = o.cast::<{cls}>().map_err(conv::err)?;\n    Ok({getter_expr(p['ty'], 't.' + p['native'] + '()')})\n}}\n")
        p["fn"] = fn
    o.append("\npub static PROP_SET: &[Option<fn(&IInspectable, &Value) -> R<()>>] = &[\n")
    for p in m.props:
        o.append(f"    Some(set_{p['fn']}),\n" if p["write"] else "    None,\n")
    o.append("];\n\npub static PROP_GET: &[Option<fn(&IInspectable) -> R<Value>>] = &[\n")
    for p in m.props:
        o.append(f"    Some(get_{p['fn']}),\n" if p["read"] or p["ty"]["t"] == "Custom" else "    None,\n")
    o.append("];\n\n")
    # observe (ABI v2.6): every mechanism of the prop's fact, as registrations the backend keeps per (h, prop)
    for i, p in enumerate(m.props):
        if not p["obs_mechs"]:
            continue
        cls = rs_path(p["class"])
        regs = []
        for mech in p["obs_mechs"]:
            if mech["kind"] == "dp":
                regs.append(f"        crate::sink::observe_dp(o, &{cls}::{p['native']}Property()?, h, prop)?,\n")
            else:
                regs.append(f"        Registration::from(o.cast::<{rs_path(mech['owner'])}>()?.{mech['event']}(move |_s, _a| {{\n"
                            f"            crate::backend::emit_changed(h, prop);\n        }})?),\n")
        o.append(f"fn observe_{p['fn']}(o: &IInspectable, h: u64, prop: u32) -> WinResult<Vec<Registration>> {{\n"
                 f"    Ok(vec![\n{''.join(regs)}    ])\n}}\n")
    o.append("\n/// ABI v2.6 `observe`: installs every mechanism of a prop's observe fact (None: no mechanism), parallel to PROPS.\n")
    o.append("pub static OBSERVE_CONNECT: &[Option<fn(&IInspectable, u64, u32) -> WinResult<Vec<Registration>>>] = &[\n")
    for p in m.props:
        o.append(f"    Some(observe_{p['fn']}),\n" if p["obs_mechs"] else "    None,\n")
    o.append("];\n\n")
    # events
    for i, e in enumerate(m.events):
        cls = rs_path(e["class"])
        if e["notify"]:
            fn = f"event{i}_{snake(short(e['class']))}_notify_{snake(e['native'])}"
            e["fn"] = fn
            o.append(f"fn {fn}(o: &IInspectable, sink: Sink) -> WinResult<Registration> {{\n"
                     f"    crate::sink::notify(o, &{cls}::{e['native']}Property()?, sink)\n}}\n")
            continue
        fn = f"event{i}_{snake(short(e['class']))}_{snake(e['native'])}"
        e["fn"] = fn
        body = []
        needs_sender = any(x["from"] == "sender" for x in e["payload"])
        if needs_sender:
            body.append(f"        let Some(s) = s.as_ref().and_then(|s| s.cast::<{cls}>().ok()) else {{ return }};")
        needs_args = any(x["from"] == "args" for x in e["payload"]) or e["o"].get("result") or e["o"].get("close")
        if needs_args:
            body.append("        let Some(a) = a.as_ref() else { return };")
        args = ", ".join(payload_expr(x, m) for x in e["payload"])
        if e["o"].get("close"):
            body.append("        if sink.close() {\n            let _ = a.SetHandled(true);\n        }")
        elif e["o"].get("sync"):
            res = e["o"].get("result")
            body.append(f"        let reply = sink.sync(vec![{args}]);")
            if res:
                body.append(f"        if conv::is_true(&reply) {{\n            let _ = a.Set{res['prop']}(true);\n        }}")
        else:
            body.append(f"        sink.post(vec![{args}]);")
        sv = "s" if needs_sender else "_s"
        av = "a" if needs_args else "_a"
        o.append(f"fn {fn}(o: &IInspectable, sink: Sink) -> WinResult<Registration> {{\n"
                 f"    o.cast::<{cls}>()?.{e['native']}(move |{sv}, {av}| {{\n" + "\n".join(body) + "\n    }).map(Into::into)\n}\n")
    o.append("\npub static EVENT_CONNECT: &[fn(&IInspectable, Sink) -> WinResult<Registration>] = &[\n")
    for e in m.events:
        o.append(f"    {e['fn']},\n")
    o.append("];\n\n")
    # slots
    o.append("pub use crate::slots::{ManyOps, SlotOps};\n\n")
    for i, s in enumerate(m.slots):
        if not s["many"]:
            continue
        cls = rs_path(s["class"])
        elem = "IInspectable" if s["elem"] == "object" else rs_path(s["elem"])
        o.append(f"fn slot{i}_items(p: &IInspectable) -> WinResult<windows_collections::IVector<{elem}>> {{\n"
                 f"    p.cast::<{cls}>()?.{s['native']}()?.cast()\n}}\n")
    o.append("\npub static SLOT_OPS: &[SlotOps] = &[\n")
    for i, s in enumerate(m.slots):
        cls = rs_path(s["class"])
        if s["many"]:
            elem = "IInspectable" if s["elem"] == "object" else rs_path(s["elem"])
            o.append(f"    crate::slots::many_ops!(slot{i}_items, {elem}),\n")
        elif s["elem"] == "object":
            o.append(f"    SlotOps::Single {{\n        set: |p, c| p.cast::<{cls}>()?.Set{s['native']}(c),\n"
                     f"        get: |p| p.cast::<{cls}>().ok()?.{s['native']}().ok(),\n    }},\n")
        else:
            o.append(f"    SlotOps::Single {{\n        set: |p, c| {{\n"
                     f"            let c = c.map(|c| c.cast::<{rs_path(s['elem'])}>()).transpose()?;\n"
                     f"            p.cast::<{cls}>()?.Set{s['native']}(c.as_ref())\n        }},\n"
                     f"        get: |p| p.cast::<{cls}>().ok()?.{s['native']}().ok().and_then(|c| c.cast::<IInspectable>().ok()),\n    }},\n")
    o.append("];\n\n")
    # attrs (Grid.Row: i32, Canvas.Left: f64)
    o.append("pub static ATTR_SET: &[fn(&IInspectable, &Value) -> R<()>] = &[\n")
    for a in m.attrs:
        target = a["target"][len("object<"):-1]
        conv_fn = "i32_" if a["ty"]["t"] == "I32" else "f64_"
        o.append(f"    |c, v| {rs_path(a['class'])}::Set{a['native']}(&c.cast::<{rs_path(target)}>().map_err(conv::err)?, conv::{conv_fn}(v)?).map_err(conv::err),\n")
    o.append("];\n\npub static ATTR_GET: &[fn(&IInspectable) -> R<Value>] = &[\n")
    for a in m.attrs:
        target = a["target"][len("object<"):-1]
        wrap = ("Value::I64(", " as i64)") if a["ty"]["t"] == "I32" else ("Value::F64(", ")")
        o.append(f"    |c| Ok({wrap[0]}{rs_path(a['class'])}::Get{a['native']}(&c.cast::<{rs_path(target)}>().map_err(conv::err)?).map_err(conv::err)?{wrap[1]}),\n")
    o.append("];\n\n")
    # methods
    for i, mt in enumerate(m.methods):
        cls = rs_path(mt["class"])
        fn = f"method{i}_{snake(short(mt['class']))}_{snake(mt['native'])}"
        mt["fn"] = fn
        if mt["o"].get("custom"):
            o.append(f"fn {fn}(o: &IInspectable, args: &[Value]) -> R<Value> {{\n"
                     f"    custom::{mt['o']['custom']}(&o.cast::<{cls}>().map_err(conv::err)?, args)\n}}\n")
            continue
        argv = []
        for j, p in enumerate(mt["params"]):
            argv.append(setter_expr(p["ty"], f"conv::arg(args, {j})?"))
        call = f"t.{mt['native']}({', '.join(argv)})"
        ret = "Ok(Value::Null)" if not mt["ret"] else f"Ok({getter_expr(mt['ret'], call)})"
        stmt = f"    {call}.map_err(conv::err)?;\n    Ok(Value::Null)" if not mt["ret"] else f"    {ret}"
        o.append(f"fn {fn}(o: &IInspectable, args: &[Value]) -> R<Value> {{\n"
                 f"    conv::arity(args, {len(mt['params'])})?;\n    let t = o.cast::<{cls}>().map_err(conv::err)?;\n{stmt}\n}}\n")
    o.append("\npub static METHOD_CALL: &[fn(&IInspectable, &[Value]) -> R<Value>] = &[\n")
    for mt in m.methods:
        o.append(f"    {mt['fn']},\n")
    o.append("];\n")
    return "".join(o)


# ---- bindgen filter -------------------------------------------------------------------------------

def gen_filter(m: Model) -> str:
    members: dict[str, set[str]] = {}

    def add(cls: str, *names: str) -> None:
        members.setdefault(cls, set()).update(names)

    for k in m.kinds:
        ctor = m.classes[k["class"]]["constructors"][0]["id"]
        add(k["class"], "CreateInstance") if ctor == "ctor:composable" else add(k["class"])
        for c in k["chain"]:
            add(c)
    for p in m.props:
        if p["ty"]["t"] == "Custom":
            add(p["class"], f"get_{p['native']}")
            continue
        if p["read"]:
            add(p["class"], f"get_{p['native']}")
        if p["write"]:
            add(p["class"], f"put_{p['native']}")
    delegates = set()
    for e in m.events:
        if e["notify"]:
            # The DependencyProperty identifier (a static getter) and the callback API (sink.rs).
            add(e["class"], f"get_{e['native']}Property")
            add("Microsoft.UI.Xaml.DependencyObject", "RegisterPropertyChangedCallback", "UnregisterPropertyChangedCallback")
            add("Microsoft.UI.Xaml.DependencyProperty")
            delegates.add("Microsoft.UI.Xaml.DependencyPropertyChangedCallback")
            continue
        add(e["class"], f"add_{e['native']}", f"remove_{e['native']}")
        # The typed event wrappers construct the delegate (`KeyEventHandler::new`), which bindgen only
        # emits for delegates the filter selects.
        delegates.add(e["delegate"].split("<", 1)[0])
        args = e["args"]
        for x in e["payload"]:
            if x["from"] == "args":
                add(args, f"get_{x['prop']}")
            else:
                add(e["class"], f"get_{x['prop']}")
        res = e["o"].get("result")
        if res:
            add(args, f"get_{res['prop']}", f"put_{res['prop']}")
        if e["o"].get("close"):
            add(args, "get_Handled", "put_Handled")
        if "." in args:          # not `object` (EventHandler<object>)
            add(args)
    for p in m.props:
        for mech in p["obs_mechs"]:
            if mech["kind"] == "dp":
                add(p["class"], f"get_{p['native']}Property")
                add("Microsoft.UI.Xaml.DependencyObject", "RegisterPropertyChangedCallback", "UnregisterPropertyChangedCallback")
                add("Microsoft.UI.Xaml.DependencyProperty")
                delegates.add("Microsoft.UI.Xaml.DependencyPropertyChangedCallback")
            else:
                add(mech["owner"], f"add_{mech['event']}", f"remove_{mech['event']}")
                delegates.add(mech["delegate"].split("<", 1)[0])
                if "." in mech["args"]:
                    add(mech["args"])
    for s in m.slots:
        add(s["class"], f"get_{s['native']}") if s["many"] else add(s["class"], f"get_{s['native']}", f"put_{s['native']}")
        if s["elem"] != "object":
            add(s["elem"])
        native = next(p["type"]["native"] for p in m.classes[s["class"]]["properties"] if p["name"] == s["native"])
        if s["many"] and "<" not in native:
            add(native)          # ItemCollection, UIElementCollection: the collection class itself
    for a in m.attrs:
        add(a["class"], f"Get{a['native']}", f"Set{a['native']}")
    for mt in m.methods:
        if not mt["o"].get("custom"):     # custom.rs calls it through the vtable (async natives need windows-future)
            add(mt["class"], mt["native"])
    lines = []
    for cls in sorted(members):
        names = sorted(members[cls])
        lines.append(f"{cls}::{{{', '.join(names)}}}\n")
    lines += [f"{e}\n" for e in sorted(m.enums)]
    lines += [f"{d}\n" for d in sorted(delegates)]
    return ("# @generated by tools/metadata/winui/gen_backend.py: windows-bindgen member filter for src/bindings.rs.\n"
            "# Kinds, props, events, slots, attrs and methods from the overrides:\n" + "".join(lines) +
            "# Runtime (backend.rs, app.rs, conv.rs, custom.rs, testing.rs):\n" + RUNTIME_FILTER)


