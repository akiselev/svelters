class GenError(Exception):
    pass


def kebab(name: str) -> str:
    """Native PascalCase -> kebab-case: StackPanel -> stack-panel, IsChecked -> is-checked (tools/metadata/common/naming.py)."""
    return naming.kebab(name)


def snake(name: str) -> str:
    return kebab(name).replace("-", "_")


def rs_path(full: str) -> str:
    return "crate::bindings::" + full.replace(".", "::")


def short(full: str) -> str:
    return full.rsplit(".", 1)[1]


def rs_str(s: str) -> str:
    return json.dumps(s)


class Model:
    def __init__(self) -> None:
        self.classes: dict[str, dict] = {}
        for p in sorted(META.glob("*.json")):
            if p.name.startswith("_"):
                continue
            k = svmeta.load_json(p)
            self.classes[k["native"]["name"]] = k
        self.types = svmeta.load_json(META / "_types.json")["types"]
        self.layers = winui_layers.Layers()
        self.ovr: dict[str, dict] = {}
        self.ovr_file: dict[str, str] = dict(self.layers.files)
        errs = []
        for p in self.layers.paths + self.layers.inferred_paths:
            errs += svmeta.check_override(p, SCHEMA)
        for cls, o in self.layers.merged.items():
            if cls not in self.classes:
                errs.append(f"{self.ovr_file[cls]}: class {cls} is not in metadata/winui (run ingest.py)")
                continue
            self.ovr[cls] = o
        if errs:
            raise GenError("\n".join(errs))
        # Inferred facts the generator cannot use or test: left out of the tables, the ledger parks them.
        self.untestable: list[dict] = []
        # Class table: every class in some kind's chain, in a stable order.
        self.kinds = []
        for cls in sorted(self.ovr, key=short):
            el = self.ovr[cls].get("element")
            if el is None:
                continue
            k = self.classes[cls]
            if k["abstract"]:
                raise GenError(f"{self.ovr_file[cls]}: {cls} is not constructible (winmd), it cannot be an element")
            tag = el.get("tag", naming.tag_for("winui", cls))
            if tag != naming.tag_for("winui", cls) and not el.get("tag_reason"):
                raise GenError(f"{self.ovr_file[cls]}: tag {tag!r} breaks the naming rule ({naming.tag_for('winui', cls)!r}) without tag_reason")
            self.kinds.append({"class": cls, "tag": tag, "chain": [cls] + k["bases"], "el": el})
        names = sorted({c for k in self.kinds for c in k["chain"]}, key=short)
        self.class_index = {c: i for i, c in enumerate(names)}
        self.class_names = names
        self.enums: list[str] = []
        self.props, self.events, self.slots, self.attrs, self.methods = [], [], [], [], []
        for cls in sorted(self.ovr, key=short):
            if cls not in self.class_index:
                raise GenError(f"{self.ovr_file[cls]}: {cls} is in no element kind's base chain")
            self._class(cls)
        # An attribute belongs to a slot that its owner class declares or inherits (Grid.Row -> Panel.children).
        for a in self.attrs:
            chain = [a["class"]] + self.classes[a["class"]]["bases"]
            cands = [i for i, s in enumerate(self.slots) if s["name"] == a["slot_name"] and s["class"] in chain]
            if not cands:
                raise GenError(f"{a['file']}: attached {a['native']}: no slot {a['slot_name']} in the chain of {a['class']}")
            a["slot"] = cands[0]
        self._bindings()
        self._observe()
        self.facts: list[dict] = []

    def owner_key(self, cls: str) -> str:
        """`Microsoft.UI.Xaml.Controls:TextBox`: the owner key of the observe facts."""
        return ":".join(self.classes[cls]["id"].rsplit(":", 2)[-2:])

    def _observe(self) -> None:
        """ABI v2.6 `observe` (milestone R4): the observe fact of every exposed prop (metadata/observe/winui.json, the
        same owner class) and the mechanisms the backend installs for it: `notify` -> the DependencyProperty change
        callback (`<Prop>Property`), `event` -> the event on the prop's class, a base, or the nearest derived class
        that declares it (UIElement.ActualSize -> FrameworkElement.SizeChanged). A mechanism the winmd cannot back
        is left out; a fact with none left is answered SVL_OBSERVE_UNSUPPORTED and gets no row."""
        doc = svmeta.load_json(ROOT / "metadata/observe/winui.json")["facts"]
        for p in self.props:
            rec = (doc.get(self.owner_key(p["class"])) or {}).get(p["native"])
            p["obs"] = rec
            p["obs_mechs"] = []
            if rec is None:
                continue
            k = self.classes[p["class"]]
            for v in rec.get("via", []):
                if v["mechanism"] == "notify":
                    if p["dp"] and f"{p['native']}Property" in set(k.get("dependency_properties", [])):
                        p["obs_mechs"].append({"kind": "dp"})
                elif v["mechanism"] == "event":
                    for ev in v["events"]:
                        hit = self.event_owner(p["class"], ev)
                        if hit:
                            p["obs_mechs"].append({"kind": "event", "event": ev, **hit})

    def event_owner(self, cls: str, event: str) -> dict | None:
        """The class declaring `event` for an instance of `cls`: the class or a base, else the nearest derived class."""
        derived = sorted((c for c, k in self.classes.items() if cls in k["bases"]), key=lambda c: len(self.classes[c]["bases"]))
        for c in [cls] + self.classes[cls]["bases"] + derived:
            for s in self.classes.get(c, {}).get("signals", []):
                if s["name"] == event:
                    return {"owner": c, "delegate": s["delegate"], "args": s["args"]}
        return None

    def origin(self, cls: str, sec: str, name: str) -> str:
        return self.layers.origin(cls, sec, name)

    def fact_id(self, cls: str, sec: str, name: str) -> str:
        return f"{self.classes[cls]['id']}:{SINGULAR[sec]}:{name}"

    def unusable(self, cls: str, sec: str, name: str, why: str) -> None:
        """An inferred fact the generator cannot use: left out (the ledger parks it). A manual one is an error."""
        if self.origin(cls, sec, name) != "inferred":
            raise GenError(why)
        self.untestable.append({"fact": self.fact_id(cls, sec, name), "kind": short(cls), "section": sec, "name": name,
                                "record_fp": self.layers.record_fp(cls, sec, name), "message": f"generator: {why}"})

    def _bindings(self) -> None:
        """Drop inferred bindings whose property or change event is not in the tables (parked or unusable)."""
        for cls, o in self.ovr.items():
            keep = []
            chain = [cls] + self.classes[cls]["bases"]
            for b in o.get("bindings", []):
                sig = (b.get("change") or {}).get("signal")
                if not any(p["name"] == b["property"] and p["class"] in chain for p in self.props):
                    self.unusable(cls, "bindings", b["name"], f"{self.ovr_file[cls]}: bind:{b['name']}: property {b['property']} is not exposed")
                elif sig and not any(e["name"] == sig and e["class"] in chain for e in self.events):
                    self.unusable(cls, "bindings", b["name"], f"{self.ovr_file[cls]}: bind:{b['name']}: event {sig} is not exposed")
                else:
                    keep.append(b)
            if keep:
                o["bindings"] = keep
            else:
                o.pop("bindings", None)

    def enum_index(self, full: str) -> int:
        if full not in self.enums:
            self.enums.append(full)
        return self.enums.index(full)

    def ty_of(self, where: str, ref: str, o: dict) -> dict:
        """Wire type of a native type ref, honouring `as`/`custom`."""
        if o.get("custom"):
            return {"t": "Custom", "custom": o["custom"]}
        if o.get("as") == "string":
            if ref != "variant":
                raise GenError(f"{where}: `as: string` only applies to object-typed props, not {ref}")
            return {"t": "ObjectString"}
        if ref in PRIM:
            return {"t": PRIM[ref]}
        m = re.fullmatch(r"enum<(.+)>", ref)
        if m:
            return {"t": "Enum", "enum": m.group(1)}
        if ref in VALUE_TYPES:
            if VALUE_TYPES[ref] == "Icon":
                return {"t": "Icon", "enum": SYMBOL_ENUM}
            return {"t": VALUE_TYPES[ref]}
        raise GenError(f"{where}: native type {ref} has no conversion (add one to conv.rs and gen_backend.py, or use `custom`)")

    def _class(self, cls: str) -> None:
        o, k, f = self.ovr[cls], self.classes[cls], self.ovr_file[cls]
        ci = self.class_index[cls]
        nprops = {p["name"]: p for p in k["properties"]}
        for p in o.get("props", []):
            where = f"{f}: prop {p['name']}"
            try:
                np = nprops.get(p["name"])
                if np is None:
                    raise GenError(f"{where}: no such property on {cls} (winmd)")
                ty = self.ty_of(where, np["type"]["ref"], p)
                custom = ty["t"] == "Custom"
                read = np["access"]["read"]
                write = np["access"]["write"] or custom
                if "test" in p and not write:
                    raise GenError(f"{where}: read-only property has a test value")
            except GenError as ex:
                self.unusable(cls, "props", p["name"], str(ex))
                continue
            if ty.get("enum"):
                ty["index"] = self.enum_index(ty["enum"])
            self.props.append({"name": kebab(p["name"]), "native": p["name"], "class": cls, "ci": ci, "ty": ty,
                               "read": read, "write": write, "dp": bool(np.get("dependency_property")), "o": p, "file": f,
                               "origin": self.origin(cls, "props", p["name"])})
        nsigs = {s["name"]: s for s in k["signals"]}
        for e in o.get("events", []):
            where = f"{f}: event {e['name']}"
            try:
                ns = nsigs.get(e["name"])
                if ns is None:
                    raise GenError(f"{where}: no such event on {cls} (winmd)")
                args_props = {p["name"]: p for p in ns["args_props"]}
                payload = []
                for item in e.get("payload", []):
                    if item["from"] == "args":
                        ap = args_props.get(item["prop"])
                        if ap is None:
                            raise GenError(f"{where}: {ns['args']} has no property {item['prop']}")
                        tref = ap["type"]["ref"]
                    else:
                        tref = self.prop_type_in_chain(cls, item["prop"], where)
                    payload.append({**item, "ref": tref})
                result = e.get("result")
                if result:
                    ap = args_props.get(result["prop"])
                    if ap is None or not ap["settable"]:
                        raise GenError(f"{where}: result prop {result['prop']} is not a settable property of {ns['args']} (winmd)")
                    if not e.get("sync"):
                        raise GenError(f"{where}: an event with a result must be sync")
                if e.get("close") and not args_props.get("Handled", {}).get("settable"):
                    raise GenError(f"{where}: close events need a settable Handled on their args")
            except GenError as ex:
                self.unusable(cls, "events", e["name"], str(ex))
                continue
            self.events.append({"name": kebab(e["name"]), "native": e["name"], "class": cls, "ci": ci, "o": e, "file": f,
                                "args": ns["args"], "sender": ns["sender"], "delegate": ns["delegate"], "payload": payload,
                                "notify": False, "section": "events", "origin": self.origin(cls, "events", e["name"])})
        for n in o.get("notify", []):
            # `notify::<prop>`: a DependencyProperty change callback on a prop of this class exposed above.
            p = next((x for x in self.props if x["class"] == cls and x["native"] == n["name"]), None)
            dps = set(k.get("dependency_properties", []))
            where = f"{f}: notify {n['name']}"
            if p is None:
                self.unusable(cls, "notify", n["name"], f"{where}: the prop is not exposed on {cls}")
            elif not (p["dp"] and f"{n['name']}Property" in dps):
                self.unusable(cls, "notify", n["name"], f"{where}: not a DependencyProperty (winmd)")
            elif not (p["read"] and p["write"]) or p["ty"]["t"] == "Custom":
                self.unusable(cls, "notify", n["name"], f"{where}: the prop is not readable and writable")
            else:
                self.events.append({"name": f"notify::{p['name']}", "native": n["name"], "class": cls, "ci": ci, "o": n, "file": f,
                                    "args": None, "sender": None, "delegate": None, "payload": [], "notify": True, "prop": p,
                                    "section": "notify", "origin": self.origin(cls, "notify", n["name"])})
        for s in o.get("slots", []):
            where = f"{f}: slot {s['name']}"
            np = nprops.get(s["prop"])
            if np is None:
                raise GenError(f"{where}: no property {s['prop']} on {cls}")
            elem, many = self.slot_elem(where, np["type"])
            if not many and not np["access"]["write"]:
                raise GenError(f"{where}: {s['prop']} is read-only")
            self.slots.append({"name": s["name"], "native": s["prop"], "class": cls, "ci": ci, "many": many,
                               "elem": elem, "default": bool(s.get("default")), "child": s.get("child", "text-block"),
                               "o": s, "file": f})
        nattached = {a["name"]: a for a in k["attached"]}
        for a in o.get("attached", []):
            where = f"{f}: attached {a['name']}"
            na = nattached.get(a["name"])
            if na is None:
                raise GenError(f"{where}: {cls} has no static Get{a['name']}/Set{a['name']} (winmd)")
            ty = self.ty_of(where, na["type"]["ref"], {})
            if ty["t"] not in ("I32", "F64"):
                raise GenError(f"{where}: only i32 and f64 attached properties are supported so far")
            self.attrs.append({"name": kebab(a["name"]), "native": a["name"], "class": cls, "ci": ci, "slot_name": a["slot"],
                               "target": na["target"]["ref"], "default": a["default"], "ty": ty, "o": a, "file": f})
        nmeth = {}
        for m in k["methods"]:
            nmeth.setdefault(m["name"], m)
        for m in o.get("methods", []):
            where = f"{f}: method {m['name']}"
            try:
                nm = nmeth.get(m["name"])
                if nm is None:
                    raise GenError(f"{where}: no such method on {cls} (winmd)")
                if m.get("custom"):
                    # A hand-written call (custom.rs `<custom>(&Class, args) -> R<Value>`): async natives and the like.
                    params, ret = [], None
                else:
                    params = [{"name": p["name"], "ty": self.ty_of(where, p["type"]["ref"], {})} for p in nm["params"]]
                    ret = None if nm["returns"]["native"] == "void" else self.ty_of(where, nm["returns"]["ref"], {})
            except GenError as ex:
                self.unusable(cls, "methods", m["name"], str(ex))
                continue
            for ty in [p["ty"] for p in params] + ([ret] if ret else []):
                if ty.get("enum"):
                    ty["index"] = self.enum_index(ty["enum"])
            self.methods.append({"name": kebab(m["name"]), "native": m["name"], "class": cls, "ci": ci, "params": params,
                                 "ret": ret, "o": m, "file": f, "origin": self.origin(cls, "methods", m["name"])})

    # Collection classes a many-slot can hold, with their element type (the class implements IVector<T>).
    COLLECTIONS = {"Microsoft.UI.Xaml.Controls.UIElementCollection": "Microsoft.UI.Xaml.UIElement",
                   "Microsoft.UI.Xaml.Controls.ItemCollection": "object"}

    def slot_elem(self, where: str, t: dict) -> tuple[str, bool]:
        """(element type, many) of a slot property: a single child (`object`, UIElement or another class: the child is
        cast to it), or a collection (`UIElementCollection`, `ItemCollection`, `IVector<T>`, `IObservableVector<T>`) of
        elements of type T. The element type is a native class name or `object` (IInspectable)."""
        ref, native = t["ref"], t["native"]
        if ref == "variant":
            return "object", False
        m = re.fullmatch(r"object<([A-Za-z0-9_.]+)>", ref)
        if m and m.group(1) in self.COLLECTIONS:
            return self.COLLECTIONS[m.group(1)], True
        m = re.fullmatch(r"Windows\.Foundation\.Collections\.I(?:Observable)?Vector<(.+)>", native)
        if m:
            return ("object" if m.group(1) == "object" else m.group(1)), True
        m = re.fullmatch(r"object<([A-Za-z0-9_.]+)>", ref)
        if m and m.group(1).startswith(("Microsoft.UI.Xaml.", "Windows.")) and "<" not in native:
            return m.group(1), False
        raise GenError(f"{where}: a slot is an object, a class or a collection of elements, not {native}")

    def prop_type_in_chain(self, cls: str, prop: str, where: str) -> str:
        for c in [cls] + self.classes[cls]["bases"]:
            for p in self.classes.get(c, {}).get("properties", []):
                if p["name"] == prop:
                    return p["type"]["ref"]
        raise GenError(f"{where}: no property {prop} on {cls} or its bases")

    def kind_text_content(self, k: dict) -> str | None:
        tc = k["el"].get("text_prop")
        if not tc:
            return None
        for p in self.props:
            if p["native"] == tc and p["class"] in k["chain"] and p["write"]:
                return p["name"]
        raise GenError(f"<{k['tag']}>: text_prop {tc} is not an exposed writable prop of its chain")

    def kind_default_slot(self, k: dict) -> int:
        for c in k["chain"]:
            for i, s in enumerate(self.slots):
                if s["class"] == c and s["default"]:
                    return i + 1
        return 0


