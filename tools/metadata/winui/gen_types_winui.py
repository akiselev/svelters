#!/usr/bin/env python3
"""Generates the WinUI non-GUI type layer (N4) from the type facts (metadata/winui/types/*.json).

Output (deterministic, checked in):
  crates/svelters-winui/src/generated/types_tables.rs   const data the hand-written core dispatches through: kinds,
                                                        method groups, props, events, ABI types, IIDs, enums, records
  crates/svelters-winui/tests/types_verify.rs           generated ledger tests for the curated types (Windows runner)
  crates/svelters-winui/src/generated/types_facts.json  fact -> tests manifest (ledger: svelters-api:v1:type:winui:*)
  packages/types/winui/<ns>/<Class>.js, <ns>.d.ts, manifest.json, and the `./winui/*` exports of package.json
  docs/site/src/content/docs/types/winui/              a page per curated type and an index

Dispatch choice (plans/milestones/N4-winui-types.md): no per-member native code. Each member is a table row (IID
index, vtable slot, parameter types) and the core calls the slot through one dynamic invoker, so the generated Rust is
data only (section 2.4) and the leaf crate's compile time does not grow with the bound scope.

  python3 tools/metadata/winui/gen_types_winui.py --write
  python3 tools/metadata/winui/gen_types_winui.py --check
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "tools/metadata/common"))
import types_winui_classify as C  # noqa: E402

CRATE = ROOT / "crates/svelters-winui"
TABLES = CRATE / "src/generated/types_tables.rs"
RS_HEADER = "// @generated by tools/metadata/winui/gen_types_winui.py from metadata/winui/types. Do not edit.\n"

IACTIVATION_FACTORY = "00000035-0000-0000-c000-000000000046"
ROOT_KIND = "Windows.Foundation.IInspectable"

PRIM_TY = {"bool": "Bool", "char16": "Char16", "i8": "I8", "u8": "U8", "i16": "I16", "u16": "U16", "i32": "I32", "u32": "U32",
           "i64": "I64", "u64": "U64", "f32": "F32", "f64": "F64", "string": "Str", "object": "Variant", "System.Guid": "Guid",
           "void": "Void"}
PRIM_LAYOUT = {"bool": (1, 1), "u8": (1, 1), "i8": (1, 1), "char16": (2, 2), "i16": (2, 2), "u16": (2, 2), "i32": (4, 4),
               "u32": (4, 4), "f32": (4, 4), "i64": (8, 8), "u64": (8, 8), "f64": (8, 8), "System.Guid": (16, 4)}


def rs_str(s: str) -> str:
    return json.dumps(s)


class Tables:
    """Interned rows of the generated Rust tables."""

    def __init__(self, facts: dict, ing: C.Ingest) -> None:
        self.facts = facts
        self.ing = ing
        self.kinds: list[str] = [ROOT_KIND] + sorted(facts["kinds"])
        self.kind_ix = {k: i for i, k in enumerate(self.kinds)}
        self.iids: list[str] = ["00000000-0000-0000-0000-000000000000"]
        self.iid_ix: dict[str, int] = {self.iids[0]: 0}
        self.tys: list[str] = []
        self.ty_ix: dict[str, int] = {}
        self.enums: list[str] = []
        self.enum_ix: dict[str, int] = {}
        self.records: list[str] = []
        self.rec_ix: dict[str, int] = {}
        self.ty("void")

    def iid(self, guid: str) -> int:
        g = guid.lower()
        if g not in self.iid_ix:
            self.iid_ix[g] = len(self.iids)
            self.iids.append(g)
        return self.iid_ix[g]

    def iid_of(self, full: str) -> int:
        return self.iid(self.ing.iid(full))

    def enum(self, name: str) -> int:
        if name not in self.enum_ix:
            self.enum_ix[name] = len(self.enums)
            self.enums.append(name)
        return self.enum_ix[name]

    def record(self, name: str) -> int:
        if name not in self.rec_ix:
            self.rec_ix[name] = len(self.records)
            self.records.append(name)
            for f in self.ing.get(name)["fields"]:
                self.ty(f["type"])
        return self.rec_ix[name]

    def layout(self, t: str) -> tuple[int, int]:
        if t in PRIM_LAYOUT:
            return PRIM_LAYOUT[t]
        c = self.ing.cat(t)
        if c == "enum":
            return (4, 4)
        if c == "struct":
            if t in C.SPECIAL_STRUCTS:
                return (8, 8)
            off, al = 0, 1
            for f in self.ing.get(t)["fields"]:
                s, a = self.layout(f["type"])
                off = (off + a - 1) // a * a + s
                al = max(al, a)
            return ((off + al - 1) // al * al, al)
        return (8, 8)

    def ty(self, t: str) -> int:
        if t in self.ty_ix:
            return self.ty_ix[t]
        expr = self.ty_expr(t)
        # Interned by expression too, so equal shapes share a row.
        key = t
        self.ty_ix[key] = len(self.tys)
        self.tys.append(expr)
        return self.ty_ix[key]

    def kind_of(self, full: str) -> int:
        return self.kind_ix.get(full, 0)

    def ty_expr(self, t: str) -> str:
        if t in PRIM_TY:
            return f"Ty::{PRIM_TY[t]}"
        head, args = C.parse(t)
        it = self.ing.get(head)
        if it is None:
            raise SystemExit(f"gen_types_winui: unknown type {t}")
        c = it["category"]
        if c == "enum":
            return f"Ty::Enum({self.enum(head)})"
        if c == "struct":
            if head == "Windows.Foundation.DateTime":
                return "Ty::DateTime"
            if head == "Windows.Foundation.TimeSpan":
                return "Ty::TimeSpan"
            return f"Ty::Record({self.record(head)})"
        if c == "class":
            if C.classify_outside(self.ing, head) == "widget":
                return f"Ty::Widget {{ iid: {self.iid_of(head)} }}"
            return f"Ty::Object {{ kind: {self.kind_of(head)}, iid: {self.iid_of(head)} }}"
        if c == "interface":
            if head in ("Windows.Foundation.IAsyncAction", "Windows.Foundation.IAsyncActionWithProgress",
                        "Windows.Foundation.IAsyncOperation", "Windows.Foundation.IAsyncOperationWithProgress"):
                progress = "WithProgress" in head
                if "Action" in head:
                    of = self.ty("void")
                    handler = "Windows.Foundation.AsyncActionWithProgressCompletedHandler<" + args[0] + ">" if progress \
                        else "Windows.Foundation.AsyncActionCompletedHandler"
                else:
                    of = self.ty(args[0])
                    handler = (f"Windows.Foundation.AsyncOperationWithProgressCompletedHandler<{args[0]}, {args[1]}>" if progress
                               else f"Windows.Foundation.AsyncOperationCompletedHandler<{args[0]}>")
                return f"Ty::Async {{ of: {of}, handler_iid: {self.iid_of(handler)}, progress: {'true' if progress else 'false'} }}"
            if head == "Windows.Foundation.IReference":
                return f"Ty::Nullable {{ of: {self.ty(args[0])}, iid: {self.iid_of(t)} }}"
            if head == C.WFC + "IVectorView":
                return f"Ty::View {{ of: {self.ty(args[0])} }}"
            if head == C.WFC + "IIterable":
                return f"Ty::Iterable {{ of: {self.ty(args[0])} }}"
            if head == C.WFC + "IMapView":
                it_iid = self.iid_of(f"{C.WFC}IIterable<{C.WFC}IKeyValuePair<{args[0]}, {args[1]}>>")
                return f"Ty::MapView {{ of: {self.ty(args[1])}, iter_iid: {it_iid} }}"
            if head == C.WFC + "IKeyValuePair":
                return f"Ty::Pair {{ key: {self.ty(args[0])}, of: {self.ty(args[1])} }}"
            return f"Ty::Object {{ kind: {self.kind_of(t)}, iid: {self.iid_of(t)} }}"
        raise SystemExit(f"gen_types_winui: no ABI type for {t} ({c})")


def core_slots(ing: C.Ingest, slot_of) -> dict[str, int]:
    """Vtable slots of the generic interfaces the core drives itself (the same for every instantiation)."""
    wfc, wf = C.WFC, "Windows.Foundation."
    status = {n: v for n, v in ing.get(wf + "AsyncStatus")["members"]}
    return {
        "view_get_at": slot_of(wfc + "IVectorView", "GetAt"), "view_size": slot_of(wfc + "IVectorView", "get_Size"),
        "iterable_first": slot_of(wfc + "IIterable", "First"), "iterator_current": slot_of(wfc + "IIterator", "get_Current"),
        "iterator_has_current": slot_of(wfc + "IIterator", "get_HasCurrent"), "iterator_move_next": slot_of(wfc + "IIterator", "MoveNext"),
        "pair_key": slot_of(wfc + "IKeyValuePair", "get_Key"), "pair_value": slot_of(wfc + "IKeyValuePair", "get_Value"),
        "reference_value": slot_of(wf + "IReference", "get_Value"),
        "async_info": None, "info_status": slot_of(wf + "IAsyncInfo", "get_Status"),
        "info_error_code": slot_of(wf + "IAsyncInfo", "get_ErrorCode"), "info_cancel": slot_of(wf + "IAsyncInfo", "Cancel"),
        "info_close": slot_of(wf + "IAsyncInfo", "Close"),
        "put_completed": slot_of(wf + "IAsyncOperation", "put_Completed"), "get_results": slot_of(wf + "IAsyncOperation", "GetResults"),
        "put_completed_progress": slot_of(wf + "IAsyncOperationWithProgress", "put_Completed"),
        "get_results_progress": slot_of(wf + "IAsyncOperationWithProgress", "GetResults"),
        "status_completed": status["Completed"], "status_canceled": status["Canceled"], "status_error": status["Error"],
    }


def acc(tb: Tables, a: dict | None) -> str:
    if not a:
        return "Acc::NONE"
    return f"Acc {{ iid: {tb.iid_of(a['iface'])}, slot: {a['slot']} }}"


def rust_tables(facts: dict) -> str:
    ing = C.Ingest()
    tb = Tables(facts, ing)
    kinds = facts["kinds"]
    methods: list[str] = []
    groups: list[tuple[str, int, int, list[int]]] = []   # (name, kind, flags, method indices)
    props: list[str] = []
    events: list[str] = []
    kind_rows: list[str] = []
    kind_groups: dict[int, list[int]] = {i: [] for i in range(len(tb.kinds))}
    kind_props: dict[int, list[tuple[str, int]]] = {i: [] for i in range(len(tb.kinds))}
    kind_events: dict[int, list[tuple[str, int]]] = {i: [] for i in range(len(tb.kinds))}

    def method_row(k: int, native: str, iid: int, slot: int, flags: list[str], m: dict) -> int:
        params = [tb.ty(p["type"]) for p in m["params"]]
        names = [p["name"] for p in m["params"]]
        outs = [tb.ty(p["type"]) for p in m.get("outs", [])]
        onames = [p["name"] for p in m.get("outs", [])]
        ret = tb.ty(m["ret_type"]) if "ret_type" in m else 0
        f = " | ".join(flags) if flags else "0"
        methods.append(f"Method {{ kind: {k}, native: {rs_str(native)}, iid: {iid}, slot: {slot}, flags: {f}, "
                       f"params: &{params}, names: &[{', '.join(rs_str(n) for n in names)}], outs: &{outs}, "
                       f"out_names: &[{', '.join(rs_str(n) for n in onames)}], ret: {ret} }}")
        return len(methods) - 1

    for name in tb.kinds[1:]:
        k = tb.kind_ix[name]
        rec = kinds[name]
        # constructors
        ctor_rows = []
        for c in sorted(rec["constructors"], key=lambda c: len(c["params"])):
            if c["iface"] is None:
                ctor_rows.append(method_row(k, "ActivateInstance", tb.iid(IACTIVATION_FACTORY), 6, ["M_STATIC", "M_CTOR", "M_ACTIVATE"],
                                            {"params": [], "ret_type": name}))
            else:
                fl = ["M_STATIC", "M_CTOR"] + (["M_COMPOSABLE"] if c["composable"] else [])
                ctor_rows.append(method_row(k, c.get("native", ""), tb.iid_of(c["iface"]), c["slot"], fl,
                                            {"params": [{"name": p["name"], "type": p["type"]} for p in c["params"]], "ret_type": name}))
        if ctor_rows:
            groups.append(("new", k, 3, ctor_rows))
            kind_groups[k].append(len(groups) - 1)
        for sec, static in (("statics", True), ("methods", False)):
            for js in sorted(rec[sec]):
                rows = []
                arities = set()
                for o in sorted(rec[sec][js], key=lambda o: len(o["params"])):
                    if len(o["params"]) in arities:
                        continue
                    arities.add(len(o["params"]))
                    fl = (["M_STATIC"] if static else []) + (["M_ASYNC"] if o["ret"]["k"] == "async" else [])
                    rows.append(method_row(k, o["native"], tb.iid_of(o["iface"]), o["slot"], fl,
                                           {"params": o["params"], "outs": o["outs"], "ret_type": o["ret_native"]}))
                groups.append((js, k, 1 if static else 0, rows))
                kind_groups[k].append(len(groups) - 1)
        for p in sorted(rec["props"], key=lambda p: p["name"]):
            props.append(f"Prop {{ name: {rs_str(p['name'])}, native: {rs_str(p['native'])}, kind: {k}, ty: {tb.ty(p['type'])}, "
                         f"get: {acc(tb, p['get'])}, set: {acc(tb, p['set'])}, dp: {acc(tb, p['dp'])} }}")
            kind_props[k].append((p["name"], len(props) - 1))
        for e in sorted(rec["events"], key=lambda e: e["name"]):
            args = [tb.ty(a["type"]) for a in e["args"]]
            events.append(f"Event {{ name: {rs_str(e['name'])}, native: {rs_str(e['native'])}, kind: {k}, iid: {tb.iid_of(e['iface'])}, "
                          f"add: {e['add']}, remove: {e['remove']}, delegate_iid: {tb.iid_of(e['delegate'])}, args: &{args} }}")
            kind_events[k].append((e["name"], len(events) - 1))

    for i, name in enumerate(tb.kinds):
        rec = kinds.get(name)
        parent = tb.kind_ix[rec["parent"]] + 1 if rec and rec.get("parent") in tb.kind_ix else 0
        is_class = bool(rec) and rec.get("kind") == "class"
        thread = {"any": "T_ANY", "ui": "T_UI", "dispatcher": "T_DISPATCHER"}[rec["thread"] if rec else "any"]
        g = sorted(kind_groups[i], key=lambda x: (groups[x][0], groups[x][2]))
        pr = [x for _, x in sorted(kind_props[i])]
        ev = [x for _, x in sorted(kind_events[i])]
        kind_rows.append(f"Kind {{ name: {rs_str(name)}, parent: {parent}, class: {'true' if is_class else 'false'}, thread: {thread}, "
                         f"thread_getter: {acc(tb, rec.get('thread_getter') if rec else None)}, groups: &{g}, props: &{pr}, events: &{ev} }}")

    # Core interfaces (resolved here from the metadata, never typed by hand).
    pt = {n: v for n, v in ing.get("Windows.Foundation.PropertyType")["members"]}

    def slot_of(iface: str, method: str) -> int:
        for m in ing.iface_methods(iface):
            if m["name"] == method:
                return m["slot"]
        raise SystemExit(f"gen_types_winui: {iface}.{method} not found")

    def class_acc(cls: str, method: str) -> str:
        for i in ing.class_ifaces(cls, own_only=False):
            for m in ing.iface_methods(i):
                if m["name"] == method:
                    return f"Acc {{ iid: {tb.iid_of(i)}, slot: {m['slot']} }}"
        raise SystemExit(f"gen_types_winui: {cls}.{method} not found")

    scalars = ["UInt8", "Int16", "UInt16", "Int32", "UInt32", "Int64", "UInt64", "Single", "Double", "Char16", "Boolean", "String",
               "Guid", "DateTime", "TimeSpan", "Point", "Size", "Rect"]
    pv = "Windows.Foundation.IPropertyValue"
    pvs = "Windows.Foundation.IPropertyValueStatics"
    pv_get = sorted((pt[n], slot_of(pv, "Get" + n)) for n in scalars)
    pv_create = sorted([(pt[n], slot_of(pvs, "Create" + n)) for n in scalars] + [(pt["Empty"], slot_of(pvs, "CreateEmpty")),
                                                                                  (pt["Inspectable"], slot_of(pvs, "CreateInspectable"))])
    core = (f"pub static CORE: Core = Core {{\n    property_value: {tb.iid_of(pv)},\n    pv_type: {slot_of(pv, 'get_Type')},\n"
            f"    pv_get: &{pv_get},\n    pv_statics: {tb.iid_of(pvs)},\n    pv_create: &{pv_create},\n"
            f"    stringable: Acc {{ iid: {tb.iid_of('Windows.Foundation.IStringable')}, slot: {slot_of('Windows.Foundation.IStringable', 'ToString')} }},\n"
            f"    dq_has_thread_access: {class_acc('Microsoft.UI.Dispatching.DispatcherQueue', 'get_HasThreadAccess')},\n"
            f"    dependency_object: {tb.iid_of('Microsoft.UI.Xaml.IDependencyObject')},\n"
            + "".join(f"    {k}: {tb.iid_of('Windows.Foundation.IAsyncInfo') if v is None else v},\n" for k, v in core_slots(ing, slot_of).items()) + "};\n")

    enum_rows = []
    for n in tb.enums:
        e = ing.get(n)
        mem = ", ".join(f"({rs_str(m[0])}, {m[1]})" for m in e["members"])
        enum_rows.append(f"EnumT {{ name: {rs_str(n)}, flags: {'true' if e.get('flags') else 'false'}, "
                         f"unsigned: {'true' if e.get('underlying') == 'u32' else 'false'}, members: &[{mem}] }}")
    rec_rows = []
    i = 0
    while i < len(tb.records):
        n = tb.records[i]
        fields = []
        off = 0
        for f in ing.get(n)["fields"]:
            s, a = tb.layout(f["type"])
            off = (off + a - 1) // a * a
            fields.append(f"Field {{ name: {rs_str(C.camel(f['name']))}, ty: {tb.ty(f['type'])}, offset: {off} }}")
            off += s
        size, al = tb.layout(n)
        rec_rows.append(f"RecordT {{ name: {rs_str(n)}, size: {size}, align: {al}, fields: &[{', '.join(fields)}] }}")
        i += 1
    # Rows interned late (record fields) are emitted too: TYS last.
    def iid_lit(g: str) -> str:
        return "0x" + g.replace("-", "")

    out = [RS_HEADER, "//! Non-GUI type tables (N4): data only, read by the hand-written core in `src/types/`.", "",
           "use super::model::*;", "",
           f"pub static KINDS: &[Kind] = &[\n" + "".join(f"    {r},\n" for r in kind_rows) + "];", "",
           f"pub static GROUPS: &[Group] = &[\n" + "".join(
               f"    Group {{ name: {rs_str(n)}, kind: {k}, flags: {['0', 'G_STATIC', 'G_CTOR', 'G_STATIC | G_CTOR'][fl]}, methods: &{rows} }},\n"
               for n, k, fl, rows in groups) + "];", "",
           f"pub static METHODS: &[Method] = &[\n" + "".join(f"    {r},\n" for r in methods) + "];", "",
           f"pub static PROPS: &[Prop] = &[\n" + "".join(f"    {r},\n" for r in props) + "];", "",
           f"pub static EVENTS: &[Event] = &[\n" + "".join(f"    {r},\n" for r in events) + "];", "",
           f"pub static ENUMS: &[EnumT] = &[\n" + "".join(f"    {r},\n" for r in enum_rows) + "];", "",
           f"pub static RECORDS: &[RecordT] = &[\n" + "".join(f"    {r},\n" for r in rec_rows) + "];", "",
           core, ]
    consts = f"/// Rows of `TYS` the core reads with.\npub const TY_U32: TyId = {tb.ty('u32')};\npub const TY_STR: TyId = {tb.ty('string')};\n"
    tys = f"pub static TYS: &[Ty] = &[\n" + "".join(f"    {e}, // {n}\n" for n, e in zip(sorted(tb.ty_ix, key=tb.ty_ix.get), tb.tys)) + "];\n"
    iids = f"/// Interface IDs (index 0: none), as u128 (`GUID::from_u128`).\npub static IIDS: &[u128] = &[\n" + "".join(
        f"    {iid_lit(g)},\n" for g in tb.iids) + "];\n"
    return "\n".join(out) + "\n" + consts + "\n" + tys + "\n" + iids


def write_all(files: dict[Path, str], check: bool, owned_globs: list[tuple[Path, str]]) -> int:
    bad: list[str] = []
    for p, text in files.items():
        if check:
            if not p.exists() or p.read_text() != text:
                bad.append(str(p.relative_to(ROOT)))
        elif not p.exists() or p.read_text() != text:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
    for d, pat in owned_globs:
        for p in d.rglob(pat) if d.exists() else []:
            if p not in files and p.name != "_rt.js":
                if check:
                    bad.append(f"{p.relative_to(ROOT)} (stale)")
                else:
                    p.unlink()
    if bad:
        print("gen_types_winui: generated files are stale: " + ", ".join(bad[:10]) + (" ..." if len(bad) > 10 else "")
              + "\n  run `python3 tools/metadata/winui/gen_types_winui.py --write`", file=sys.stderr)
        return 1
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    facts = C.load_facts()
    import types_pkg  # noqa: E402
    import types_winui_js as J  # noqa: E402
    files = {TABLES: rust_tables(facts)}
    import types_winui_tests as T  # noqa: E402
    g = J.Gen(facts, C.Ingest())
    files.update(g.files(types_pkg))
    files.update(T.Tests(facts).files())
    rc = write_all(files, not a.write, [(J.OUT, "*.js"), (J.OUT, "*.d.ts"), (J.DOCS, "*.md")])
    for w in sorted(set(g.warnings)):
        print("gen_types_winui: warning:", w, file=sys.stderr)
    if rc == 0:
        print(f"gen_types_winui: {len(facts['kinds'])} kinds, {len(files)} files {'written' if a.write else 'are current'}")
    return rc


if __name__ == "__main__":
    sys.exit(main())
