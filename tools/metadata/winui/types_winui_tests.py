"""Generated ledger tests of the curated WinUI non-GUI types (N4): crates/svelters-winui/tests/types_verify.rs and its
fact manifest crates/svelters-winui/src/generated/types_facts.json. Used by gen_types_winui.py.

Fact groups per curated type (ids `svelters-api:v1:type:winui:<Namespace>:<Type>:<group>`), each one generated test
run on the windows-winui runner (`harness = false`, one STA thread):
  construct  the subject (`subjects:` in the overrides) is a SHARED handle of its kind; `describe(SVL_KIND)` names it
  props      every readable prop reads; writable plain props round-trip a sample
  methods    every method resolves with the descriptor the facts say (static/async flags, arity); zero-argument readers run
  statics    every static resolves; those with plain arguments run on sample arguments
  events     every event connects and disconnects; known triggers deliver
  async      the `async_checks:` round trip resolves (and the expected value), a failure rejects with a NativeError
  lifetime   destroy releases the handle (stale after) and the live-handle count returns to its baseline
  thread     dispatcher-class objects: the object's DispatcherQueue has thread access on the UI thread
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import types_winui_classify as C

ROOT = Path(__file__).resolve().parents[3]
TESTS = ROOT / "crates/svelters-winui/tests/types_verify.rs"
FACTS = ROOT / "crates/svelters-winui/src/generated/types_facts.json"
HEADER = "// @generated by tools/metadata/winui/gen_types_winui.py from metadata/winui/types. Do not edit.\n"

READER_PREFIXES = ("get", "to", "is", "has", "stringify")
# Native events with a trigger the tests can cause: (setup statements, trigger statements). `w` is the subject.
EVENT_TRIGGERS = {
    ("Windows.Foundation.Collections.PropertySet", "map-changed"): ['h.call(w, "insert", &[s("k"), Value::F64(1.0)]).unwrap();'],
    ("Microsoft.UI.Dispatching.DispatcherQueueTimer", "tick"): [
        'h.set(w, "interval", Value::F64(10.0)).unwrap();', 'h.call(w, "start", &[]).unwrap();', "h.pump(200);",
        'h.call(w, "stop", &[]).unwrap();'],
}


def rs_str(s: str) -> str:
    return json.dumps(s)


def lit(v) -> str:
    """A JSON-ish literal as a Rust `Value` expression (`<temp>` / `$temp` is the test's temporary directory)."""
    if isinstance(v, bool):
        return f"Value::Bool({'true' if v else 'false'})"
    if isinstance(v, int):
        return f"Value::I64({v})"
    if isinstance(v, float):
        return f"Value::F64({v!r})"
    if v is None:
        return "Value::Null"
    if isinstance(v, str):
        if v in ("<temp>", "$temp"):
            return "s(&temp)"
        if v.startswith("$") and v[1:].isdigit():
            return f"r[{int(v[1:])}].clone()"
        if v == "$subject":
            return "Value::Handle(w)"
        return f"s({rs_str(v)})"
    if isinstance(v, list):
        return f"Value::List(vec![{', '.join(lit(x) for x in v)}])"
    if isinstance(v, dict):
        return "Value::Map(vec![" + ", ".join(f"({rs_str(k)}.into(), {lit(x)})" for k, x in v.items()) + "])"
    raise SystemExit(f"types_winui_tests: no literal for {v!r}")


def sample(slot: dict, facts: dict) -> tuple[str, str] | None:
    """(value written, value read back) for a plain slot, or None."""
    k = slot["k"]
    if k == "bool":
        return ("Value::Bool(true)", "Value::Bool(true)")
    if k == "float":
        return ("Value::F64(0.25)", "Value::F64(0.25)")
    if k == "int":
        return ("Value::I64(1)", "Value::I64(1)")
    if k == "string":
        return ('s("svelters")', 's("svelters")')
    if k == "timespan":
        return ("Value::F64(25.0)", "Value::F64(25.0)")
    if k == "enum":
        e = facts["enums"].get(slot["t"])
        if not e or len(e["native"]) < 2:
            return None
        name = C.kebab(e["native"][1])
        return (f"s({rs_str(name)})", f"s({rs_str(name)})")
    if k == "flags":
        e = facts["enums"].get(slot["t"])
        nz = [(n, v) for n, v in zip(e["native"], [m[1] for m in e["members"]]) if v and v & (v - 1) == 0] if e else []
        if not nz:
            return None
        name = C.kebab(nz[0][0])
        return (f"Value::List(vec![s({rs_str(name)})])", f"Value::List(vec![s({rs_str(name)})])")
    if k == "record":
        st = facts["structs"].get(slot["t"])
        if not st:
            return None
        fields = []
        for f in st["fields"]:
            ft = f["type"]
            if ft in ("u8", "i32", "u32", "i16", "u16", "i64", "u64"):
                fields.append((f["name"], "Value::I64(1)"))
            elif ft in ("f32", "f64"):
                fields.append((f["name"], "Value::F64(1.0)"))
            else:
                return None
        m = "Value::Map(vec![" + ", ".join(f"({rs_str(n)}.into(), {v})" for n, v in fields) + "])"
        return (m, m)
    return None


def arg_sample(slot: dict, facts: dict) -> str | None:
    s = sample(slot, facts)
    return s[0] if s else None


class Tests:
    def __init__(self, facts: dict) -> None:
        self.facts = facts
        self.kinds = facts["kinds"]
        self.fns: list[tuple[str, str]] = []
        self.records: list[dict] = []

    def chain(self, n: str) -> list[str]:
        out = [n]
        p = self.kinds[n].get("parent")
        while p and p in self.kinds and p not in out:
            out.append(p)
            p = self.kinds[p].get("parent")
        return out

    def subject(self, n: str) -> list[str]:
        """Statements that bind `w` (the subject handle) for kind `n`."""
        sub = self.kinds[n].get("subject")
        if not sub:
            return []
        if "new" in sub:
            return [f"let w = h.new_object({rs_str(n)}, &[{', '.join(lit(a) for a in sub['new'])}]).unwrap();"]
        if "construct" in sub:
            props = ", ".join(f"({rs_str(k)}, {lit(v)})" for k, v in sub["construct"].items())
            return [f"let w = h.construct({rs_str(n)}, &[{props}]).unwrap();"]
        if "static" in sub:
            m, *args = sub["static"]
            call = "await_static" if m.endswith("Async") else "call_static"
            return [f"let w = handle(h.{call}({rs_str(n)}, {rs_str(m)}, &[{', '.join(lit(a) for a in args)}]).unwrap());"]
        if "queue" in sub:
            return ['let q = handle(h.call_static("Microsoft.UI.Dispatching.DispatcherQueue", "getForCurrentThread", &[]).unwrap());',
                    f"let w = handle(h.call_keep(q, {rs_str(sub['queue'])}, &[]).unwrap());"]
        raise SystemExit(f"types_winui_tests: unknown subject form for {n}: {sub}")

    def add(self, n: str, group: str, body: list[str], needs_subject: bool = True) -> None:
        rec = self.kinds[n]
        short = rec["name"].lower()
        fn = f"type_{short}_{group}"
        pre = ["let mut h = Harness::new();", "let temp = Harness::temp_dir(" + rs_str(short) + ");", "let _ = &temp;"]
        if needs_subject:
            pre += self.subject(n)
        src = f"pub fn {fn}() {{\n" + "".join(f"    {l}\n" for l in pre + body) + "}\n"
        self.fns.append((fn, src))
        ns = rec["namespace"]
        record = {"fact": f"svelters-api:v1:type:winui:{ns}:{rec['name']}:{group}", "kind": n, "name": group, "section": "types",
                  "tests": [fn], "origin": "manual"}
        digest = hashlib.sha256(json.dumps({k: v for k, v in rec.items() if k not in ("curated",)}, sort_keys=True).encode()).hexdigest()[:16]
        fp = hashlib.sha256(json.dumps({"record": record, "facts": digest, "test": src}, sort_keys=True).encode()).hexdigest()[:16]
        self.records.append({**record, "fingerprint": fp})

    def build(self) -> None:
        for n in sorted(self.kinds):
            rec = self.kinds[n]
            if not rec.get("curated"):
                continue
            has_subject = bool(rec.get("subject"))
            kind_id = f"h.kind({rs_str(n)})"
            if has_subject:
                self.add(n, "construct", [
                    "let info = h.info(w).unwrap();",
                    "assert_eq!(info.lifetime, SVL_LIFE_SHARED, \"a type object is a SHARED handle\");",
                    f"assert_eq!(info.kind, {kind_id});",
                    f"assert_eq!(h.describe_kind(info.kind).unwrap().0, {rs_str(n)});",
                ])
                body = []
                for c in self.chain(n):
                    for p in self.kinds[c]["props"]:
                        if p["get"]:
                            body.append(f"let v = h.get(w, {rs_str(p['name'])}).unwrap_or_else(|e| panic!(\"read {p['name']}: {{e}}\"));")
                            body.append(f"assert!(!matches!(v, Value::Error(_)), \"read {p['name']}: {{v:?}}\");")
                        sm = sample(p["slot"], self.facts) if p["set"] else None
                        if sm:
                            body.append(f"h.set(w, {rs_str(p['name'])}, {sm[0]}).unwrap_or_else(|e| panic!(\"write {p['name']}: {{e}}\"));")
                            if p["get"]:
                                body.append(f"assert_eq!(h.get(w, {rs_str(p['name'])}).unwrap(), {sm[1]}, \"{p['name']} after a write\");")
                if body:
                    self.add(n, "props", body)
            # methods: descriptors for all, run the zero-argument readers
            body = [f"let k = {kind_id};"]
            for js, ovs in sorted(rec["methods"].items()):
                arities = sorted({len(o["params"]) for o in ovs})
                is_async = all(o["ret"]["k"] == "async" for o in ovs)
                body.append(f"let d = h.describe_member(k, NameKind::Method, {rs_str(js)}).expect({rs_str(js + ' resolves')});")
                body.append(f"assert_eq!(d.flags & SVL_M_ASYNC != 0, {'true' if is_async else 'false'}, {rs_str(js + ': async flag')});")
                body.append(f"assert_eq!(d.flags & SVL_M_STATIC, 0, {rs_str(js + ': instance method')});")
                body.append(f"assert_eq!(d.params.len(), {max(arities) + (1 if is_async else 0)}, {rs_str(js + ': arity')});")
                if has_subject and not is_async and 0 in arities and js.startswith(READER_PREFIXES):
                    body.append(f"let v = h.call_keep(w, {rs_str(js)}, &[]).unwrap_or_else(|e| panic!(\"{js}(): {{e}}\"));")
                    body.append(f"assert!(answered(&v), \"{js}(): {{v:?}}\");")
            if len(body) > 1:
                self.add(n, "methods", body, needs_subject=has_subject and any(l.startswith("let v = h.call_keep(w") for l in body))
            # statics
            body = [f"let k = {kind_id};"]
            for js, ovs in sorted(rec["statics"].items()):
                wire = js
                is_async = all(o["ret"]["k"] == "async" for o in ovs)
                arities = sorted({len(o["params"]) for o in ovs})
                if js in rec["methods"]:
                    wire = "static:" + js
                body.append(f"let d = h.describe_member(k, NameKind::Method, {rs_str(wire)}).expect({rs_str(js + ' resolves')});")
                body.append(f"assert!(d.flags & SVL_M_STATIC != 0, {rs_str(js + ': static')});")
                body.append(f"assert_eq!(d.flags & SVL_M_ASYNC != 0, {'true' if is_async else 'false'}, {rs_str(js + ': async flag')});")
                if is_async:
                    continue
                for o in ovs:
                    args = [arg_sample(p["slot"], self.facts) for p in o["params"]]
                    if any(a is None for a in args):
                        continue
                    body.append(f"let v = h.call_static({rs_str(n)}, {rs_str(wire)}, &[{', '.join(args)}]).unwrap_or_else(|e| panic!(\"{js}: {{e}}\"));")
                    body.append(f"assert!(answered(&v), \"{js}: {{v:?}}\");")
            if len(body) > 1:
                self.add(n, "statics", body, needs_subject=False)
            # events
            if rec["events"] and has_subject:
                body = []
                for e in rec["events"]:
                    body.append(f"h.listen(w, {rs_str(e['name'])}, true).unwrap_or_else(|e| panic!(\"listen {e['name']}: {{e}}\"));")
                    trig = EVENT_TRIGGERS.get((n, e["name"]))
                    if trig:
                        body += trig
                        body.append("h.pump(50);")
                        body.append(f"assert!(!h.event_args(w, {rs_str(e['name'])}).is_empty(), \"{e['name']} was delivered\");")
                    body.append(f"h.listen(w, {rs_str(e['name'])}, false).unwrap();")
                self.add(n, "events", body)
            # async
            checks = rec.get("async_checks")
            if checks:
                body = ["let mut r: Vec<Value> = Vec::new();"]
                for step in checks["steps"]:
                    recv, method, *args = step
                    a = ", ".join(lit(x) for x in args)
                    is_async = method.endswith("Async")
                    if recv == "$subject" or (isinstance(recv, str) and recv.startswith("$")):
                        target = "w" if recv == "$subject" else f"handle(r[{int(recv[1:])}].clone())"
                        call = f"h.await_call({target}, {rs_str(method)}, &[{a}])" if is_async else f"h.call_keep({target}, {rs_str(method)}, &[{a}])"
                    else:
                        call = f"h.await_static({rs_str(recv)}, {rs_str(method)}, &[{a}])" if is_async else f"h.call_static({rs_str(recv)}, {rs_str(method)}, &[{a}])"
                    body.append(f"r.push({call}.unwrap_or_else(|e| panic!(\"{method}: {{e}}\")));")
                if "expect" in checks:
                    body.append(f"assert_eq!(r.last().unwrap(), &{lit(checks['expect'])});")
                if "reject" in checks:
                    recv, method, *args = checks["reject"]
                    a = ", ".join(lit(x) for x in args)
                    target = "w" if recv == "$subject" else f"handle(r[{int(recv[1:])}].clone())"
                    body.append(f"let err = h.await_call({target}, {rs_str(method)}, &[{a}]).unwrap_err();")
                    body.append("assert!(err.contains(\"winrt\"), \"a WinRT NativeError: {err}\");")
                self.add(n, "async", body, needs_subject=has_subject)
            # lifetime
            if has_subject:
                self.add(n, "lifetime", [
                    "let before = h.live_handles();",
                    "h.destroy(w);",
                    "assert!(h.info(w).is_err(), \"stale after destroy\");",
                    "assert_eq!(h.live_handles(), before - 1, \"one handle released\");",
                ])
            if has_subject and rec["thread"] == "dispatcher":
                self.add(n, "thread", [
                    'let q = handle(h.get(w, "dispatcherQueue").unwrap());',
                    'assert_eq!(h.get(q, "hasThreadAccess").unwrap(), Value::Bool(true), "created on the one UI thread");',
                ])

    def files(self) -> dict[Path, str]:
        self.build()
        body = "".join(src + "\n" for _, src in self.fns)
        table = "".join(f"        ({rs_str(fn)}, {fn}),\n" for fn, _ in self.fns)
        text = (HEADER + "//! Ledger tests of the curated WinUI non-GUI types (N4). Windows only:\n"
                "//! `cargo test -p svelters-winui --test types_verify` (one STA thread, `harness = false`).\n\n"
                "#[cfg(windows)]\n#[allow(unused_variables, unused_mut, clippy::all)]\nmod tests {\n"
                "    use svelters_abi::{NameKind, SVL_LIFE_SHARED, SVL_M_ASYNC, SVL_M_STATIC, Value};\n"
                "    use svelters_winui::testing::Harness;\n\n"
                "    fn s(x: &str) -> Value {\n        Value::Str(x.into())\n    }\n\n"
                "    /// A call that reached WinRT: a value, or the native error it answered (a WinRT `NativeError`, never a\n"
                "    /// marshalling failure). Readers run on sample subjects, where some legitimately refuse (`GetArray` of an object).\n"
                "    fn answered(v: &Value) -> bool {\n        match v {\n            Value::Error(e) => e.domain == \"winrt\",\n"
                "            _ => true,\n        }\n    }\n\n"
                "    fn handle(v: Value) -> u64 {\n        match v {\n            Value::Handle(h) => h,\n"
                "            other => panic!(\"expected a handle, got {other:?}\"),\n        }\n    }\n\n"
                + "\n".join("    " + l if l else "" for l in body.rstrip().split("\n")) + "\n\n"
                + "    pub static TESTS: &[(&str, fn())] = &[\n" + table + "    ];\n}\n\n"
                "fn main() {\n    #[cfg(windows)]\n    let tests = tests::TESTS;\n    #[cfg(not(windows))]\n"
                "    let tests: &[(&str, fn())] = &[];\n    std::process::exit(svelters_winui::harness::main(tests));\n}\n")
        manifest = {"schema": "svelters-winui-type-facts/v1", "facts": sorted(self.records, key=lambda r: r["fact"])}
        return {TESTS: text, FACTS: json.dumps(manifest, indent=1, sort_keys=True) + "\n"}
