    # ---- the core's table ----
    def rust(self) -> str:
        L = [HEADER.replace("//", "//!", 1), "//! See crate::types_table for the types.\n",
             "use crate::types_table::{AsyncMember, Cat, TypeClass};\n\n",
             "pub static TYPE_CLASSES: &[TypeClass] = &[\n"]
        cat = {"value": "Value", "object": "Object", "statics": "Statics"}
        for q, t in sorted(self.types.items()):
            L.append(f"    TypeClass {{ name: \"{q}\", cat: Cat::{cat[t['category']]}, framework: \"{t['framework']}\" }},\n")
        L.append("];\n\npub static ASYNC: &[AsyncMember] = &[\n")
        rows = []
        for q, t in sorted(self.types.items()):
            for m in t["methods"]:
                if m.get("async"):
                    rows.append(f"    AsyncMember {{ class: \"{q}\", sel: \"{m['sel']}\", is_static: {'true' if m['static'] else 'false'}, "
                                f"shape: \"{m['async']['shape']}\", args: {len(m['params'])} }},\n")
        L += sorted(rows)
        L.append("];\n")
        # On x86-64 the runtime encodes BOOL as `c` (signed char), so the reflective paths can't tell it
        # from an integer; these selectors and KVC keys return BOOL per the facts (plus NSObject's own).
        bools = set(NSOBJECT_BOOL_SELS)
        for t in self.types.values():
            bools.update(m["sel"] for m in t["methods"] if m["ret"].get("k") == "bool")
            for p in t["props"]:
                if p["type"]["k"] == "bool":
                    bools.update((p["getter"], p["key"]))
        sdk = json.loads((ROOT / "metadata/appkit/_enums.json").read_text())["sdk"].removeprefix("MacOSX")
        L.append(f"\n/// The macOS SDK the facts were read against: on an older macOS, its newer members are absent.\n")
        L.append(f"pub const SDK_MACOS: &str = \"{sdk}\";\n")
        L.append("\n/// Selectors and KVC keys whose value is BOOL (sorted; see `types_table::returns_bool`).\n")
        L.append("pub static BOOL_SELS: &[&str] = &[\n")
        L += [f"    \"{s}\",\n" for s in sorted(bools)]
        L.append("];\n")
        return "".join(L)

    def files(self) -> dict[Path, str]:
        out: dict[Path, str] = {}
        for q in self.types:
            out[OUT / FW_DIR[self.types[q]["framework"]] / f"{q}.js"] = self.class_js(q)
        for fw, d in FW_DIR.items():
            out[OUT / d / "index.js"] = self.index_js(fw)
            if any(e["framework"] == fw for e in self.enums.values()):
                out[OUT / d / "enums.js"] = self.enums_js(fw)
            out[OUT / f"{d}.d.ts"] = self.dts(fw)
        out[OUT / "manifest.json"] = json.dumps(self.manifest(), indent=1, sort_keys=True) + "\n"
        own = {f"./appkit/{d}": {"types": f"./appkit/{d}.d.ts", "default": f"./appkit/{d}/index.js"} for d in sorted(FW_DIR.values())}
        own["./manifest-appkit"] = "./appkit/manifest.json"
        out[PKG / "package.json"] = types_pkg.package_json(PKG / "package.json", own, "./appkit/", ["./manifest-appkit"])
        out[RUST] = self.rust()
        out[TESTS] = gen_tests(self)
        out[FACTS_OUT] = gen_facts(self)
        out[DOCS / "index.md"] = self.doc_index()
        for q, t in self.types.items():
            if t["curated"]:
                out[DOCS / f"{q.lower()}.md"] = self.doc_page(q)
        return out


