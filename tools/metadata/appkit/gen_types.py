def rs_str(s: str) -> str:
    return json.dumps(s)


def rs_j(v) -> str:
    if v is None:
        return "J::Null"
    if isinstance(v, bool):
        return f"J::Bool({'true' if v else 'false'})"
    if isinstance(v, int):
        return f"J::I({v})"
    if isinstance(v, float):
        return f"J::F({v!r})"
    return f"J::S({rs_str(v)})"


def fn_name(q: str, group: str) -> str:
    return f"types_{q.lower()}_{group}"


def zero_arg_readers(methods: list[dict], static: bool) -> list[str]:
    out = []
    for m in methods:
        if m["static"] != static or m["params"] or m.get("async") or m.get("ctor") or m["ret"]["k"] == "void":
            continue
        if m.get("throws") or DENY.match(m["sel"]):
            continue
        out.append(m["sel"])
    return sorted(set(out))


def gen_tests(gen: "Gen") -> str:
    L = [HEADER.replace("tools/metadata/appkit/gen_types.py", "tools/metadata/appkit/gen_types.py (tests)"),
         "//! Non-GUI type facts (N4) on the real AppKit runtime: one case per (curated type, fact group) and a\n"
         "//! `members` case per bound type. Results go to the AppKit ledger (`ledger.py import --toolkit appkit`).\n"
         "//! An empty suite on other platforms.\n\n",
         "fn main() {\n    #[cfg(target_os = \"macos\")]\n    svelters_apple::testing::run_cases(true, mac::CASES);\n"
         "    #[cfg(not(target_os = \"macos\"))]\n    svelters_apple::testing::run_cases(false, &[]);\n}\n\n",
         "#[cfg(target_os = \"macos\")]\n#[allow(non_upper_case_globals)]\nmod mac {\n    use svelters_appkit::testing::types::{self as t, J, Members, Spec};\n\n"]
    cases = []
    for q in sorted(gen.types):
        t = gen.types[q]
        methods, props = gen.members_of(q)
        mem = sorted({(m["sel"], m["static"]) for m in t["methods"]})
        keys = sorted({p["key"] for p in t["props"]}) if t["category"] != "value" else []
        L.append(f"    static {q}_MEMBERS: Members = Members {{\n        class: {rs_str(q)},\n"
                 f"        members: &[{', '.join(f'({rs_str(s)}, {str(st).lower()})' for s, st in mem)}],\n"
                 f"        keys: &[{', '.join(rs_str(k) for k in keys)}],\n    }};\n")
        L.append(f"    fn {fn_name(q, 'members')}() {{\n        t::members(&{q}_MEMBERS);\n    }}\n\n")
        cases.append(fn_name(q, "members"))
        if not t["curated"]:
            continue
        subj = t.get("subject") or ["new", []]
        sc = t.get("string_ctor")
        sample = {"NSURL": "https://example.com/", "NSAttributedString": "Hello", "NSMutableAttributedString": "Hello",
                  "NSUUID": "E621E1F8-C36C-495A-93FC-0C247A3E6E5F", "NSLocale": "en_US", "NSURLComponents": "https://example.com/"}.get(q, "x")
        prow = ", ".join(f"({rs_str(p['key'])}, {rs_str(p['getter'])}, {str(bool(p.get('setter')) and t['category'] != 'value').lower()}, {rs_str(p['type']['k'])})"
                         for p in props)
        asy = sorted({(m["sel"], m["static"], len(m["params"])) for m in methods if m.get("async")})
        L.append(f"    static {q}: Spec = Spec {{\n        class: {rs_str(q)},\n        value: {str(t['category'] == 'value').lower()},\n"
                 f"        subject: ({rs_str(subj[0])}, &[{', '.join(rs_j(v) for v in subj[1])}]),\n"
                 f"        string_ctor: {f'Some(({rs_str(sc)}, {rs_str(sample)}))' if sc else 'None'},\n"
                 f"        constructible: {str(bool(t['constructible'])).lower()},\n"
                 f"        props: &[{prow}],\n"
                 f"        readers: &[{', '.join(rs_str(s) for s in zero_arg_readers(methods, False))}],\n"
                 f"        statics: &[{', '.join(rs_str(s) for s in zero_arg_readers(methods, True))}],\n"
                 f"        members: &[{', '.join(f'({rs_str(s)}, {str(st).lower()})' for s, st in mem)}],\n"
                 f"        asyncs: &[{', '.join(f'({rs_str(s)}, {str(st).lower()}, {n})' for s, st, n in asy)}],\n    }};\n")
        for g in CURATED_GROUPS + (["async"] if asy else []):
            fn = "asyncs" if g == "async" else g
            L.append(f"    fn {fn_name(q, g)}() {{\n        t::{fn}(&{q});\n    }}\n")
            cases.append(fn_name(q, g))
        L.append("\n")
    L.append("    pub static CASES: &[(&str, fn())] = &[\n")
    L += [f"        ({rs_str(c)}, {c}),\n" for c in cases]
    L.append("    ];\n}\n")
    return "".join(L)


CURATED_GROUPS = ["construct", "props", "methods", "statics", "lifetime"]


def gen_facts(gen: "Gen") -> str:
    import hashlib
    facts = []
    for q in sorted(gen.types):
        t = gen.types[q]
        digest = hashlib.sha256(json.dumps(t, sort_keys=True).encode()).hexdigest()[:16]
        groups = ["members"]
        if t["curated"]:
            groups = CURATED_GROUPS + ["members"] + (["async"] if any(m.get("async") for m in gen.members_of(q)[0]) else [])
        for g in groups:
            facts.append({"fact": f"svelters-api:v1:type:appkit:{t['framework']}:{q}:{g}", "facts_digest": digest, "kind": q,
                          "name": g, "section": "types", "tests": [fn_name(q, g)]})
    return json.dumps({"schema": "svelters-types-facts/v1", "toolkit": "appkit", "facts": facts}, indent=1, sort_keys=True) + "\n"


def write_all(files: dict[Path, str], check: bool, dirs: list[Path]) -> int:
    bad = 0
    stale = []
    for d in dirs:
        if d.exists():
            for p in d.rglob("*"):
                if p.is_file() and p not in files:
                    stale.append(p)
    for p, text in sorted(files.items()):
        if check:
            if not p.exists() or p.read_text() != text:
                print(f"stale: {p.relative_to(ROOT)}", file=sys.stderr)
                bad += 1
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            if not p.exists() or p.read_text() != text:
                p.write_text(text)
    for p in stale:
        if check:
            print(f"not generated: {p.relative_to(ROOT)}", file=sys.stderr)
            bad += 1
        else:
            p.unlink()
    return 1 if bad else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    a = ap.parse_args()
    gen = Gen(TA.load_facts())
    files = gen.files()
    rc = write_all(files, a.check, [OUT, DOCS])
    if not a.check:
        print(f"{len(gen.types)} classes -> {OUT.relative_to(ROOT)}, {RUST.relative_to(ROOT)}, {DOCS.relative_to(ROOT)}")
    return rc


if __name__ == "__main__":
    sys.exit(main())
