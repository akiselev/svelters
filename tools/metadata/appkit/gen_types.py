#!/usr/bin/env python3
"""Generates the `svelters:appkit/<fw>` modules and the core's table from the AppKit type facts (N4).

The AppKit counterpart of tools/metadata/qt/gen_types_js.py. Input: metadata/appkit/types/{Foundation,AppKit}.json
(types_appkit_classify.py). Output (deterministic, checked in):
  packages/types/appkit/<fw>/<Class>.js      one file per class, one named export, no top-level side effects
  packages/types/appkit/<fw>/enums.js        the NS_ENUM / NS_OPTIONS the bound members use (frozen, pure)
  packages/types/appkit/<fw>/index.js        re-exports
  packages/types/appkit/<fw>.d.ts            `declare module 'svelters:appkit/<fw>'` typings
  packages/types/appkit/manifest.json        per class: native name, hierarchy, imports, signature references (Q9)
  packages/types/package.json                the `./appkit/*` and `./manifest-appkit` exports (common/types_pkg.py)
  crates/svelters-appkit/src/generated/types.rs   bound classes and async members (const data, no unsafe)
  examples/counter-mac/tests/types.rs        generated ledger tests (macOS CI): per curated type construct, props,
                                             methods, statics, lifetime, members (+ async); `members` per bound type
  metadata/appkit/types/facts.json           their ledger facts (`svelters-api:v1:type:appkit:<Fw>:<Class>:<group>`)
  docs/site/src/content/docs/types/appkit/   a page per curated type and an index of every bound type

Runtime contract with the core (crates/svelters-appkit/src/types.rs): kinds are ObjC class names; methods are
called by **selector** (`call(this, 'setString:forType:', [s, t])`), so the JS name is only the typing/docs name;
properties by KVC key (`getProp(this, 'levelsOfUndo')`); `init…` initializers are statics through `callStatic`;
async members pass their arguments and the `{ signal }` options to `callAsync`.

  python3 tools/metadata/appkit/gen_types.py --write
  python3 tools/metadata/appkit/gen_types.py --check
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "tools/metadata/common"))
import types_appkit_classify as TA  # noqa: E402
import types_pkg  # noqa: E402

PKG = ROOT / "packages/types"
OUT = PKG / "appkit"
RUST = ROOT / "crates/svelters-appkit/src/generated/types.rs"
DOCS = ROOT / "docs/site/src/content/docs/types/appkit"
HEADER = "// Generated by tools/metadata/appkit/gen_types.py from metadata/appkit/types/*.json. Do not edit.\n"

# Observability facts (R0/R4): `<Framework>:<Class>` -> prop -> record. Only element classes have them today, so
# type getters are plain reads unless a fact appears for their class.
OBSERVE: dict[str, dict[str, dict]] = {o.split(":", 1)[1]: ps for o, ps in
                                       json.loads((ROOT / "metadata/observe/appkit.json").read_text())["facts"].items()}

JS_RESERVED = {"break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum",
               "export", "extends", "false", "finally", "for", "function", "if", "import", "in", "instanceof", "new", "null",
               "return", "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with", "yield",
               "let", "static", "await", "async", "of", "arguments", "eval", "interface", "package", "private", "protected",
               "public", "implements"}
INSTANCE_RESERVED = {"constructor", "prototype", "dispose", "on", "equals", "equal", "svlHandle", "disposed", "nativeType",
                     "__svlBoxed", "__proto__", "peek", "toString"}
STATIC_RESERVED = {"name", "length", "prototype", "caller", "arguments", "call", "apply", "bind", "native", "bases",
                   "signalArgs", "from"}
SHAPES = {
    "Rect": "{ x: number; y: number; width: number; height: number }",
    "Size": "{ width: number; height: number }",
    "Point": "{ x: number; y: number }",
    "Insets": "{ top: number; right: number; bottom: number; left: number }",
    "Range": "{ location: number; length: number }",
}
FW_DIR = {"Foundation": "foundation", "AppKit": "appkit"}


def inst_name(js: str) -> str:
    return js + "_" if js in INSTANCE_RESERVED or js in JS_RESERVED else js


def static_name(js: str) -> str:
    return js + "_" if js in STATIC_RESERVED or js in JS_RESERVED else js


def ident(name: str) -> str:
    return name + "_" if name in JS_RESERVED else name


def kebab(s: str) -> str:
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"-\1", s).lower()


class Gen:
    def __init__(self, facts: dict) -> None:
        self.types: dict[str, dict] = facts["types"]
        self.enums: dict[str, dict] = facts["enums"]
        self.fallback: dict[tuple[str, str], str] = {}
        self._plan_imports()

    # ---- hierarchy ----
    def root_base(self, q: str) -> str:
        return "NativeValue" if self.types[q]["category"] == "value" else "NativeObject"

    def parent(self, q: str) -> str | None:
        """The JS superclass: the nearest bound ancestor with the same root base (value and object classes
        cannot extend each other: NSMutableAttributedString flattens NSAttributedString's members)."""
        p = self.types[q].get("parent")
        if p and p in self.types and self.root_base(p) == self.root_base(q) and self.types[q]["category"] != "statics":
            return p
        return None

    def ancestors(self, q: str) -> list[str]:
        out, p = [], self.parent(q)
        while p:
            out.append(p)
            p = self.parent(p)
        return out

    def flattened(self, q: str) -> list[str]:
        """Bound ancestors whose members this class repeats (across a value/object boundary)."""
        if self.parent(q) is not None:
            return []
        out, p = [], self.types[q].get("parent")
        while p and p in self.types:
            out.append(p)
            p = self.types[p].get("parent")
        return out

    def members_of(self, q: str) -> tuple[list[dict], list[dict]]:
        """(methods, props) emitted in `q`'s class body: its own plus flattened ancestors' (first wins)."""
        methods, props = [], []
        seen_m, seen_p = set(), set()
        value_target = self.types[q]["category"] == "value"
        prop_names = {p["name"] for c in [q] + self.flattened(q) for p in self.types[c]["props"]}
        prop_getters = {p["getter"] for c in [q] + self.flattened(q) for p in self.types[c]["props"]}
        for c in [q] + self.flattened(q):
            for m in self.types[c]["methods"]:
                key = (m["js"], m["static"])
                if key in seen_m:
                    continue
                if m.get("ctor") and c != q:
                    continue  # initializers of an ancestor make the ancestor
                if not m["static"] and (m["js"] in prop_names or (not m["params"] and m["sel"] in prop_getters)):
                    continue  # the property accessor is the JS member
                seen_m.add(key)
                methods.append(m)
            for p in self.types[c]["props"]:
                if p["name"] in seen_p:
                    continue
                seen_p.add(p["name"])
                props.append(dict(p, setter=None, readonly=True) if value_target else p)
        if self.parent(q):
            inherited_methods = self.chain_methods(q)
            inherited_props = self.chain_props(q)
            props = [p for p in props if p["name"] not in inherited_methods]
            methods = [m for m in methods if m["static"] or m["js"] not in inherited_props]
        return methods, props

    # ---- wraps ----
    def wrap_target(self, t: dict) -> str | None:
        if t["k"] in ("object", "value") and t.get("t") in self.types and self.types[t["t"]]["category"] != "statics":
            return t["t"]
        if t["k"] in ("list", "map") and "of" in t:
            return self.wrap_target(t["of"])
        return None

    def chain_methods(self, q: str) -> set[str]:
        out: set[str] = set()
        for a in self.ancestors(q):
            out |= {m["js"] for m in self.members_of(a)[0] if not m["static"]}
        return out

    def chain_props(self, q: str) -> set[str]:
        out: set[str] = set()
        for a in self.ancestors(q):
            out |= {p["name"] for p in self.members_of(a)[1]}
        return out

    def slots_of(self, q: str):
        methods, props = self.members_of(q)
        for m in methods:
            yield m["ret"]
            if m.get("async"):
                yield m["async"]["result"]
        for p in props:
            yield p["type"]

    def wraps_of(self, q: str) -> set[str]:
        out = {w for s in self.slots_of(q) if (w := self.wrap_target(s))}
        out.discard(q)
        return out

    def _reaches_with_extends(self, edges: dict, start: str, goal: str) -> bool:
        seen, stack = set(), [(start, False)]
        while stack:
            n, used = stack.pop()
            if (n, used) in seen:
                continue
            seen.add((n, used))
            if n == goal and used:
                return True
            p = self.parent(n)
            if p:
                stack.append((p, True))
            for w in edges.get(n, ()):
                stack.append((w, used))
        return False

    def _plan_imports(self) -> None:
        edges: dict[str, set[str]] = {q: set() for q in self.types}
        for q in sorted(self.types):
            for w in sorted(self.wraps_of(q)):
                target = None
                for cand in [w] + self.ancestors(w):
                    if cand == q or cand in self.ancestors(q) or not self._reaches_with_extends(edges, cand, q):
                        target = cand
                        break
                if target is None:
                    self.fallback[(q, w)] = self.root_base(w)
                elif target != w:
                    self.fallback[(q, w)] = target
                if target and target != q:
                    edges[q].add(target)

    def wrap_class(self, q: str, w: str) -> str:
        return self.fallback.get((q, w), w)

    def imports_of(self, q: str) -> list[str]:
        out: list[str] = []
        p = self.parent(q)
        if p:
            out.append(p)
        for w in sorted(self.wraps_of(q)):
            t = self.wrap_class(q, w)
            if t in self.types and t != q and t not in out:
                out.append(t)
        return out

    def w_expr(self, q: str, t: dict, e: str) -> str:
        w = self.wrap_target(t)
        if not w:
            return e
        if t["k"] == "list":
            return f"({e})?.map((e) => {self.w_expr(q, t['of'], 'e')}) ?? null"
        if t["k"] == "map":
            return f"((m) => m && Object.fromEntries(Object.entries(m).map(([k, e]) => [k, {self.w_expr(q, t['of'], 'e')}])))({e})"
        cls = self.wrap_class(q, w)
        fn = "wrapValue" if self.types[w]["category"] == "value" else "wrapObject"
        return f"{fn}({cls}, {e})"

    def rel(self, q: str, other: str) -> str:
        a, b = FW_DIR[self.types[q]["framework"]], FW_DIR[self.types[other]["framework"]] if other in self.types else None
        return f"./{other}.js" if a == b else f"../{b}/{other}.js"

    # ---- JS ----
    def arg_expr(self, p: dict) -> str:
        n = ident(p["name"])
        return f"typeArg({n})" if p["type"]["k"] == "type" else n

    def method_js(self, q: str, m: dict, uses: set[str]) -> str:
        params = [ident(p["name"]) for p in m["params"]]
        args = "[" + ", ".join(self.arg_expr(p) for p in m["params"]) + "]"
        if any(p["type"]["k"] == "type" for p in m["params"]):
            uses.add("typeArg")
        native = self.types[q]["name"]
        if m.get("async"):
            res = m["async"]["result"]
            shape = ""
            if self.wrap_target(res):
                shape = f", (r) => {self.w_expr(q, res, 'r')}"
            sig = ", ".join(params + ["options"])
            if m["static"]:
                uses.add("callStaticAsync")
                body = f"return callStaticAsync('{native}', '{m['sel']}', {args}, options{shape});"
            else:
                uses.add("callAsync")
                body = f"return callAsync(this, '{m['sel']}', {args}, options{shape});"
            name = static_name(m["js"]) if m["static"] else inst_name(m["js"])
            return f"  {'static ' if m['static'] else ''}{name}({sig}) {{\n    {body}\n  }}\n"
        if m["static"]:
            uses.add("callStatic")
            raw = f"callStatic('{native}', '{m['sel']}', {args})"
        else:
            uses.add("call")
            raw = f"call(this, '{m['sel']}', {args})"
        e = self.w_expr(q, m["ret"], raw)
        if m["ret"]["k"] == "void":
            body = f"{raw};"
        else:
            body = f"return {e};"
        name = static_name(m["js"]) if m["static"] else inst_name(m["js"])
        return f"  {'static ' if m['static'] else ''}{name}({', '.join(params)}) {{\n    {body}\n  }}\n"

    def class_js(self, q: str) -> str:
        t = self.types[q]
        methods, props = self.members_of(q)
        uses: set[str] = {"CONSTRUCT"}
        base = self.parent(q) or self.root_base(q)
        if base in ("NativeValue", "NativeObject"):
            uses.add(base)
        body: list[str] = [f"  static native = '{q}';\n", f"  static bases = {json.dumps([q] + t['bases'])};\n"]
        # constructor
        ctor_lines = ["  static [CONSTRUCT](...args) {\n"]
        if t.get("string_ctor"):
            uses.add("callStatic")
            ctor_lines.append(f"    if (args.length === 1 && typeof args[0] === 'string') {{\n"
                              f"      const r = callStatic('{q}', '{t['string_ctor']}', args);\n"
                              f"      if (r === null || r === undefined) throw new TypeError(`{q}: {t['string_ctor']} refused ${{JSON.stringify(args[0])}}`);\n"
                              f"      return r;\n    }}\n")
        writable = {p["name"]: p["key"] for p in props if p.get("setter") and t["category"] != "value"}
        if t["constructible"] and t["category"] != "statics":
            uses |= {"construct", "constructProps", "isProps"}
            pm = ", ".join(f"'{k}': ['{v}']" for k, v in sorted(writable.items()))
            ctor_lines.append(f"    if (isProps(args)) return construct('{q}', constructProps(this, args[0], {{{pm}}}));\n")
        ctor_lines.append(f"    throw new TypeError('{q} has no such constructor: use a static (new…, …With…)');\n  }}\n")
        body.append("".join(ctor_lines))
        if t["category"] == "value":
            uses.add("call")
            body.append("  equal(other) {\n    return call(this, 'isEqual:', [other]);\n  }\n")
            body.append("  toString() {\n    return call(this, 'description', []);\n  }\n")
        for m in sorted((m for m in methods if m["static"]), key=lambda m: m["js"]):
            body.append(self.method_js(q, m, uses))
        for m in sorted((m for m in methods if not m["static"]), key=lambda m: m["js"]):
            body.append(self.method_js(q, m, uses))
        for p in props:
            name = inst_name(p["name"])
            fact = OBSERVE.get(f"{t['framework']}:{q}", {}).get(kebab(p["key"]))
            klass = (fact or {}).get("class")
            if t["category"] == "value":
                uses.add("call")
                get = self.w_expr(q, p["type"], f"call(this, '{p['getter']}', [])")
            elif klass in ("exact", "partial"):
                uses.add("observed")
                get = self.w_expr(q, p["type"], f"observed(this, '{p['key']}')")
            elif klass == "set_only":
                uses.add("observedLocal")
                get = self.w_expr(q, p["type"], f"observedLocal(this, '{p['key']}')")
            else:
                uses.add("getProp")
                get = self.w_expr(q, p["type"], f"getProp(this, '{p['key']}')")
            body.append(f"  get {name}() {{\n    return {get};\n  }}\n")
            if p.get("setter") and t["category"] != "value":
                uses.add("setProp")
                body.append(f"  set {name}(v) {{\n    setProp(this, '{p['key']}', v);\n  }}\n")
        for s in self.slots_of(q):
            w = self.wrap_target(s)
            if w:
                uses.add("wrapValue" if self.types[w]["category"] == "value" else "wrapObject")
        imports = self.imports_of(q)
        lines = [HEADER, f"import {{ {', '.join(sorted(uses))} }} from '../../src/core.js';\n"]
        extra_bases = {self.wrap_class(q, w) for w in self.wraps_of(q)} & {"NativeObject", "NativeValue"}
        if extra_bases - uses:
            lines[1] = f"import {{ {', '.join(sorted(uses | extra_bases))} }} from '../../src/core.js';\n"
        for i in imports:
            lines.append(f"import {{ {i} }} from '{self.rel(q, i)}';\n")
        lines.append(f"\nexport class {q} extends {base} {{\n")
        lines.append("\n".join(body))
        lines.append("}\n")
        return "".join(lines)

    def enums_js(self, fw: str) -> str:
        out = [HEADER, "// NS_ENUM / NS_OPTIONS values used by the bound members (numbers cross the bridge as is).\n"]
        for n, e in sorted(self.enums.items()):
            if e["framework"] != fw:
                continue
            body = ", ".join(f"{json.dumps(k)}: {v}" for k, v in e["members"].items() if abs(v) < 2 ** 53)
            out.append(f"\nexport const {n} = /* @__PURE__ */ Object.freeze({{ {body} }});\n")
        return "".join(out)

    def index_js(self, fw: str) -> str:
        names = sorted(q for q, t in self.types.items() if t["framework"] == fw)
        lines = [HEADER] + [f"export {{ {q} }} from './{q}.js';\n" for q in names]
        if any(e["framework"] == fw for e in self.enums.values()):
            lines.append("export * from './enums.js';\n")
        return "".join(lines)

    # ---- typings ----
    def ts(self, t: dict, q: str, param: bool = False) -> str:
        k = t["k"]
        base = {
            "void": "void", "bool": "boolean", "int": "number", "float": "number", "enum": "number", "flags": "number",
            "string": "string", "number": "number", "bytes": "Uint8Array", "date": "Date", "null": "null", "any": "unknown",
            "type": "string | { readonly native: string }",
        }.get(k)
        if base is None:
            if k == "record":
                base = t["t"]
            elif k == "list":
                base = f"Array<{self.ts(t.get('of', {'k': 'any'}), q)}>"
            elif k == "map":
                base = f"Record<string, {self.ts(t.get('of', {'k': 'any'}), q)}>"
            elif k in ("object", "value"):
                w = t["t"]
                base = w if w in self.types else ("NativeValue" if k == "value" else "NativeObject")
            else:
                base = "unknown"
        if t.get("nullable") and base not in ("unknown", "void", "null"):
            base += " | null"
        return base

    def method_ts(self, q: str, m: dict) -> str:
        ps = ", ".join(f"{ident(p['name'])}: {self.ts(p['type'], q, True)}" for p in m["params"])
        name = static_name(m["js"]) if m["static"] else inst_name(m["js"])
        pre = "static " if m["static"] else ""
        if m.get("async"):
            ps = ", ".join(x for x in [ps, "options?: AsyncOptions"] if x)
            return f"    {pre}{name}({ps}): Promise<{self.ts(m['async']['result'], q)}>;"
        notes = []
        if m.get("throws"):
            notes.append("@throws NativeError (the method's NSError)")
        doc = f"    /** `{'+' if m['static'] and not m.get('ctor') else '-'}[{q} {m['sel']}]`{(' ' + ' '.join(notes)) if notes else ''} */\n"
        return f"{doc}    {pre}{name}({ps}): {self.ts(m['ret'], q)};"

    def dts(self, fw: str) -> str:
        mod = f"svelters:appkit/{FW_DIR[fw]}"
        names = sorted(q for q, t in self.types.items() if t["framework"] == fw)
        refs: set[str] = set()
        for q in names:
            methods, props = self.members_of(q)
            for m in methods:
                for sl in [m["ret"]] + [p["type"] for p in m["params"]] + ([m["async"]["result"]] if m.get("async") else []):
                    refs |= TA.refs_of(sl)
            for pr in props:
                refs |= TA.refs_of(pr["type"])
            if self.parent(q):
                refs.add(self.parent(q))
        other = sorted(w for w in refs if w in self.types and self.types[w]["framework"] != fw)
        L = [HEADER, f"declare module '{mod}' {{\n",
             "  import type { NativeObject, NativeValue, AsyncOptions } from '@svelters/types/core';\n"]
        if other:
            omod = {self.types[o]["framework"] for o in other}
            for ofw in sorted(omod):
                L.append(f"  import type {{ {', '.join(o for o in other if self.types[o]['framework'] == ofw)} }} from 'svelters:appkit/{FW_DIR[ofw]}';\n")
        L.append("\n")
        for n, sh in SHAPES.items():
            L.append(f"  export type {n} = {sh};\n")
        for n, e in sorted(self.enums.items()):
            if e["framework"] == fw:
                body = "; ".join(f"readonly {json.dumps(k)}: {v}" for k, v in e["members"].items() if abs(v) < 2 ** 53)
                L.append(f"  export const {n}: {{ {body} }};\n")
        for q in names:
            t = self.types[q]
            methods, props = self.members_of(q)
            base = self.parent(q) or self.root_base(q)
            L.append(f"\n  /** `{q}` ({fw}), {t['category']}, lifetime shared{'; main thread only' if t.get('thread') == 'main' else ''} */\n")
            L.append(f"  export class {q} extends {base} {{\n    static readonly native: string;\n")
            ctor = []
            if t.get("string_ctor"):
                ctor.append("string: string")
            writable = [p for p in props if p.get("setter") and t["category"] != "value"]
            if t["constructible"] and t["category"] != "statics":
                pt = "; ".join(f"{p['name']}?: {self.ts(p['type'], q, True)}" for p in writable)
                ctor.append(f"props?: {{ {pt} }}" if pt else "props?: {}")
            for c in ctor:
                L.append(f"    constructor({c});\n")
            if not ctor:
                L.append("    protected constructor();\n")
            if t["category"] == "value":
                L.append(f"    equal(other: {q} | null): boolean;\n    toString(): string;\n")
            for m in sorted((m for m in methods if m["static"]), key=lambda m: m["js"]):
                L.append(self.method_ts(q, m) + "\n")
            for m in sorted((m for m in methods if not m["static"]), key=lambda m: m["js"]):
                L.append(self.method_ts(q, m) + "\n")
            for p in props:
                ro = "readonly " if (p["readonly"] or t["category"] == "value" or not p.get("setter")) else ""
                L.append(f"    {ro}{inst_name(p['name'])}: {self.ts(p['type'], q)};\n")
            L.append("  }\n")
        L.append("}\n")
        return "".join(L)

    # ---- manifest (Q9) ----
    def manifest(self) -> dict:
        mods: dict = {}
        for q, t in sorted(self.types.items()):
            fw = t["framework"]
            mod = mods.setdefault(f"svelters:appkit/{FW_DIR[fw]}", {"dir": FW_DIR[fw], "exports": {}})
            sig = set()
            methods, props = self.members_of(q)
            for m in methods:
                for s in [m["ret"]] + [p["type"] for p in m["params"]] + ([m["async"]["result"]] if m.get("async") else []):
                    sig |= {r for r in TA.refs_of(s) if r in self.types}
                    sig |= TA.enums_of(s)
            for p in props:
                sig |= {r for r in TA.refs_of(p["type"]) if r in self.types}
                sig |= TA.enums_of(p["type"])
            if self.parent(q):
                sig.add(self.parent(q))
            sig.discard(q)
            mod["exports"][q] = {
                "category": t["category"], "extends": self.parent(q), "file": f"{FW_DIR[fw]}/{q}.js", "implements": [],
                "imports": self.imports_of(q), "native": q, "signature": sorted(sig),
            }
        return {"schema": "svelters-types-manifest/v1", "toolkit": "appkit", "modules": mods}

    # ---- docs ----
    def doc_page(self, q: str) -> str:
        t = self.types[q]
        fw = t["framework"]
        mod = f"svelters:appkit/{FW_DIR[fw]}"
        methods, props = self.members_of(q)
        L = ["---", f"title: {q}", f'description: "{q} from {mod}, a {t["category"]} class generated from objc2 facts."', "---", "",
             "```js", f"import {{ {q} }} from '{mod}';", "```", "", "## Class", "",
             f"`{q}` ({fw}), category **{t['category']}**{' (main thread only)' if t.get('thread') == 'main' else ''}.", ""]
        if t["category"] == "value":
            L.append("Lifetime: an immutable Objective-C object behind a **SHARED** handle (one strong reference). Sharing an "
                     "immutable object is indistinguishable from copying it, so there is no identity contract: `equals()` uses "
                     "`isEqual:`, `toString()` is `description`. Setters and mutating selectors are hidden (decision Q3).")
        else:
            L.append("Lifetime: **SHARED**: one JS object per native object, holding one strong reference (retain); "
                     "`dispose()` or garbage collection drops our reference only.")
        L += ["", f"Facts: `metadata/appkit/types/{fw}.json`; ledger fact ids `svelters-api:v1:type:appkit:{fw}:{q}:*` in "
              "`metadata/verified/appkit.json`. Methods are called by selector; the JS name joins the selector's pieces.", ""]
        L += ["## Construct", ""]
        if t.get("string_ctor"):
            L.append(f"- `new {q}(string)`: `{t['string_ctor']}`")
        if t["constructible"]:
            L.append(f"- `new {q}(props?)`: `[[{q} alloc] init]`, then the properties by KVC")
        ctors = [m for m in methods if m.get("ctor")]
        for m in sorted(ctors, key=lambda m: m["js"]):
            L.append(f"- `{q}.{static_name(m['js'])}({', '.join(p['name'] for p in m['params'])})`: `-[{q} {m['sel']}]`")
        if not (t.get("string_ctor") or t["constructible"] or ctors):
            L.append("Not constructible: instances come from statics or other objects.")
        stat = [m for m in methods if m["static"] and not m.get("ctor")]
        if stat:
            L += ["", "## Statics", ""]
            for m in sorted(stat, key=lambda m: m["js"]):
                L.append(f"- `{q}.{static_name(m['js'])}({', '.join(p['name'] for p in m['params'])})`: `+{m['sel']}`"
                         + (" (async)" if m.get("async") else "") + (" (throws)" if m.get("throws") else ""))
        inst = [m for m in methods if not m["static"]]
        if inst:
            L += ["", "## Methods", ""]
            for m in sorted(inst, key=lambda m: m["js"]):
                L.append(f"- `{inst_name(m['js'])}({', '.join(p['name'] for p in m['params'])})`: `-{m['sel']}`"
                         + (" (async: returns a Promise; `{ signal }` cancels)" if m.get("async") else "")
                         + (" (throws a NativeError)" if m.get("throws") else ""))
        if props:
            L += ["", "## Properties", ""]
            for p in props:
                L.append(f"- `{p['name']}`{' (read-only)' if p['readonly'] or t['category'] == 'value' else ''}: KVC `{p['key']}`"
                         f" ({p['origin']})")
        if t["blocked"]:
            L += ["", "## Not bound", ""]
            for sel, why in sorted(t["blocked"].items()):
                L.append(f"- `{sel}`: {why}")
        return "\n".join(L) + "\n"

