#!/usr/bin/env python3
"""Generate the AppKit backend tables and verification tests.

Inputs (only these):
  metadata/appkit/*.json               ingested facts (tools/metadata/appkit/ingest.py, checked in)
  metadata/overrides/appkit/*.yaml     annotations (schema: tools/metadata/appkit/override.schema.json)
Outputs (checked in, byte-identical on rerun):
  crates/svelters-appkit/src/generated/tables.rs   kinds, props, enums, signals, methods, slots
  examples/counter-mac/tests/generated.rs          one test per annotated fact (runs on macOS)

Every override fact is resolved against the ingested metadata of its class and bases; an
unresolvable fact is an error. Usage: python3 tools/metadata/appkit/gen_backend.py [--check]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / "common"))
import names  # noqa: E402
import svmeta  # noqa: E402

ROOT = HERE.parents[2]
META = ROOT / "metadata/appkit"
OVERRIDES = ROOT / "metadata/overrides/appkit"
SCHEMA = HERE / "override.schema.json"
OUT_TABLES = ROOT / "crates/svelters-appkit/src/generated/tables.rs"
OUT_TESTS = ROOT / "examples/counter-mac/tests/generated.rs"
HEADER = "// @generated by tools/metadata/appkit/gen_backend.py from metadata/appkit/*.json and metadata/overrides/appkit/*.yaml. Do not edit.\n"

SCALAR_TY = {"bool": "Bool", "i32": "I32", "i64": "I64", "u32": "U32", "u64": "U64", "f32": "F32", "f64": "F64",
             "string": "Str", "rect": "Rect", "size": "Size", "point": "Point", "insets": "Insets", "range": "Range", "list": "List"}
STRUCT_FIELDS = {"rect": ("SVL_T_RECT", ["x", "y", "width", "height"]), "size": ("SVL_T_SIZE", ["width", "height"]),
                 "point": ("SVL_T_POINT", ["x", "y"]), "insets": ("SVL_T_INSETS", ["top", "right", "bottom", "left"])}
INTEGER = {"i32", "i64", "u32", "u64"}
FLOAT = {"f32", "f64"}


class GenError(Exception):
    pass


def rs(s: str) -> str:
    return json.dumps(s)


def ident(*parts: str) -> str:
    return "_".join(p.lower().replace("-", "_").replace(":", "") for p in parts)


def value(v, ref: str | None = None) -> str:
    """A Rust `V` literal for a JS sample; `ref` types structs as their well-known records."""
    if ref in STRUCT_FIELDS and isinstance(v, dict):
        ty, fields = STRUCT_FIELDS[ref]
        return f"V::Record {{ ty: {ty}, fields: vec![{', '.join(value(float(v[f])) for f in fields)}] }}"
    if isinstance(v, bool):
        return f"V::Bool({'true' if v else 'false'})"
    if isinstance(v, int):
        return f"V::I64({v})"
    if isinstance(v, float):
        return f"V::F64({v!r})"
    if isinstance(v, str):
        return f"V::Str({rs(v)}.into())"
    if isinstance(v, list):
        return f"V::List(vec![{', '.join(value(x) for x in v)}])"
    if isinstance(v, dict):
        return "V::Map(vec![" + ", ".join(f"({rs(k)}.into(), {value(x)})" for k, x in v.items()) + "])"
    raise GenError(f"unsupported sample {v!r}")


class Model:
    def __init__(self):
        self.meta = {p.stem: svmeta.load_json(p) for p in sorted(META.glob("NS*.json"))}
        enums = svmeta.load_json(META / "_enums.json")["enums"]
        self.enums = {e["name"]: {"flags": e["flags"], "members": [(m["js"], m["value"]) for m in e["members"]]} for e in enums}
        self.ov = {}
        errs = []
        for p in sorted(OVERRIDES.glob("*.yaml")):
            errs += svmeta.check_override(p, SCHEMA)
            data = svmeta.load_yaml(p)
            if data.get("class") != p.stem:
                errs.append(f"{p.name}: class must be {p.stem}")
            self.ov[p.stem] = data
        if errs:
            raise GenError("\n".join(errs))
        missing = sorted(set(self.ov) - set(self.meta))
        if missing:
            raise GenError(f"overrides without ingested metadata (run ingest.py): {missing}")
        self.classes = sorted(self.meta)
        self.kid = {c: i + 1 for i, c in enumerate(self.classes)}

    def chain(self, cls: str) -> list[str]:
        """The class and its ingested bases, most derived first."""
        return [cls] + [b for b in self.meta[cls]["bases"] if b in self.meta]

    def find_prop(self, cls: str, js: str):
        for c in self.chain(cls):
            for p in self.meta[c]["properties"]:
                if p["js_name"] == js:
                    return c, p
        return None, None

    def has_method(self, cls: str, sel: str) -> bool:
        return any(m["selector"] == sel for c in self.chain(cls) for m in self.meta[c]["methods"])

    def element_for(self, cls: str) -> str | None:
        """The tag to test a class's facts on: its own, else the first element (by tag) deriving from it."""
        own = (self.ov.get(cls, {}).get("element") or {}).get("tag")
        if own:
            return own
        cands = sorted((ov["element"]["tag"], c) for c, ov in self.ov.items() if ov.get("element") and cls in self.chain(c))
        return cands[0][0] if cands else None


def build(m: Model):
    enum_names = sorted(m.enums)
    extra_enums = []  # (name, members) from overrides
    for cls in m.classes:
        for e in m.ov.get(cls, {}).get("enums", []):
            owner, p = m.find_prop(cls, e["prop"])
            if p is None:
                raise GenError(f"{cls}: enums: unknown prop {e['prop']}")
            if p["type"]["ref"] not in INTEGER:
                raise GenError(f"{cls}: enums: prop {e['prop']} is {p['type']['ref']}, not an integer")
            extra_enums.append((f"{cls}.{e['prop']}", sorted(e["members"].items(), key=lambda kv: kv[1])))
    all_enums = [(n, m.enums[n]["flags"], m.enums[n]["members"]) for n in enum_names] + [(n, False, mem) for n, mem in sorted(extra_enums)]
    eidx = {n: i for i, (n, _, _) in enumerate(all_enums)}
    prop_enum = {n.split(".", 1)[0] + "\0" + n.split(".", 1)[1]: i for i, (n, _, _) in enumerate(all_enums) if "." in n}

    def ty_of(cls: str, p: dict) -> str | None:
        ref = p["type"]["ref"]
        if (cls + "\0" + p["js_name"]) in prop_enum:
            return f"Ty::Enum({prop_enum[cls + chr(0) + p['js_name']]})"
        if ref in SCALAR_TY:
            return f"Ty::{SCALAR_TY[ref]}"
        if ref.startswith(("enum<", "flags<")):
            n = ref[ref.index("<") + 1:-1]
            if n not in eidx:
                return None
            return f"Ty::{'Flags' if ref.startswith('flags') else 'Enum'}({eidx[n]})"
        if ref == "object":
            return 'Ty::Object("")'
        if ref.startswith("object<"):
            return f"Ty::Object({rs(ref[7:-1])})"
        return None

    kinds, props, signals, methods, slots = [], [], [], [], []
    for cls in m.classes:
        ov = m.ov.get(cls, {})
        el = ov.get("element") or {}
        bases = [b for b in m.meta[cls]["bases"] if b in m.meta]
        parent = m.kid[bases[0]] if bases else 0
        if el:
            want = names.class_tag(cls)
            if el["tag"] != want:
                raise GenError(f"{cls}: tag must be {want!r} (class name without NS, kebab-case)")
        ctor = "Ctor::New"
        if el.get("construct") == "window":
            w = el.get("window") or {}
            mask_members = dict(m.enums["NSWindowStyleMask"]["members"])
            try:
                mask = sum(mask_members[x] for x in w["style_mask"])
            except KeyError as e:
                raise GenError(f"{cls}: unknown style mask member {e}") from None
            ctor = f"Ctor::Window {{ width: {float(w['width'])!r}, height: {float(w['height'])!r}, style_mask: {mask} }}"
        kinds.append(f"    KindInfo {{ class: {rs(cls)}, tag: {rs(el.get('tag', ''))}, parent: {parent}, toplevel: {str(el.get('lifetime') == 'toplevel').lower()}, ctor: {ctor} }},\n")
        k = m.kid[cls]
        for p in m.meta[cls]["properties"]:
            t = ty_of(cls, p)
            if t is None:
                continue
            props.append(f"    PropInfo {{ kind: {k}, name: {rs(p['js_name'])}, key: {rs(p['name'])}, ty: {t}, writable: {str(p['access']['write']).lower()}, setter: \"\" }},\n")
        # props named in overrides of a subclass resolve along the chain; check they exist
        for p in ov.get("props", []):
            if m.find_prop(cls, p["name"])[1] is None:
                raise GenError(f"{cls}: props: unknown property {p['name']}")
        for s in ov.get("setters", []):
            if not m.has_method(cls, s["selector"]):
                raise GenError(f"{cls}: setters: {s['selector']} is not an ingested method")
            if names.selector_arity(s["selector"]) != 1:
                raise GenError(f"{cls}: setters: {s['selector']} must take one argument")
            ref = s["type"]
            t = ty_of(cls, {"js_name": s["name"], "type": {"ref": ref}})
            if t is None:
                raise GenError(f"{cls}: setters: unsupported type {ref}")
            props.append(f"    PropInfo {{ kind: {k}, name: {rs(s['name'])}, key: \"\", ty: {t}, writable: true, setter: {rs(s['selector'])} }},\n")
        for s in ov.get("signals", []):
            via = s["via"]
            if via == "target_action":
                if s["name"] != "action":
                    raise GenError(f"{cls}: the target-action signal is named `action` (the native property)")
                native = ""
            elif via == "notification":
                native = s.get("notification") or ""
                if s["name"] != names.notification_signal(native):
                    raise GenError(f"{cls}: signal {s['name']} must be named {names.notification_signal(native)!r}")
            else:
                native = s.get("selector") or ""
                if s["name"] != names.selector_name(native):
                    raise GenError(f"{cls}: signal {s['name']} must be named {names.selector_name(native)!r}")
            for a in s.get("args", []):
                if m.find_prop(cls, a)[1] is None:
                    raise GenError(f"{cls}: signal {s['name']}: unknown arg prop {a}")
            sync = "SyncResult::VetoBool" if s.get("result") == "veto_bool" else "SyncResult::None"
            if (s.get("delivery") == "sync") != (s.get("result", "none") != "none"):
                raise GenError(f"{cls}: signal {s['name']}: delivery sync needs a result and vice versa")
            vias = {"target_action": "TargetAction", "notification": "Notification", "delegate": "Delegate"}
            args = ", ".join(rs(a) for a in s.get("args", []))
            signals.append(f"    SignalInfo {{ kind: {k}, name: {rs(s['name'])}, via: Via::{vias[via]}, native: {rs(native)}, sync: {sync}, args: &[{args}] }},\n")
        for meth in ov.get("methods", []):
            if not m.has_method(cls, meth["selector"]):
                raise GenError(f"{cls}: methods: {meth['selector']} is not an ingested method")
            if meth["name"] != names.selector_name(meth["selector"]):
                raise GenError(f"{cls}: method {meth['name']} must be named {names.selector_name(meth['selector'])!r}")
            methods.append(f"    MethodInfo {{ kind: {k}, name: {rs(meth['name'])}, selector: {rs(meth['selector'])} }},\n")
        for sl in ov.get("slots", []):
            ops = sl["ops"]
            for key in ("set", "append", "insert_at", "insert_relative"):
                if key in ops and not m.has_method(cls, ops[key]):
                    raise GenError(f"{cls}: slot {sl['name']}: {ops[key]} is not an ingested method")
            for sel in ops.get("remove", []) + ops.get("detach", []):
                if not any(m.has_method(c, sel) for c in m.classes):
                    raise GenError(f"{cls}: slot {sl['name']}: {sel} is not an ingested method")
            for key in ("get", "list"):
                if key in ops and m.find_prop(cls, names.kebab(ops[key]))[1] is None:
                    raise GenError(f"{cls}: slot {sl['name']}: {ops[key]} is not a property")
            many = sl["cardinality"] == "many"
            if many and not (ops.get("append") or ops.get("insert_at") or ops.get("insert_relative")):
                raise GenError(f"{cls}: slot {sl['name']}: a many slot needs append/insert_at/insert_relative")
            if not many and not ops.get("set"):
                raise GenError(f"{cls}: slot {sl['name']}: a one slot needs set")
            clear = "Clear::EmptyView" if ops.get("clear") == "empty_view" else "Clear::Nil"
            rem = ", ".join(rs(x) for x in ops.get("remove", []))
            det = ", ".join(rs(x) for x in ops.get("detach", []))
            slots.append(
                f"    SlotInfo {{ kind: {k}, name: {rs(sl['name'])}, default: {str(bool(sl.get('default'))).lower()}, many: {str(many).lower()}, "
                f"set: {rs(ops.get('set', ''))}, get: {rs(ops.get('get', ''))}, clear: {clear}, append: {rs(ops.get('append', ''))}, "
                f"insert_at: {rs(ops.get('insert_at', ''))}, insert_relative: {rs(ops.get('insert_relative', ''))}, list: {rs(ops.get('list', ''))}, "
                f"remove: &[{rem}], detach: &[{det}] }},\n")

    o = [HEADER, "#![allow(dead_code)]\n", "use crate::tables::*;\n\n"]
    o.append(f"pub static KINDS: &[KindInfo] = &[\n{''.join(kinds)}];\n\n")
    o.append(f"pub static PROPS: &[PropInfo] = &[\n{''.join(props)}];\n\n")
    o.append("pub static ENUMS: &[EnumInfo] = &[\n")
    for n, flags, mem in all_enums:
        ms = ", ".join(f"({rs(a)}, {v})" for a, v in mem)
        o.append(f"    EnumInfo {{ name: {rs(n)}, flags: {str(flags).lower()}, members: &[{ms}] }},\n")
    o.append("];\n\n")
    o.append(f"pub static SIGNALS: &[SignalInfo] = &[\n{''.join(signals)}];\n\n")
    o.append(f"pub static METHODS: &[MethodInfo] = &[\n{''.join(methods)}];\n\n")
    o.append(f"pub static SLOTS: &[SlotInfo] = &[\n{''.join(slots)}];\n")
    return "".join(o)


def tests(m: Model) -> str:
    cases: list[tuple[str, str, str]] = []  # (name, doc, body)

    def add(name, doc, body):
        if any(n == name for n, _, _ in cases):
            raise GenError(f"duplicate test {name}")
        cases.append((name, doc, body))

    for cls in m.classes:
        ov = m.ov.get(cls, {})
        el = ov.get("element")
        tag = m.element_for(cls)
        if el:
            add(f"kind_{ident(cls)}", f"kind {cls}: <{el['tag']}> creates an {cls}",
                f'    let o = h.create({rs(el["tag"])});\n    assert!(h.is_kind(o, {rs(cls)}), "is a {cls}");\n'
                f'    assert_eq!(h.lifetime(o), {2 if el["lifetime"] == "toplevel" else 1});\n    h.destroy(o);\n')
            add(f"readable_{ident(cls)}", f"every readable table prop of <{el['tag']}> reads back without an error",
                f'    let o = h.create({rs(el["tag"])});\n    let mut bad = Vec::new();\n'
                f'    for name in h.readable_props({rs(el["tag"])}) {{\n        if let Err(e) = h.get(o, name) {{\n            bad.push(format!("{{name}}: {{e}}"));\n        }}\n    }}\n'
                f'    h.destroy(o);\n    assert!(bad.is_empty(), "unreadable props: {{bad:#?}}");\n')
        if tag is None:
            continue
        for p in ov.get("props", []):
            if "sample" not in p:
                continue
            _, meta = m.find_prop(cls, p["name"])
            ref = meta["type"]["ref"]
            exp = p.get("expect", p["sample"])
            if ref in FLOAT and isinstance(exp, int) and not isinstance(exp, bool):
                exp = float(exp)
            add(f"prop_{ident(cls, p['name'])}", f"prop {cls}.{p['name']}: {p['provenance']}",
                f'    let o = h.create({rs(tag)});\n    h.set(o, {rs(p["name"])}, {value(p["sample"], ref)}).unwrap();\n'
                f'    assert_eq!(h.get(o, {rs(p["name"])}).unwrap(), {value(exp, ref)});\n    h.destroy(o);\n')
        for s in ov.get("setters", []):
            if "sample" not in s:
                continue
            add(f"setter_{ident(cls, s['name'])}", f"setter {cls}.{s['name']} ({s['selector']}): {s['provenance']}",
                f'    let o = h.create({rs(tag)});\n    h.set(o, {rs(s["name"])}, {value(s["sample"], s["type"])}).unwrap();\n'
                f'    assert!(h.get(o, {rs(s["name"])}).is_err(), "setter-only props are not readable");\n    h.destroy(o);\n')
        for sl in ov.get("slots", []):
            ops = sl["ops"]
            name = sl["name"]
            if sl["cardinality"] == "many":
                body = (f'    let p = h.create({rs(tag)});\n    let a = h.create("view");\n    let b = h.create("view");\n'
                        f'    h.insert(p, a, None, Some({rs(name)})).unwrap();\n    h.insert(p, b, Some(a), Some({rs(name)})).unwrap();\n'
                        f'    assert_eq!(h.native_list(p, {rs(ops["list"])}), vec![h.obj(b), h.obj(a)], "b inserted before a");\n'
                        f'    assert!(h.superview(a) == Some(h.obj(p)), "a is a subview");\n'
                        f'    h.remove(p, b).unwrap();\n    assert!(h.superview(b).is_none(), "removed child is detached");\n'
                        f'    assert_eq!(h.native_list(p, {rs(ops["list"])}), vec![h.obj(a)]);\n'
                        f'    h.remove(p, b).unwrap_err();\n    h.insert(p, b, None, Some({rs(name)})).unwrap();\n'
                        f'    assert_eq!(h.native_list(p, {rs(ops["list"])}), vec![h.obj(a), h.obj(b)], "re-inserted at the end");\n'
                        f'    h.destroy(p);\n    h.destroy(a);\n    h.destroy(b);\n')
            else:
                clear = ('    assert!(h.native_get(p, {g}).is_some_and(|v| v != h.obj(b)), "cleared to a fresh view");\n'
                         if ops.get("clear") == "empty_view" else '    assert!(h.native_get(p, {g}).is_none(), "cleared");\n').format(g=rs(ops["get"]))
                body = (f'    let p = h.create({rs(tag)});\n    let a = h.create("view");\n    let b = h.create("view");\n'
                        f'    h.insert(p, a, None, Some({rs(name)})).unwrap();\n    assert!(h.native_get(p, {rs(ops["get"])}) == Some(h.obj(a)), "a set");\n'
                        f'    h.insert(p, b, None, Some({rs(name)})).unwrap();\n    assert!(h.native_get(p, {rs(ops["get"])}) == Some(h.obj(b)), "b replaces a");\n'
                        f'    assert!(h.alive(a), "the replaced child stays alive (handle)");\n    h.remove(p, a).unwrap_err();\n'
                        f'    h.remove(p, b).unwrap();\n{clear}    h.destroy(p);\n    h.destroy(a);\n    h.destroy(b);\n')
            add(f"slot_{ident(cls, name)}", f"slot {cls}.{name}: {sl['provenance']}", body)
        for s in ov.get("signals", []):
            verify = s.get("verify", "none")
            if s["via"] == "delegate" and s.get("result") == "veto_bool":
                body = (f'    let w = h.create({rs(tag)});\n    h.call(w, "make-key-and-order-front", vec![]).unwrap();\n'
                        f'    h.listen(w, {rs(s["name"])}, true).unwrap();\n    h.set_sync_reply(V::Bool(true));\n    h.perform_close(w);\n'
                        f'    assert!(h.alive(w) && h.is_visible(w), "a true result (preventDefault) vetoes the close");\n'
                        f'    assert!(h.take_events().iter().any(|e| e.0 == w && e.1 == {rs(s["name"])}), "the handler ran");\n'
                        f'    h.set_sync_reply(V::Null);\n    h.perform_close(w);\n    h.pump(50);\n'
                        f'    assert!(!h.alive(w), "no decision lets the window close");\n'
                        f'    assert!(h.take_gone().contains(&(w, svelters_abi::SVL_GONE_CLOSED)), "reported closed");\n')
            elif s["via"] == "delegate":
                body = (f'    let w = h.create({rs(tag)});\n    h.call(w, "make-key-and-order-front", vec![]).unwrap();\n'
                        f'    h.listen(w, {rs(s["name"])}, true).unwrap();\n    h.close_window(w);\n    h.pump(50);\n'
                        f'    assert!(h.take_events().iter().any(|e| e.0 == w && e.1 == {rs(s["name"])}), "posted");\n'
                        f'    assert!(h.take_gone().contains(&(w, svelters_abi::SVL_GONE_CLOSED)), "reported closed");\n')
            elif verify in ("send_action", "perform_click", "post"):
                trig = {"send_action": "h.send_action(o)", "perform_click": "h.perform_click(o)",
                        "post": f'h.post_notification(o, {rs(s.get("notification", ""))})'}[verify]
                nargs = len(s.get("args", []))
                body = (f'    let o = h.create({rs(tag)});\n    h.take_events();\n    h.listen(o, {rs(s["name"])}, true).unwrap();\n    {trig};\n'
                        f'    let ev = h.take_events();\n    assert!(ev.iter().any(|e| e.0 == o && e.1 == {rs(s["name"])} && e.2.len() == {nargs}), "delivered: {{ev:?}}");\n'
                        f'    h.listen(o, {rs(s["name"])}, false).unwrap();\n    {trig};\n'
                        f'    assert!(h.take_events().iter().all(|e| e.1 != {rs(s["name"])}), "not delivered after listen off");\n    h.destroy(o);\n')
            else:
                continue
            add(f"signal_{ident(cls, s['name'])}", f"signal {cls}.{s['name']} ({s['via']}): {s['provenance']}", body)
        for meth in ov.get("methods", []):
            if meth.get("test") is False:
                continue
            exp = meth.get("expect")
            check = (f'    assert_eq!(h.get(o, {rs(exp["get"])}).unwrap(), {value(exp["value"])});\n' if exp else "")
            body = (f'    let o = h.create({rs(tag)});\n    h.call(o, {rs(meth["name"])}, vec![]).unwrap();\n{check}    h.destroy(o);\n')
            add(f"method_{ident(cls, meth['name'])}", f"method {cls}.{meth['name']} ({meth['selector']}): {meth['provenance']}", body)

    o = [HEADER, "//! One test per annotated AppKit fact. macOS only (an empty suite elsewhere):\n",
         "//! `cargo test -p counter-mac --test generated` (cases run in order on the main thread).\n\n"]
    o.append('#[cfg(target_os = "macos")]\n#[allow(unused_imports)]\nmod cases {\n')
    o.append("    use svelters_abi::Value as V;\n    use svelters_abi::{SVL_T_INSETS, SVL_T_POINT, SVL_T_RECT, SVL_T_SIZE};\n")
    o.append("    use svelters_appkit::testing::Harness;\n")
    for name, doc, body in cases:
        o.append(f"\n    /// {doc}\n    pub fn {name}() {{\n        let h = Harness::shared();\n")
        o.append("".join("    " + line + "\n" if line else "\n" for line in body.rstrip("\n").split("\n")))
        o.append("    }\n")
    o.append("\n    pub static CASES: &[(&str, fn())] = &[\n")
    for name, _, _ in cases:
        o.append(f"        ({rs(name)}, {name}),\n")
    o.append("    ];\n}\n\n")
    o.append('fn main() {\n    #[cfg(target_os = "macos")]\n    svelters_apple::testing::run_cases(true, cases::CASES);\n'
             '    #[cfg(not(target_os = "macos"))]\n    svelters_apple::testing::run_cases(false, &[]);\n}\n')
    return "".join(o)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the checked-in outputs are stale")
    a = ap.parse_args()
    try:
        m = Model()
        outs = {OUT_TABLES: build(m), OUT_TESTS: tests(m)}
    except GenError as e:
        print(f"gen_backend: {e}", file=sys.stderr)
        return 1
    stale = [p for p, t in outs.items() if not p.exists() or p.read_text() != t]
    if a.check:
        for p in stale:
            print(f"gen_backend: {p.relative_to(ROOT)} is stale", file=sys.stderr)
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(outs[p])
    print(f"{len(stale)} files written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
