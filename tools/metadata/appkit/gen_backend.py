STRUCT_TY = {"rect": "SVL_T_RECT", "size": "SVL_T_SIZE", "point": "SVL_T_POINT", "insets": "SVL_T_INSETS"}


def s_value(v, ref: str | None = None) -> str | None:
    """The `S` literal of a sample (static row tables), or None when the rows cannot carry it."""
    if ref in STRUCT_FIELDS and isinstance(v, dict):
        _, fields = STRUCT_FIELDS[ref]
        return f"S::Rec({STRUCT_TY[ref]}, &[{', '.join(repr(float(v[f])) for f in fields)}])"
    if isinstance(v, bool):
        return f"S::Bool({'true' if v else 'false'})"
    if isinstance(v, int):
        return f"S::F64({float(v)!r})" if ref in FLOAT else f"S::I64({v})"
    if isinstance(v, float):
        return f"S::F64({v!r})"
    if isinstance(v, str):
        return f"S::Str({rs(v)})"
    if isinstance(v, list) and all(isinstance(x, str) for x in v):
        return f"S::Names(&[{', '.join(rs(x) for x in v)}])"
    return None


def fact_id(cls: str, section: str, name: str) -> str:
    return f"svelters-api:v1:type:appkit:AppKit:{cls}:{section}:{name}"


class Tests:
    """The generated test source plus its facts manifest (fact -> tests, fingerprint, origin)."""

    def __init__(self, m: Model):
        self.m = m
        self.cases: list[tuple[str, str, str]] = []      # (name, doc, body): one function per fact
        self.rows: dict[str, list[tuple[str, str, str]]] = {"prop": [], "signal": [], "bind": [], "observe": []}  # (test, doc, row literal)
        self.facts: list[dict] = []
        self.untestable: list[dict] = []
        self.names: set[str] = set()

    def _name(self, name: str) -> None:
        if name in self.names:
            raise GenError(f"duplicate test {name}")
        self.names.add(name)

    def fact(self, cls, section, name, record, test, src, strength=None):
        layer, fp = self.m.layer(cls, section, name) if section != "element" else ("manual", None)
        f = {"fact": fact_id(cls, section, name), "kind": cls, "section": section, "name": name, "origin": layer,
             "tests": [test], "fingerprint": svmeta.fingerprint({"record": record, "tests": src})}
        if fp:
            f["record_fp"] = fp
        if strength:
            f["strength"] = strength
        self.facts.append(f)

    def add(self, name, doc, body, fact):
        self._name(name)
        self.cases.append((name, doc, body))
        cls, section, fname, record = fact
        self.fact(cls, section, fname, record, name, [body])

    def row(self, table, name, doc, literal, fact, strength=None):
        self._name(name)
        self.rows[table].append((name, doc, literal))
        cls, section, fname, record = fact
        self.fact(cls, section, fname, record, name, [literal, ROW_FNS[table]], strength)

    def cannot(self, cls, section, name, why):
        """An annotation the generator cannot test. Inferred ones are parked by the ledger; manual ones stay
        untested (they are not facts in the manifest)."""
        layer, fp = self.m.layer(cls, section, name)
        if layer == "inferred":
            self.untestable.append({"fact": fact_id(cls, section, name), "kind": cls, "section": section, "name": name,
                                    "record_fp": fp, "message": f"generator: {why}"})


def find_signal(m: Model, cls: str, name: str) -> dict | None:
    for c in m.chain(cls):
        for s in m.ov.get(c, {}).get("signals", []):
            if s["name"] == name:
                return s
    return None


def select_tab_body(tag: str, s: dict) -> str:
    """A tab view delegate signal (`verify: select_tab`): two items, then a native selection (or a third item for the
    number-of-items signal) is delivered while listened and not after listen off; a vetoing signal keeps the selection
    when JS answers true and lets it move when JS answers null."""
    n = rs(s["name"])
    nargs = len(s.get("args", []))
    head = (f'    let o = h.create({rs(tag)});\n    let a = h.create("tab-view-item");\n    let b = h.create("tab-view-item");\n'
            f'    h.insert(o, a, None, None).unwrap();\n    h.insert(o, b, None, None).unwrap();\n'
            f'    assert_eq!(h.get(o, "selected-tab-view-item").unwrap(), V::Handle(a), "the first item is selected");\n'
            f'    h.take_events();\n    h.listen(o, {n}, true).unwrap();\n')
    delivered = f'    let ev = h.take_events();\n    assert!(ev.iter().any(|e| e.0 == o && e.1 == {n} && e.2.len() == {nargs}), "delivered: {{ev:?}}");\n'
    tail = f'    h.destroy(o);\n    h.destroy(a);\n    h.destroy(b);\n'
    if "number-of" in s["name"]:
        c = '    let c = h.create("tab-view-item");\n'
        return (head + c + f'    h.insert(o, c, None, None).unwrap();\n' + delivered +
                f'    h.listen(o, {n}, false).unwrap();\n    h.remove(o, c).unwrap();\n'
                f'    assert!(h.take_events().iter().all(|e| e.1 != {n}), "not delivered after listen off");\n'
                + tail + '    h.destroy(c);\n')
    if s.get("result") == "veto_bool":
        return (head + '    h.set_sync_reply(V::Bool(true));\n    h.call(o, "select-next-tab-view-item", vec![]).unwrap();\n' + delivered +
                '    assert_eq!(h.get(o, "selected-tab-view-item").unwrap(), V::Handle(a), "a true result (preventDefault) keeps the selection");\n'
                '    h.set_sync_reply(V::Null);\n    h.call(o, "select-next-tab-view-item", vec![]).unwrap();\n'
                '    assert_eq!(h.get(o, "selected-tab-view-item").unwrap(), V::Handle(b), "no decision lets the selection move");\n'
                f'    h.listen(o, {n}, false).unwrap();\n    h.take_events();\n    h.set_sync_reply(V::Bool(true));\n'
                '    h.call(o, "select-previous-tab-view-item", vec![]).unwrap();\n'
                '    assert_eq!(h.get(o, "selected-tab-view-item").unwrap(), V::Handle(a), "not asked after listen off");\n'
                '    h.set_sync_reply(V::Null);\n' + tail)
    return (head + '    h.call(o, "select-next-tab-view-item", vec![]).unwrap();\n' + delivered +
            f'    h.listen(o, {n}, false).unwrap();\n    h.call(o, "select-previous-tab-view-item", vec![]).unwrap();\n'
            f'    assert!(h.take_events().iter().all(|e| e.1 != {n}), "not delivered after listen off");\n' + tail)


def find_sample(m: Model, cls: str, prop: str):
    """(sample, expect) of the nearest prop record with a sample along the chain, else None."""
    for c in m.chain(cls):
        for p in m.ov.get(c, {}).get("props", []):
            if p["name"] == prop and "sample" in p:
                return p["sample"], p.get("expect", p["sample"])
    return None


def tests(m: Model) -> tuple[str, list[dict], list[dict]]:
    t = Tests(m)
    add = t.add

    for cls in m.classes:
        ov = m.ov.get(cls, {})
        el = ov.get("element")
        tag = m.element_for(cls)
        if el:
            add(f"kind_{ident(cls)}", f"kind {cls}: <{el['tag']}> creates an {cls}",
                f'    let o = h.create({rs(el["tag"])});\n    assert!(h.is_kind(o, {rs(cls)}), "is a {cls}");\n'
                f'    assert_eq!(h.lifetime(o), {2 if el["lifetime"] == "toplevel" else 1});\n    h.destroy(o);\n',
                (cls, "element", "kind", el))
            add(f"readable_{ident(cls)}", f"every readable table prop of <{el['tag']}> reads back without an error",
                f'    let o = h.create({rs(el["tag"])});\n    let mut bad = Vec::new();\n'
                f'    for name in h.readable_props({rs(el["tag"])}) {{\n        if let Err(e) = h.get(o, name) {{\n            bad.push(format!("{{name}}: {{e}}"));\n        }}\n    }}\n'
                f'    h.destroy(o);\n    assert!(bad.is_empty(), "unreadable props: {{bad:#?}}");\n',
                (cls, "element", "readable", {"props": sorted(p["name"] for c in m.chain(cls) for p in m.meta[c]["properties"])}))
        if tag is None:
            for sec in ("props", "setters", "signals", "methods", "bindings", "slots"):
                for r in ov.get(sec, []):
                    t.cannot(cls, sec, r["name"], "no element derives from the class")
            continue
        for p in ov.get("props", []):
            if "sample" not in p:
                t.cannot(cls, "props", p["name"], "no sample")
                continue
            _, meta = m.find_prop(cls, p["name"])
            ref = meta["type"]["ref"]
            exp = p.get("expect", p["sample"])
            if ref in FLOAT and isinstance(exp, int) and not isinstance(exp, bool):
                exp = float(exp)
            name = f"prop_{ident(cls, p['name'])}"
            if m.layer(cls, "props", p["name"])[0] == "inferred":
                sv, ev = s_value(p["sample"], ref), s_value(exp, ref)
                if sv is None or ev is None:
                    t.cannot(cls, "props", p["name"], f"sample {p['sample']!r} has no row value")
                    continue
                t.row("prop", name, f"prop {cls}.{p['name']}: {p['provenance']}",
                      f"PropRow {{ tag: {rs(tag)}, name: {rs(p['name'])}, setter: {rs(meta['accessors'].get('set', ''))}, sample: {sv}, expect: {ev} }}", (cls, "props", p["name"], p))
                continue
            add(name, f"prop {cls}.{p['name']}: {p['provenance']}",
                f'    let o = h.create({rs(tag)});\n    h.set(o, {rs(p["name"])}, {value(p["sample"], ref)}).unwrap();\n'
                f'    assert_eq!(h.get(o, {rs(p["name"])}).unwrap(), {value(exp, ref)});\n    h.destroy(o);\n', (cls, "props", p["name"], p))
        for s in ov.get("setters", []):
            if "sample" not in s:
                continue
            add(f"setter_{ident(cls, s['name'])}", f"setter {cls}.{s['name']} ({s['selector']}): {s['provenance']}",
                f'    let o = h.create({rs(tag)});\n    h.set(o, {rs(s["name"])}, {value(s["sample"], s["type"])}).unwrap();\n'
                f'    assert!(h.get(o, {rs(s["name"])}).is_err(), "setter-only props are not readable");\n    h.destroy(o);\n',
                (cls, "setters", s["name"], s))
        for sl in ov.get("slots", []):
            ops = sl["ops"]
            name = sl["name"]
            child = sl.get("child", "view")
            child_view = m.is_view(m.class_of_tag(child))
            if sl["cardinality"] == "many":
                # Children that are not views (tab-view-item, menu-item) have no superview: the list is the check.
                attached = f'    assert!(h.superview(a) == Some(h.obj(p)), "a is a subview");\n' if child_view else ""
                detached = f'    assert!(h.superview(b).is_none(), "removed child is detached");\n' if child_view else ""
                body = (f'    let p = h.create({rs(tag)});\n    let a = h.create({rs(child)});\n    let b = h.create({rs(child)});\n'
                        f'    h.insert(p, a, None, Some({rs(name)})).unwrap();\n    h.insert(p, b, Some(a), Some({rs(name)})).unwrap();\n'
                        f'    assert_eq!(h.native_list(p, {rs(ops["list"])}), vec![h.obj(b), h.obj(a)], "b inserted before a");\n'
                        f'{attached}'
                        f'    h.remove(p, b).unwrap();\n{detached}'
                        f'    assert_eq!(h.native_list(p, {rs(ops["list"])}), vec![h.obj(a)]);\n'
                        f'    h.remove(p, b).unwrap_err();\n    h.insert(p, b, None, Some({rs(name)})).unwrap();\n'
                        f'    assert_eq!(h.native_list(p, {rs(ops["list"])}), vec![h.obj(a), h.obj(b)], "re-inserted at the end");\n'
                        f'    h.destroy(p);\n    h.destroy(a);\n    h.destroy(b);\n')
            else:
                clear = ('    assert!(h.native_get(p, {g}).is_some_and(|v| v != h.obj(b)), "cleared to a fresh view");\n'
                         if ops.get("clear") == "empty_view" else '    assert!(h.native_get(p, {g}).is_none(), "cleared");\n').format(g=rs(ops["get"]))
                body = (f'    let p = h.create({rs(tag)});\n    let a = h.create({rs(child)});\n    let b = h.create({rs(child)});\n'
                        f'    h.insert(p, a, None, Some({rs(name)})).unwrap();\n    assert!(h.native_get(p, {rs(ops["get"])}) == Some(h.obj(a)), "a set");\n'
                        f'    h.insert(p, b, None, Some({rs(name)})).unwrap();\n    assert!(h.native_get(p, {rs(ops["get"])}) == Some(h.obj(b)), "b replaces a");\n'
                        f'    assert!(h.alive(a), "the replaced child stays alive (handle)");\n    h.remove(p, a).unwrap_err();\n'
                        f'    h.remove(p, b).unwrap();\n{clear}    h.destroy(p);\n    h.destroy(a);\n    h.destroy(b);\n')
            add(f"slot_{ident(cls, name)}", f"slot {cls}.{name}: {sl['provenance']}", body, (cls, "slots", name, sl))
        for s in ov.get("signals", []):
            verify = s.get("verify", "none")
            if m.layer(cls, "signals", s["name"])[0] == "inferred":
                if s["via"] == "notification" and verify == "post":
                    t.row("signal", f"signal_{ident(cls, s['name'])}", f"signal {cls}.{s['name']} ({s['via']}): {s['provenance']}",
                          f"SignalRow {{ tag: {rs(tag)}, signal: {rs(s['name'])}, notification: {rs(s['notification'])}, nargs: {len(s.get('args', []))} }}",
                          (cls, "signals", s["name"], s), strength="delivery")
                else:
                    t.cannot(cls, "signals", s["name"], f"no generated test for {s['via']} signals with verify {verify}")
                continue
            if s["via"] == "delegate" and verify == "select_tab":
                body = select_tab_body(tag, s)
            elif s["via"] == "delegate" and s.get("result") == "veto_bool":
                body = (f'    let w = h.create({rs(tag)});\n    h.call(w, "make-key-and-order-front", vec![]).unwrap();\n'
                        f'    h.listen(w, {rs(s["name"])}, true).unwrap();\n    h.set_sync_reply(V::Bool(true));\n    h.perform_close(w);\n'
                        f'    assert!(h.alive(w) && h.is_visible(w), "a true result (preventDefault) vetoes the close");\n'
                        f'    assert!(h.take_events().iter().any(|e| e.0 == w && e.1 == {rs(s["name"])}), "the handler ran");\n'
                        f'    h.set_sync_reply(V::Null);\n    h.perform_close(w);\n    h.pump(50);\n'
                        f'    assert!(!h.alive(w), "no decision lets the window close");\n'
                        f'    assert!(h.take_gone().contains(&(w, svelters_abi::SVL_GONE_CLOSED)), "reported closed");\n')
            elif s["via"] == "delegate":
                body = (f'    let w = h.create({rs(tag)});\n    h.call(w, "make-key-and-order-front", vec![]).unwrap();\n'
                        f'    h.listen(w, {rs(s["name"])}, true).unwrap();\n    h.close_window(w);\n    h.pump(50);\n'
                        f'    assert!(h.take_events().iter().any(|e| e.0 == w && e.1 == {rs(s["name"])}), "posted");\n'
                        f'    assert!(h.take_gone().contains(&(w, svelters_abi::SVL_GONE_CLOSED)), "reported closed");\n')
            elif verify in ("send_action", "perform_click", "post", "app_send_action"):
                trig = {"send_action": "h.send_action(o)", "perform_click": "h.perform_click(o)", "app_send_action": "h.app_send_action(o)",
                        "post": f'h.post_notification(o, {rs(s.get("notification", ""))})'}[verify]
                nargs = len(s.get("args", []))
                body = (f'    let o = h.create({rs(tag)});\n    h.take_events();\n    h.listen(o, {rs(s["name"])}, true).unwrap();\n    {trig};\n'
                        f'    let ev = h.take_events();\n    assert!(ev.iter().any(|e| e.0 == o && e.1 == {rs(s["name"])} && e.2.len() == {nargs}), "delivered: {{ev:?}}");\n'
                        f'    h.listen(o, {rs(s["name"])}, false).unwrap();\n    {trig};\n'
                        f'    assert!(h.take_events().iter().all(|e| e.1 != {rs(s["name"])}), "not delivered after listen off");\n    h.destroy(o);\n')
            else:
                continue
            add(f"signal_{ident(cls, s['name'])}", f"signal {cls}.{s['name']} ({s['via']}): {s['provenance']}", body, (cls, "signals", s["name"], s))
        for meth in ov.get("methods", []):
            if meth.get("test") is False:
                t.cannot(cls, "methods", meth["name"], "test: false")
                continue
            exp = meth.get("expect") or {}
            check = (f'    assert_eq!(h.get(o, {rs(exp["get"])}).unwrap(), {value(exp["value"])});\n' if "get" in exp else "")
            args = ", ".join(value(a) for a in meth.get("args", []))
            if "returns" in exp:
                call = f'    let r = h.call(o, {rs(meth["name"])}, vec![{args}]).unwrap();\n    assert_eq!(r, {value(exp["returns"])}, "returned");\n'
            else:
                call = f'    h.call(o, {rs(meth["name"])}, vec![{args}]).unwrap();\n'
            body = (f'    let o = h.create({rs(tag)});\n{call}{check}    h.destroy(o);\n')
            add(f"method_{ident(cls, meth['name'])}", f"method {cls}.{meth['name']} ({meth['selector']}): {meth['provenance']}", body,
                (cls, "methods", meth["name"], meth))
        for b in ov.get("bindings", []):
            sig = find_signal(m, cls, b["change"]["signal"])
            smp = find_sample(m, cls, b["property"])
            why = None
            if sig is None or sig["via"] == "delegate":
                why = f"change signal {b['change']['signal']} is not a target-action or notification signal"
            elif smp is None:
                why = f"no prop sample for {b['property']}"
            if why:
                t.cannot(cls, "bindings", b["name"], why)
                continue
            _, meta = m.find_prop(cls, b["property"])
            ref = meta["type"]["ref"]
            sample, exp = smp
            sv, ev = s_value(sample, ref), s_value(exp, ref)
            if sv is None or ev is None:
                t.cannot(cls, "bindings", b["name"], f"sample {sample!r} has no row value")
                continue
            trigger = sig.get("notification", "") if sig["via"] == "notification" else ""
            arg0 = b["change"].get("value", "arg0") == "arg0"
            echo_none = b["echo"]["strategy"] == "none"
            t.row("bind", f"bind_{ident(cls, b['name'])}", f"bind:{b['name']} on {cls} via {sig['name']}: {b['provenance']}",
                  f"BindRow {{ tag: {rs(tag)}, prop: {rs(b['property'])}, signal: {rs(sig['name'])}, trigger: {rs(trigger)}, "
                  f"sample: {sv}, expect: {ev}, arg0: {str(arg0).lower()}, echo_none: {str(echo_none).lower()} }}",
                  (cls, "bindings", b["name"], b))

    observe_rows(m, t)

    o = [HEADER, "//! One test per annotated AppKit fact. macOS only (an empty suite elsewhere):\n",
         "//! `cargo test -p counter-mac --test generated` (cases run in order on the main thread).\n",
         "//! Inferred facts (metadata/inferred/appkit) and bindings are table-driven: one runner per table,\n",
         "//! one named case per row. `SVELTERS_TEST_RESULTS=<file>` records every result for the ledger.\n\n"]
    o.append('#[cfg(target_os = "macos")]\n#[allow(unused_imports, dead_code)]\nmod cases {\n')
    o.append("    use svelters_abi::Value as V;\n    use svelters_abi::{SVL_T_INSETS, SVL_T_POINT, SVL_T_RECT, SVL_T_SIZE};\n")
    o.append("    use svelters_appkit::testing::{Harness, ObsCheck, ObserveRow, S, Trig, User};\n")
    for name, doc, body in t.cases:
        o.append(f"\n    /// {doc}\n    pub fn {name}() {{\n        let h = Harness::shared();\n")
        o.append("".join("    " + line + "\n" if line else "\n" for line in body.rstrip("\n").split("\n")))
        o.append("    }\n")
    # `test_setup` of the elements: props the harness sets on every create of the tag (Harness::set_setup).
    setup = []
    for cls in m.classes:
        el = m.ov.get(cls, {}).get("element") or {}
        for s in el.get("test_setup", []):
            owner, meta = m.find_prop(cls, s["name"])
            setter = next((x for c in m.chain(cls) for x in m.ov.get(c, {}).get("setters", []) if x["name"] == s["name"]), None)
            ref = meta["type"]["ref"] if meta else setter["type"] if setter else None
            if ref is None:
                raise GenError(f"{cls}: test_setup: unknown prop {s['name']}")
            sv = s_value(s["value"], ref)
            if sv is None:
                raise GenError(f"{cls}: test_setup: {s['name']}: value {s['value']!r} has no row value")
            setup.append(f"        ({rs(el['tag'])}, {rs(s['name'])}, {sv}),\n")
    if setup:
        o.append("\n    /// `test_setup` of the element overrides: set right after every create of the tag.\n")
        o.append(f"    pub static SETUP: &[(&str, &str, S)] = &[\n{''.join(setup)}    ];\n")
    o.append("\n    pub static CASES: &[(&str, fn())] = &[\n")
    for name, _, _ in t.cases:
        o.append(f"        ({rs(name)}, {name}),\n")
    o.append("    ];\n\n")
    o.append(ROW_STRUCTS)
    tables = {"prop": "PROP_ROWS", "signal": "SIGNAL_ROWS", "bind": "BIND_ROWS", "observe": "OBSERVE_ROWS"}
    types = {"prop": "PropRow", "signal": "SignalRow", "bind": "BindRow", "observe": "ObserveRow"}
    for table in ("prop", "signal", "bind", "observe"):
        o.append(f"\n    pub static {tables[table]}: &[{types[table]}] = &[\n")
        for name, doc, lit in t.rows[table]:
            o.append(f"        // {name}: {doc}\n        {lit},\n")
        o.append("    ];\n\n")
        o.append(ROW_FNS[table])
    o.append("\n    pub static ROWS: &[(&str, fn(usize), usize)] = &[\n")
    for table in ("prop", "signal", "bind", "observe"):
        for i, (name, _, _) in enumerate(t.rows[table]):
            o.append(f"        ({rs(name)}, {table}_row, {i}),\n")
    o.append("    ];\n}\n\n")
    o.append('fn main() {\n    #[cfg(target_os = "macos")]\n    {\n')
    if setup:
        o.append('        svelters_appkit::testing::Harness::shared().set_setup(cases::SETUP);\n')
    o.append('        svelters_apple::testing::run_table_cases(true, cases::CASES, cases::ROWS);\n    }\n'
             '    #[cfg(not(target_os = "macos"))]\n    svelters_apple::testing::run_cases(false, &[]);\n}\n')
    facts = sorted(t.facts, key=lambda f: f["fact"])
    untestable = sorted(t.untestable, key=lambda f: f["fact"])
    return "".join(o), facts, untestable


def observe_rows(m: Model, t: Tests) -> None:
    """ABI v2.6 observe facts (milestone R4; REACTIVITY.md 4.5): one row per fact of a class an element derives from,
    run through the real path (`observe` -> KVO / notification / target-action -> host.prop_changed) by
    `svelters_appkit::testing::observe_row`. The check follows the fact: none/set_only -> unsupported, constant ->
    refused, a `verify: cross` trigger, a KVC sample -> change, else connect; a fallback mechanism adds its user path
    where the runner can synthesize it (typing for NSControlTextDidChangeNotification, a click for an NSButton's
    action, the arrow key for an NSSlider's)."""
    harness = svmeta.fingerprint({"testing.rs": TESTING_RS.read_text()})
    for cls in m.classes:
        tag = m.element_for(cls)
        if tag is None:
            continue
        for js, rec in sorted(m.observe.get(cls, {}).items()):
            _, meta = m.find_prop(cls, js)
            via = rec.get("via", [])
            kvo = meta["name"] if any(v["mechanism"] == "notify" for v in via) else ""
            smp = find_sample(m, cls, js)
            sv = s_value(smp[0], meta["type"]["ref"]) if smp else None
            verify = rec.get("verify") or {}
            user = "None"
            chain = m.chain(cls)
            if any(v["mechanism"] == "notification" and v["name"] in ("NSControlTextDidChangeNotification", "NSTextDidChangeNotification") for v in via):
                user = "Type"
            elif any(v["mechanism"] == "target_action" for v in via):
                # A click on a pop-up button opens its menu (a modal tracking loop): never synthesized.
                clickable = ("NSButton" in chain and "NSPopUpButton" not in chain) or "NSSwitch" in chain
                user = "Click" if clickable else "Key" if "NSSlider" in chain else "None"
            if rec["class"] in ("none", "set_only"):
                check, strength, user = "ObsCheck::Unsupported", "unsupported", "None"
            elif rec["class"] == "constant":
                check, strength, user = "ObsCheck::Refused", "refused", "None"
            elif verify.get("check") == "cross":
                trig = "".join(w.title() for w in verify["trigger"].split("-"))
                check, strength = f"ObsCheck::Cross(Trig::{trig})", "change"
            elif kvo and sv is not None and meta["access"]["write"]:
                check, strength = "ObsCheck::Change", "change"
            else:
                check, strength = "ObsCheck::Connect", "change" if user != "None" else "connect"
            acc = meta.get("accessors") or {}
            requires = acc.get("set", "") if check == "ObsCheck::Change" else acc.get("get", "")
            name = f"observe_{ident(cls, js)}"
            lit = (f"ObserveRow {{ tag: {rs(tag)}, prop: {rs(js)}, kvo: {rs(kvo)}, check: {check}, "
                   f"sample: {f'Some({sv})' if check == 'ObsCheck::Change' else 'None'}, user: User::{user}, requires: {rs(requires)} }}")
            t._name(name)
            t.rows["observe"].append((name, f"observe {cls}.{js}: {rec['class']}", lit))
            record = {k: v for k, v in rec.items() if k not in ("layer", "record_fp")}
            f = {"fact": rec["fact"], "kind": f"AppKit:{cls}", "section": "observe", "name": js, "origin": rec["layer"],
                 "tests": [name], "strength": strength,
                 "fingerprint": svmeta.fingerprint({"record": record, "tests": [lit, ROW_FNS["observe"], harness]})}
            if rec["layer"] == "inferred":
                f["record_fp"] = rec["record_fp"]
            t.facts.append(f)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the checked-in outputs are stale")
    a = ap.parse_args()
    try:
        m = Model()
        src, facts, untestable = tests(m)
        manifest = {"toolkit": "appkit", "version": m.version, "facts": facts, "untestable": untestable}
        outs = {OUT_TABLES: build(m), OUT_TESTS: src, OUT_FACTS: json.dumps(manifest, indent=1, sort_keys=True) + "\n"}
    except GenError as e:
        print(f"gen_backend: {e}", file=sys.stderr)
        return 1
    stale = [p for p, t in outs.items() if not p.exists() or p.read_text() != t]
    if a.check:
        for p in stale:
            print(f"gen_backend: {p.relative_to(ROOT)} is stale", file=sys.stderr)
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(outs[p])
    print(f"{len(stale)} files written; {len(facts)} facts ({sum(f['origin'] == 'inferred' for f in facts)} inferred), "
          f"{len(untestable)} inferred untestable")
    return 0


if __name__ == "__main__":
    sys.exit(main())
