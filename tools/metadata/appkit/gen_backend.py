SCALAR_TY = {"bool": "Bool", "i32": "I32", "i64": "I64", "u32": "U32", "u64": "U64", "f32": "F32", "f64": "F64",
             "string": "Str", "rect": "Rect", "size": "Size", "point": "Point", "insets": "Insets", "range": "Range", "list": "List"}
STRUCT_FIELDS = {"rect": ("SVL_T_RECT", ["x", "y", "width", "height"]), "size": ("SVL_T_SIZE", ["width", "height"]),
                 "point": ("SVL_T_POINT", ["x", "y"]), "insets": ("SVL_T_INSETS", ["top", "right", "bottom", "left"])}
INTEGER = {"i32", "i64", "u32", "u64"}
FLOAT = {"f32", "f64"}


class GenError(Exception):
    pass


def rs(s: str) -> str:
    return json.dumps(s)


def ident(*parts: str) -> str:
    return "_".join(p.lower().replace("-", "_").replace(":", "") for p in parts)


def value(v, ref: str | None = None) -> str:
    """A Rust `V` literal for a JS sample; `ref` types structs as their well-known records."""
    if ref in STRUCT_FIELDS and isinstance(v, dict):
        ty, fields = STRUCT_FIELDS[ref]
        return f"V::Record {{ ty: {ty}, fields: vec![{', '.join(value(float(v[f])) for f in fields)}] }}"
    if isinstance(v, bool):
        return f"V::Bool({'true' if v else 'false'})"
    if isinstance(v, int):
        return f"V::I64({v})"
    if isinstance(v, float):
        return f"V::F64({v!r})"
    if isinstance(v, str):
        return f"V::Str({rs(v)}.into())"
    if isinstance(v, list):
        return f"V::List(vec![{', '.join(value(x) for x in v)}])"
    if isinstance(v, dict):
        return "V::Map(vec![" + ", ".join(f"({rs(k)}.into(), {value(x)})" for k, x in v.items()) + "])"
    raise GenError(f"unsupported sample {v!r}")


class Model:
    def __init__(self):
        self.meta = {p.stem: svmeta.load_json(p) for p in sorted(META.glob("NS*.json"))}
        enum_doc = svmeta.load_json(META / "_enums.json")
        enums = enum_doc["enums"]
        # the toolkit version of the ledger and the probe: the SDK the metadata was ingested from
        self.version = enum_doc["sdk"].removeprefix("MacOSX")
        self.enums = {e["name"]: {"flags": e["flags"], "members": [(m["js"], m["value"]) for m in e["members"]]} for e in enums}
        # ingested < inferred < manual (appkit_layers.py); origin[(class, section, name)] = (layer, record fingerprint)
        self.ov, self.origin, errs = layers.load()
        if errs:
            raise GenError("\n".join(errs))
        missing = sorted(set(self.ov) - set(self.meta))
        if missing:
            raise GenError(f"overrides without ingested metadata (run ingest.py): {missing}")
        self.classes = sorted(self.meta)
        self.kid = {c: i + 1 for i, c in enumerate(self.classes)}
        # ABI v2.6 observe facts (metadata/observe/appkit.json, merged by tools/metadata/common/observe.py), by class.
        self.observe = {o.split(":", 1)[1]: props for o, props in svmeta.load_json(OBSERVE)["facts"].items()}

    def layer(self, cls: str, section: str, name: str) -> tuple[str, str | None]:
        return self.origin.get((cls, section, name), ("manual", None))

    def chain(self, cls: str) -> list[str]:
        """The class and its ingested bases, most derived first."""
        return [cls] + [b for b in self.meta[cls]["bases"] if b in self.meta]

    def find_prop(self, cls: str, js: str):
        for c in self.chain(cls):
            for p in self.meta[c]["properties"]:
                if p["js_name"] == js:
                    return c, p
        return None, None

    def has_method(self, cls: str, sel: str) -> bool:
        return any(m["selector"] == sel for c in self.chain(cls) for m in self.meta[c]["methods"])

    def class_of_tag(self, tag: str) -> str | None:
        return next((c for c, ov in self.ov.items() if (ov.get("element") or {}).get("tag") == tag), None)

    def is_view(self, cls: str) -> bool:
        return "NSView" in self.chain(cls)

    def element_for(self, cls: str) -> str | None:
        """The tag to test a class's facts on: its own, else the first element (by tag) deriving from it."""
        own = (self.ov.get(cls, {}).get("element") or {}).get("tag")
        if own:
            return own
        cands = sorted((ov["element"]["tag"], c) for c, ov in self.ov.items() if ov.get("element") and cls in self.chain(c))
        return cands[0][0] if cands else None


def build(m: Model):
    enum_names = sorted(m.enums)
    extra_enums = []  # (name, members) from overrides
    for cls in m.classes:
        for e in m.ov.get(cls, {}).get("enums", []):
            owner, p = m.find_prop(cls, e["prop"])
            if p is None:
                raise GenError(f"{cls}: enums: unknown prop {e['prop']}")
            if p["type"]["ref"] not in INTEGER:
                raise GenError(f"{cls}: enums: prop {e['prop']} is {p['type']['ref']}, not an integer")
            extra_enums.append((f"{cls}.{e['prop']}", sorted(e["members"].items(), key=lambda kv: kv[1])))
    all_enums = [(n, m.enums[n]["flags"], m.enums[n]["members"]) for n in enum_names] + [(n, False, mem) for n, mem in sorted(extra_enums)]
    eidx = {n: i for i, (n, _, _) in enumerate(all_enums)}
    prop_enum = {n.split(".", 1)[0] + "\0" + n.split(".", 1)[1]: i for i, (n, _, _) in enumerate(all_enums) if "." in n}

    def ty_of(cls: str, p: dict) -> str | None:
        ref = p["type"]["ref"]
        if (cls + "\0" + p["js_name"]) in prop_enum:
            return f"Ty::Enum({prop_enum[cls + chr(0) + p['js_name']]})"
        if ref in SCALAR_TY:
            return f"Ty::{SCALAR_TY[ref]}"
        if ref.startswith(("enum<", "flags<")):
            n = ref[ref.index("<") + 1:-1]
            if n not in eidx:
                return None
            return f"Ty::{'Flags' if ref.startswith('flags') else 'Enum'}({eidx[n]})"
        if ref == "object":
            return 'Ty::Object("")'
        if ref.startswith("object<"):
            return f"Ty::Object({rs(ref[7:-1])})"
        return None

    kinds, props, signals, methods, slots, writes = [], [], [], [], [], []
    for cls in m.classes:
        ov = m.ov.get(cls, {})
        el = ov.get("element") or {}
        bases = [b for b in m.meta[cls]["bases"] if b in m.meta]
        parent = m.kid[bases[0]] if bases else 0
        if el:
            want = names.class_tag(cls)
            if el["tag"] != want:
                raise GenError(f"{cls}: tag must be {want!r} (class name without NS, kebab-case)")
        ctor = "Ctor::New"
        if el.get("construct") == "window":
            w = el.get("window") or {}
            mask_members = dict(m.enums["NSWindowStyleMask"]["members"])
            try:
                mask = sum(mask_members[x] for x in w["style_mask"])
            except KeyError as e:
                raise GenError(f"{cls}: unknown style mask member {e}") from None
            ctor = f"Ctor::Window {{ width: {float(w['width'])!r}, height: {float(w['height'])!r}, style_mask: {mask} }}"
        kinds.append(f"    KindInfo {{ class: {rs(cls)}, tag: {rs(el.get('tag', ''))}, parent: {parent}, toplevel: {str(el.get('lifetime') == 'toplevel').lower()}, ctor: {ctor} }},\n")
        k = m.kid[cls]
        # A read-only property written through methods (`write: {selector, clear}`): writable, plus a PROP_WRITES row.
        own_writes = {p["name"]: p["write"] for p in ov.get("props", []) if p.get("write")}
        for js, w in own_writes.items():
            if not m.has_method(cls, w["selector"]) or names.selector_arity(w["selector"]) != 1:
                raise GenError(f"{cls}: props: {js}: write selector {w['selector']} must be an ingested one-argument method")
            if w.get("clear") and (not m.has_method(cls, w["clear"]) or names.selector_arity(w["clear"]) != 0):
                raise GenError(f"{cls}: props: {js}: clear selector {w['clear']} must be an ingested method without arguments")

        def prop_row(p: dict, write: dict | None) -> None:
            t = ty_of(cls, p)
            if t is None:
                if write:
                    raise GenError(f"{cls}: props: {p['js_name']}: write on a property of an unsupported type")
                return
            writable = p["access"]["write"] or bool(write)
            props.append(f"    PropInfo {{ kind: {k}, name: {rs(p['js_name'])}, key: {rs(p['name'])}, ty: {t}, writable: {str(writable).lower()}, setter: \"\" }},\n")
            if write:
                writes.append((len(props), write["selector"], write.get("clear", ""), ""))

        for p in m.meta[cls]["properties"]:
            prop_row(p, own_writes.get(p["js_name"]))
        # props named in overrides of a subclass resolve along the chain; check they exist
        for p in ov.get("props", []):
            owner, meta = m.find_prop(cls, p["name"])
            if meta is None:
                raise GenError(f"{cls}: props: unknown property {p['name']}")
            if p.get("write") and owner != cls:
                prop_row(meta, p["write"])  # an inherited property, written differently on this class: a row of its own
        for s in ov.get("setters", []):
            if not m.has_method(cls, s["selector"]):
                raise GenError(f"{cls}: setters: {s['selector']} is not an ingested method")
            want = 2 if s.get("count") else 1
            if names.selector_arity(s["selector"]) != want:
                raise GenError(f"{cls}: setters: {s['selector']} must take {want} argument(s)")
            if s.get("count") and (not m.has_method(cls, s["count"]) or names.selector_arity(s["count"]) != 1):
                raise GenError(f"{cls}: setters: count selector {s['count']} must be an ingested one-argument method")
            ref = s["type"]
            if s.get("count") and ref != "list":
                raise GenError(f"{cls}: setters: an indexed setter ({s['name']}) takes a list")
            t = ty_of(cls, {"js_name": s["name"], "type": {"ref": ref}})
            if t is None:
                raise GenError(f"{cls}: setters: unsupported type {ref}")
            props.append(f"    PropInfo {{ kind: {k}, name: {rs(s['name'])}, key: \"\", ty: {t}, writable: true, setter: {rs(s['selector'])} }},\n")
            if s.get("count"):
                writes.append((len(props), s["selector"], "", s["count"]))
        for s in ov.get("signals", []):
            via = s["via"]
            if via == "target_action":
                if s["name"] != "action":
                    raise GenError(f"{cls}: the target-action signal is named `action` (the native property)")
                native = ""
            elif via == "notification":
                native = s.get("notification") or ""
                if s["name"] != names.notification_signal(native):
                    raise GenError(f"{cls}: signal {s['name']} must be named {names.notification_signal(native)!r}")
            else:
                native = s.get("selector") or ""
                if s["name"] != names.selector_name(native):
                    raise GenError(f"{cls}: signal {s['name']} must be named {names.selector_name(native)!r}")
            for a in s.get("args", []):
                if m.find_prop(cls, a)[1] is None:
                    raise GenError(f"{cls}: signal {s['name']}: unknown arg prop {a}")
            sync = "SyncResult::VetoBool" if s.get("result") == "veto_bool" else "SyncResult::None"
            if (s.get("delivery") == "sync") != (s.get("result", "none") != "none"):
                raise GenError(f"{cls}: signal {s['name']}: delivery sync needs a result and vice versa")
            vias = {"target_action": "TargetAction", "notification": "Notification", "delegate": "Delegate"}
            args = ", ".join(rs(a) for a in s.get("args", []))
            signals.append(f"    SignalInfo {{ kind: {k}, name: {rs(s['name'])}, via: Via::{vias[via]}, native: {rs(native)}, sync: {sync}, args: &[{args}] }},\n")
        for meth in ov.get("methods", []):
            if not m.has_method(cls, meth["selector"]):
                raise GenError(f"{cls}: methods: {meth['selector']} is not an ingested method")
            if meth["name"] != names.selector_name(meth["selector"]):
                raise GenError(f"{cls}: method {meth['name']} must be named {names.selector_name(meth['selector'])!r}")
            methods.append(f"    MethodInfo {{ kind: {k}, name: {rs(meth['name'])}, selector: {rs(meth['selector'])} }},\n")
        for sl in ov.get("slots", []):
            ops = sl["ops"]
            if sl.get("child") and m.class_of_tag(sl["child"]) is None:
                raise GenError(f"{cls}: slot {sl['name']}: child <{sl['child']}> is not an element")
            # `declared_on`: the selectors live above the ingested chain (NSResponder.menu); the backend checks them at run time.
            if sl.get("declared_on") and sl["declared_on"] in m.chain(cls):
                raise GenError(f"{cls}: slot {sl['name']}: declared_on {sl['declared_on']} is ingested: drop declared_on")
            checked = not sl.get("declared_on")
            for key in ("set", "append", "insert_at", "insert_relative"):
                if checked and key in ops and not m.has_method(cls, ops[key]):
                    raise GenError(f"{cls}: slot {sl['name']}: {ops[key]} is not an ingested method")
            for sel in ops.get("remove", []) + ops.get("detach", []):
                if checked and not any(m.has_method(c, sel) for c in m.classes):
                    raise GenError(f"{cls}: slot {sl['name']}: {sel} is not an ingested method")
            for key in ("get", "list"):
                if checked and key in ops and m.find_prop(cls, names.kebab(ops[key]))[1] is None:
                    raise GenError(f"{cls}: slot {sl['name']}: {ops[key]} is not a property")
            many = sl["cardinality"] == "many"
            if many and not (ops.get("append") or ops.get("insert_at") or ops.get("insert_relative")):
                raise GenError(f"{cls}: slot {sl['name']}: a many slot needs append/insert_at/insert_relative")
            if not many and not ops.get("set"):
                raise GenError(f"{cls}: slot {sl['name']}: a one slot needs set")
            clear = "Clear::EmptyView" if ops.get("clear") == "empty_view" else "Clear::Nil"
            rem = ", ".join(rs(x) for x in ops.get("remove", []))
            det = ", ".join(rs(x) for x in ops.get("detach", []))
            slots.append(
                f"    SlotInfo {{ kind: {k}, name: {rs(sl['name'])}, default: {str(bool(sl.get('default'))).lower()}, many: {str(many).lower()}, "
                f"set: {rs(ops.get('set', ''))}, get: {rs(ops.get('get', ''))}, clear: {clear}, append: {rs(ops.get('append', ''))}, "
                f"insert_at: {rs(ops.get('insert_at', ''))}, insert_relative: {rs(ops.get('insert_relative', ''))}, list: {rs(ops.get('list', ''))}, "
                f"remove: &[{rem}], detach: &[{det}] }},\n")

    o = [HEADER, "#![allow(dead_code)]\n", "use crate::tables::*;\n\n"]
    o.append(f"pub static KINDS: &[KindInfo] = &[\n{''.join(kinds)}];\n\n")
    o.append(f"pub static PROPS: &[PropInfo] = &[\n{''.join(props)}];\n\n")
    o.append("pub static ENUMS: &[EnumInfo] = &[\n")
    for n, flags, mem in all_enums:
        ms = ", ".join(f"({rs(a)}, {v})" for a, v in mem)
        o.append(f"    EnumInfo {{ name: {rs(n)}, flags: {str(flags).lower()}, members: &[{ms}] }},\n")
    o.append("];\n\n")
    o.append(f"pub static SIGNALS: &[SignalInfo] = &[\n{''.join(signals)}];\n\n")
    o.append(f"pub static METHODS: &[MethodInfo] = &[\n{''.join(methods)}];\n\n")
    o.append(f"pub static SLOTS: &[SlotInfo] = &[\n{''.join(slots)}];\n\n")
    # Props written through methods (`write:` on a read-only property, indexed setters with `count`), by PROPS id.
    o.append("pub static PROP_WRITES: &[PropWrite] = &[\n")
    for pid, sel, clear, count in writes:
        o.append(f"    PropWrite {{ prop: {pid}, selector: {rs(sel)}, clear: {rs(clear)}, count: {rs(count)} }},\n")
    o.append("];\n\n")
    # ABI v2.6 observe facts: one row per fact, on the class the fact is written on.
    cls_rs = {"constant": "Constant", "set_only": "SetOnly", "exact": "Exact", "partial": "Partial", "none": "None"}
    o.append("pub static OBSERVE: &[ObserveInfo] = &[\n")
    for cls in m.classes:
        for js, rec in sorted(m.observe.get(cls, {}).items()):
            _, meta = m.find_prop(cls, js)
            if meta is None:
                raise GenError(f"observe fact AppKit:{cls}:{js}: no such property")
            via = rec.get("via", [])
            kvo = meta["name"] if any(v["mechanism"] == "notify" for v in via) else ""
            notes = ", ".join(rs(v["name"]) for v in via if v["mechanism"] == "notification")
            action = any(v["mechanism"] == "target_action" for v in via)
            o.append(f"    ObserveInfo {{ kind: {m.kid[cls]}, name: {rs(js)}, kvo: {rs(kvo)}, class: ObsClass::{cls_rs[rec['class']]}, "
                     f"notifications: &[{notes}], action: {str(action).lower()}, proportional: {str(rec.get('value_cost') == 'proportional').lower()} }},\n")
    o.append("];\n")
    return "".join(o)


