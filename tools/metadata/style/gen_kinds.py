#!/usr/bin/env python3
"""Generate packages/style/src/kinds.generated.js: per element tag, the GTK CSS name and the Qt
class that type selectors map to, and which tags need a `sv-k-<tag>` marker class because another
tag shares their CSS name / Qt class (docs/notes/x6-styling.md).

GTK half: a live probe (PyGObject, Gtk 4, needs a display: run under xvfb-run) instantiates each
tagged widget and reads `get_css_name()`. Qt half: `construct.class` of the element overrides.
`--check` regenerates and compares.
"""
import argparse
import json
import sys
import warnings
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "packages/style/src/kinds.generated.js"


def gtk_tags():
    tags = {}
    for p in sorted((ROOT / "metadata/gtk").glob("*.json")):
        d = json.loads(p.read_text())
        el = d.get("element")
        if el and el.get("tag"):
            tags[el["tag"]] = p.stem
    return tags


def qt_tags():
    import yaml

    tags = {}
    for p in sorted((ROOT / "metadata/overrides/qt").glob("*.yaml")):
        d = yaml.safe_load(p.read_text())
        for el in d.get("elements", []):
            tags[el["tag"]] = el["construct"]["class"]
    return tags


def probe_gtk(tags):
    import gi

    gi.require_version("Gtk", "4.0")
    from gi.repository import Gtk, GObject

    warnings.filterwarnings("ignore")
    Gtk.init()
    out = {}
    for tag, name in tags.items():
        cls = getattr(Gtk, name, None)
        if cls is None:
            continue
        try:
            w = GObject.new(cls.__gtype__)
        except Exception:
            continue
        if not isinstance(w, Gtk.Widget):
            continue  # event controllers and other non-widget kinds are not styled
        out[tag] = {"css": w.get_css_name(), "classes": sorted(w.get_css_classes())}
    return out


def build():
    g = gtk_tags()
    q = qt_tags()
    probed = probe_gtk(g)
    kinds = {}
    for tag in sorted(set(g) | set(q)):
        k = {}
        if tag in probed:
            k["gtk"] = probed[tag]
        if tag in q:
            k["qt"] = q[tag]
        kinds[tag] = k
    by_css, by_qt = {}, {}
    for tag, k in kinds.items():
        if "gtk" in k:
            by_css.setdefault(k["gtk"]["css"], []).append(tag)
        if "qt" in k:
            by_qt.setdefault(k["qt"], []).append(tag)
    for tag, k in kinds.items():
        amb = []
        if "gtk" in k and len(by_css[k["gtk"]["css"]]) > 1:
            amb.append("gtk")
        if "qt" in k and len(by_qt[k["qt"]]) > 1:
            amb.append("qt")
        if amb:
            k["ambiguous"] = amb
    return kinds


def render(kinds):
    body = json.dumps(kinds, indent=1, sort_keys=True)
    return (
        "// GENERATED by tools/metadata/style/gen_kinds.py. Do not edit.\n"
        "// tag -> { gtk: { css, classes }, qt: <class>, ambiguous?: [toolkits] }. `ambiguous` kinds share a GTK CSS\n"
        "// name or a Qt class with another tag; the renderer adds `sv-k-<tag>` and type selectors use it.\n"
        f"export const KINDS = {body};\n"
    )


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(build())
    if a.check:
        if OUT.read_text() != text:
            print("kinds.generated.js is stale: run xvfb-run -a python3 tools/metadata/style/gen_kinds.py", file=sys.stderr)
            sys.exit(1)
        print("kinds.generated.js ok")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT}")
