#!/usr/bin/env python3
"""Render the style property tables (metadata/style/<toolkit>.yaml, checked and expanded into the
`style` section of metadata/semantics/<toolkit>.json by gen_semantics.py) as
packages/style/src/props.generated.js, the table @svelters/style, the build plugin and the
renderer use, and as crates/svelters-style/src/tables.generated.rs, the Rust engine's tables
(CS0). The docs reference pages are rendered from the JS module by docs/site/scripts.

  python3 tools/metadata/style/gen_props.py           # write
  python3 tools/metadata/style/gen_props.py --check   # fail if the output is stale
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "packages/style/src/props.generated.js"
OUT_RS = ROOT / "crates/svelters-style/src/tables.generated.rs"
TOOLKITS = ["gtk", "qt", "appkit", "winui", "egui"]


def render() -> str:
    sets: list[list[str]] = []
    tables = {}
    for tk in TOOLKITS:
        spec = json.loads((ROOT / f"metadata/semantics/{tk}.json").read_text())
        st = spec["style"]
        props = {}
        for name, p in st["properties"].items():
            e = {"via": p["via"]}
            if p["via"] == "setter":
                e.update(prop=p["prop"], native=p["native"], type=p["type"], kinds=p["kinds"])
            elif p["via"] == "child-attr":
                e.update(attr=p["attr"], type=p["type"], parents=p["parents"])
            elif "decl_type" in p:
                e["type"] = p["decl_type"]  # decl dialect: the value grammar
            if "tags" in p:
                if p["tags"] not in sets:
                    sets.append(p["tags"])
                e["tags"] = sets.index(p["tags"])
            if "values" in p:
                e["values"] = p["values"]
            if p.get("inline_only"):
                e["inlineOnly"] = True
            if "range" in p:
                e["range"] = p["range"]
            if p.get("note"):
                e["note"] = p["note"]
            props[name] = e
        tables[tk] = {
            "dialect": st["dialect"],
            "setterSelectors": st["setter_selectors"],
            "units": {u: r["scale"] for u, r in st["units"].items()},
            "props": props,
        }
    lines = [
        "// @generated by tools/metadata/style/gen_props.py from metadata/style/{gtk,qt,appkit,winui}.yaml and the egui kind table (through the",
        "// `style` section of metadata/semantics/*.json). Do not edit.",
        "//",
        "// Per toolkit: the native styling dialect (css | qss | none), the selectors a setter rule takes,",
        "// the length units and every style property with how it is applied: `css` (the X6 translator),",
        "// `setter` (setProp of `prop` on the tags of TAG_SETS[tags]) or `child-attr` (setChildAttr `attr`",
        "// on the children of the tags of TAG_SETS[tags]).",
        "",
        "/** Tag lists shared by the entries below (index = `tags`). */",
        "export const TAG_SETS = [",
    ]
    for s in sets:
        lines.append(f"  {json.dumps(s)},")
    lines += ["];", "", "export const STYLE_TABLES = {"]
    for tk in TOOLKITS:
        t = tables[tk]
        lines.append(f"  {tk}: {{")
        lines.append(f"    dialect: {json.dumps(t['dialect'])},")
        lines.append(f"    setterSelectors: {json.dumps(t['setterSelectors'])},")
        lines.append(f"    units: {json.dumps(t['units'])},")
        lines.append("    props: {")
        for name, e in t["props"].items():
            lines.append(f"      {json.dumps(name)}: {json.dumps(e, separators=(', ', ': '))},")
        lines += ["    },", "  },"]
    lines += ["};", ""]
    return "\n".join(lines)


RS_DIALECT = {"css": "Css", "qss": "Qss", "decl": "Decl", "none": "None"}
RS_VIA = {"css": "Css", "setter": "Setter", "child-attr": "ChildAttr"}
RS_TYPE = {
    "length": "Length", "number": "Number", "int": "Int", "bool": "Bool", "string": "String",
    "enum": "Enum", "color": "Color", "insets": "Insets", "font-weight": "FontWeight",
    "border": "Raw", "shadow": "Shadow", "transition": "Transition", "image": "Image", "content": "Content",
    "transition-property": "TransitionProperty", "time-list": "TimeList", "easing-list": "EasingList",
}


def rs_str(s: str) -> str:
    return json.dumps(s)  # a JSON string of ASCII text is a valid Rust string literal


def rs_f64(v, sign: str) -> str:
    """A range bound: a finite number, or an infinite open end (`sign` `-` for the minimum)."""
    return f"{sign}f64::INFINITY" if v is None else f"{float(v)!r}_f64"


def rs_list(xs: list[str]) -> str:
    return "&[" + ", ".join(rs_str(x) for x in xs) + "]"


def render_rs() -> str:
    lines = [
        "// @generated by tools/metadata/style/gen_props.py from metadata/style/{gtk,qt,appkit,winui}.yaml and the egui kind table (through the",
        "// `style` section of metadata/semantics/*.json). Do not edit.",
        "",
        "use crate::table::{Dialect, Prop, Table, ValueType, Via};",
        "",
    ]
    for tk in TOOLKITS:
        st = json.loads((ROOT / f"metadata/semantics/{tk}.json").read_text())["style"]
        lines.append(f"pub static {tk.upper()}: Table = Table {{")
        lines.append(f"    toolkit: {rs_str(tk)},")
        lines.append(f"    dialect: Dialect::{RS_DIALECT[st['dialect']]},")
        lines.append(f"    setter_selectors: {rs_list(st['setter_selectors'])},")
        units = ", ".join(f"({rs_str(u)}, {float(r['scale'])!r}_f32)" for u, r in st["units"].items())
        lines.append(f"    units: &[{units}],")
        lines.append("    props: &[")
        for name in sorted(st["properties"]):
            p = st["properties"][name]
            ty = p.get("type") if p["via"] != "css" else p.get("decl_type")
            target = p.get("prop") if p["via"] == "setter" else p.get("attr", "")
            tags = p.get("parents") if p["via"] == "child-attr" else p.get("tags", [])
            lines.append(
                f"        Prop {{ name: {rs_str(name)}, via: Via::{RS_VIA[p['via']]}, target: {rs_str(target or '')}, "
                f"ty: ValueType::{RS_TYPE.get(ty, 'Raw')}, values: {rs_list(p.get('values', []))}, "
                f"tags: {rs_list(tags or [])}, inline_only: {'true' if p.get('inline_only') else 'false'} }},"
            )
        lines.append("    ],")
        ranges = [(n, st["properties"][n]["range"]) for n in sorted(st["properties"]) if "range" in st["properties"][n]]
        lines.append("    ranges: &[" + "".join(f"\n        ({rs_str(n)}, {rs_f64(r.get('min'), '-')}, {rs_f64(r.get('max'), '')})," for n, r in ranges) + ("\n    ]," if ranges else "],"))
        lines += ["};", ""]
    lines.append("/// Every generated table.")
    lines.append("pub static ALL: &[&Table] = &[" + ", ".join(f"&{tk.upper()}" for tk in TOOLKITS) + "];")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    stale = []
    for out, text in ((OUT, render()), (OUT_RS, render_rs())):
        if out.exists() and out.read_text() == text:
            continue
        if a.check:
            stale.append(out.relative_to(ROOT).as_posix())
        else:
            out.write_text(text)
    if stale:
        print(f"gen_props: {', '.join(stale)} stale; run python3 tools/metadata/style/gen_props.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
