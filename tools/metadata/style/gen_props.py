#!/usr/bin/env python3
"""Render the style property tables (metadata/style/<toolkit>.yaml, checked and expanded into the
`style` section of metadata/semantics/<toolkit>.json by gen_semantics.py) as
packages/style/src/props.generated.js, the table @svelters/style, the build plugin and the
renderer use. The docs reference pages are rendered from that module by docs/site/scripts.

  python3 tools/metadata/style/gen_props.py           # write
  python3 tools/metadata/style/gen_props.py --check   # fail if the output is stale
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "packages/style/src/props.generated.js"
TOOLKITS = ["gtk", "qt"]


def render() -> str:
    sets: list[list[str]] = []
    tables = {}
    for tk in TOOLKITS:
        spec = json.loads((ROOT / f"metadata/semantics/{tk}.json").read_text())
        st = spec["style"]
        props = {}
        for name, p in st["properties"].items():
            e = {"via": p["via"]}
            if p["via"] == "setter":
                e.update(prop=p["prop"], native=p["native"], type=p["type"], kinds=p["kinds"])
            elif p["via"] == "child-attr":
                e.update(attr=p["attr"], type=p["type"], parents=p["parents"])
            if "tags" in p:
                if p["tags"] not in sets:
                    sets.append(p["tags"])
                e["tags"] = sets.index(p["tags"])
            if "values" in p:
                e["values"] = p["values"]
            if p.get("inline_only"):
                e["inlineOnly"] = True
            if p.get("note"):
                e["note"] = p["note"]
            props[name] = e
        tables[tk] = {
            "dialect": st["dialect"],
            "setterSelectors": st["setter_selectors"],
            "units": {u: r["scale"] for u, r in st["units"].items()},
            "props": props,
        }
    lines = [
        "// @generated by tools/metadata/style/gen_props.py from metadata/style/{gtk,qt}.yaml (through the",
        "// `style` section of metadata/semantics/*.json). Do not edit.",
        "//",
        "// Per toolkit: the native styling dialect (css | qss | none), the selectors a setter rule takes,",
        "// the length units and every style property with how it is applied: `css` (the X6 translator),",
        "// `setter` (setProp of `prop` on the tags of TAG_SETS[tags]) or `child-attr` (setChildAttr `attr`",
        "// on the children of the tags of TAG_SETS[tags]).",
        "",
        "/** Tag lists shared by the entries below (index = `tags`). */",
        "export const TAG_SETS = [",
    ]
    for s in sets:
        lines.append(f"  {json.dumps(s)},")
    lines += ["];", "", "export const STYLE_TABLES = {"]
    for tk in TOOLKITS:
        t = tables[tk]
        lines.append(f"  {tk}: {{")
        lines.append(f"    dialect: {json.dumps(t['dialect'])},")
        lines.append(f"    setterSelectors: {json.dumps(t['setterSelectors'])},")
        lines.append(f"    units: {json.dumps(t['units'])},")
        lines.append("    props: {")
        for name, e in t["props"].items():
            lines.append(f"      {json.dumps(name)}: {json.dumps(e, separators=(', ', ': '))},")
        lines += ["    },", "  },"]
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if OUT.exists() and OUT.read_text() == text:
        return 0
    if a.check:
        print("gen_props: packages/style/src/props.generated.js is stale; run python3 tools/metadata/style/gen_props.py", file=sys.stderr)
        return 1
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
