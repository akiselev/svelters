"""The TypeScript types shared by the GTK and Qt typings: value records, boxed values, native errors.

Both generators write the same `values.d.ts` next to their own `.d.ts`, so the two toolkits give
the same TS type to the same concept (docs/notes/js-native-serdes.md section 3.5).
"""
from __future__ import annotations

from pathlib import Path

VALUES_DTS = """// Generated by tools/metadata/common/tsvalues.py -- do not edit.
// Value types shared by every toolkit's typings. Plain objects with portable field names; the host
// converts them to QRect / graphene_rect_t / GdkRectangle, QMargins / GtkBorder, QColor / GdkRGBA, ...

export interface Rect { x: number; y: number; width: number; height: number }
export interface Size { width: number; height: number }
export interface Point { x: number; y: number }
/** Top, right, bottom, left: the order CSS uses. */
export interface Insets { top: number; right: number; bottom: number; left: number }
/** Components are 0..1. Properties typed `Color | string` also take a CSS color string. */
export interface Color { red: number; green: number; blue: number; alpha: number }
/** `month` is 1-based, as in both toolkits (not as in `Date`). */
export interface DateParts { year: number; month: number; day: number }
export interface TimeParts { hour: number; minute: number; second: number; ms: number }

/** A JSON-like tree plus `Date`, bytes and boxed values: what `QVariant` / `GVariant` slots take and give. */
export type Variant = null | boolean | number | string | Date | Uint8Array | NativeVariant | Variant[] | { [key: string]: Variant };

/** A `GVariant` with an exact type signature (`variant('(ii)', [1, 2])`); Qt ignores everything but a basic signature. */
export interface NativeVariant { readonly signature: string; readonly value: Variant }
export declare function variant(signature: string, value: Variant): NativeVariant;

/**
 * An opaque native value (QIcon, QFont, GIcon, PangoFontDescription, ...). `dispose()` releases
 * it at once and is idempotent; a value that is only dropped is released at a later checkpoint.
 */
export interface Boxed<Name extends string = string> {
  readonly typeName: Name;
  readonly disposed: boolean;
  dispose(): void;
}

/** A native failure (GError, a mapped C++ exception) thrown from a host op or rejecting a Promise. */
export interface NativeError extends Error {
  /** The error domain, e.g. `g-io-error-quark`. */
  domain: string;
  /** An enum member name when the domain has an error enum, else a number. */
  code: string | number | null;
}
"""


def write_values_dts(path: Path) -> None:
    path = Path(path)
    if path.exists() and path.read_text() == VALUES_DTS:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(VALUES_DTS)
