#!/usr/bin/env python3
"""Generate the renderer's binding table from the `bindings` annotations.

Inputs (only these):
  gtk: metadata/gtk/*.json   (`bindings` list on a kind with an `element.tag`; merged from metadata/overrides/gtk/*.yaml by ingest.py)
  qt:  metadata/overrides/qt/*.yaml   (`bindings` list on an `elements[]` entry)
  appkit: metadata/overrides/appkit/*.yaml + metadata/appkit/*.json   (`bindings` list on a class; applies to the element classes deriving from it)
  winui:  metadata/overrides/winui/*.yaml + metadata/winui/*.json     (same; property and signal are kebab-case JS names)
Outputs (checked in, byte-identical on rerun):
  packages/renderer/src/bindings.generated.js   table used by renderer.bind(el, name, get, set)
  packages/renderer/types/bindings.d.ts         `bind:<name>` types per tag

The schema extension is documented in docs/notes/fork-bindings.md section 6. Each binding is checked
against the facts it refers to (property exists and is writable, the change signal exists, the echo
strategy is backed by the backend's own suppression annotation). Toolkits that define the same
`bind:<name>` on a tag but differ in what the renderer sees (prop, signal, ...) become candidate
variants: BINDINGS[tag][name] is then an array and the renderer picks the first the host resolves.

Usage: python3 tools/metadata/common/gen_bindings.py [--check]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import naming  # noqa: E402
import svmeta  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
GTK_META = ROOT / "metadata/gtk"
QT_OVERRIDES = ROOT / "metadata/overrides/qt"
OUT_JS = ROOT / "packages/renderer/src/bindings.generated.js"
OUT_DTS = ROOT / "packages/renderer/types/bindings.d.ts"

HEADER = "// @generated by tools/metadata/common/gen_bindings.py from the `bindings` annotations. Do not edit.\n"

# neutral type ref -> (renderer coercion, TypeScript type)
TYPES = {"string": ("string", "string"), "bool": ("bool", "boolean"), "i32": ("number", "number"), "u32": ("number", "number"),
         "i64": ("number", "number"), "f32": ("number", "number"), "f64": ("number", "number"),
         # structured values pass through the renderer; the host converts them by descriptor
         "date": ("value", "{ year: number; month: number; day: number }"), "time": ("value", "{ hour: number; minute: number; second: number; ms: number }"),
         "datetime": ("value", "Date"), "record": ("value", "Record<string, unknown>"),
         # enums travel by member name (the backend converts both ways)
         "enum": ("string", "string")}
DIRECTIONS = {"two_way", "read_only"}
STRATEGIES = {"host_suppressed", "compare", "none"}


class GenError(Exception):
    pass


def common_fields(where: str, b: dict) -> dict:
    """The renderer-visible fields of a binding, validated for shape."""
    name = b.get("name")
    if not name:
        raise GenError(f"{where}: binding without a name")
    where = f"{where} bind:{name}"
    if b.get("direction") not in DIRECTIONS:
        raise GenError(f"{where}: direction must be one of {sorted(DIRECTIONS)}")
    ref = (b.get("type") or {}).get("ref")
    if isinstance(ref, str) and re.fullmatch(r"enum<.+>", ref):
        ref = "enum"
    if ref not in TYPES:
        raise GenError(f"{where}: type {ref!r} is not supported by the renderer ({sorted(TYPES)})")
    echo = b.get("echo") or {}
    if echo.get("strategy") not in STRATEGIES:
        raise GenError(f"{where}: echo.strategy must be one of {sorted(STRATEGIES)}")
    signal = (b.get("change") or {}).get("signal")
    if b["direction"] == "two_way" and not signal:
        raise GenError(f"{where}: a two_way binding needs change.signal")
    if not b.get("property"):
        raise GenError(f"{where}: missing property")
    if not b.get("provenance"):
        raise GenError(f"{where}: missing provenance")
    life = b.get("lifetime") or {}
    if not life.get("on_native_death") or not life.get("on_destroy"):
        raise GenError(f"{where}: lifetime.on_native_death and lifetime.on_destroy are required")
    return {
        "prop": b["property"],
        "signal": signal,
        "type": TYPES[ref][0],
        "direction": b["direction"],
        "compare": bool(echo.get("compare_before_set")),
        "readBack": bool(echo.get("read_back")),
        "valueFrom": (b.get("change") or {}).get("value", "arg0"),
        "tsType": TYPES[ref][1],
    }


def gtk_bindings() -> dict[str, dict[str, dict]]:
    """tag -> name -> fields, checked against the kind and its interfaces."""
    out: dict[str, dict[str, dict]] = {}
    for path in sorted(GTK_META.glob("*.json")):
        kind = svmeta.load_json(path)
        # Bindings annotated on a base class apply to subclass elements (inherited.bindings).
        inh = []
        for r in (kind.get("inherited") or {}).get("bindings", []):
            base = svmeta.load_json(GTK_META / (r["from"].rsplit(":", 1)[-1] + ".json"))
            inh += [b for b in base.get("bindings", []) if b["name"] == r["name"]]
        if inh and (kind.get("element") or {}).get("tag"):
            kind = {**kind, "bindings": list(kind.get("bindings", [])) + inh}
        if not kind.get("bindings"):
            continue
        tag = (kind.get("element") or {}).get("tag")
        if not tag:
            if kind.get("abstract") or kind.get("kind") == "interface":
                continue  # applies to subclass elements through inheritance
            raise GenError(f"{path.name}: bindings on a kind without an element tag")
        props, signals = {}, {}
        for src in [kind] + [
            svmeta.load_json(GTK_META / (i.split(".", 1)[1] + ".json")) for i in kind.get("bases", []) + kind.get("interfaces", [])
            if i.startswith("Gtk.") and (GTK_META / (i.split(".", 1)[1] + ".json")).exists()
        ]:
            for p in src.get("properties", []):
                props.setdefault(p.get("js_name") or p["name"], p)
            for s in src.get("signals", []):
                signals.setdefault(s.get("js_event") or s["name"], s)
        for b in kind["bindings"]:
            where = f"gtk <{tag}>"
            fields = common_fields(where, b)
            p = props.get(b["property"])
            if p is None:
                raise GenError(f"{where} bind:{b['name']}: unknown property {b['property']}")
            if b["direction"] == "two_way" and not p["access"]["write"]:
                raise GenError(f"{where} bind:{b['name']}: property {b['property']} is not writable")
            sig = signals.get(fields["signal"])
            if fields["signal"] and sig is None:
                raise GenError(f"{where} bind:{b['name']}: unknown signal {fields['signal']}")
            if b["echo"]["strategy"] == "host_suppressed" and sig is not None and sig["name"] not in p.get("echo_suppress", []):
                raise GenError(f"{where} bind:{b['name']}: host_suppressed, but property {b['property']} has no echo_suppress for {sig['name']}")
            if b["name"] in out.setdefault(tag, {}):
                raise GenError(f"{where}: duplicate bind:{b['name']}")
            out[tag][b["name"]] = fields
    return out


QT_META = ROOT / "metadata/qt"


def qt_inherited(cls: str, key: str, files: dict[str, dict]) -> list[dict]:
    """`inherit:` records of `cls` and its bases (nearest first), as gen_cpp.py applies them."""
    meta = QT_META / f"{cls}.json"
    chain = [cls] + (svmeta.load_json(meta).get("bases", []) if meta.exists() else [])
    out = []
    for c in chain:
        out += ((files.get(c) or {}).get("inherit") or {}).get(key, [])
    return out


def qt_bindings() -> dict[str, dict[str, dict]]:
    out: dict[str, dict[str, dict]] = {}
    files = {path.stem: svmeta.load_yaml(path) for path in sorted(QT_OVERRIDES.glob("*.yaml"))}
    for stem, data in files.items():
        for el in data.get("elements", []):
            if not el.get("bindings"):
                continue
            tag = el["tag"]
            excl = set(el.get("exclude", []))
            cls = el["construct"]["class"]
            props = {p["js"]: p for p in qt_inherited(cls, "props", files)[::-1] if p["js"] not in excl}
            props.update({p["js"]: p for p in el.get("props", [])})
            signals = {s["js"]: s for s in qt_inherited(cls, "signals", files)[::-1] if s["js"] not in excl}
            signals.update({s["js"]: s for s in el.get("signals", [])})
            for b in el["bindings"]:
                where = f"qt <{tag}>"
                fields = common_fields(where, b)
                p = props.get(b["property"])
                if p is None:
                    raise GenError(f"{where} bind:{b['name']}: unknown property {b['property']}")
                if fields["signal"] and fields["signal"] not in signals:
                    raise GenError(f"{where} bind:{b['name']}: unknown signal {fields['signal']}")
                if b["echo"]["strategy"] == "host_suppressed" and not p.get("suppress_signals"):
                    raise GenError(f"{where} bind:{b['name']}: host_suppressed, but prop {b['property']} has no suppress_signals")
                if b["name"] in out.setdefault(tag, {}):
                    raise GenError(f"{where}: duplicate bind:{b['name']}")
                out[tag][b["name"]] = fields
    return out

APPKIT_META = ROOT / "metadata/appkit"
WINUI_META = ROOT / "metadata/winui"


kebab = naming.kebab  # the shared rule (tools/metadata/common/naming.py): IsChecked -> is-checked


def _add_binding(out: dict, tag: str, b: dict, tk: str, props: dict, signals: dict) -> None:
    """Validate binding `b` of `<tag>` against `props` (name -> writable) and `signals` (name -> payload length)."""
    where = f"{tk} <{tag}>"
    fields = common_fields(where, b)
    name = b["name"]
    if b["property"] not in props:
        raise GenError(f"{where} bind:{name}: unknown property {b['property']}")
    if b["direction"] == "two_way" and not props[b["property"]]:
        raise GenError(f"{where} bind:{name}: property {b['property']} is not writable")
    sig = fields["signal"]
    if sig and sig not in signals:
        raise GenError(f"{where} bind:{name}: unknown signal {sig}")
    if sig and fields["valueFrom"] == "arg0" and signals[sig] < 1:
        raise GenError(f"{where} bind:{name}: value is arg0, but signal {sig} carries no arguments")
    if b["name"] in out.setdefault(tag, {}):
        raise GenError(f"{where}: duplicate bind:{name}")
    out[tag][name] = fields


def appkit_bindings() -> dict[str, dict[str, dict]]:
    """AppKit bindings: tag from `element.tag`; one on a class without an element applies to the element
    classes whose chain includes it."""
    ov = {p.stem: svmeta.load_yaml(p) for p in sorted(APPKIT_OVERRIDES.glob("*.yaml"))}
    meta = {p.stem: svmeta.load_json(p) for p in sorted(APPKIT_META.glob("NS*.json"))}
    chain = lambda cls: [cls] + [c for c in meta[cls]["bases"] if c in meta]  # noqa: E731
    elements = {c: o["element"]["tag"] for c, o in ov.items() if (o.get("element") or {}).get("tag")}
    out: dict[str, dict[str, dict]] = {}
    for el_cls, tag in sorted(elements.items(), key=lambda kv: kv[1]):
        props: dict[str, bool] = {}
        signals: dict[str, int] = {}
        for c in chain(el_cls):
            for p in meta[c]["properties"]:
                props.setdefault(p["js_name"], bool(p["access"]["write"]))
            for p in ov.get(c, {}).get("props", []):
                props.setdefault(p["name"], True)
            for s in ov.get(c, {}).get("signals", []):
                signals.setdefault(s["name"], len(s.get("args", [])))
        for c in chain(el_cls):
            for b in ov.get(c, {}).get("bindings", []):
                _add_binding(out, tag, b, "appkit", props, signals)
    return out


def winui_elements() -> dict[str, str]:
    """class (full name) -> tag for every WinUI element kind (`element` present in the override)."""
    out = {}
    for path in sorted(WINUI_OVERRIDES.glob("*.yaml")):
        data = svmeta.load_yaml(path)
        el = data.get("element")
        if el is None:
            continue
        short = data["class"].rsplit(".", 1)[1]
        out[data["class"]] = el.get("tag") or kebab(short)
    return out


def winui_bindings() -> dict[str, dict[str, dict]]:
    """WinUI bindings; `property` and `change.signal` are kebab-case JS names. Bindings on a base class apply
    to the element kinds whose chain includes it."""
    ov = {}
    for path in sorted(WINUI_OVERRIDES.glob("*.yaml")):
        data = svmeta.load_yaml(path)
        ov[data["class"]] = data
    meta = {}
    for path in sorted(WINUI_META.glob("*.json")):
        if not path.name.startswith("_"):
            k = svmeta.load_json(path)
            meta[k["native"]["name"]] = k
    out: dict[str, dict[str, dict]] = {}
    for cls, tag in sorted(winui_elements().items(), key=lambda kv: kv[1]):
        props: dict[str, bool] = {}
        signals: dict[str, int] = {}
        chain = [cls] + meta[cls]["bases"]
        for c in chain:
            writable = {p["name"]: bool(p["access"]["write"]) for p in meta[c]["properties"]} if c in meta else {}
            for p in ov.get(c, {}).get("props", []):
                props.setdefault(kebab(p["name"]), writable.get(p["name"], True))
            for e in ov.get(c, {}).get("events", []):
                signals.setdefault(kebab(e["name"]), len(e.get("payload", [])))
        for c in chain:
            for b in ov.get(c, {}).get("bindings", []):
                _add_binding(out, tag, b, "winui", props, signals)
    return out


def gtk_toplevels() -> dict[str, dict]:
    """tag -> how a toplevel of this kind is shown (lifetime class `toplevel` in the merged metadata)."""
    out: dict[str, dict] = {}
    for path in sorted(GTK_META.glob("*.json")):
        kind = svmeta.load_json(path)
        tag = (kind.get("element") or {}).get("tag")
        if not tag or (kind.get("lifetime") or {}).get("class") != "toplevel" or kind.get("abstract"):
            continue
        dialog = path.stem.endswith("Dialog") or path.stem == "Assistant"
        out[tag] = {"open": ["present"], "modeless": ["present"], "modalProp": True, "dialog": dialog}
    return out


def qt_toplevels() -> dict[str, dict]:
    out: dict[str, dict] = {}
    files = {path.stem: svmeta.load_yaml(path) for path in sorted(QT_OVERRIDES.glob("*.yaml"))}
    for data in files.values():
        for el in data.get("elements", []):
            cls = el["construct"]["class"]
            meta = QT_META / f"{cls}.json"
            if not meta.exists():
                continue
            m = svmeta.load_json(meta)
            if (m.get("lifetime") or {}).get("class") != "toplevel":
                continue
            dialog = cls == "QDialog" or "QDialog" in m.get("bases", [])
            has_modal = any(p["js"] == "modal" for p in qt_inherited(cls, "props", files) + el.get("props", []))
            out[el["tag"]] = {"open": ["open", "present"] if dialog else ["present"], "modeless": ["present"],
                              "modalProp": has_modal, "dialog": dialog}
    return out


