#!/usr/bin/env python3
"""Generate the GTK backend tables, slot dispatch, verification tests and .d.ts from metadata/gtk/*.json.

Inputs: only metadata/gtk/*.json (the overrides are already merged in by ingest.py).
Outputs (all checked in, byte-identical on rerun):
  crates/svelters-gtk/src/generated/{mod,tables,slots,verify}.rs
  packages/renderer/types/gtk.d.ts  (stable, checked-in location for app/fixture typechecking)

Usage: python3 tools/metadata/gtk/gen_backend.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "common"))
import svmeta  # noqa: E402
from tsvalues import write_values_dts  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
META = ROOT / "metadata/gtk"
OUT = ROOT / "crates/svelters-gtk/src/generated"
DTS = ROOT / "packages/renderer/types/gtk.d.ts"
SCHEMA = ROOT / "packages/testhost/src/schema.json"

HEADER = "// @generated by tools/metadata/gtk/gen_backend.py from metadata/gtk/*.json. Do not edit.\n"
TYPE_PREFIX = "svelters-api:v1:type:gtk:"

VALUE_TY = {"bool": "Bool", "i32": "I32", "u32": "U32", "i64": "I64", "u64": "U64", "f32": "F32", "f64": "F64",
            "string": "Str", "variant": "Variant"}
F_READ, F_WRITE, F_CONSTRUCT, F_CONSTRUCT_ONLY, F_EXPLICIT_NOTIFY, F_VIRTUAL = 1, 2, 4, 8, 16, 32
HANDLER_RESULT = {"none": 0, "bool_stop": 1, "value": 2}
DOM_EVENT = {"clicked": "click", "changed": "change"}


def rs(s: str) -> str:
    return json.dumps(s, ensure_ascii=True)


def value_ty(ref: str) -> str:
    head = ref.split("<")[0]
    return VALUE_TY.get(ref) or {"enum": "Enum", "flags": "Flags", "object": "Object", "boxed": "Boxed"}.get(head, "Other")


def gir_name(doc: dict) -> str:
    return doc["id"].rsplit(":", 1)[-1]


def rust_type(gir: str) -> str:
    ns, _, name = gir.rpartition(".")
    return f"gtk::{name}"


class Model:
    def __init__(self):
        self.docs = {p.stem: json.loads(p.read_text()) for p in sorted(META.glob("*.json"))}
        objs = [d for d in self.docs.values() if d["kind"] in ("object", "interface")]
        self.kinds = sorted(objs, key=lambda d: d["native"]["gtype"])
        self.kind_id = {d["id"]: i + 1 for i, d in enumerate(self.kinds)}
        self.by_id = {d["id"]: d for d in self.docs.values()}
        self.props: list[tuple[int, dict]] = []
        self.signals: list[tuple[int, dict]] = []
        self.methods: list[tuple[int, dict]] = []
        self.slots: list[tuple[int, dict, dict]] = []
        for d in self.kinds:
            k = self.kind_id[d["id"]]
            self.props += [(k, p) for p in sorted(d["properties"], key=lambda p: p["name"])]
            self.signals += [(k, s) for s in sorted(d["signals"], key=lambda s: s["name"])]
            # Only zero-arg generated calls go into METHODS; `dispatch: dynamic` methods are called
            # through GIRepository (X1) and only get verification tests.
            self.methods += [(k, m) for m in sorted(d["methods"], key=lambda m: m["name"])
                             if "annotated" in m and m.get("dispatch", "zero_arg") == "zero_arg"]
            for s in d.get("children", {}).get("slots", []):
                self.slots.append((k, s, d))
        self.slots.sort(key=lambda t: (t[0], t[1]["name"]))
        # X3 child attributes: one entry per (slot, attr); the ATTRS table id is the position + 1.
        self.attrs: list[tuple[int, int, dict, dict, dict]] = []
        for i, (k, s, d) in enumerate(self.slots):
            for a in s.get("attrs", []):
                self.attrs.append((k, i + 1, s, d, a))
        self.tags = {d["element"]["tag"]: d for d in self.kinds if "element" in d}

    def kind_ref(self, gir: str) -> int:
        ns, _, n = gir.rpartition(".")
        return self.kind_id.get(f"{TYPE_PREFIX}{ns}:{n}", 0)

    def subject(self, d: dict) -> str:
        """Name the harness uses to create an instance exercising facts annotated on kind d."""
        if "element" in d:
            return d["element"]["tag"]
        if d["kind"] == "object" and not d["abstract"]:
            return d["native"]["gtype"]
        return d["verify_subject"]["tag"]


