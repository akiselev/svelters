    o.append(f"\npub static KINDS: [KindInfo; {len(m.kinds)}] = [\n")
    for d in m.kinds:
        parent = 0
        if d["bases"]:
            parent = m.kind_ref(d["bases"][0])
        ifaces = sorted(k for k in (m.kind_ref(i) for i in d["interfaces"]) if k)
        tag = d.get("element", {}).get("tag", "")
        slot = d.get("children", {}).get("default_slot") or ""
        o.append(f"    KindInfo {{ name: {rs(gir_name(d))}, tag: {rs(tag)}, gtype: {rs(d['native']['gtype'])}, parent: {parent}, "
                 f"ifaces: &[{', '.join(map(str, ifaces))}], is_abstract: {str(bool(d['abstract'])).lower()}, "
                 f"is_interface: {str(d['kind'] == 'interface').lower()}, default_slot: {rs(slot)} }},\n")
    o.append("];\n")

    o.append(f"\npub static PROPS: [PropInfo; {len(m.props)}] = [\n")
    for k, p in m.props:
        a = p["access"]
        fl = ((F_READ if a["read"] else 0) | (F_WRITE if a["write"] else 0) | (F_CONSTRUCT if a["construct"] else 0)
              | (F_CONSTRUCT_ONLY if a["construct_only"] else 0)
              | (F_EXPLICIT_NOTIFY if p["notify"]["explicit"] else 0) | (F_VIRTUAL if p.get("virtual") else 0))
