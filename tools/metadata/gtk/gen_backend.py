RECORD_TS = {"Gdk:RGBA": "Color | string", "Gdk:Rectangle": "Rect", "Graphene:Rect": "Rect", "Graphene:Size": "Size",
             "Graphene:Point": "Point", "Gtk:Border": "Insets"}
BOXED_STRING_FORM = {"Pango:FontDescription", "Gio:Icon"}


def ts_type(ref: str, m: "Model | None" = None) -> str:
    """The TypeScript type of a property value (see packages/renderer/types/values.d.ts for the shared ones)."""
    head, _, inner = ref.partition("<")
    inner = inner.rstrip(">")
    scalar = {"bool": "boolean", "i32": "number", "u32": "number", "i64": "number", "u64": "number", "f32": "number",
              "f64": "number", "string": "string"}
    if head in scalar:
        return scalar[head]
    short = inner.removeprefix(TYPE_PREFIX)
    if head == "enum" and m is not None and inner in m.by_id:
        return " | ".join(json.dumps(x["nick"]) for x in m.by_id[inner]["members"])
    if head == "flags" and m is not None and inner in m.by_id:
        return "Array<" + " | ".join(json.dumps(x["nick"]) for x in m.by_id[inner]["members"] if x["value"]) + ">"
    if head == "enum":
        return "string"
    if head == "flags":
        return "string[]"
    if head == "list" and inner == "string":
        return "string[]"
    if head == "boxed":
        if short in RECORD_TS:
            return RECORD_TS[short]
        return f'Boxed<"{short.replace(":", ".")}">' + (" | string" if short in BOXED_STRING_FORM else "")
    if head == "object":
        # Object-valued properties take a handle; interface objects without a kind (GIcon) are boxed.
        return "number | Boxed" if short in ("Gio:Icon", "Gdk:Paintable") else "number"
    return "unknown"


def coarse_type(ref: str) -> str | None:
    """The coarse value type the renderer coerces attribute strings by (`host.propType`)."""
    head = ref.split("<")[0]
    return {"bool": "boolean", "i32": "integer", "u32": "integer", "i64": "integer", "u64": "integer",
            "f32": "number", "f64": "number", "string": "string", "enum": "enum", "flags": "flags",
            "list": "list", "boxed": "record"}.get(head)


def gen_schema(m: "Model") -> str:
    """Element tag -> prop -> coarse type, for hosts without a backend (packages/testhost)."""
    def chain(d):
        out = [d]
        for b in d["bases"]:
            ns, _, n = b.partition(".")
            out.append(m.by_id.get(f"{TYPE_PREFIX}{ns}:{n}"))
        for i in d["interfaces"]:
            ns, _, n = i.partition(".")
            out.append(m.by_id.get(f"{TYPE_PREFIX}{ns}:{n}"))
        return [x for x in out if x]

    schema = {}
    for tag in sorted(m.tags):
        props = {}
        for d in chain(m.tags[tag]):
            for p in d["properties"]:
                c = coarse_type(p["type"]["ref"])
                # Only the types attribute coercion acts on: strings, enums and records need no help.
                if c in ("boolean", "integer", "number") and (p["access"]["write"] or p.get("virtual")):
                    props.setdefault(p["js_name"], c)
                    props.setdefault(p["name"], c)
        schema[tag] = dict(sorted(props.items()))
    return json.dumps(schema, indent=2, sort_keys=True) + "\n"


def attr_types(m: Model) -> dict[str, str]:
    """`parent:<name>` attributes of every slot, with the union of their value types."""
    out: dict[str, list[str]] = {}
    for _, _, _, _, a in m.attrs:
        t = ts_type(a["type"], m)
        if t not in out.setdefault(a["name"], []):
            out[a["name"]].append(t)
    return {n: " | ".join(ts) for n, ts in out.items()}


def gen_dts(m: Model) -> str:
    o = ["// @generated by tools/metadata/gtk/gen_backend.py from metadata/gtk/*.json. Do not edit.\n",
         "export interface SvlEvent { type: string; target: unknown; args: unknown[]; }\n",
         "export type SvlHandler = (e: SvlEvent) => void;\n",
         "import type { Boxed, Color, Insets, Point, Rect, Size } from './values';\n\n"]
    for d in m.kinds:
        name = gir_name(d)
        ext = []
        if d["bases"] and d["bases"][0].startswith("Gtk."):
            ext.append(f"Gtk{d['bases'][0].split('.')[1]}Props")
        ext += [f"Gtk{i.split('.')[1]}Props" for i in d["interfaces"] if i.startswith("Gtk.") and d["kind"] == "object"
                and not any(i in b_d["interfaces"] for b_d in [m.by_id.get(TYPE_PREFIX + d["bases"][0].replace(".", ":"), {"interfaces": []})]
                            if d["bases"])]
        ext = [e for e in ext if f"{TYPE_PREFIX}Gtk:{e[3:-5]}" in m.kind_id]
        lines = []
        for p in sorted(d["properties"], key=lambda p: p["js_name"]):
            if p["access"]["write"] and not p["access"]["construct_only"] or p.get("virtual"):
                lines.append(f"  {p['js_name']}?: {ts_type(p['type']['ref'], m)};\n")
        if name == "Widget":
            for an, aty in sorted(attr_types(m).items()):
                lines.append(f"  'parent:{an}'?: {aty};\n")
        for s in sorted(d["signals"], key=lambda s: s["name"]):
            dom = DOM_EVENT.get(s["js_event"], s["js_event"])
            key = f"on{dom}"
            if not key.isidentifier():
                key = rs(key)
            lines.append(f"  {key}?: SvlHandler;\n")
        e = f" extends {', '.join(ext)}" if ext else ""
        o.append(f"export interface Gtk{name}Props{e} {{\n{''.join(lines)}}}\n")
    o.append("\nexport interface GtkElements {\n")
    for tag in sorted(m.tags):
        o.append(f"  {tag}: Gtk{gir_name(m.tags[tag])}Props;\n")
    o.append("}\n")
    return "".join(o)


def gen_types(m: Model) -> str:
    """GTypes register lazily; call each concrete class's get_type before name lookup."""
    ks = [d for d in m.kinds if d["kind"] == "object" and not d["abstract"] and d["native"].get("get_type")]
    o = [HEADER, "\nunsafe extern \"C\" {\n"]
    o += [f"    fn {d['native']['get_type']}() -> usize;\n" for d in ks]
    o.append("}\n\n/// Register the GType named `gtype` (no-op for unknown names). Must run after `gtk::init`.\npub fn ensure_registered(gtype: &str) {\n    match gtype {\n")
    o += [f"        {rs(d['native']['gtype'])} => {{ unsafe {{ {d['native']['get_type']}() }}; }}\n" for d in ks]
    o.append("        _ => {}\n    }\n}\n")
    return "".join(o)


def toolkit_version(m: Model) -> str:
    return next(iter(m.docs.values()))["source"]["gir"]["version"]


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def main() -> int:
    m = Model()
    write(OUT / "mod.rs", HEADER + "\npub mod slots;\npub mod tables;\npub mod types;\n#[cfg(test)]\nmod verify;\n")
    write(OUT / "tables.rs", gen_tables(m))
    write(OUT / "slots.rs", gen_slots(m))
    write(OUT / "types.rs", gen_types(m))
    verify, facts, errors = gen_verify(m)
    if errors:
        print("gen_backend: manual facts without a working generated test (fix or drop them):", file=sys.stderr)
        for e in errors:
            print("  " + e, file=sys.stderr)
        return 1
    write(OUT / "verify.rs", verify)
    write(OUT / "facts.json", json.dumps({"toolkit": "gtk", "version": toolkit_version(m), "facts": facts}, indent=1, sort_keys=True) + "\n")
    write(DTS, gen_dts(m))
    write(SCHEMA, gen_schema(m))
    write_values_dts(ROOT / "packages/renderer/types/values.d.ts")
    print(f"{len(m.kinds)} kinds, {len(m.props)} props, {len(m.signals)} signals, {len(m.slots)} slots, {len(m.methods)} methods",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
