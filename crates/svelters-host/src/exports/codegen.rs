//! Typings, JS stubs and the `svelters-exports/1` JSON, generated from a [`Schema`] value (SV24: the
//! methods of [`Schema`]; the free functions use this process's [`schema()`]).
//!
//! The same JS serves two ways: [`dump`] writes `<module>.js` for bundlers (they import
//! `@svelters/types/core` and sibling stubs as `./<module>.js`), and the QuickJS host serves it as the
//! built-in module `svelters:app/<module>` (core from the built-in `svelters:core`).
// ZU3: build-time codegen (`svelters exports` dump), not run in an app.
#![allow(clippy::disallowed_methods)]

use super::schema::{ClassSchema, MemberSchema, ModuleSchema, Schema, ValueSchema, schema};
use super::{MemberKind, prop_key};
use serde_json::{Value as Json, json};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const HEADER: &str = "Generated by svelters from the app's Rust exports (svelters-exports/1). Do not edit.";

fn wrap_call(m: &MemberSchema, call: &str) -> String {
    match &m.sig.ret.wrap {
        Some(w) => format!("({w})({call})"),
        None => call.to_string(),
    }
}

fn params(m: &MemberSchema) -> String {
    m.sig.params.iter().map(|p| p.name).collect::<Vec<_>>().join(", ")
}

/// The declared parameters plus `options` for an offloaded member.
fn params_with_options(m: &MemberSchema) -> String {
    let mut p: Vec<&str> = m.sig.params.iter().map(|p| p.name).collect();
    if m.offload.is_some() {
        p.push("options");
    }
    p.join(", ")
}

/// `callAsync(...)`'s trailing `shape` argument: the result wrapper, if any (for a stream: the item's).
fn shape(m: &MemberSchema) -> String {
    let w = match &m.sig.items {
        Some(t) => &t.wrap,
        None => &m.sig.ret.wrap,
    };
    match w {
        Some(w) => format!(", {w}"),
        None => String::new(),
    }
}

/// The JS module `svelters:app/<module>` of this process's schema ([`Schema::javascript`]).
pub fn javascript(module: &str, core: &str, sibling: &dyn Fn(&str) -> String) -> Option<String> {
    schema().javascript(module, core, sibling)
}

/// `app.d.ts` of this process's schema ([`Schema::typescript`]).
pub fn typescript() -> String {
    schema().typescript()
}

/// The `svelters-exports/1` JSON of this process's schema ([`Schema::json`]).
pub fn json() -> String {
    schema().json()
}

/// [`Schema::dump`] of this process's schema.
pub fn dump(dir: &Path) -> std::io::Result<DumpReport> {
    schema().dump(dir)
}

impl Schema {
    /// The JS module `svelters:app/<module>`. `core` is the specifier of `@svelters/types/core`;
    /// `sibling` maps another module name to its specifier.
    pub fn javascript(&self, module: &str, core: &str, sibling: &dyn Fn(&str) -> String) -> Option<String> {
        let m = self.module(module)?;
        Some(js_module(m, core, sibling))
    }

    /// `app.d.ts`: one `declare module 'svelters:app/<module>'` per module.
    pub fn typescript(&self) -> String {
        typescript_of(self)
    }

    /// The `svelters-exports/1` JSON (what `svelters-compile` reads for app module types).
    pub fn json(&self) -> String {
        json_of(self)
    }

    /// Writes `exports.json`, `app.d.ts` and one `<module>.js` per module into `dir` (for Vite,
    /// svelte-check and the compiler), rewriting only files whose content changed. Stale module files
    /// from removed modules are deleted.
    pub fn dump(&self, dir: &Path) -> std::io::Result<DumpReport> {
        dump_of(self, dir)
    }
}

fn js_module(m: &ModuleSchema, core: &str, sibling: &dyn Fn(&str) -> String) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "// svelters:app/{} - {HEADER}", m.name);
    let members = || m.functions.iter().chain(m.classes.iter().flat_map(|c| c.methods.iter().chain(c.statics.iter())));
    let offloaded = members().any(|x| x.offload.is_some() && x.sig.items.is_none());
    let streams = members().any(|x| x.sig.items.is_some());
    let stores = m.classes.iter().any(|c| c.store.is_some());
    let mut extra = String::new();
    if offloaded {
        extra.push_str("callAsync, callStaticAsync, ");
    }
    if streams {
        extra.push_str("stream, streamStatic, ");
    }
    if stores {
        extra.push_str("observed, ");
    }
    let _ = writeln!(s, "import {{ NativeObject, CONSTRUCT, call, callStatic, {extra}construct, getProp, setProp, wrapObject, registerClass }} from '{core}';");
    let mut by_mod: std::collections::BTreeMap<&str, Vec<&str>> = Default::default();
    for (om, c) in &m.imports {
        by_mod.entry(om).or_default().push(c);
    }
    for (om, cs) in by_mod {
        let list = cs.iter().map(|c| format!("{c} as {om}${c}")).collect::<Vec<_>>().join(", ");
        let _ = writeln!(s, "import {{ {list} }} from '{}';", sibling(om));
    }
    s.push_str(
        "\n// Without the renderer (no `__svelters_node`) a result is a bare handle number: release it when the wrapper is collected.\n\
const gc = typeof FinalizationRegistry === 'function' ? new FinalizationRegistry((h) => { try { globalThis.__svelters_host.destroy(h); } catch {} }) : null;\n\
const own = (w) => { const h = w.svlHandle; if (gc && typeof h === 'number' && typeof globalThis.__svelters_node !== 'function') gc.register(w, h); };\n",
    );
    for c in &m.classes {
        js_class(&mut s, c);
    }
    if !m.classes.is_empty() {
        let names = m.classes.iter().map(|c| c.name).collect::<Vec<_>>().join(", ");
        let _ = writeln!(s, "\n// For persist(): a persisted object comes back as its class.\nregisterClass({names});");
    }
    let kind = format!("app:{}", m.name);
    for f in &m.functions {
        let p = params(f);
        if f.sig.items.is_some() {
            let _ = writeln!(
                s,
                "\nexport function {}({}) {{\n  return streamStatic('{kind}', '{}', [{p}], options{});\n}}",
                f.name,
                params_with_options(f),
                f.name,
                shape(f)
            );
            continue;
        }
        if f.offload.is_some() {
            let _ = writeln!(
                s,
                "\nexport function {}({}) {{\n  return callStaticAsync('{kind}', '{}', [{p}], options{});\n}}",
                f.name,
                params_with_options(f),
                f.name,
                shape(f)
            );
            continue;
        }
        let _ = writeln!(s, "\nexport function {}({p}) {{\n  return {};\n}}", f.name, wrap_call(f, &format!("callStatic('{kind}', '{}', [{p}])", f.name)));
    }
    for v in &m.values {
        js_value(&mut s, &kind, v);
    }
    s
}

/// A module-level value (E3): read once when the module is evaluated. An app-wide store and a service's
/// value are the same Rust object in every runtime, so a hot reload sees the same state.
fn js_value(s: &mut String, kind: &str, v: &ValueSchema) {
    let m = &v.member;
    let _ = writeln!(s, "\nexport const {} = /* @__PURE__ */ {};", m.name, wrap_call(m, &format!("callStatic('{kind}', '{}', [])", m.name)));
}

fn js_class(s: &mut String, c: &ClassSchema) {
    let _ = writeln!(s, "\nexport class {} extends NativeObject {{", c.name);
    let _ = writeln!(s, "  static native = '{}';", c.native);
    match &c.constructor {
        Some(_) => {
            let _ = writeln!(s, "  static [CONSTRUCT](...args) {{\n    return construct('{}', args);\n  }}", c.native);
        }
        None if c.store.is_some() => {
            let _ = writeln!(s, "  static [CONSTRUCT]() {{\n    throw new TypeError('{} is a store: import its instance (an exported static or a service)');\n  }}", c.name);
        }
        None => {
            let _ = writeln!(s, "  static [CONSTRUCT]() {{\n    throw new TypeError('{} has no #[js(constructor)]');\n  }}", c.name);
        }
    }
    let _ = writeln!(s, "  constructor(...args) {{\n    super(...args);\n    own(this);\n  }}");
    for p in &c.props {
        let key = prop_key(&p.name);
        // E3: a store field is `exact` (every write goes through the store): a reactive read.
        let read = if c.store.is_some() { "observed" } else { "getProp" };
        if p.thunk.is_some() {
            let _ = writeln!(s, "  get {key}() {{\n    return {};\n  }}", wrap_call(p, &format!("{read}(this, '{}')", p.name)));
        }
        if p.setter.is_some() {
            let _ = writeln!(s, "  set {key}(v) {{\n    setProp(this, '{}', v);\n  }}", p.name);
        }
    }
    for m in &c.methods {
        let p = params(m);
        if m.sig.items.is_some() {
            let _ = writeln!(s, "  {}({}) {{\n    return stream(this, '{}', [{p}], options{});\n  }}", prop_key(&m.name), params_with_options(m), m.name, shape(m));
            continue;
        }
        if m.offload.is_some() {
            let _ = writeln!(s, "  {}({}) {{\n    return callAsync(this, '{}', [{p}], options{});\n  }}", prop_key(&m.name), params_with_options(m), m.name, shape(m));
            continue;
        }
        let _ = writeln!(s, "  {}({p}) {{\n    return {};\n  }}", prop_key(&m.name), wrap_call(m, &format!("call(this, '{}', [{p}])", m.name)));
    }
    for m in &c.statics {
        let p = params(m);
        if m.sig.items.is_some() {
            let _ = writeln!(
                s,
                "  static {}({}) {{\n    return streamStatic('{}', '{}', [{p}], options{});\n  }}",
                prop_key(&m.name),
                params_with_options(m),
                c.native,
                m.name,
                shape(m)
            );
            continue;
        }
        if m.offload.is_some() {
            let _ = writeln!(
                s,
                "  static {}({}) {{\n    return callStaticAsync('{}', '{}', [{p}], options{});\n  }}",
                prop_key(&m.name),
                params_with_options(m),
                c.native,
                m.name,
                shape(m)
            );
            continue;
        }
        let _ = writeln!(s, "  static {}({p}) {{\n    return {};\n  }}", prop_key(&m.name), wrap_call(m, &format!("callStatic('{}', '{}', [{p}])", c.native, m.name)));
    }
    s.push_str("}\n");
}

fn doc(s: &mut String, indent: &str, docs: &str, throws: &[&str], module: &str) {
    doc_runs(s, indent, docs, throws, module, None);
}

/// What the typings say about where an offloaded member runs.
fn runs_on(m: &MemberSchema) -> Option<String> {
    let o = m.offload?;
    if m.sig.items.is_some() {
        let mut line = match o.exec {
            super::Exec::Worker => "A stream produced on a worker thread (rayon)".to_string(),
            super::Exec::Blocking => "A stream produced on the blocking pool".to_string(),
            super::Exec::Local => "A stream (async iterable)".to_string(),
            super::Exec::Tokio => "A stream produced on tokio".to_string(),
        };
        line.push_str(": bounded (the producer waits while the reader is behind); leaving the loop or aborting closes it.");
        return Some(line);
    }
    let mut line = match o.exec {
        super::Exec::Worker => "Runs on a worker thread (rayon)".to_string(),
        super::Exec::Blocking => "Runs on the blocking pool".to_string(),
        super::Exec::Local => "Runs on the JS thread (async)".to_string(),
        super::Exec::Tokio => "Runs on tokio".to_string(),
    };
    if o.supersede {
        line.push_str("; a new call supersedes the one in flight");
    }
    if o.max_in_flight > 0 {
        line.push_str(&format!("; at most {} in flight per object, more wait", o.max_in_flight));
    }
    line.push_str(". Rejects with NativeError `svelters` `cancelled` on abort, `panic` on a Rust panic.");
    Some(line)
}

/// E2: `@param` lines for typed arrays a member moves out of JS (`Buffer<T>` parameters).
fn moved_params(m: &MemberSchema) -> Vec<String> {
    m.sig
        .params
        .iter()
        .zip(&m.desc.params)
        .filter(|(_, slot)| slot.tag == svelters_abi::SVL_BYTES && matches!(super::buffers::spec(slot.ty), Some((_, super::buffers::Take::Move))))
        .map(|(p, _)| format!("@param {} moved to Rust: the array is detached (length 0) once the call starts; use the result instead", p.name))
        .collect()
}

fn doc_member(s: &mut String, indent: &str, m: &MemberSchema, module: &str) {
    doc_lines(s, indent, m.docs, &m.sig.throws, module, runs_on(m), moved_params(m));
}

fn doc_runs(s: &mut String, indent: &str, docs: &str, throws: &[&str], module: &str, runs: Option<String>) {
    doc_lines(s, indent, docs, throws, module, runs, Vec::new());
}

fn doc_lines(s: &mut String, indent: &str, docs: &str, throws: &[&str], module: &str, runs: Option<String>, params: Vec<String>) {
    let mut lines: Vec<String> = docs.lines().map(|l| l.trim().to_string()).filter(|l| !l.is_empty()).collect();
    if let Some(r) = runs {
        lines.push(r);
    }
    lines.extend(params);
    if !throws.is_empty() {
        lines.push(format!("@throws NativeError `app:{module}` {}", throws.iter().map(|c| format!("`{c}`")).collect::<Vec<_>>().join(" | ")));
    }
    if lines.is_empty() {
        return;
    }
    if lines.len() == 1 {
        let _ = writeln!(s, "{indent}/** {} */", lines[0]);
    } else {
        let _ = writeln!(s, "{indent}/**");
        for l in lines {
            let _ = writeln!(s, "{indent} * {l}");
        }
        let _ = writeln!(s, "{indent} */");
    }
}

fn ts_params(m: &MemberSchema) -> String {
    let mut p: Vec<String> = m
        .sig
        .params
        .iter()
        .zip(&m.desc.params)
        .map(|(p, slot)| {
            if slot.has(svelters_abi::SVL_D_OPTIONAL) {
                format!("{}?: {}", p.name, p.ty.ts)
            } else {
                format!("{}: {}", p.name, p.ty.ts)
            }
        })
        .collect();
    if m.offload.is_some() {
        p.push(match &m.sig.progress {
            Some(t) => format!("options?: WorkOptions<{}>", t.ts),
            None => "options?: AsyncOptions".to_string(),
        });
    }
    p.join(", ")
}

/// The TS result type: `Promise<T>` for offloaded members, `NativeStream<T>` for streams.
fn ts_ret(m: &MemberSchema) -> String {
    if let Some(t) = &m.sig.items {
        return format!("NativeStream<{}>", t.ts);
    }
    if m.offload.is_some() { format!("Promise<{}>", m.sig.ret.ts) } else { m.sig.ret.ts.clone() }
}

fn typescript_of(schema: &Schema) -> String {
    let mut s = format!("// {HEADER}\n");
    for m in &schema.modules {
        let _ = writeln!(s, "\ndeclare module 'svelters:app/{}' {{", m.name);
        let members = || m.functions.iter().chain(m.classes.iter().flat_map(|c| c.methods.iter().chain(c.statics.iter())));
        let mut core = vec!["NativeObject".to_string()];
        if members().any(|x| x.offload.is_some() && x.sig.progress.is_none()) {
            core.push("AsyncOptions".into());
        }
        if members().any(|x| x.offload.is_some() && x.sig.progress.is_some()) {
            core.push("WorkOptions".into());
        }
        let body = ts_module_body(m);
        // E2: the read-only typed array interfaces `Shared<[T]>` uses.
        for e in svelters_abi::Elem::ALL {
            let name = super::buffers::readonly_ts(e);
            let used = body.match_indices(&name).any(|(i, _)| !body[i + name.len()..].starts_with(|c: char| c.is_ascii_alphanumeric()));
            if used {
                core.push(name);
            }
        }
        if members().any(|x| x.sig.items.is_some()) {
            core.push("NativeStream".into());
        }
        let _ = writeln!(s, "  import type {{ {} }} from '@svelters/types/core';", core.join(", "));
        s.push_str(&body);
        s.push_str("}\n");
    }
    s
}

fn ts_module_body(m: &ModuleSchema) -> String {
    let mut s = String::new();
    {
        for t in &m.types {
            doc(&mut s, "  ", &t.docs, &[], &m.name);
            let _ = writeln!(s, "  export {}", t.decl);
        }
        for c in &m.classes {
            if c.store.is_some() {
                let mut d = c.docs.trim().to_string();
                if !d.is_empty() {
                    d.push('\n');
                }
                d.push_str("A reactive store: its fields are `exact` (reactive reads in effects and templates); writable fields accept `bind:`.");
                doc(&mut s, "  ", &d, &[], &m.name);
            } else {
                doc(&mut s, "  ", c.docs, &[], &m.name);
            }
            let _ = writeln!(s, "  export class {} extends NativeObject {{", c.name);
            match &c.constructor {
                Some(k) => {
                    doc_member(&mut s, "    ", k, &m.name);
                    let _ = writeln!(s, "    constructor({});", ts_params(k));
                }
                None => {
                    let _ = writeln!(s, "    private constructor();");
                }
            }
            for p in &c.props {
                doc(&mut s, "    ", p.docs, &p.sig.throws, &m.name);
                let ty = if p.thunk.is_some() { p.sig.ret.ts.clone() } else { p.sig.params.first().map(|x| x.ty.ts.clone()).unwrap_or_default() };
                let ro = if p.setter.is_none() { "readonly " } else { "" };
                let _ = writeln!(s, "    {ro}{}: {ty};", prop_key(&p.name));
            }
            for x in &c.methods {
                doc_member(&mut s, "    ", x, &m.name);
                let _ = writeln!(s, "    {}({}): {};", prop_key(&x.name), ts_params(x), ts_ret(x));
            }
            for x in &c.statics {
                doc_member(&mut s, "    ", x, &m.name);
                let _ = writeln!(s, "    static {}({}): {};", prop_key(&x.name), ts_params(x), ts_ret(x));
            }
            for e in &c.events {
                let mut d = e.docs.trim().to_string();
                if e.latest {
                    if !d.is_empty() {
                        d.push('\n');
                    }
                    d.push_str("Latest value: delivered at most once per checkpoint.");
                }
                doc(&mut s, "    ", &d, &[], &m.name);
                let arg = match &e.payload {
                    Some(t) => format!("e: {}", t.ts),
                    None => String::new(),
                };
                let _ = writeln!(s, "    on(event: '{}', fn: ({arg}) => void): () => void;", e.name);
            }
            s.push_str("  }\n");
        }
        for f in &m.functions {
            doc_member(&mut s, "  ", f, &m.name);
            let _ = writeln!(s, "  export function {}({}): {};", f.name, ts_params(f), ts_ret(f));
        }
        for v in &m.values {
            let mut d = v.member.docs.trim().to_string();
            if !d.is_empty() {
                d.push('\n');
            }
            d.push_str(match v.what {
                "service" => "A service (started with the app, stopped at shutdown): the same Rust object after a hot reload.",
                _ => "App-wide (a Rust `static`): the same Rust object after a hot reload.",
            });
            doc(&mut s, "  ", &d, &[], &m.name);
            let _ = writeln!(s, "  export const {}: {};", v.member.name, v.member.sig.ret.ts);
        }
    }
    s
}

fn member_json(m: &MemberSchema) -> Json {
    json!({
        "name": m.name,
        "rust": m.rust,
        "kind": match m.kind {
            MemberKind::Method => "method",
            MemberKind::Static => "static",
            MemberKind::Constructor => "constructor",
            MemberKind::Getter | MemberKind::Setter => "property",
        },
        "params": m.sig.params.iter().zip(&m.desc.params).map(|(p, slot)| json!({
            "name": p.name,
            "type": p.ty.ts,
            "optional": slot.has(svelters_abi::SVL_D_OPTIONAL),
        })).collect::<Vec<_>>(),
        "returns": m.sig.ret.ts,
        "throws": m.sig.throws,
        "readonly": m.kind == MemberKind::Getter && m.setter.is_none(),
        "writeonly": m.thunk.is_none(),
        "runsOn": m.offload.map_or("ui", |o| o.exec.name()),
        "async": m.offload.is_some(),
        "supersede": m.offload.is_some_and(|o| o.supersede),
        "maxInFlight": m.offload.map_or(0, |o| o.max_in_flight),
        "progress": m.sig.progress.as_ref().map(|t| t.ts.clone()),
        "stream": m.sig.items.as_ref().map(|t| t.ts.clone()),
        "docs": m.docs.trim(),
    })
}

fn json_of(schema: &Schema) -> String {
    let modules: Vec<Json> = schema
        .modules
        .iter()
        .map(|m| {
            json!({
                "name": m.name,
                "specifier": format!("svelters:app/{}", m.name),
                "classes": m.classes.iter().map(|c| json!({
                    "name": c.name,
                    "native": c.native,
                    "rust": c.rust,
                    "shared": c.shared,
                    "docs": c.docs.trim(),
                    "constructor": c.constructor.as_ref().map(member_json),
                    "store": c.store.is_some(),
                    "props": c.props.iter().map(|p| {
                        let ty = if p.thunk.is_some() { p.sig.ret.ts.clone() } else { p.sig.params.first().map(|x| x.ty.ts.clone()).unwrap_or_default() };
                        // E3: store fields are `exact` by construction (every write goes through the
                        // store and is announced, verified by delivery); other getters are plain reads.
                        let field = c.store.as_ref().and_then(|st| st.fields.iter().find(|f| f.name == p.name));
                        let mut j = json!({
                            "name": p.name,
                            "type": ty,
                            "readonly": p.setter.is_none(),
                            "observability": if field.is_some() { "exact" } else { "none" },
                            "docs": p.docs.trim(),
                        });
                        if let Some(f) = field {
                            j["verified"] = json!("delivery");
                            j["proportional"] = json!(f.proportional);
                        }
                        j
                    }).collect::<Vec<_>>(),
                    "events": c.events.iter().map(|e| json!({
                        "name": e.name,
                        "latest": e.latest,
                        "payload": e.payload.as_ref().map(|t| t.ts.clone()),
                        "docs": e.docs.trim(),
                    })).collect::<Vec<_>>(),
                    "methods": c.methods.iter().map(member_json).collect::<Vec<_>>(),
                    "statics": c.statics.iter().map(member_json).collect::<Vec<_>>(),
                })).collect::<Vec<_>>(),
                "functions": m.functions.iter().map(member_json).collect::<Vec<_>>(),
                "values": m.values.iter().map(|v| json!({
                    "name": v.member.name,
                    "rust": v.member.rust,
                    "kind": v.what,
                    "type": v.member.sig.ret.ts,
                    "docs": v.member.docs.trim(),
                })).collect::<Vec<_>>(),
                "types": m.types.iter().map(|t| {
                    let mut j = json!({
                        "name": t.name,
                        "kind": t.kind,
                        "docs": t.docs.trim(),
                        "fields": t.fields.iter().map(|(n, ty, opt)| json!({"name": n, "type": ty, "optional": opt})).collect::<Vec<_>>(),
                        "values": t.values,
                    });
                    // RA2: tagged unions and JSON Schema definitions.
                    if let Some(tag) = &t.tag {
                        j["tag"] = json!(tag);
                        j["variants"] = json!(t.variants.iter().map(|v| json!({
                            "name": v.name,
                            "docs": v.docs.trim(),
                            "fields": v.fields.iter().map(|(n, ty, opt)| json!({"name": n, "type": ty, "optional": opt})).collect::<Vec<_>>(),
                            "inner": v.inner,
                        })).collect::<Vec<_>>());
                    }
                    if let Some(s) = &t.schema {
                        j["type"] = json!(t.decl.split_once(" = ").map_or("", |(_, ts)| ts.trim_end_matches(';')));
                        j["schema"] = s.clone();
                    }
                    j
                }).collect::<Vec<_>>(),
            })
        })
        .collect();
    let mut out = serde_json::to_string_pretty(&json!({ "schema": "svelters-exports/1", "modules": modules })).unwrap_or_default();
    out.push('\n');
    out
}

/// What [`dump`] wrote.
#[derive(Debug, Default)]
pub struct DumpReport {
    /// Files whose content changed (only those are rewritten).
    pub written: Vec<PathBuf>,
    pub unchanged: usize,
}

fn dump_of(schema: &Schema, dir: &Path) -> std::io::Result<DumpReport> {
    std::fs::create_dir_all(dir)?;
    let mut files: Vec<(PathBuf, String)> = vec![(dir.join("exports.json"), schema.json()), (dir.join("app.d.ts"), schema.typescript())];
    for m in &schema.modules {
        files.push((dir.join(format!("{}.js", m.name)), js_module(m, "@svelters/types/core", &|o| format!("./{o}.js"))));
    }
    let mut report = DumpReport::default();
    for (path, text) in &files {
        if std::fs::read_to_string(path).ok().as_deref() == Some(text.as_str()) {
            report.unchanged += 1;
            continue;
        }
        std::fs::write(path, text)?;
        report.written.push(path.clone());
    }
    for e in std::fs::read_dir(dir)?.flatten() {
        let p = e.path();
        if p.extension().is_some_and(|x| x == "js") && !files.iter().any(|(f, _)| f == &p) {
            std::fs::remove_file(&p)?;
            report.written.push(p);
        }
    }
    Ok(report)
}

/// [`dump`] in debug builds (`debug_assertions`), a no-op in release builds. For a dev host to call
/// on start, so typings and stubs follow every Rust rebuild.
pub fn dump_if_debug(dir: &Path) -> std::io::Result<DumpReport> {
    if cfg!(debug_assertions) { dump(dir) } else { Ok(DumpReport::default()) }
}

/// The source of a host built-in module: `svelters:app/<module>` or `svelters:core`.
pub(crate) fn builtin_module(name: &str) -> Option<String> {
    if name == "svelters:core" {
        return Some(include_str!("../../../../packages/types/src/core.js").to_string());
    }
    let module = name.strip_prefix("svelters:app/")?;
    javascript(module, "svelters:core", &|o| format!("svelters:app/{o}"))
}
