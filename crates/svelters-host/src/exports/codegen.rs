//! Typings, JS stubs and the `svelters-exports/1` JSON, generated from the [`Schema`].
//!
//! The same JS serves two ways: [`dump`] writes `<module>.js` for bundlers (they import
//! `@svelters/types/core` and sibling stubs as `./<module>.js`), and the QuickJS host serves it as the
//! built-in module `svelters:app/<module>` (core from the built-in `svelters:core`).

use super::schema::{ClassSchema, MemberSchema, ModuleSchema, schema};
use super::{MemberKind, prop_key};
use serde_json::{Value as Json, json};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const HEADER: &str = "Generated by svelters from the app's Rust exports (svelters-exports/1). Do not edit.";

fn wrap_call(m: &MemberSchema, call: &str) -> String {
    match &m.sig.ret.wrap {
        Some(w) => format!("({w})({call})"),
        None => call.to_string(),
    }
}

fn params(m: &MemberSchema) -> String {
    m.sig.params.iter().map(|p| p.name).collect::<Vec<_>>().join(", ")
}

/// The declared parameters plus `options` for an offloaded member.
fn params_with_options(m: &MemberSchema) -> String {
    let mut p: Vec<&str> = m.sig.params.iter().map(|p| p.name).collect();
    if m.offload.is_some() {
        p.push("options");
    }
    p.join(", ")
}

/// `callAsync(...)`'s trailing `shape` argument: the result wrapper, if any.
fn shape(m: &MemberSchema) -> String {
    match &m.sig.ret.wrap {
        Some(w) => format!(", {w}"),
        None => String::new(),
    }
}

/// The JS module `svelters:app/<module>`. `core` is the specifier of `@svelters/types/core`;
/// `sibling` maps another module name to its specifier.
pub fn javascript(module: &str, core: &str, sibling: &dyn Fn(&str) -> String) -> Option<String> {
    let m = schema().module(module)?;
    Some(js_module(m, core, sibling))
}

fn js_module(m: &ModuleSchema, core: &str, sibling: &dyn Fn(&str) -> String) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "// svelters:app/{} - {HEADER}", m.name);
    let offloaded = m.functions.iter().chain(m.classes.iter().flat_map(|c| c.methods.iter().chain(c.statics.iter()))).any(|x| x.offload.is_some());
    let asyncs = if offloaded { "callAsync, callStaticAsync, " } else { "" };
    let _ = writeln!(s, "import {{ NativeObject, CONSTRUCT, call, callStatic, {asyncs}construct, getProp, setProp, wrapObject }} from '{core}';");
    let mut by_mod: std::collections::BTreeMap<&str, Vec<&str>> = Default::default();
    for (om, c) in &m.imports {
        by_mod.entry(om).or_default().push(c);
    }
    for (om, cs) in by_mod {
        let list = cs.iter().map(|c| format!("{c} as {om}${c}")).collect::<Vec<_>>().join(", ");
        let _ = writeln!(s, "import {{ {list} }} from '{}';", sibling(om));
    }
    s.push_str(
        "\n// Without the renderer (no `__svelters_node`) a result is a bare handle number: release it when the wrapper is collected.\n\
const gc = typeof FinalizationRegistry === 'function' ? new FinalizationRegistry((h) => { try { globalThis.__svelters_host.destroy(h); } catch {} }) : null;\n\
const own = (w) => { const h = w.svlHandle; if (gc && typeof h === 'number' && typeof globalThis.__svelters_node !== 'function') gc.register(w, h); };\n",
    );
    for c in &m.classes {
        js_class(&mut s, c);
    }
    let kind = format!("app:{}", m.name);
    for f in &m.functions {
        let p = params(f);
        if f.offload.is_some() {
            let _ = writeln!(
                s,
                "\nexport function {}({}) {{\n  return callStaticAsync('{kind}', '{}', [{p}], options{});\n}}",
                f.name,
                params_with_options(f),
                f.name,
                shape(f)
            );
            continue;
        }
        let _ = writeln!(s, "\nexport function {}({p}) {{\n  return {};\n}}", f.name, wrap_call(f, &format!("callStatic('{kind}', '{}', [{p}])", f.name)));
    }
    s
}

fn js_class(s: &mut String, c: &ClassSchema) {
    let _ = writeln!(s, "\nexport class {} extends NativeObject {{", c.name);
    let _ = writeln!(s, "  static native = '{}';", c.native);
    match &c.constructor {
        Some(_) => {
            let _ = writeln!(s, "  static [CONSTRUCT](...args) {{\n    return construct('{}', args);\n  }}", c.native);
        }
        None => {
            let _ = writeln!(s, "  static [CONSTRUCT]() {{\n    throw new TypeError('{} has no #[js(constructor)]');\n  }}", c.name);
        }
    }
    let _ = writeln!(s, "  constructor(...args) {{\n    super(...args);\n    own(this);\n  }}");
    for p in &c.props {
        let key = prop_key(&p.name);
        if p.thunk.is_some() {
            let _ = writeln!(s, "  get {key}() {{\n    return {};\n  }}", wrap_call(p, &format!("getProp(this, '{}')", p.name)));
        }
        if p.setter.is_some() {
            let _ = writeln!(s, "  set {key}(v) {{\n    setProp(this, '{}', v);\n  }}", p.name);
        }
    }
    for m in &c.methods {
        let p = params(m);
        if m.offload.is_some() {
            let _ = writeln!(s, "  {}({}) {{\n    return callAsync(this, '{}', [{p}], options{});\n  }}", prop_key(&m.name), params_with_options(m), m.name, shape(m));
            continue;
        }
        let _ = writeln!(s, "  {}({p}) {{\n    return {};\n  }}", prop_key(&m.name), wrap_call(m, &format!("call(this, '{}', [{p}])", m.name)));
    }
    for m in &c.statics {
        let p = params(m);
        if m.offload.is_some() {
            let _ = writeln!(
                s,
                "  static {}({}) {{\n    return callStaticAsync('{}', '{}', [{p}], options{});\n  }}",
                prop_key(&m.name),
                params_with_options(m),
                c.native,
                m.name,
                shape(m)
            );
            continue;
        }
        let _ = writeln!(s, "  static {}({p}) {{\n    return {};\n  }}", prop_key(&m.name), wrap_call(m, &format!("callStatic('{}', '{}', [{p}])", c.native, m.name)));
    }
    s.push_str("}\n");
}

fn doc(s: &mut String, indent: &str, docs: &str, throws: &[&str], module: &str) {
    doc_runs(s, indent, docs, throws, module, None);
}

/// What the typings say about where an offloaded member runs.
fn runs_on(m: &MemberSchema) -> Option<String> {
    let o = m.offload?;
    let mut line = match o.exec {
        super::Exec::Worker => "Runs on a worker thread (rayon)".to_string(),
        super::Exec::Blocking => "Runs on the blocking pool".to_string(),
        super::Exec::Local => "Runs on the JS thread (async)".to_string(),
        super::Exec::Tokio => "Runs on tokio".to_string(),
    };
    if o.supersede {
        line.push_str("; a new call supersedes the one in flight");
    }
    if o.max_in_flight > 0 {
        line.push_str(&format!("; at most {} in flight per object, more wait", o.max_in_flight));
    }
    line.push_str(". Rejects with NativeError `svelters` `cancelled` on abort, `panic` on a Rust panic.");
    Some(line)
}

fn doc_runs(s: &mut String, indent: &str, docs: &str, throws: &[&str], module: &str, runs: Option<String>) {
    let mut lines: Vec<String> = docs.lines().map(|l| l.trim().to_string()).filter(|l| !l.is_empty()).collect();
    if let Some(r) = runs {
        lines.push(r);
    }
    if !throws.is_empty() {
        lines.push(format!("@throws NativeError `app:{module}` {}", throws.iter().map(|c| format!("`{c}`")).collect::<Vec<_>>().join(" | ")));
    }
    if lines.is_empty() {
        return;
    }
    if lines.len() == 1 {
        let _ = writeln!(s, "{indent}/** {} */", lines[0]);
    } else {
        let _ = writeln!(s, "{indent}/**");
        for l in lines {
            let _ = writeln!(s, "{indent} * {l}");
        }
        let _ = writeln!(s, "{indent} */");
    }
}

fn ts_params(m: &MemberSchema) -> String {
    let mut p: Vec<String> = m
        .sig
        .params
        .iter()
        .zip(&m.desc.params)
        .map(|(p, slot)| {
            if slot.has(svelters_abi::SVL_D_OPTIONAL) {
                format!("{}?: {}", p.name, p.ty.ts)
            } else {
                format!("{}: {}", p.name, p.ty.ts)
            }
        })
        .collect();
    if m.offload.is_some() {
        p.push(match &m.sig.progress {
            Some(t) => format!("options?: WorkOptions<{}>", t.ts),
            None => "options?: AsyncOptions".to_string(),
        });
    }
    p.join(", ")
}

/// The TS result type: `Promise<T>` for offloaded members.
fn ts_ret(m: &MemberSchema) -> String {
    if m.offload.is_some() { format!("Promise<{}>", m.sig.ret.ts) } else { m.sig.ret.ts.clone() }
}

/// `app.d.ts`: one `declare module 'svelters:app/<module>'` per module.
pub fn typescript() -> String {
    let mut s = format!("// {HEADER}\n");
    for m in &schema().modules {
        let _ = writeln!(s, "\ndeclare module 'svelters:app/{}' {{", m.name);
        let members = || m.functions.iter().chain(m.classes.iter().flat_map(|c| c.methods.iter().chain(c.statics.iter())));
        let mut core = vec!["NativeObject"];
        if members().any(|x| x.offload.is_some() && x.sig.progress.is_none()) {
            core.push("AsyncOptions");
        }
        if members().any(|x| x.offload.is_some() && x.sig.progress.is_some()) {
            core.push("WorkOptions");
        }
        let _ = writeln!(s, "  import type {{ {} }} from '@svelters/types/core';", core.join(", "));
        for t in &m.types {
            doc(&mut s, "  ", &t.docs, &[], &m.name);
            let _ = writeln!(s, "  export {}", t.decl);
        }
        for c in &m.classes {
            doc(&mut s, "  ", c.docs, &[], &m.name);
            let _ = writeln!(s, "  export class {} extends NativeObject {{", c.name);
            match &c.constructor {
                Some(k) => {
                    doc(&mut s, "    ", k.docs, &k.sig.throws, &m.name);
                    let _ = writeln!(s, "    constructor({});", ts_params(k));
                }
                None => {
                    let _ = writeln!(s, "    private constructor();");
                }
            }
            for p in &c.props {
                doc(&mut s, "    ", p.docs, &p.sig.throws, &m.name);
                let ty = if p.thunk.is_some() { p.sig.ret.ts.clone() } else { p.sig.params.first().map(|x| x.ty.ts.clone()).unwrap_or_default() };
                let ro = if p.setter.is_none() { "readonly " } else { "" };
                let _ = writeln!(s, "    {ro}{}: {ty};", prop_key(&p.name));
            }
            for x in &c.methods {
                doc_runs(&mut s, "    ", x.docs, &x.sig.throws, &m.name, runs_on(x));
                let _ = writeln!(s, "    {}({}): {};", prop_key(&x.name), ts_params(x), ts_ret(x));
            }
            for x in &c.statics {
                doc_runs(&mut s, "    ", x.docs, &x.sig.throws, &m.name, runs_on(x));
                let _ = writeln!(s, "    static {}({}): {};", prop_key(&x.name), ts_params(x), ts_ret(x));
            }
            s.push_str("  }\n");
        }
        for f in &m.functions {
            doc_runs(&mut s, "  ", f.docs, &f.sig.throws, &m.name, runs_on(f));
            let _ = writeln!(s, "  export function {}({}): {};", f.name, ts_params(f), ts_ret(f));
        }
        s.push_str("}\n");
    }
    s
}

fn member_json(m: &MemberSchema) -> Json {
    json!({
        "name": m.name,
        "rust": m.rust,
        "kind": match m.kind {
            MemberKind::Method => "method",
            MemberKind::Static => "static",
            MemberKind::Constructor => "constructor",
            MemberKind::Getter | MemberKind::Setter => "property",
        },
        "params": m.sig.params.iter().zip(&m.desc.params).map(|(p, slot)| json!({
            "name": p.name,
            "type": p.ty.ts,
            "optional": slot.has(svelters_abi::SVL_D_OPTIONAL),
        })).collect::<Vec<_>>(),
        "returns": m.sig.ret.ts,
        "throws": m.sig.throws,
        "readonly": m.kind == MemberKind::Getter && m.setter.is_none(),
        "writeonly": m.thunk.is_none(),
        "runsOn": m.offload.map_or("ui", |o| o.exec.name()),
        "async": m.offload.is_some(),
        "supersede": m.offload.is_some_and(|o| o.supersede),
        "maxInFlight": m.offload.map_or(0, |o| o.max_in_flight),
        "progress": m.sig.progress.as_ref().map(|t| t.ts.clone()),
        "docs": m.docs.trim(),
    })
}

/// The `svelters-exports/1` JSON (what `svelters-compile` reads for app module types).
pub fn json() -> String {
    let modules: Vec<Json> = schema()
        .modules
        .iter()
        .map(|m| {
            json!({
                "name": m.name,
                "specifier": format!("svelters:app/{}", m.name),
                "classes": m.classes.iter().map(|c| json!({
                    "name": c.name,
                    "native": c.native,
                    "rust": c.rust,
                    "shared": c.shared,
                    "docs": c.docs.trim(),
                    "constructor": c.constructor.as_ref().map(member_json),
                    "props": c.props.iter().map(|p| {
                        let ty = if p.thunk.is_some() { p.sig.ret.ts.clone() } else { p.sig.params.first().map(|x| x.ty.ts.clone()).unwrap_or_default() };
                        json!({
                            "name": p.name,
                            "type": ty,
                            "readonly": p.setter.is_none(),
                            "observability": "none",
                            "docs": p.docs.trim(),
                        })
                    }).collect::<Vec<_>>(),
                    "methods": c.methods.iter().map(member_json).collect::<Vec<_>>(),
                    "statics": c.statics.iter().map(member_json).collect::<Vec<_>>(),
                })).collect::<Vec<_>>(),
                "functions": m.functions.iter().map(member_json).collect::<Vec<_>>(),
                "types": m.types.iter().map(|t| json!({
                    "name": t.name,
                    "kind": t.kind,
                    "docs": t.docs.trim(),
                    "fields": t.fields.iter().map(|(n, ty, opt)| json!({"name": n, "type": ty, "optional": opt})).collect::<Vec<_>>(),
                    "values": t.values,
                })).collect::<Vec<_>>(),
            })
        })
        .collect();
    let mut out = serde_json::to_string_pretty(&json!({ "schema": "svelters-exports/1", "modules": modules })).unwrap_or_default();
    out.push('\n');
    out
}

/// What [`dump`] wrote.
#[derive(Debug, Default)]
pub struct DumpReport {
    /// Files whose content changed (only those are rewritten).
    pub written: Vec<PathBuf>,
    pub unchanged: usize,
}

/// Writes `exports.json`, `app.d.ts` and one `<module>.js` per module into `dir` (for Vite,
/// svelte-check and the compiler), rewriting only files whose content changed. Stale module files
/// from removed modules are deleted.
pub fn dump(dir: &Path) -> std::io::Result<DumpReport> {
    std::fs::create_dir_all(dir)?;
    let mut files: Vec<(PathBuf, String)> = vec![(dir.join("exports.json"), json()), (dir.join("app.d.ts"), typescript())];
    for m in &schema().modules {
        files.push((dir.join(format!("{}.js", m.name)), js_module(m, "@svelters/types/core", &|o| format!("./{o}.js"))));
    }
    let mut report = DumpReport::default();
    for (path, text) in &files {
        if std::fs::read_to_string(path).ok().as_deref() == Some(text.as_str()) {
            report.unchanged += 1;
            continue;
        }
        std::fs::write(path, text)?;
        report.written.push(path.clone());
    }
    for e in std::fs::read_dir(dir)?.flatten() {
        let p = e.path();
        if p.extension().is_some_and(|x| x == "js") && !files.iter().any(|(f, _)| f == &p) {
            std::fs::remove_file(&p)?;
            report.written.push(p);
        }
    }
    Ok(report)
}

/// [`dump`] in debug builds (`debug_assertions`), a no-op in release builds. For a dev host to call
/// on start, so typings and stubs follow every Rust rebuild.
pub fn dump_if_debug(dir: &Path) -> std::io::Result<DumpReport> {
    if cfg!(debug_assertions) { dump(dir) } else { Ok(DumpReport::default()) }
}

/// The source of a host built-in module: `svelters:app/<module>` or `svelters:core`.
pub(crate) fn builtin_module(name: &str) -> Option<String> {
    if name == "svelters:core" {
        return Some(include_str!("../../../../packages/types/src/core.js").to_string());
    }
    let module = name.strip_prefix("svelters:app/")?;
    javascript(module, "svelters:core", &|o| format!("svelters:app/{o}"))
}
