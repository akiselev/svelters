//! The runtime spec tables (`svelters-compile --kinds`): an ES module with what
//! `@svelters/native-runtime` needs to resolve attributes it only sees at run time, i.e. the keys
//! of a spread on a native element and every attribute of `<svelte:element this={tag}>`
//! (docs/notes/native-compiler/runtime-contract.md "Spread attributes"). Built from the same
//! [`Spec`] the compiler checks static attributes against, so both resolve names the same way.
//!
//! Shape (`kinds` holds every kind reachable from a tag through its chain):
//!
//! ```js
//! export const backend = "gtk";
//! export const aliases = { click: "clicked" };            // spec event_aliases
//! export const tags = { button: "Gtk.Button" };            // tag -> kind id
//! export const kinds = {
//!   "Gtk.Button": {
//!     c: ["Gtk.Button", "Gtk.Widget"],                     // chain (kind ids in the spec)
//!     p: { label: ["label", 3, "string", null, 0, 0] },   // js -> [native, flags, type, default, values, binding]
//!     e: { clicked: ["clicked", 0, ["after"]] },          // signal -> [js_event, sync, phases]
//!     t: "label",                                          // text-content prop (0: none)
//!     top: 0,                                              // toplevel: [present method or null]
//!   },
//! };
//! ```
//!
//! Prop flags: 1 writable, 2 readable, 4 nullable, 8 string_form. Types are the spec's, with
//! `strlist` for a list of strings. `values`: enum / flags names (0: none). `binding`:
//! `[signal, arg]` of the kind's binding plan for the prop (arg -1: read back), 0 when none.

use super::spec::{BindingValue, KindSpec, Lifetime, PropType, PropertySpec, Spec};
use serde_json::{Value, json};
use std::collections::BTreeSet;
use std::fmt::Write;

fn prop_type(p: &PropertySpec) -> &'static str {
    match p.ty {
        PropType::Bool => "bool",
        PropType::I32 => "i32",
        PropType::U32 => "u32",
        PropType::I64 => "i64",
        PropType::F64 => "f64",
        PropType::String => "string",
        PropType::Enum => "enum",
        PropType::Flags => "flags",
        PropType::Object => "object",
        PropType::List if p.of.as_deref() == Some("string") => "strlist",
        PropType::List => "list",
        PropType::Record => "record",
        PropType::Boxed => "boxed",
        PropType::Other => "other",
    }
}

fn kind_table(k: &KindSpec, spec: &Spec) -> Value {
    let mut props = serde_json::Map::new();
    for p in k.props.values() {
        let flags = u8::from(p.writable) | u8::from(p.readable) << 1 | u8::from(p.nullable) << 2 | u8::from(p.string_form) << 3;
        let values = match &p.values {
            Some(v) if matches!(p.ty, PropType::Enum | PropType::Flags) => json!(v),
            _ => json!(0),
        };
        let binding = k
            .bindings
            .values()
            .find(|b| b.property == p.js)
            .map(|b| json!([b.event, match b.value { BindingValue::Arg(n) => n as i64, BindingValue::Readback => -1 }]))
            .unwrap_or(json!(0));
        props.insert(p.js.clone(), json!([p.native, flags, prop_type(p), p.default.clone().unwrap_or(Value::Null), values, binding]));
    }
    // bindings declared on this kind for a prop of an ancestor kind
    let mut bindings = serde_json::Map::new();
    for b in k.bindings.values() {
        if !k.props.values().any(|p| p.js == b.property) {
            bindings.insert(b.property.clone(), json!([b.event, match b.value { BindingValue::Arg(n) => n as i64, BindingValue::Readback => -1 }]));
        }
    }
    let mut events = serde_json::Map::new();
    for s in k.signals.values() {
        let js = if s.js_event == s.name || s.js_event.is_empty() { json!(0) } else { json!(s.js_event) };
        events.insert(s.name.clone(), json!([js, u8::from(s.sync), s.phases]));
    }
    let chain: Vec<&String> = k.chain.iter().filter(|c| spec.kinds.contains_key(*c)).collect();
    let mut t = json!({ "c": chain, "p": props, "e": events });
    if !bindings.is_empty() {
        t["b"] = Value::Object(bindings);
    }
    if let Some(tc) = &k.text_content {
        t["t"] = json!(tc);
    }
    if k.lifetime == Lifetime::Toplevel {
        t["top"] = json!([k.present]);
    }
    t
}

/// The ES module `@svelters/native-runtime/kinds` resolves to for this spec.
pub fn kinds_module(spec: &Spec) -> String {
    let mut used = BTreeSet::new();
    for kind in spec.tags.values() {
        if let Some(k) = spec.kinds.get(kind) {
            used.insert(kind.as_str());
            used.extend(k.chain.iter().filter(|c| spec.kinds.contains_key(*c)).map(String::as_str));
        }
    }
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// @generated by `svelters-compile --kinds` from the {} spec: the runtime tables of spreads and <svelte:element>\n// (docs/notes/native-compiler/runtime-contract.md \"Spread attributes\"). Do not edit.",
        spec.backend
    );
    let _ = writeln!(out, "export const backend = {};", json!(spec.backend));
    let _ = writeln!(out, "export const aliases = {};", json!(spec.event_aliases));
    let _ = writeln!(out, "export const tags = {};", json!(spec.tags));
    out.push_str("export const kinds = {\n");
    for id in used {
        let _ = writeln!(out, "  {}: {},", json!(id), kind_table(&spec.kinds[id], spec));
    }
    out.push_str("};\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::semantics::SpecBackend;

    #[test]
    fn gtk_button_has_its_chain_props_and_events() {
        let b = SpecBackend::builtin("gtk").unwrap();
        let m = kinds_module(b.spec());
        assert!(m.contains("export const tags = {"));
        assert!(m.contains("\"button\":\"Gtk.Button\""));
        let line = m.lines().find(|l| l.trim_start().starts_with("\"Gtk.Button\":")).expect("Gtk.Button row");
        assert!(line.contains("\"Gtk.Widget\""), "{line}");
        assert!(line.contains("\"label\":[\"label\""), "{line}");
        assert!(line.contains("\"clicked\":[0,"), "{line}");
        // Gtk.Widget, reached through the chain, is a row of its own
        assert!(m.lines().any(|l| l.trim_start().starts_with("\"Gtk.Widget\":")));
    }

    #[test]
    fn every_builtin_spec_builds() {
        for tk in ["gtk", "qt", "appkit", "winui", "egui"] {
            let b = SpecBackend::builtin(tk).unwrap();
            let m = kinds_module(b.spec());
            assert!(m.len() > 1000, "{tk}");
        }
    }
}
