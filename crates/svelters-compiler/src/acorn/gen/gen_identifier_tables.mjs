// Regenerates ../generated.rs (port of acorn 8.19.0 src/generated/*.js identifier tables).
// Usage: node gen_identifier_tables.mjs <path to acorn/src/generated> > ../generated.rs
import path from "node:path"

const dir = process.argv[2]
if (!dir) {
  console.error("usage: node gen_identifier_tables.mjs <acorn/src/generated>")
  process.exit(1)
}

async function load(name) {
  const file = path.resolve(dir, name + ".js")
  return (await import("file://" + file)).default
}

// Expand a regexp character-class body (as acorn writes it) into inclusive [lo, hi] ranges.
function ranges(classBody) {
  const re = new RegExp("[" + classBody + "]")
  const out = []
  for (let c = 0; c <= 0xffff; c++) {
    if (re.test(String.fromCharCode(c))) {
      if (out.length && out[out.length - 1][1] === c - 1) out[out.length - 1][1] = c
      else out.push([c, c])
    }
  }
  return out
}

const start = await load("nonASCIIidentifierStartChars")
const chars = await load("nonASCIIidentifierChars")
const astralStart = await load("astralIdentifierStartCodes")
const astral = await load("astralIdentifierCodes")

const fmtRanges = (rs) => rs.map(([a, b]) => `(0x${a.toString(16)}, 0x${b.toString(16)})`).join(", ")
let out = "// This file was generated by gen/gen_identifier_tables.mjs from acorn 8.19.0 src/generated.\n"
out += "// Do not modify manually!\n"
out += "#![cfg_attr(rustfmt, rustfmt_skip)]\n\n"
out += "/// nonASCIIidentifierStartChars as sorted inclusive BMP ranges.\n"
out += `pub static NON_ASCII_IDENTIFIER_START: &[(u16, u16)] = &[${fmtRanges(ranges(start))}];\n`
out += "/// nonASCIIidentifierStartChars + nonASCIIidentifierChars as sorted inclusive BMP ranges.\n"
out += `pub static NON_ASCII_IDENTIFIER: &[(u16, u16)] = &[${fmtRanges(ranges(start + chars))}];\n`
out += "/// astralIdentifierStartCodes (run-length pairs from 0x10000).\n"
out += `pub static ASTRAL_IDENTIFIER_START_CODES: &[u32] = &[${astralStart.join(", ")}];\n`
out += "/// astralIdentifierCodes (run-length pairs from 0x10000).\n"
out += `pub static ASTRAL_IDENTIFIER_CODES: &[u32] = &[${astral.join(", ")}];\n`
process.stdout.write(out)
