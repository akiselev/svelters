#!/usr/bin/env python3
"""Generate ../utils/entities.rs from Svelte's `phases/1-parse/utils/entities.js`.

SVELTERS: upstream ships the table as a JS object literal; we generate the Rust table from it
instead of hand-copying (docs/notes/native-compiler/deviations.md). Order is preserved: the
upstream regex alternation tries entity names in object-key order, and so does our matcher.

Usage:
    python3 gen_entities.py <svelte checkout>/packages/svelte/src/compiler/phases/1-parse/utils/entities.js
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "utils", "entities.rs")

ENTRY = re.compile(r"^\s*(?:'([^']+)'|([A-Za-z0-9]+)):\s*(\d+),?\s*$")


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = sys.argv[1]
    entries = []
    with open(src, encoding="utf-8") as f:
        for line in f:
            m = ENTRY.match(line)
            if m:
                entries.append((m.group(1) or m.group(2), int(m.group(3))))
    if len(entries) < 2000:
        sys.exit(f"only {len(entries)} entries parsed from {src}; format changed?")
    names = [n for n, _ in entries]
    if len(set(names)) != len(names):
        sys.exit("duplicate entity names")

    lines = [
        "// @generated by src/svelte/parse/gen/gen_entities.py from",
        "// svelte/src/compiler/phases/1-parse/utils/entities.js (5.57.2 @ f3de3f2). Do not edit.",
        "// https://html.spec.whatwg.org/entities.json from https://dev.w3.org/html5/html-author/charref",
        "",
        "/// `(name, code point)` in upstream key order (the order the entity regex tries them).",
        f"pub static ENTITIES: [(&str, u32); {len(entries)}] = [",
    ]
    for name, code in entries:
        lines.append(f'    ("{name}", {code}),')
    lines.append("];")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(entries)} entities to {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
