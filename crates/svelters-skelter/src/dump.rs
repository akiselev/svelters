//! The build-time dump of an app's typings and specs into its `.svelters/app` (`--dump-types`), as
//! `svelters_egui::dump` writes it from egui's kind registry, for an embedder that runs on skelter
//! alone: one call writes the exports (`svelters_host::exports::dump`: `exports.json`, `app.d.ts`,
//! one stub per module), then from the [`Kinds`] registry and the backend's registered behaviours
//!
//! - `kinds.json`: the app kinds' spec fragment ([`spec::fragment_with`]: `kinds`, `tags`, plus
//!   `behaviors` and draft `bind_sources` when there are any), for `svelters-compile --spec-fragment`
//!   and live compiles;
//! - `kinds.d.ts`: the app kinds' `svelteHTML.IntrinsicElements` entries ([`kinds_typings`]: props,
//!   `bind:` keys, `on<event>` handlers) and, for a kind with methods, its `bind:this` interface;
//! - when the backend has behaviours: `behaviors.d.ts` ([`behaviors_typings`]) and
//!   `behaviors/<ns>.js` ([`SkelterBackend::behavior_modules`]).
//!
//! The typings build on `@svelters/native-runtime/types/egui` (skelter's surface uses egui's JS
//! names, so its built-in elements and `EguiAttrs`, `EguiWidgetProps`, `SvlEvent`, `SvlUiEvent` and
//! `NativeElement` are the ones there). Only changed files are rewritten.
// ZU3: build-time codegen, not run per frame.
#![allow(clippy::disallowed_methods)]

use crate::kinds::Kinds;
use crate::spec::{self, BindSource};
use crate::surface::{KindSpec, ValueType};
use crate::SkelterBackend;
use std::fmt::Write as _;
use std::path::Path;
pub use svelters_host::exports::DumpReport;

const TYPINGS_HEADER: &str = "// @generated by crates/svelters-skelter/src/dump.rs from the skelter kind registry. Do not edit.\n";

fn ts_doc(out: &mut String, indent: &str, doc: &str) {
    let doc = doc.trim();
    if !doc.is_empty() {
        let _ = writeln!(out, "{indent}/** {} */", doc.replace("*/", "*\\/").replace('\n', " "));
    }
}

fn ts_key(name: &str) -> String {
    if name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') && !name.starts_with(|c: char| c.is_ascii_digit()) {
        name.to_string()
    } else {
        format!("'{name}'")
    }
}

fn ts_of(ty: ValueType) -> String {
    match ty {
        ValueType::Bool => "boolean".into(),
        ValueType::I64 | ValueType::F64 => "number".into(),
        ValueType::Str | ValueType::Color => "string".into(),
        ValueType::Enum(values) => values.iter().map(|v| format!("'{v}'")).collect::<Vec<_>>().join(" | "),
        ValueType::StrList => "string[]".into(),
        ValueType::NumList | ValueType::IdList => "number[]".into(),
        ValueType::Record => "Record<string, unknown>".into(),
        ValueType::Any => "unknown".into(),
    }
}

/// The members of one kind's own props, `bind:` keys and handlers (`indent`-prefixed lines).
fn ts_members(out: &mut String, indent: &str, k: &'static KindSpec, bindings: &serde_json::Value) {
    for p in k.props {
        ts_doc(out, indent, p.doc);
        let t = ts_of(p.ty);
        let ty = if p.nullable { format!("{t} | null") } else { t };
        let _ = writeln!(out, "{indent}{}?: {ty};", ts_key(p.name));
        if p.native {
            let _ = writeln!(out, "{indent}{}?: {ty};", ts_key(&format!("bind:{}", p.name)));
            if bindings.get(p.name).and_then(|b| b.get("commit")).is_some() {
                let _ = writeln!(out, "{indent}{}?: {ty};", ts_key(&format!("bind:{}|commit", p.name)));
            }
        }
    }
    for s in k.signals {
        ts_doc(out, indent, s.doc);
        // EV1: the DOM-style events get a `SvlUiEvent` and a capture form
        if s.bubbles {
            let _ = writeln!(out, "{indent}{}?: (e: SvlUiEvent) => void;", ts_key(&format!("on{}", s.name)));
            let _ = writeln!(out, "{indent}{}?: (e: SvlUiEvent) => void;", ts_key(&format!("on{}capture", s.name)));
            continue;
        }
        let args: Vec<String> = s.args.iter().map(|(_, t)| ts_of(*t)).collect();
        let params: Vec<String> = s.args.iter().zip(&args).map(|((n, _), t)| format!("{}: {t}", n.replace('-', "_"))).collect();
        // a sync signal's handler gets a `SvlEvent` first (runtime `dispatch_sync`)
        let params = if s.sync { std::iter::once(format!("e: SvlEvent<[{}]>", args.join(", "))).chain(params).collect::<Vec<_>>().join(", ") } else { params.join(", ") };
        let _ = writeln!(out, "{indent}{}?: ({params}) => void;", ts_key(&format!("on{}", s.name)));
    }
}

/// The interface name of a kind's `bind:this` node (`QuantityFieldElement`).
fn element_name(k: &KindSpec) -> String {
    format!("{}Element", k.name.replace(['-', '.'], "_"))
}

/// `kinds.d.ts`: the `svelteHTML.IntrinsicElements` entries of the app's kinds ([`Kinds::with_app`];
/// on top of the built-in elements of `@svelters/native-runtime/types/egui`) with their props,
/// `bind:` keys and `on<event>` handlers, and for each kind with methods its `bind:this` node,
/// `<Name>Element` (RA3), listed in `HTMLElementTagNameMap`.
pub fn kinds_typings(all: &Kinds) -> String {
    let app: Vec<&'static KindSpec> = all.iter().filter(|m| m.app && m.surface.tag.is_some()).map(|m| m.surface).collect();
    let mut s = String::from(TYPINGS_HEADER);
    s.push_str("import type { EguiAttrs, EguiWidgetProps, SvlEvent, SvlUiEvent } from '@svelters/native-runtime/types/egui';\n");
    let with_methods: Vec<&'static KindSpec> = app.iter().copied().filter(|k| k.chain().any(|c| !c.methods.is_empty())).collect();
    if !with_methods.is_empty() {
        s.push_str("import type { NativeElement } from '@svelters/native-runtime/types/egui';\n");
        for k in &with_methods {
            let _ = writeln!(s, "\n/** `bind:this` on `<{}>`: the element node with the kind's methods (RA3). */", k.tag.unwrap_or(k.name));
            let _ = writeln!(s, "export interface {} extends NativeElement {{", element_name(k));
            let mut seen: Vec<&str> = Vec::new();
            for m in k.chain().filter(|c| c.name != "Widget").flat_map(|c| c.methods.iter()) {
                if seen.contains(&m.name) {
                    continue;
                }
                seen.push(m.name);
                ts_doc(&mut s, "  ", m.doc);
                let args: Vec<String> = m.params.iter().map(|(n, t)| format!("{}: {}", n.replace('-', "_"), ts_of(*t))).collect();
                let ret = m.ret.map_or("void".to_string(), ts_of);
                let _ = writeln!(s, "  {}({}): {ret};", ts_key(m.name), args.join(", "));
            }
            s.push_str("}\n");
        }
    }
    s.push_str("\ndeclare global {\n  namespace svelteHTML {\n    interface IntrinsicElements {\n");
    for k in &app {
        ts_doc(&mut s, "      ", k.doc);
        let widget = k.chain().any(|c| c.name == "Widget");
        let _ = writeln!(s, "      {}: EguiAttrs<{}{{", ts_key(k.tag.expect("tagged")), if widget { "EguiWidgetProps & " } else { "" });
        let bindings = spec::bindings_json(k);
        let bases: Vec<&'static KindSpec> = k.chain().collect();
        for b in bases.iter().rev().filter(|b| b.name != "Widget") {
            ts_members(&mut s, "        ", b, &bindings);
        }
        s.push_str("      }>;\n");
    }
    s.push_str("    }\n  }\n");
    if !with_methods.is_empty() {
        // svelte-check types `bind:this` on an element from this map
        s.push_str("  interface HTMLElementTagNameMap {\n");
        for k in &with_methods {
            let _ = writeln!(s, "    {}: {};", ts_key(k.tag.expect("tagged")), element_name(k));
        }
        s.push_str("  }\n");
    }
    s.push_str("}\n\nexport {};\n");
    s
}

/// `behaviors.d.ts`: an ambient `declare module 'svelters:behaviors/<ns>'` per namespace of
/// `tags` (`<ns>.<name>`, [`SkelterBackend::behavior_tags`]), each behaviour an `Action`. A skelter
/// behaviour's params are untyped (`behavior.rs`: any ABI value), so they type as a record of
/// `unknown`, and it declares no events.
pub fn behaviors_typings(tags: &[String]) -> String {
    let mut sorted: Vec<(&str, &str)> = tags.iter().filter_map(|t| t.split_once('.')).collect();
    sorted.sort_unstable();
    let mut s = String::from(TYPINGS_HEADER);
    let mut ns_open: Option<&str> = None;
    for (ns, name) in sorted {
        if ns_open != Some(ns) {
            if ns_open.is_some() {
                s.push_str("}\n");
            }
            let _ = writeln!(s, "\ndeclare module 'svelters:behaviors/{ns}' {{");
            s.push_str("  import type { Action } from 'svelte/action';\n");
            ns_open = Some(ns);
        }
        let _ = writeln!(s, "\n  /** `use:{name}`: the app's Rust behaviour `{ns}.{name}`; its params are set as given. */");
        let _ = writeln!(s, "  export const {name}: Action<any, Record<string, unknown> | undefined>;");
    }
    if ns_open.is_some() {
        s.push_str("}\n");
    }
    s
}

/// Writes this binary's typings and specs into `dir` (an app's `.svelters/app`) from `all`, with no
/// behaviours or draft bind sources: [`dump_with`].
pub fn dump(dir: &Path, all: &Kinds) -> std::io::Result<DumpReport> {
    dump_with(dir, all, None, &[])
}

/// The one-call replacement for `svelters_egui::dump` on skelter: `svelters_host::exports::dump`
/// (`exports.json`, `app.d.ts`, the module stubs), then `kinds.json` ([`spec::fragment_with`]),
/// `kinds.d.ts` ([`kinds_typings`]) and, when `backend` has behaviours, `behaviors.d.ts`
/// ([`behaviors_typings`]) and `behaviors/<ns>.js` ([`SkelterBackend::behavior_modules`]). Only
/// changed files are rewritten.
pub fn dump_with(dir: &Path, all: &Kinds, backend: Option<&SkelterBackend>, bind_sources: &[BindSource]) -> std::io::Result<DumpReport> {
    let mut report = svelters_host::exports::dump(dir)?;
    let tags = backend.map(SkelterBackend::behavior_tags).unwrap_or_default();
    let mut text = serde_json::to_string_pretty(&spec::fragment_with(all, &tags, bind_sources)).expect("fragment json");
    text.push('\n');
    let mut files = vec![("kinds.json".to_string(), text), ("kinds.d.ts".to_string(), kinds_typings(all))];
    let modules = backend.map(SkelterBackend::behavior_modules).unwrap_or_default();
    if !modules.is_empty() {
        files.push(("behaviors.d.ts".to_string(), behaviors_typings(&tags)));
        std::fs::create_dir_all(dir.join("behaviors"))?;
    }
    files.extend(modules.into_iter().map(|(ns, text)| (format!("behaviors/{ns}.js"), text)));
    for (name, text) in files {
        let path = dir.join(name);
        if std::fs::read_to_string(&path).ok().as_deref() == Some(text.as_str()) {
            report.unchanged += 1;
        } else {
            std::fs::write(&path, text)?;
            report.written.push(path);
        }
    }
    Ok(report)
}

impl SkelterBackend {
    /// [`dump_with`] of this backend's kinds and registered behaviours.
    pub fn dump(&self, dir: &Path, bind_sources: &[BindSource]) -> std::io::Result<DumpReport> {
        let kinds = self.0.kinds.clone();
        dump_with(dir, &kinds, Some(self), bind_sources)
    }
}
